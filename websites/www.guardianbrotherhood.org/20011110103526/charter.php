					<h3 align="left"><i><font face="verdana" color="#800000">-= Interguild 
                    Relations =- </font></i></h3>
                    <p align="left"><font face="verdana" size="2">No guild member shall at 
                    any time place another guild member on /ignore.
                    <img border="0" src="/images/gb/char2a.jpg" align="right" width="231" height="286"><br>
                    <br>
                    No guild member shall knowingly disobey the direct order of 
                    their House Lord or a guild officer <br>
                    so long as that order is not against guild policy or guild 
                    disputes. <br>
                    <br>
                    No guild member shall disrespect another guild member in any 
                    public forum, including guildspeak. <br>
                    <br>
                    Guild members shall refrain from using foul language or 
                    lewd/overtly sexual language while in <br>
                    guildspeak. <br>
                    <br>
                    It shall be required that an all-guild meeting be called 
                    once per month. This meeting <br>
                    shall be held at a predetermined location in the world of Norrath, as decided by the <br>
                    Guildmaster. In the event that such a meeting pertains to 
                    matters of high importance, <br>
                    the meeting shall take place in a 'virtual chat room' 
                    prepared by the Duke of URL. <br>
                    It is the responsibility of the Guildmaster to schedule 
                    Guild meetings. <br>
                    <br>
                    Any member requiring assistance should first place said 
                    request with their <br>
                    House Lord. If he or she is not available and you cannot get 
                    a friend <br>
                    to help, a general request over guild speak can be made. 
                    General requests <br>
                    for gifts of time, money, teleports or items should be kept 
                    to a minimum. <br>
                    Everyone must play the game for themselves if possible. If 
                    someone asks you <br>
                    to stop asking for something, please be respectful of their 
                    request. <br>
                    <br>
                    Grievances against other members are to be settled with the 
                    chain of <br>
                    command in place for the guild member this grievance is 
                    filed against. <br>
                    Namely, against a squire, this should be resolved by their 
                    captain. Matters <br>
                    are to escalate up the chain of command as necessary, but 
                    should only reach <br>
                    the Council of Lords if the Lord of the grieved member 
                    cannot come to a <br>
                    decision on the matter. <br>
&nbsp;</font></p>
                    <h3 align="left"><i><font face="verdana" color="#800000">-= Norrathian 
                    Relations =- </font></i></h3>
                    <p align="left"><font face="verdana" size="2">Do not steal kills or camps 
                    from another player without consent. <br>
                    <br>
                    Do not steal loot from other players without consent. (i.e. 
                    random roll) <br>
                    <br>
                    Do not beg for items/corpse recovery <br>
                    <br>
                    Do not use /Anon at any time. <br>
                    <br>
                    Do not camp guards with the intent of removing the 
                    protection of new <br>
                    players. <br>
                    <br>
                    Treat players as you would like to be treated. <br>
                    <br>
                    Keep in mind that your actions reflect the guild as a whole, 
                    and not just <br>
                    yourself. Inappropriate behavior is subject to reprimand up 
                    to and including guild removal. </font></p>
                    <h3 align="left">&nbsp;</h3>
                    <h3 align="left"><i><font face="verdana" color="#800000">-= Invitation To 
                    The Guild =- </font></i></h3>
                    <p align="left"><font face="verdana" size="2">Any officer that invites a 
                    player into the guild accepts FULL responsibility <br>
                    for the member. This includes notification of rules and 
                    regulations. <br>
                    <br>
                    The inviting officer is required to fill out the invitation 
                    form or send an email <br>
                    to
                    <a href="mailto:invite@guardianbrotherhood.org" style="color: 00714">
                    invite@guardianbrotherhood.org</a> within 24 hours listing 
                    the following: <br>
                    Name of new member <br>
                    Race/Class/Gender <br>
                    Reason for inviting <br>
                    Date/time of invite <br>
                    Joining House (if applicable) <br>
                    All alts of primary character <br>
                    <br>
                    The inviting officer is responsible for the player's conduct 
                    unless they have <br>
                    joined a Lord's House, at which point the presiding Lord 
                    assumes responsibility. <br>
                    <br>
&nbsp;</font></p>
                    <h3 align="left"><i><font face="verdana"><font color="#800000">-= Chain 
                    Of Command =-</font> </font></i></h3>
                    <p align="left"><font face="verdana" size="2">When you are recruited, the 
                    officer that recruits you is your immediate <br>
                    contact. He or she will remain so until you choose to join 
                    and are accepted <br>
                    into a Lords' House. <br>
                    <br>
                    Please contact the person immediately above you in the chain 
                    of command when <br>
                    possible. This cuts down on excessive guild chat and creates 
                    a more <br>
                    enjoyable experience for everyone. <br>
                    <br>
                    Disputes between members are first handled by their 
                    immediate superior within <br>
                    their respective house, following up to the Lord of that 
                    house. A grievance is <br>
                    only to be taken outside the house chain of command when the 
                    grievance is against <br>
                    that house's Lord. <br>
                    <br>
                    Grievance's against a Lord shall be taken to the Council of 
                    Lords or the GM for resolution. <br>
                    <br>
                    Grievance's against the Guildmaster shall be taken to the 
                    Council of Lords. <br>
                    <br>
                    Lords have the power to issue commands to all members of 
                    their house. They can also <br>
                    command those outside their House at the discretion of that 
                    members' Lord. </font></p>
                    <p align="left">&nbsp;</p>
                    <h3 align="left"><i><font face="verdana" color="#800000">-= Removal Of 
                    Guild Members =- </font></i></h3>
                    <p align="left"><font face="verdana" size="2">Members of the Council of 
                    Lords and the Guildmaster may remove any player <br>
                    as they see fit. The player's Lord must be notified as to 
                    the reason for <br>
                    dismissal, but his or her consent is not necessary. <br>
                    <br>
                    Lords may only be removed by a majority vote within the 
                    Council of Lords or <br>
                    by the GM. (requires both GM's unanimous decision if more 
                    than 1 exists) <br>
                    <br>
                    <br>
                    ~ Rankings O' Ye Guild ~ <br>
                    The Titles of Office are as follows <br>
                    Initiate <br>
                    Squire <br>
                    Knight <br>
                    Captain <br>
                    Lords <br>
                    Ambassador <br>
                    Duke <br>
                    Guildmaster <br>
                    <br>
                    Initiates are fresh recruits to the Guardian Brotherhood. 
                    These are members <br>
                    that have not yet sworn fealty to a particular house. 
                    Initiates are members <br>
                    in their trial times. They are subject to the just rulings 
                    of all members <br>
                    ranked above them. <br>
                    <br>
                    Squires are the basic Guild Members who have sworn fealty to 
                    a Lords <br>
                    House. They are the proud rank and file. <br>
                    <br>
                    Knights are promoted from ranks of squires for their service 
                    to other players. <br>
                    Knights must be known as a benefit to the Guild and have a 
                    good reputation. <br>
                    Knights may make suggestions to their Captains about 
                    potential worthy squire <br>
                    candidates. <br>
                    Knights may request up to 5 squires be allowed into Guild 
                    (One full <br>
                    adventuring group). <br>
                    <br>
                    Captains are the promotion from Knighthood. <br>
                    Captains are appointed by Lords to assist them. <br>
                    Captains help their Lord settling disputes among the Knights 
                    and Squires. <br>
                    Captains may demote and expel Knights and Squires and 
                    initiates for <br>
                    bringing shame upon the Guild. <br>
                    Captains must enforce the Laws of The Guild Among their 
                    Knights and Squires <br>
                    Captains may make squires into the Guild and retain 5 
                    Knights (One full <br>
                    adventuring group). <br>
                    <br>
                    The Honor Guard are those members who have not yet sworn 
                    fealty to a house <br>
                    yet have earned a rank higher than Initiate. <br>
                    They are promoted by the GM and gain rank as normal (Knight, 
                    Captain) but without House fealty. <br>
                    They may join a Lord's House at any time and leave the HG 
                    retaining their current rank. <br>
                    The HG may be given special tasks by the Guildmaster. <br>
                    <br>
                    Lordship is conferred upon an individual based on a majority 
                    vote of the <br>
                    Council of Lords. The nomination is made by any member of 
                    the CoL (Council of Lords) <br>
                    in the Council Chambers (forums). <br>
                    Lords are required to participate in the guild forums and 
                    carefully monitor <br>
                    the CoL forum especially. Failure to participate for more 
                    than 1 week without <br>
                    prior notification and consent by the CoL is subject to loss 
                    of Lord status. <br>
                    Lords constitute their own &quot;House&quot; and must set the 
                    guidelines of such. <br>
                    Lords are responsible for all members within their 'House' 
                    and must <br>
                    settle all disputes between its members. <br>
                    Lords may appoint up to 5 Captains (One full adventuring 
                    group). <br>
                    <br>
                    Council of Lords is made up of all current Lords. <br>
                    Council of Lords is the primary ruling body for the guild.
                    <br>
                    Council of Lords handles all day-to-day duties. <br>
                    Any Lord can initiate legislation and if 2nd, that 
                    legislation is put to a vote. All <br>
                    votes must be completed within 7 days. <br>
                    A majority vote is needed to pass legislation, if not enough 
                    Lords vote on it, <br>
                    60% or better, then the measure is not passed by default.
                    <br>
                    Council of Lords has the power to initiate /guildwar only by 
                    a 100% unanimous vote. <br>
                    Council of Lords has the power to override any decision made 
                    by the GM by a unanimous vote. <br>
                    Council of Lords has the power to override any legislation 
                    initiated by the GM by a majority vote. <br>
                    Council of Lords has the power to remove a Guildmaster by an 
                    unanimous vote of no confidence. A <br>
                    vote of no confidence is initiated by any Lord within the 
                    Council and must be second to be <br>
                    put to a vote. <br>
                    <br>
                    Ambassadors are a minimum of Level 30. <br>
                    Ambassadors are Lords assigned to negotiate with other 
                    Guilds for Alliance, <br>
                    Pax or Events. <br>
                    Ambassadors execute special assignments from the Council of 
                    Lords. <br>
                    Ambassadors are responsible to set up Events with other 
