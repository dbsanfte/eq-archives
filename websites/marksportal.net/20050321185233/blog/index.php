<!-- Post meta -->
<div class="meta">
Posted on January 23rd, 2005. <!-- By Mark. --> About <a href="http://www.marksportal.net/blog/index.php?cat=3" title="View all posts in The Narrow Path">The Narrow Path</a>. <a href="http://www.marksportal.net/blog/index.php?p=46#comments">No Comments</a>.</div>

<!-- Actual post -->
<div class="storycontent">
	<p>I just finished watching the <a href="http://www.imdb.com/title/tt0167260/">The Lord of the Rings: The Return of the King</a>, which is quite a great end to the trilogy.   While there were many great lines in the movie, this particular one from Theoden rang out in my ears.</p>
	<blockquote><p>My body is broken.  I go to my fathers.  And even in their mighty company I shall not now be ashamed</p></blockquote>
	<p>As Christians, I think we sometimes forget about those who went before.  Their bravery, sacrifice, and unwavering devotion to Christ.  Will I be able to hold my head high at the end of my life as I stand before God, His Angels, and the multitudes of believers who went before me?  Listen to Paul&#8217;s words in the Book of Romans as he describes the place we enter when we are in prayer:</p>
	<blockquote><p>“But you have come to Mount Zion, to the heavenly Jerusalem, the city of the living God. You have come to thousands upon thousands of angels in joyful assembly, to the church of the firstborn, whose names are written in heaven. You have come to God, the judge of all men, to the spirits of righteous men made perfect, to Jesus the mediator of a new covenant, and to the sprinked blood that speaks a better word than the blood of Abel.” (Hebrews 12:22-24, NIV)</p></blockquote>
	<p>That is a mighty gathering.  I hope that when I am finally called away from earth that I will be able to enter that great assembly without shame.</p>
</div>			
