	<p>Yesterday I was flipping through the radio stations as I was driving back to my office when, for some reason, I stopped at <a href="http://www.kkup.com">91.5 FM KKUP</a>.   Over the speakers,  a man of British accent was talking about the concepts of time, direction, and man&#8217;s desires.   Since I only listened to it for a brief period I was not able to really understand his thoughts on the subject or even his central points.   I quickly jotted down the radio station and time of day to find out who I was listening to.  I later discovered I was listening to an old recording of a man named <a href="http://www.alanwatts.com/">Alan Watts</a>, who died in 1973, and I was listening to the &#8220;<a href="http://www.kkup.com/kkuptuesday.html#1pm">The Alan Watts Hour</a>&#8220;.  I think the lecture series was titled, &#8220;<a href="http://www.alanwatts.com/ac_lectures.html">Man in Nature</a>&#8221; but I&#8217;m not sure.   My interest has been peaked in the little I&#8217;ve heard so I might have to find the lecture series and give it a full listen.</p>
	<p>On a side note, <a href="http://www.kkup.com/">KKUP</a> does seem to have a nice variety of <a href="http://www.kkup.com/schedule.html">programs</a>.
</p>
