<h3 class="storytitle" id="post-43"><a href="http://www.marksportal.net/blog/index.php?p=43" rel="bookmark" title="Permanent Link: The Call of Abraham">The Call of Abraham</a></h3>
<!-- Post meta -->
<div class="meta">
Posted on January 4th, 2005. <!-- By Mark. --> About <a href="http://www.marksportal.net/blog/index.php?cat=3" title="View all posts in The Narrow Path">The Narrow Path</a>. <a href="http://www.marksportal.net/blog/index.php?p=43#comments">No Comments</a>.</div>

<!-- Actual post -->
<div class="storycontent">
	<p>I&#8217;ve always thought that God called Abraham out of Ur to go to the land of Canaan (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Genesis+12%3A1-3&#038;section=2&#038;version=nas">Gen 12:1-3</a>).   Imagine my surprise when I found that wasn&#8217;t the case.  Going back to <a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Genesis+11%3A31-32&#038;section=2&#038;version=nas">Gen 11:31-32</a> it states that Abraham&#8217;s father Terah had it in his mind to go to the land of Canaan, but they ended up stopping in Haran and stayed there.  It wasn&#8217;t until after Terah died that God came to Abraham and told him to complete the journey his father had started.  </p>
	<p>So now I wonder, why did Terah wish to go to Canaan?  I suppose one reason Terah wished to leave Ur was because of his <a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Genesis+11%3A28&#038;section=0&#038;version=nas">son&#8217;s death</a>, but I can&#8217;t be certain.  Did God ask Terah to begin this journey to Canaan?
</p>
