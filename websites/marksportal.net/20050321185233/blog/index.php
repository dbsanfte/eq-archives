<h3 class="storytitle" id="post-41"><a href="http://www.marksportal.net/blog/index.php?p=41" rel="bookmark" title="Permanent Link: &#8230;and stuff.">&#8230;and stuff.</a></h3>
<!-- Post meta -->
<div class="meta">
Posted on December 20th, 2004. <!-- By Mark. --> About <a href="http://www.marksportal.net/blog/index.php?cat=1" title="View all posts in General">General</a>. <a href="http://www.marksportal.net/blog/index.php?p=41#comments">1 Comment</a>.</div>

<!-- Actual post -->
<div class="storycontent">
	<p>I haven&#8217;t really mentioned it yet, but I&#8217;m an avid gamer.  Sometimes I wonder if it&#8217;s a curse or not since it does tend to suck a lot of my time up.   I tend to play games like <a href="http://www.sierra.com/product.do?gamePlatformId=35">Half-Life</a>,  <a href="http://www.callofduty.com">Call of Duty</a>, or <a href="http://www.everquest.com>Everquest</a>.   Basically the popular MMORPG&#8217;s and FPS games out there.  Recently there has been a flux of great sequels that have come out, which has sucked my time up even more.   My current, rekindled addiction is  <a href="http://www.everquest2.com">Everquest 2</a>.   </p>
	<p>Anyways, EQ2 had some bad server troubles this last weekend which allowed me to try out a new game a friend gave me for Christmas, <a href="http://www.eagames.com/official/moh/pacassault/us/home.jsp">Medal  of Honor: Pacific Assault</a>.   This turned out to be quite a fun game!    The story line seems to be quite good thus far.   It starts you out on D-Day thrusting you into battle&#8230;.of which I died.  As I laid on the ground passing into darkness voices of my old boot camp Sargent rang to my ears.   I was then thrusted back in time to my boot camp days and was then lead through how to use the controls.  It was very cool, not to mention how funny the Sargent was.   <img src='http://www.marksportal.net/blog/wp-images/smilies/icon_smile.gif' alt=':)' class='wp-smiley' /> </p>
	<p>In other news&#8230;Christmas shopping is done.  YAY!   I don&#8217;t know why I put it off so long.  I think the worst was when I was gathering gifts on Dec 23rd. <img src='http://www.marksportal.net/blog/wp-images/smilies/icon_smile.gif' alt=':)' class='wp-smiley' />    Every year I tell myself, &#8220;Next year, you need to start earlier!&#8221;.   This year is no exception to my internal condemning. <img src='http://www.marksportal.net/blog/wp-images/smilies/icon_smile.gif' alt=':)' class='wp-smiley' /> </p>
	<p>I saw <a href="http://www.imdb.com/title/tt0385004/">The House of Flying Daggers</a> this weekend.  Pretty good movie.  It wasn&#8217;t near as good as <a href="http://www.imdb.com/title/tt0299977/">Hero</a>, but it was still enjoyable.   It probably should be seen if you enjoy those kinds of films.</p>
	<p>Oh&#8230;I found that <a href="http://gallery.menalto.com/">Gallery 2</a> is currently in an Alpha state.   That was quite a surprise to me.   I didn&#8217;t really like the layout of ver. 1.x, however this new version looks to be quite nice.  Once it enters a beta state I&#8217;ll probably try to replace my current homemade gallery program with this one.
</p>
