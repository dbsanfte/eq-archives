<h3 class="storytitle" id="post-44"><a href="http://www.marksportal.net/blog/index.php?p=44" rel="bookmark" title="Permanent Link: Nobody Special">Nobody Special</a></h3>
<!-- Post meta -->
<div class="meta">
Posted on January 16th, 2005. <!-- By Mark. --> About <a href="http://www.marksportal.net/blog/index.php?cat=3" title="View all posts in The Narrow Path">The Narrow Path</a>. <a href="http://www.marksportal.net/blog/index.php?p=44#comments">1 Comment</a>.</div>

<!-- Actual post -->
<div class="storycontent">
	<p>I&#8217;ve been reading the <a href="http://www.amazon.com/exec/obidos/tg/detail/-/0060598247/qid=1105941995">&#8220;Chronicles of Narnia&#8221;</a>, which is a collection of children&#8217;s books written by <a href="http://www.cslewis.org/">C.S. Lewis</a>.  They tend to have a heavy Christian theme in them which I really enjoy.   In one of the books, &#8220;The Horse and his Boy&#8221;, the talking horse named Bree was downcast because he had been out-shown by &#8220;a child, a mere foal&#8221;.    Bree was proud because of all the great acts of bravery he had done while in the land of the Calormen and had expected that, due to that bravery, he would be a great horse in the land of Narnia.   While Bree was sulking,  an old hermit came up to him and said, </p>
	<blockquote><p>You&#8217;re not quite the great Horse you had come to think, from living among poor dumb horses.   Of course you were braver and cleverer than them.  You could hardly help being that.  It doesn&#8217;t follow that you&#8217;ll be anyone very special in Narnia.  But as long as you know you&#8217;re nobody special, you&#8217;ll be a very decent sort of Horse, on the whole, and taking one thing with another.</p></blockquote>
	<p>Equally I think there are many on earth whose good works shine in the midst of all the bad that are out there, but once we are all in heaven we will be amoungst MANY people who will have done equally or even greater works.   We must never be proud about the good works that we do on earth, for they are just the normal works of those who are of God.
</p>
