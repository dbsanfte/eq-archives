				<h2 id="post-68">
					<a href="http://www.marksportal.net/blog/?p=68" rel="bookmark">United we stand</a>
				</h2>
				<div class="entry">
						<p>Lately I&#8217;ve been finding a reoccurring theme in scripture that I had not seen before.  It has to do with the unity of the body of Christ.   I&#8217;m sure we are all familiar with the following verse from Acts pertaining to the new believers after Christ&#8217;s resurrection.</p>
	<blockquote><p>Now the full number of those who believed were of one heart and soul<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Acts+4%3A32" title="English Standard Version Bible" class="extlink">Acts 4:32</a>)</p></blockquote>
	<p>There is also talk of unity later on when Paul and Barnabas were sent off on what will later be called their &#8220;missionary journeys&#8221;.</p>
	<blockquote><p>While they were worshiping the Lord and fasting, the Holy Spirit said,  “Set apart for me Barnabas and Saul for the work to which I have called them.” Then after fasting and praying they laid their hands on them and sent them off.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Acts+13%3A2-3" title="English Standard Version Bible" class="extlink">Acts 13:2-3</a>)</p></blockquote>
	<p>And later about the believers in Jerusalem&#8230;</p>
	<blockquote><p> Then it seemed good to the apostles and the elders, with the whole church, to choose men from among them and send them to Antioch with Paul and Barnabas.<br />
 (<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Acts+15%3A22" title="English Standard Version Bible" class="extlink">Acts 15:22</a>)</p></blockquote>
	<p>So while reading today I found it mentioned in Paul&#8217;s first letter to the Corinthians&#8230;</p>
	<blockquote><p> I appeal to you, brothers, by the name of our Lord Jesus Christ, that all of you agree and that there be no divisions among you, but that you be united in the same mind and the same judgment.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=1+Corinthians+1%3A10" title="English Standard Version Bible" class="extlink">1 Corinthians 1:10</a>)</p></blockquote>
	<p>Even Christ talks about unity&#8230;</p>
	<blockquote><p>Again I say to you, if two of you agree on earth about anything they ask, it will be done for them by my Father in heaven. For where two or three are gathered in my name, there am I among them.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Matthew+18%3A19-20" title="English Standard Version Bible" class="extlink">Matthew 18:19-20</a>) </p></blockquote>
	<p>I think it was also with unity in mind that it was written&#8230;</p>
	<blockquote><p>Remember those who are in prison, as though in prison with them, and those who are mistreated, since you also are in the body.<br />
 (<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Hebrews+13%3A3" title="English Standard Version Bible" class="extlink">Hebrews 13:3</a>) </p></blockquote>
	<p>Unity is an important part of the Christian faith and is needed more and more as the world ages.  The practice of unity can be tough, but those who practice it will have a mighty presence in this world.</p>
