				<h2 id="post-66">
					<a href="http://www.marksportal.net/blog/?p=66" rel="bookmark">Why we have nations</a>
				</h2>
				<div class="entry">
						<p>Paul made a very interesting statement in his address to the philosophers in Athens.</p>
	<blockquote><p>And he made from one man every nation of mankind to live on all the face of the earth, having determined allotted periods and the boundaries of their dwelling place, that they should seek God, in the hope that they might feel their way toward him and find him. Yet he is actually not far from each one of us<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Acts+17%3A26-27" title="English Standard Version Bible" class="extlink">Acts 17:26-27</a>)</p></blockquote>
	<p>Before Christ, God&#8217;s hope was that the nations of the world would seek after Him.  And during that period God choose to overlook mankind&#8217;s ignorance.   However, now that Christ has come God is commanding people to repent of their ignorance&#8230;their sins.   </p>
	<blockquote><p>The times of ignorance God overlooked, but know he commands all people everywhere to repent, because he has fixed a day on which he will judge the world in righteousness by a man whom he has appointed; and of this he has given assurance to all by raising him from the dead.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Acts+17%3A30-31" title="English Standard Version Bible" class="extlink">Acts 17:30-31</a>)</p></blockquote>
	<p>This last statement by Paul also gives me another impression that I had not had before.   Christ is the standard that the world will be judged by.  Now I know that it doesn&#8217;t exactly say that.  What the above scripture says is that God will judge the world through Christ.  However I also can&#8217;t shake the feeling that Christ, being the perfect man, will also be the weight by which mankind will be judged.</p>
