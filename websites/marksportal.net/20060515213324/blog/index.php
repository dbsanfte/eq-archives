				<h2 id="post-65">
					<a href="http://www.marksportal.net/blog/?p=65" rel="bookmark">Controlling the Flesh</a>
				</h2>
				<div class="entry">
						<blockquote><p>The heart is deceitful above all things,<br />
and desperately sick;<br />
who can understand it?<br />
“I the Lord search the heart<br />
and test the mind,<br />
to give every man according to his ways,<br />
according to the fruit of his deeds.”<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Jeremiah+17%3A9-10" title="English Standard Version Bible" class="extlink">Jeremiah 17:9-10</a>)</p></blockquote>
	<p>I was reading Jeremiah during lunch today and ran into the above Scripture.   It&#8217;s something I think about a lot.  What are my motives?  Am I doing what is right, what is just?  As I grow older I see more and more just how true the above Scripture is.   Our hearts, my heart, is a deceitful thing.  I think that&#8217;s why Scripture tells us:</p>
	<blockquote><p>For if you live according to the flesh you will die, but if by the Spirit you put to death the deeds of the body, you will live.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Romans+8%3A13" title="English Standard Version Bible" class="extlink">Romans 8:13</a>)</p></blockquote>
	<blockquote><p>But I say, walk by the Spirit, and you will not gratify the desires of the flesh.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Galatians+5%3A16" title="English Standard Version Bible" class="extlink">Galatians 5:16</a>)</p></blockquote>
	<blockquote><p>For the desires of the flesh are against the Spirit, and the desires of the Spirit are against the flesh, for these are opposed to each other, to keep you from doing the things you want to do.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Galatians+5%3A17" title="English Standard Version Bible" class="extlink">Galatians 5:17</a>)</p></blockquote>
	<blockquote><p>&#8230;we all once lived in the passions of our flesh, carrying out the desires of the body and the mind, and were by nature children of wrath, like the rest of mankind.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Ephesians+2%3A3" title="English Standard Version Bible" class="extlink">Ephesians 2:3</a>)</p></blockquote>
	<blockquote><p>For all that is in the world—the desires of the flesh and the desires of the eyes and pride in possessions—is not from the Father but is from the world.<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=1+John+2%3A16" title="English Standard Version Bible" class="extlink">1 John 2:16</a>)</p></blockquote>
	<p>I&#8217;m not sure if you&#8217;ve experienced this yet or not, but I find as I grow to understand God I see this great struggle between the flesh and the Spirit that is mentioned above.  Sometimes it seems to me that our time here on earth is meant to learn how to get control over our bodies and to learn to walk in the Spirit once again.   I&#8217;m reminded of Adam and Eve.  Once they ate from the fruit of the tree their bodies(emotions, desires) had control over them, rather than they having control over their bodies.   I think of God&#8217;s words to Cain:</p>
	<blockquote><p>but for Cain and his offering he had no regard. So Cain was very angry, and his face fell.  The Lord said to Cain, “Why are you angry, and why has your face fallen?  If you do well, will you not be accepted?  And if you do not do well, sin is crouching at the door. Its desire is for you, but you must rule over it.”<br />
(<a href="http://www.gnpcb.org/esv/search/?go=Go&amp;q=Genesis+4%3A5-7" title="English Standard Version Bible" class="extlink">Genesis 4:5-7</a>)</p></blockquote>
	<p>God seems to tell Cain to get control of himself, of his emotions.  If he does not, then &#8220;sin is crouching at the door&#8221;.  But it&#8217;s more than just controlling your thoughts or feelings it&#8217;s also listening to and obeying the Spirit.   I have a feeling that Cain was not obeying or following the Spirit since v5 says that God &#8220;had no regard&#8221; for Cain&#8217;s offering and then in v7 He tells Cain, &#8220;If you do well, will you not be accepted?&#8221;.   So why did God not accept Cain&#8217;s offering?  It appears to me it was because Cain was not &#8220;doing well&#8221; before he ever offered the &#8220;fruit of the ground&#8221; to God.   I suspect it was due to his lack of control over his feelings and lack of obedience to the Spirit.
</p>
