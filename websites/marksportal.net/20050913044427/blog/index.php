<div class="post-info"><h2 class="post-title"><a href="http://www.marksportal.net/blog/?p=57" rel="bookmark" title="Permanent Link: From the Heart">From the Heart</a></h2>
Posted by Mark under <a href="http://www.marksportal.net/blog/index.php?cat=3" title="View all posts in The Narrow Path" rel="category tag">The Narrow Path</a><br/><a href="http://www.marksportal.net/blog/?p=57#comments">[5] Comments</a>&nbsp;</div>
<div class="post-content">
		<p>I&#8217;m constantly disappointed when I hear people in the Church mention how they are &#8220;convicted&#8221; or &#8220;feeling guilty&#8221; that they are not witnessing or &#8220;reaching out to others&#8221;.   While I agree that doing these things are good, I believe it is ONLY good when it&#8217;s coming from a loving heart, NOT a guilty heart.  As Paul says,</p>
	<blockquote><p>&#8220;If I speak with the tongues of men and of angels, but do not have love, I have become a noisy gong or a clanging cymbal. &#8221; (1 Corinthians 13:1,NASB95)</p></blockquote>
	<p>This does not just apply to &#8220;tongues&#8221; but anything.  If we do anything without the heart of love, it just becomes a &#8220;noisy gong&#8221;.  So what do we do if we don&#8217;t love the things of God?   I believe we simply ask God, the creator of our body and spirit, to give us the spirit of love.   To open our eyes to see why He loves these things.  Once you do this, before long you will be sharing the gospel, but it will no longer be from a feeling of guilt, but one done out of a genuine heart.  We must be careful not to try to make our actions align with what we &#8220;think&#8221; it should be, but that we ask God to align our spirit with His.  As God works on re-building our spirits, we will find the actions start to come naturally.   I&#8217;ll end here with Christ&#8217;s words.</p>
	<blockquote><p>&#8220;“The good man out of the good treasure of his heart brings forth what is good; and the evil man out of the evil treasure brings forth what is evil; for his mouth speaks from that which fills his heart.&#8221; (Luke 6:45,NASB95)</p></blockquote>
	<p class="post-info">
													
