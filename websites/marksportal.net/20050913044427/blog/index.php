<div class="post-info"><h2 class="post-title"><a href="http://www.marksportal.net/blog/?p=52" rel="bookmark" title="Permanent Link: The Son of Man">The Son of Man</a></h2>
Posted by Mark under <a href="http://www.marksportal.net/blog/index.php?cat=3" title="View all posts in The Narrow Path" rel="category tag">The Narrow Path</a><br/><a href="http://www.marksportal.net/blog/?p=52#comments">No Comments</a>&nbsp;</div>
<div class="post-content">
		<p>This week&#8217;s bible study was on Rev. 1.   As we discussed the chapter I realized that the description of the &#8220;son of man&#8221; matched another description in the Book of Daniel.</p>
	<blockquote><p>&#8220;and in the middle of the lampstands I saw one like a son of man, clothed in a robe reaching to the feet, and girded across His chest with a golden sash. His head and His hair were white like white wool, like snow; and His eyes were like a flame of fire. His feet were like burnished bronze, when it has been made to glow in a furnace, and His voice was like the sound of many waters. In His right hand He held seven stars, and out of His mouth came a sharp two-edged sword; and His face was like the sun shining in its strength. &#8221; (Revelation 1:13-16,NASB95)</p></blockquote>
	<blockquote><p>&#8220;I lifted my eyes and looked, and behold, there was a certain man dressed in linen, whose waist was girded with a belt of pure gold of Uphaz. His body also was like beryl, his face had the appearance of lightning, his eyes were like flaming torches, his arms and feet like the gleam of polished bronze, and the sound of his words like the sound of a tumult. &#8221; (Daniel 10:5-6,NASB95)</p></blockquote>
	<p>Then I realized how the two experiences were very similar&#8230;.</p>
	<blockquote><p>&#8220;When I saw Him, I fell at His feet like a dead man. And He placed His right hand on me, saying, “Do not be afraid; I am the first and the last, &#8221; (Revelation 1:17,NASB95)</p></blockquote>
	<blockquote><p>&#8220;So I was left alone and saw this great vision; yet no strength was left in me, for my natural color turned to a deathly pallor, and I retained no strength. But I heard the sound of his words; and as soon as I heard the sound of his words, I fell into a deep sleep on my face, with my face to the ground. Then behold, a hand touched me and set me trembling on my hands and knees&#8230;.Then he said to me, “Do not be afraid, Daniel,&#8221; (Daniel 10:8-10,12,NASB95)</p></blockquote>
	<p>You know, the whole &#8220;Son of Man&#8221; thing threw me for a bit.   I mean popular belief is that the &#8220;Son of Man&#8221; in Rev 1 is Jesus.   If that&#8217;s so, why didn&#8217;t John say the &#8220;Son of God&#8221;.   Then I realized that &#8220;Son of Man&#8221; was just a description&#8230;&#8221;I saw one <strong>like</strong> a son of man&#8221;.   So basically John&#8217;s just saying that it looks more like a human being than another kind of angelic being, like those found in Ezekiel 1.</p>
