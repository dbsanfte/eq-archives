                              <center>
                                <b>The Thumper V2 Success Story<br>
                                </b><i><font size="2">September 4, 2001</font></i> 
                                <br>
                              </center>
                            </td>
                          </tr>
						 
                          <tr> 
                            <td width="9" height="3933" bgcolor="#e4dccb">&nbsp;</td>
                            <td height="3933" width="318" bgcolor="#e4dccb" valign="top"> 
                              <p><font size="2">Well you've definitely heard of 
                                this device by now, I'm sure. If you haven't, 
                                then you have some serious catching up to do. 
                                <br>
                                <br>
                                For those of you leveling the hard way, the Thumper 
                                V2 is a device that allows you to increase your 
                                character's skills (including spellcasting) while 
                                you are AFK. Yep -- no more sitting at your keyboard 
                                medding and casting a lvl 1 spell until the fizzles 
                                disappear. <br>
                                <br>
                                We first noticed them in March of this year, and 
                                now (just 5 months later) they have their own 
                                production shop, support department, and are already 
                                recognized as the first company to ever produce 
                                a successful add-on product to the leading MMPORG 
                                games out on the market. Not only that, their 
                                support department is like none-other. Stories 
                                of them bending over backwards to make buying 
                                experiences enjoyable abound everywhere. In fact, 
                                they still stick with their policy of adding a 
                                special surprise to random orders (sometimes a 
                                free 9V battery eliminator or a free 6ft. extension 
                                cable). Their customers even receive periodic 
                                e-mails to make sure everything with their device 
                                is working as expected. How's that for customer 
                                service? Wow.<br>
                                <br>
                                So how did this little device get started? Join 
                                us in our exclusive interview with Chris, the 
                                cofounder of GM Associates:<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>So what were the events 
                                that led to the birth of the Thumper V2?</b><br>
                                <br>
                                <b>&lt;Chris&gt;:</b> First of all, I love games. 
                                Games have always been a part of my life and always 
                                will be. Early on, I became quite entranced with 
                                EQ, a game I'm sure you are well aware of. Well, 
                                the game was fantastic but it rapidly became a 
                                game of mouse clicking -- and I found myself with 
                                this great feeling after I leveled, followed soon 
                                after with annoyance at having to click my way 
                                through the skills. And, to be honest, the clicking 
                                was monotonous and boring. I mean even the theory 
                                behind it was ridiculous. Here you were, spending 
                                all this time adventuring, supposedly gaining 
                                skills until the point where you are ready to 
                                level and all of the sudden, these new skills 
                                you gained while adventuring wouldn't be realized 
                                until you clicked your mouse 2,000 times over 
                                a skill button. <br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>Then what happened?</b><br>
                                <br>
                                <b>&lt;Chris&gt;: </b> I remember complaining 
                                about it to my father, who just happens to have 
                                a very heavy electronics background. I told him 
                                he should make me a device that automatically 
                                clicks so I wouldn't have to suffer through the 
                                skill enhancement phases of my character. And, 
                                there were several skills I never even practiced 
                                because I didn't have the patience to click them.<br>
                                <br>
                                <b>&lt;BG&gt;: So your father built the first 
                                Thumper?</b><br>
                                <br>
                                <b>&lt;Chris&gt;:</b> Yes. He was the electronics 
                                guru behind the scenes and I was the guy who looked 
                                over his shoulder and said -- yeah, that looks 
                                great, Dad! In fact, he's so adept at electronics 
                                the very first prototype worked right after he 
                                was finished with the soldering iron.<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>So soon after you released 
                                the Thumper V2?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> Oh God no. We had issues 
                                galore. And the design had just begun. We also 
                                had the issue of production time -- if each unit 
                                was going to take an hour to build there was no 
                                way we would be able to price it reasonably to 
                                get it off the ground.<br>
                                <br>
                                <b>&lt;BG&gt;: </b><b>Then what happened?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> After literally 50 or 60 
                                prototypes, we finally had a workable circuit 
                                board that could be reproduced in a reasonable 
                                amount of time. Then it became a game of lining 
                                up our suppliers for all the components.</font> 
                                <br>
                                <font size="2"><br>
                                <b>&lt;BG&gt;: So where was the actual first Thumper 
                                given life?</b><br>
                                <br>
                                <b>&lt;Chris&gt;:</b> &lt;laugh&gt; Well, the 
                                first one to actually thump with the working randomized 
                                timer was in my father's basement.<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>Why the randomized timer?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> That's a long story...one 
                                that is surrounded by quite a bit of controversy.<br>
                                <br>
                                <b>&lt;BG&gt;: </b><b>What do you mean?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;: </b>Early on we knew that this 
                                device would cause some controversy because we 
                                knew some people would view this as a cheat. We 
                                took the viewpoint that it was a convenience or 
                                luxury for the serious gamer since the device 
                                doesn't actually allow you to violate any of the 
                                coded game rules. In other words, you can't all 
                                of the sudden become lvl 60 after using this device. 
                                Even while our users thump, they are still abiding 
                                by the game's environment and in-game economic 
                                rules.</font><font size="2"> The only difference 
                                is that they are progressing through their skills 
                                at a much faster rate than normal players. Knowing 
                                that some people would feel strongly against this 
                                device, we altered our original design. With our 
                                initial design (which was never released), we 
                                knew there would be a risk that if we became too 
                                popular, the game makers might try to programmatically 
                                discover our Thumpers. So, we built a randomized 
                                timer into the design of all of our units so that 
                                there is no standard signature of a thumper. In 
                                other words, using a thumper would elicit a signature 
                                that would be similar to that of a normal player 
                                -- meaning our Thumpers could remain anonymous.<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>How does the randomizer 
                                work ?<br>
                                <br>
                                &lt;Chris&gt;:</b> Now that we cannot release, 
                                for obvious reasons. Suffice it to say that it 
                                would require a significant effort to try to track 
                                programmatically, and every Thumper is unique 
                                in its randomization.</font></p>
                              <p><font size="2"><b>&lt;BG&gt;:</b> <b>So what 
                                was the reaction once the Thumper V2 was released?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> It was mixed. We did receive 
                                a fair amount of hate mail, but we also received 
                                a fair amount of love mail, for lack of a better 
                                word. That gave us the feedback we were looking 
                                for -- that there was a large segment of the gaming 
                                population that would love this device.<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>What was the reaction of 
                                the game makers?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> Hmmm. That's a touchy subject. 
                                Suffice it to say that they were not pleased with 
                                our little invention. We've received several e-mails 
                                from their customer support department describing 
                                all the reasons why we should not be selling our 
                                device.<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>Which game makers did this?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> I'd rather not say. It's 
                                a natural reaction, I think, for them to be protective 
                                of their user base.<br>
                                <br>
                                <b>&lt;BG&gt;:</b> <b>So what did you do after 
                                you received their e-mails?<br>
                                </b> <br>
                                <b>&lt;Chris&gt;:</b> Nothing really. At that 
                                point we knew we had a winning product. When the 
                                game makers themselves contact you in an effort 
                                to curtail your product, you know you're on the 
                                right path.<br>
                                <br>
