<br />
We had time, and no real pressure so we practiced on Idol unslowed twice to give a better test for the clerics and tanks.  We went ahead and killed on the second run.   Main concern was the tank switch and the duration of the fight.   We felt confident we had a good chance at AoW.   Considering that we cant use the same method we planned on (which is why we died so miserably the first time we ever attempted him) we had to come up with a new method of dealing with him.    Well we lost 4 people to the real life monster but still had a very close margin.    So we prepped up and pulled the big bastard.   Flaw in our strategy caused us to lose the MT at 80%.   Let me tell you, even with 8500 hps, defensive, and a quadding 1100+  hitting fucker there is no room for error when you have to get a new tank on him.    Well, not sure the exact order of things,  but by the time AoW was at 60% there was no more defensive and it was serious pucker time.<br />
