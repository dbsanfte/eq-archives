<h2>Tuesday, July 20,  2004</h2>	
<div class="post">
	 <h3 class="storytitle" id="post-34"><a href="http://www.marksportal.net/index.php?p=34" rel="bookmark" title="Permanent Link: Free Will">Free Will</a></h3>
	<div class="meta">posted by: Mark @ 11:10 pm </div>
	
	<div id="wplinks" class="storycontent">
			<p>Throughout the years I&#8217;ve been told that we all have free will and for the most part, I&#8217;ve believed it.  However, the last year or two I&#8217;ve been challenging the things that I&#8217;ve been told.  Free will is one of them.   While free will isn&#8217;t mentioned in the Bible, I can understand why we would think that we do have free will.   There&#8217;s Adam having to make the choice to choose the fruit that Eve offered (<i><a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Genesis+3&#038;section=2&#038;version=nas">Genesis 3</a></i>).  There&#8217;s Christ telling us to go and sin no more(<i><a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=John+8%3A1-11&#038;section=2&#038;version=nas">John 8:1-11</a></i>).  There&#8217;s Paul telling us to flee immorality(<i><a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=1Corinthians+6%3A18&#038;section=2&#038;version=nas">1 Corinthians 6:18</a></i>).  And there is the letters to the churches where Christ tells the churches to shape up or face judgement(<i><a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Revelation+1-3&#038;section=2&#038;version=nas">Revelation 1-3</a></i>).    Based on all these it appears that we have a choice to choose Christ or not&#8230;to obey God or not.    While I understand this, there are other verses in scripture, and ideas not in scripture, that seem to point in the other direction, that free will does not exist.  So let&#8217;s explore these&#8230;</p>
	<p><i>&#8220;For this is the word of promise: “At this time I will come, and Sarah shall have a son.” And not only this, but there was Rebekah also, when she had conceived twins by one man, our father Isaac; for though the twins were not yet born and had not done anything good or bad, so that God’s purpose according to His choice would stand, not because of works but because of Him who calls, it was said to her, “The older will serve the younger.” Just as it is written, “Jacob I loved, but Esau I hated.”"(<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Romans+9%3A9-13&#038;section=2&#038;version=nas">Romans 9:9-13</a>, NASB95) </i></p>
	<p>So according to this verse, Esau did not have a choice to follow God or not.  He could never obtain God&#8217;s love, for God had chosen to love Jacob and hate Esau.  Paul understood that this seemed unfair so he continued explaining:</p>
	<p><i>&#8220;What shall we say then? There is no injustice with God, is there? May it never be! For He says to Moses, “I will have mercy on whom I have mercy, and I will have compassion on whom I have compassion.” So then it does not depend on the man who wills or the man who runs, but on God who has mercy. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Romans+9%3A14-16&#038;section=2&#038;version=nas">Romans 9:14-16</a>, NASB95) </i></p>
	<p>It is impossible for us to follow God.  It&#8217;s is by God&#8217;s will, and that alone, that we follow God.  Paul mentions in Romans&#8230;</p>
	<p><i>&#8220;as it is written, “There is none righteous, not even one; There is none who understands, There is none who seeks for God; All have turned aside, together they have become useless; There is none who does good, There is not even one.” &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Romans+3%3A10-12&#038;section=2&#038;version=nas">Romans 3:10-12</a>, NASB95) </i></p>
	<p>No one seeks after God.  No one is able to follow and obey God, that&#8217;s why the Laws of the Old Testament were created, to show you that you couldn&#8217;t follow God.   It is by grace and grace alone that anyone is saved.  As Christ said, </p>
	<p><i>&#8220;“You did not choose Me but I chose you, and appointed you that you would go and bear fruit, and that your fruit would remain, so that whatever you ask of the Father in My name He may give to you. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=John+15%3A16&#038;section=2&#038;version=nas">John 15:16</a>, NASB95) </i></p>
	<p>God chose us.  We did not choose him.  We couldn&#8217;t because as Romans stated, no one seeks God.   God had to seek after us&#8230;God had to choose us&#8230;God had to change us.   Going back to Romans 9, Paul leaves Jacob and Esau and moves over to the Pharoh of Egypt, during the times of Moses.</p>
	<p><i>&#8220;For the Scripture says to Pharaoh, “For this very purpose I raised you up, to demonstrate My power in you, and that My name might be proclaimed throughout the whole earth.” So then He has mercy on whom He desires, and He hardens whom He desires. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Romans+9%3A17-18&#038;section=2&#038;version=nas">Romans 9:17-18</a>, NASB95) </i></p>
	<p>The Pharaoh is another person who had no choice.   God would not allow the Pharaoh to give up the Israelites.  As Exodus says:</p>
	<p><i>&#8220;The Lord said to Moses, “When you go back to Egypt see that you perform before Pharaoh all the wonders which I have put in your power; but I will harden his heart so that he will not let the people go. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Exodus+4%3A21&#038;section=2&#038;version=nas">Exodus 4:21</a>, NASB95) </i></p>
	<p>God hardened the Pharaoh&#8217;s heart so that God could display His power to the world.  Where was Pharaoh&#8217;s choice in all this?   This seems unfair, doesn&#8217;t it?   Paul continues in Romans 9:</p>
	<p><i>&#8220;You will say to me then, “Why does He still find fault? For who resists His will?” On the contrary, who are you, O man, who answers back to God? The thing molded will not say to the molder, “Why did you make me like this,” will it? Or does not the potter have a right over the clay, to make from the same lump one vessel for honorable use and another for common use? What if God, although willing to demonstrate His wrath and to make His power known, endured with much patience vessels of wrath prepared for destruction? And He did so to make known the riches of His glory upon vessels of mercy, which He prepared beforehand for glory, even us, whom He also called, not from among Jews only, but also from among Gentiles. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Romans+9%3A19-24&#038;section=2&#038;version=nas">Romans 9:19-24</a>, NASB95) </i></p>
	<p>We are created beings.  There is no getting around that.  As created beings, God created us all for a purpose.  Some were created for destruction, others were created for mercy.   It is in God&#8217;s hands that our fate is decided.  Not ours.  </p>
	<p><i>&#8220;The mind of man plans his way, But the Lord directs his steps. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Proverbs+16%3A9&#038;section=2&#038;version=nas">Proverbs 16:9</a>, NASB95) </i></p>
	<p>God is the one who directs our steps.  We can plan until we are blue in the face, but it is God who is in control.  It is God who blesses us or curses us.   As Paul says in Ephesians:</p>
	<p><i>&#8220;For we are His workmanship, created in Christ Jesus for good works, which God prepared beforehand so that we would walk in them. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Ephesians+2%3A10&#038;section=2&#038;version=nas">Ephesians 2:10</a>, NASB95) </i></p>
	<p>Those who have been chosen to be saved by God have been chosen before the foundations of the world were built.   And God has already prepared the good works that those who are saved are to do.   So by the time we all pass away, we will have done everything that God had created us to do.</p>
	<p>Now I know much of this sounds cold, heartless and harsh, but let me approach this from another stand point.    Why is it so important for us to have a choice in our adult life?  Did you choose whether to be born or not?   Did you choose the family you were born into?  Did you choose your name?   Did you choose who would live around you as a kid?  Did you choose the circumstances that happened in your life?  Ignoring suicide, will you have a choice when you are to die?   There are MANY MANY MANY things that we do not have a choice in.   Why do you need to have free will in choosing God or not?  Why do you need to have free will to do what is right or do what is wrong?   If we are to assume that we have a choice we would have two options:  To obey God(and live in heaven) or to not obey God(and live in hell).  Is this much of a choice?  Is this really a choice we want to make on our own?  It doesn&#8217;t seem like much of a choice to me.   </p>
	<p>Ultimately whether we have free will or not is meaningless to us right now.   Either way we will have to continue making choices, whether they are choices that God has already made for us(pre-destined) or a choice God lets us make(free will).  The only place where I can see a difference is our comfortablity with the choices we make.   Those who believe in free will might make a choice and wonder if it&#8217;s a right one, while those who believe in pre-destination will be confident that God had already determined the choice that they decided on.
</p>
	</div>
	
