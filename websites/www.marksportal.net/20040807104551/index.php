<h2>Thursday, July 8,  2004</h2>	
<div class="post">
	 <h3 class="storytitle" id="post-29"><a href="http://www.marksportal.net/index.php?p=29" rel="bookmark" title="Permanent Link: Obedience, suffering, and faith">Obedience, suffering, and faith</a></h3>
	<div class="meta">posted by: Mark @ 5:24 pm </div>
	
	<div id="wplinks" class="storycontent">
			<p>Yesterday I was reading through Hebrews and several things popped out at me.</p>
	<p><i>&#8220;During the days of Jesus&#8217; life on earth, he offered up prayers and petitions with loud cries and tears to the one who could save him from death, and he was heard because of his reverent submission.&#8221; (Hebrews 5:7, NIV)</i></p>
	<p>At first read you might think that the first part of this verse is talking about the garden at Gethsemane where Matthew says that Christ was &#8220;sorrowful and troubled"(26:37) and Luke says that Christ&#8217;s &#8220;sweat was like drops of blood falling to the ground."(22:44).  However, Hebrews is telling us that Christ &#8220;offered up prayers and petitions with loud cries and tears&#8221; through out his life on earth.  This was not a one time thing.  And Christ&#8217;s prayers were answered &#8220;because of his reverent submission&#8221; to God.  The verses go on to say&#8230;</p>
	<p><i>&#8220;Although he was a son, he learned obedience from what he suffered&#8230;&#8221; (Hebrews 5:8a, NIV)</i></p>
	<p>And later on Paul says to us&#8230;.</p>
	<p><i>&#8220;Endure hardship as discipline; God is treating you as sons.&#8221; (Hebrews 12:7, NIV)</i></p>
	<p>Suffering and hardships are a part of the Christian life.  However, through these troubles we will learn obedience to God.  How obedience is learned from suffering, I&#8217;m not sure yet.  What I do know, though, is that if we reverently submit to God, He will answer our prayers.  </p>
	<p>Another thing that I started thinking about yesterday is faith.   It seems that a lot of people today think that faith = belief that God exists.  I can understand that, since they usually get that from this verse:</p>
	<p><i>&#8220;And without faith it is impossible to please God, because anyone who comes to him must believe that he exists and that he rewards those who earnestly seek him.&#8221;  (Hebrews 11:6, NIV)</i></p>
	<p>However, that is not faith.   Faith is needed to &#8220;believe that he exists", but that is not the definition of faith.  The definition of faith is given several verses prior to the above.</p>
	<p><i>&#8220;Now faith is being sure of what we hope for and certain of what we do not see.&#8221;  (Hebrews 11:1, NIV)</i></p>
	<p>One of the things I&#8217;ve heard discussed before is, &#8220;Will there be faith in heaven?&#8221;   In most cases I&#8217;ve heard that it will not be needed, however based on the definition Paul gave I&#8217;d have to disagree.  If God came to me and said, &#8220;Mark, I&#8217;m going to have you move to Maine&#8221; and I believed God, that would be faith.   Abraham did this as we read below,</p>
	<p><i>&#8220;By faith Abraham, when called to go to a place he would later receive as his inheritance, obeyed and went, even though he did not know where he was going.&#8221; (Hebrews 11:8, NIV)</i></p>
	<p>Abraham didn&#8217;t need to &#8220;believe God existed”.  God came down and told him to go.  Abraham&#8217;s faith came into play when he trusted what God told him and stepped forward knowing that what God said would come to pass.  As the book of James says,</p>
	<p><i>”You believe that God is one.  You do well; the demons also believe, and shudder.” (James 2:19, NAS)</i></p>
	<p>Even the demons believe God exists!  Believing God exists doesn’t really do anything.  What God is looking for is that you believe what He says…that you trust Him.  Faith is trusting in God, believing that what He says WILL come true.  This is what the serpent in the garden of Eden was leading Adam and Eve from. </p>
	<p><i>”The serpent said to the woman, “You surely will not die!” (Genesis 3:3, NASB)</i></p>
	<p>“Don’t believe God”, the serpent cried out.  “Don’t trust what he says!  It won’t happen!”   Since that time humans have struggled to trust God, even though He has always been proven trustworthy.
</p>
