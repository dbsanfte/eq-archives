	<div class="meta">posted by: Mark @ 1:18 pm </div>
	
	<div id="wplinks" class="storycontent">
			<p>I wonder at times what the Spiritual Laws are that Spiritual beings are bound by.   God seems to do most of His work through creation.  For instance He uses one nation to punish another nation.  He speaks through the prophets.   What I find really interesting, though, is that Satan seems to act in the same way.   For the most part, Satan doesn&#8217;t come out and start enslaving people or cause supernatural things to happen, he does his mischief in more subtle ways&#8230;using other people, planting certain thoughts in our minds, etc.  Satan, who is in every way contrary to God, is using what seems to be the same methods that God uses.   I wonder if the spiritual realm is much more complicated then we could ever imagine.   While the physical can affect the spiritual and the spiritual can affect the physical, Scripture seems to put ALOT more weight in the spiritual.</p>
