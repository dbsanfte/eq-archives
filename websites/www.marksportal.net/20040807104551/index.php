	 <h3 class="storytitle" id="post-36"><a href="http://www.marksportal.net/index.php?p=36" rel="bookmark" title="Permanent Link: The Fear of David">The Fear of David</a></h3>
	<div class="meta">posted by: Mark @ 11:29 pm </div>
	
	<div id="wplinks" class="storycontent">
			<p>Recently I&#8217;ve been trying to learn the guitar.  I&#8217;ve been practicing on praise music, as the songs seems to be easy and I want to learn them so I can play during my own personal worship times with God.    One of the praise songs I&#8217;m learning is &#8220;Create In Me A Clean Heart&#8221; which is based on <a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Psalm+51%3A10-12&#038;section=2&#038;version=nas">Psalm 51:10-12</a>.   As I was learning the song I was suddenly struck with, what felt like, the emotions David must have been feeling at the time.   Let me explain.</p>
	<p>David was a shepard who was recruited into King Saul&#8217;s court to play music for him.    David had probably seen King Saul as he was filled with God&#8217;s Spirit.   David probably also saw when God had taken that Holy Spirit from King Saul.   Now go forward a bit.  In <a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=2Samuel+11&#038;section=2&#038;version=nas">2 Samuel 11</a> David sins against God by killing Bathsheba&#8217;s husband so that he could make her his wife.  After this happens, Nathan the prophet goes to David and rebukes him for what he&#8217;s done (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=2Samuel+12&#038;section=2&#038;version=nas">2 Samuel 12</a>).   David&#8217;s eyes are opened and his spirit is pierced.   Seeing his sin and knowing how God took away His Holy Spirit from King Saul, David cry&#8217;s out to God in fear and repentance:</p>
	<p><i>&#8220;Create in me a clean heart, O God, And renew a steadfast spirit within me. Do not cast me away from Your presence And do not take Your Holy Spirit from me. Restore to me the joy of Your salvation And sustain me with a willing spirit. &#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Psalm+51%3A10-12&#038;section=2&#038;version=nas">Psalm 51:10-12</a>, NASB95) </i>
</p>
	</div>
	
