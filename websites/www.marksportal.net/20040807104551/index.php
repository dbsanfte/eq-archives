<h2>Thursday, July 15,  2004</h2>	
<div class="post">
	 <h3 class="storytitle" id="post-33"><a href="http://www.marksportal.net/index.php?p=33" rel="bookmark" title="Permanent Link: Knowing">Knowing</a></h3>
	<div class="meta">posted by: Mark @ 3:37 pm </div>
	
	<div id="wplinks" class="storycontent">
			<p>Yesterday evening I was in a discussion with a group of people about the difference between knowing about God and knowing God.   We all agreed that knowing about God is having knowledge about Him, where as knowing God is the actual relationship with Him.   For example, I could know about the President if I read his biography, but I wouldn&#8217;t really know the President unless I spent time with him.  The same is true of God.  If I just read books on God I would just be gathering knowledge about him.  I wouldn&#8217;t know God until I spent time with him. </p>
	<p>So with that in mind&#8230;.I was reading the book of Philippians today when I ran across this:</p>
	<p><i>&#8220;More than that, I count all things to be loss in view of the surpassing value of knowing Christ Jesus my Lord, for whom I have suffered the loss of all things, and count them but rubbish so that I may gain Christ, and may be found in Him, not having a righteousness of my own derived from the Law, but that which is through faith in Christ, the righteousness which comes from God on the basis of faith, that I may know Him and the power of His resurrection and the fellowship of His sufferings, being conformed to His death; in order that I may attain to the resurrection from the dead.&#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?word=Philippians+3%3A8-11&#038;section=2&#038;version=nas">Philipians 3:8-11</a>, NAS)</i></p>
	<p>After reading this I found my thoughts to be centering around &#8220;that I may know Him and the power of His resurrection and the fellowship of His sufferings".   Isn&#8217;t it interesting that Paul wanted to know the fellowship of Christ&#8217;s sufferings?  Can we truly know Christ without knowing/experiencing His sufferings?  In the Book of Jeremiah God spoke to Shallum, the king of Judah, and used his father Josiah as an example.</p>
	<p><i>&#8220;&#8216;Do you[Shallum] become a king because you are competing in cedar? Did not your father[Josiah] eat and drink And do justice and righteousness? Then it was well with him.  He pled the cause of the afflicted and needy; Then it was well. Is not that what it means to know Me?&#8217; Declares the LORD.&#8221; (<a href="http://bible1.crosswalk.com/OnlineStudyBible/bible.cgi?passage=jer+22:15-16&#038;version=nas">Jeremiah 22:15-16</a>, NAS)</i></p>
	<p>To know God, to know Christ, is to obey.  It&#8217;s to act.  It&#8217;s to do.  I STRONGLY recommend reading up about the meaning of the word know <a href="http://bible1.crosswalk.com/Dictionaries/BakersEvangelicalDictionary/bed.cgi?word=know">here</a>.</p>
	</div>
	
