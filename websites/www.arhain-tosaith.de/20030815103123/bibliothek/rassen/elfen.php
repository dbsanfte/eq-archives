		<td width="50%" height="415">
		<p class="white">
		Obwohl die Gesellschaft der Elfen nicht	annähernd so brutal und beherrschend wie manch andere Gesellschaft Istaria's ist (sowohl in der Vergangenheit als auch in der Gegenwart), kennen und 
		schätzen die Elfen jedoch Ordnung, Struktur und Disziplin.<br><br>
		Obwohl die Elfen im großen und ganzen eine Zusammenarbeit mit den anderen lebenden Rassen bevorzugen, verfolgen sie doch ihre eigenen Interessen und Ziele wann immer es ihnen möglich ist.<br><br>
		Von der Statur her sind Elfen ähnlich gebaut wie <a href="menschen.php">Menschen</a>, obwohl sie durchschnittlich etwas größer und schlanker sind. Elfen besitzen einen ausgezeichneten Gehörsinn 
		und ihre Ohren sind so geformt, das sie Geräusche bestmöglich aufnehmen können. Dies verleiht den Elfen ihr typisches Markenzeichen - ihre spitzen Ohren.<br><br>
		Ihre Haut ist etwas heller als die ihre Vetter - den <a href="menschen.php">Menschen</a>, jedoch nicht so unterschiedlich, als das man sie als völlig verschieden betrachten könnte. Elfen besitzen 
		einen hervorragenden Gleichgewichtssinn und ausgezeichnete Geschicklichkeit; viele der berühmten Späher und Kundschafter Istaria's waren Elfen. Ebenso sind Elfen für ihre exzellenten Fernkampffähigkeiten 
		berühmt - insbesondere im Umgang mit Pfeil und Bogen.
