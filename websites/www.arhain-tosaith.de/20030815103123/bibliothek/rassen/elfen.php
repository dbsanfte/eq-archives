		<td width="50%" height="430">
		<p class="white">
		Es wird gesagt, das die Elfen von Istaria einst ein sanftes und mystisches Volk waren und im Einklang mit der Natur lebten. Während die Elfen von heute immernoch ein beachtliches
		mystisches Können besitzen sind sie doch weit davon entfernt von dem, was man als gutmütig und sanft bezeichnen würde.<br><br>
		Die Gesellschaft der Elfen ist sehr streng gegliedert und ist in der Struktur einer militärischen Einheit nicht ganz unähnlich. Alle Elfen sind dazu verpflichtet, für eine Mindestdauer 
		von 10 Jahren in der Elfenarmee zu dienen. Gerade mit dem Beginn des <i>"Zeitalters der Klagen"</i> waren die Elfen darauf angewiesen, nach Befehl und Gehorsam zu handeln, um in Angesicht 
		der Bedrohung durch die <i>"Withered Aegis"</i> bestehen zu können.<br><br>
		Die Elfen glauben, das es den festen Strukturen ihrer Gesellschaft zu verdanken ist, das sie so lange gegen die <i>"Withered Aegis"</i> standhalten konnten, bevor ihre Heimat Feladan 
		durch einen heftigen Angriff der Untoten Horden fiel.<br><br>
		Die im Exil lebenden Elfen, die den Angriff auf Feladan überlebten, erhalten die Gesellschaft der Elfen von der Stadt Tazoon aus am Leben.
		</p>
		</td>
