		<td height="18" colspan="2" background="../../pics/back_top_hell_large.jpg"><a name="#Feladan"></a><p class="question" align="center"><font class="white"><b>::</b></font> FELADAN - EHEMALIGE HEIMAT DER ELFEN <font class="white"><b>::</b></font></p></td>
	    </tr>
	    <tr>
		<td height="2" colspan="2" background="../../pics/line2.jpg"></td>
	    </tr>
	    <tr>
		<td colspan="2">
		<p class="white"><br>
		Feladan war die Hauptstadt der Elfen, bis sie vor ca. 25 Jahren von den Untoten komplett überrannt wurde. Die Stadt selbst lag im Herzen des riesigen Waldes von Feladan - süd-südöstlich von Aughundell.
		Der Fall von Feladan war - wie viele glaubten - der Anfang vom Ende der lebenden Rassen im Kampf gegen die <i>"Withered Aegis"</i> und ihre untoten Horden.<br><br>
		Die Elfen waren seit langem die Verbündeten der <a href="menschen.php">Menschen</a>, insbesondere im Kampf gegen die Untoten. Für die Elfen waren die Mauern von Feladan die letzte Verteidigungslinie und 
		sie kämpften erbittert um jeden Meter ihrer Heimat, der von den Untoten erobert wurde. Es starben mehr Elfen bei der Verteidigung der Stadt als in allen anderen Kämpfen gegen die Untoten zusammen.<br><br>
		Die <a href="menschen.php">Menschen</a> unterstützten die Elfen mit Material und Truppen so gut sie konnten, doch all die Bemühungen der Elfen und Menschen halfen nicht, den Untergang der Stadt abzuwenden. 
		Letztendlich besetzten die Untoten die Stadt und vertrieben die restlichen Elfen aus ihrer angestammten Heimat in Richtung der Mauern von Tazoon.<br><br>
		Feladan ist heute nurnoch ein verdrehtes Abbild einer einst ruhmreichen Stadt. Der einstmals grüne Wald , der die Stadt umgab, ist inzwischen nurnoch ein dunkles und dichtes Geflecht entstellter Natur.
		An anderen Stellen gibt es nurnoch verfluchtes Ödland, wo einstmals üppige Vegetation existierte. Die Schönheit der Stadt , mit ihren Wohnungen und Gebäuden in den Wipfeln der Bäume, ist inzwischen 
		verschwunden und die Architektur der Elfen ist heute nurnoch eine Karikatur ihrer vergangenen Pracht.<br><br>
		Eine massive Festungsanlage der Untoten teilt die Stadt buchstäblich in 2 Hälften mit der Stadt als Barriere zwischen dem Ödland und einer Festung der <i>"Withered Aegis"</i> tief in der östlichen Wildnis.<br><br>
		Die restlichen Überlebenden des Elfenhofs, die nun in Tazoon leben, entwickeln ständig neue Pläne und Strategien um ihre gefallene Stadt aus den Klauen der Untoten befreien zu können. Durch den Sieg
		der lebenden Rassen über die <i>"Withered Aegis"</i> bei der Schlacht um Tazoon scheinen die Pläne der Elfen für die Rückeroberung ihres Heimatlandes früher als erwartet das Licht der Welt erblicken zu können.
		<br><br>
