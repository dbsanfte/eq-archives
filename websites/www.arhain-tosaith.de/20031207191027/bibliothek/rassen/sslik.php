		<td colspan="2">
		<p class='white'><br>
		Während des <i>"Zeitalters des Krieger-Königs"</i> flohen die Sslik vor der Verfolgung durch die anderen Rassen in den Dschungel von <i>"Lesser Aradoth"</i>. Nur die <a href="saris.php">Saris</a> und die <a href="menschen.php">Menschen</a> 
		scheinen keine direkte Schuld an der Not der Sslik zu haben; die <a href="menschen.php">Menschen</a> allein deswegen, weil sie sich im allgemeinen neutral zu den Sslik verhalten haben. Nachdem die Sslik sich in dieser Region angesiedelt hatten, 
		begannen sie mit dem Unterfangen, eine Siedlung zu bauen, die sie leicht gegen die zu erwartenden Angriffe durch die anderen lebenden Rassen verteidigen konnten. Das Ergebnis war eine im Dschungel gelegene, eindrucksvolle Festung. Die Mauern 
		und Gebäude von Sslanis  sind mit einer Unmenge an Steinen verstärkt. Dies spiegelt die Vorliebe der Sslik für Steine gegenüber anderen Rohstoffen wider.<br><br>
		Mit den neutralen <a href="menschen.php">Menschen</a> auf der anderen Seite der <i>"Sable Straits"</i> und den idealistischen <a href="saris.php">Saris</a> als befreundete Nachbarn erlebte Sslanis niemals die Belagerungen und Angriffe, gegen 
		die die Stadt ursprünglich gebaut wurde. Die Stadt konnte sich ungestört entwickeln und dient heute als Zentrum für den Handel zwischen den <a href="saris.php">Saris</a>, den <a href="menschen.php">Menschen</a> und den Sslik. Zu Beginn des 
		<i>"Zeitalters der Klagen"</i> war Sslanis eine der wenigen Städte, die noch nicht dem Zerfall durch die dunklen Kräfte der <i>"Withered Aegis"</i> ausgesetzt waren. In Sslanis gibt es viele eindrucksvolle Trainingscamps und Fertigungsanlagen. 
		Durch die Neuöffnung der Reisetore nach der Schlacht um Tazoon, entwickelte sich Sslanis zu einer bedeutenden Metropole für Training, Herstellung und Handel, was nicht zuletzt durch die abgeschiedene Lage der Stadt weit hinter der Frontlinie 
		begünstigt wurde.<br><br>
		</p>
