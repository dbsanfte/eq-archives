		<td colspan='2'>
		<p class='white'><br>
		Sslik  haben ein extrem breites Spektrum an Farbgebungen ihrer schuppigen Haut, von dunklen Brauntönen bis hin zu geschwungenen gelben und roten Farbstreifen. Auch das Aussehen ihrer Schädel variiert stark und ist von Familienstammbaum 
		abhängig; von kurzen, abgeflachten Schnauzen bis hin zu den häufig vorkommenden langen, dünnen Schädeln, so wie sie bei Kaimanen vorkommen. Sslik sind im Durchschnitt fast 2 Meter groß.<br><br>
		Die Sslik sind extrem starke und konzentrierte Lebewesen. Sie sind für ihre exzellenten Fähigkeiten als Kämpfer und Heiler gleichermaßen bekannt und setzen diese Fähigkeiten in Zeiten großer Not zum Schutz ihrer Rasse ein. Durch ihre 
		natürliche Stärke und ihre gute Konzentration sind sie für bestimmte Handwerksberufe besonders geeignet; sie sind ausgezeichnete Rüstungs- und Waffenschmiede, außerdem sind sie sehr begabt bei der Forschung nach neuen Zaubersprüchen.<br><br> 
		Die neu geschaffenen Verbindungen zwischen den größten Städten Istaria's mit Hilfe der Reisetore, brachte die Vorliebe der Sslik für das Basteln und Tüfteln (Tinkering) zum Vorschein; eine Fähigkeit, für die sie scheinbar ein natürliches 
		Talent besitzen. Die <a href="gnome.php">Gnome</a> entsendeten ihre fähigsten und begabtesten Tüftler nach Sslanis, um die Sslik auszubilden. So entwickelte sich die ersten freundschaftlichen Beziehungen zwischen den Gnomen und den Sslik.
		<br><br>
		</p>
