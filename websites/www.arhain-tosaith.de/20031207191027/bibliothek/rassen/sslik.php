		<td width="50%" height="430">
		<p class="white">
		Die Sslik sind eine reptilienartige Rasse und sie haben, neben den Drachen von Istaria, eine der fremdartigsten äußeren Erscheinungen von allen lebenden Rassen. Das auffälligste Merkmal ist ihre asexuelle Natur. 
		Alle Sslik sind in der Lage, Eier zu legen und ihre Jungen auszubrüten.<br><br>
		In ihrer Geschichte lebten die Sslik ein nomadisches Leben und wurden von den anderen Rassen oft als Ausgestoßene betrachtet. Ihre Ankunft in den Dschungeln von Süd-Aradoth während des <i>"Zeitalters des Krieger-Königs"</i> 
		war nicht gerade friedlich; die Sslik wurden von den meisten anderen Rassen gejagt und getötet und selbst heute noch werden sie von manchen als Barbaren und Wilde betrachtet. Die Sslik suchten Zuflucht an einem der 
		vermutlich unwirtlichsten Plätze , wurden sie doch in fast allen anderen Regionen Istaria's nahezu ausgerottet.<br><br>
		Die <a href="saris.php">Saris</a> waren die erste Rassen, die die Sslik als gleichwertige Lebewesen betrachteten. Bis zum heutigen Tag bringen sich beide Rassen ein gegenseitiges Vertrauen entgegen und haben einen 
		gewissen Sinn für eine Zusammenarbeit entwickelt.<br><br>
		Es erscheint fast wie ein Wink des Schicksals, das die Sslik größtenteils von den Angriffen durch die <i>"Withered Aegis"</i> verschont geblieben sind, was nicht zuletzt an der abgeschiedenen Lage ihres Lebensraumes 
		liegt.
		</p>
		</td>
	    </tr>
