		<td width="50%" height="410">
		<p class="white">
		Die ehemaligen Verfolger der Sslik jedoch hatten während des <i>"Zeitalters der Klagen"</i> auf dem Hauptkontinent sehr unter den Angriffen durch die Untoten zu leiden. Die Sslik brannten darauf, den anderen lebenden Rassen 
		im Kampf gegen die <i>"Withered Aegis"</i> beizustehen, doch sie machen kein Geheimnis daraus, das sie die Unannehmlichkeiten und den Kummer, den sie wegen der anderen Rassen erdulden mussten, bis heute nicht vergessen haben.<br><br> 
		Die Sslik befinden sich nun in einer wesentlich besseren Position als die anderen Rassen. Nur die Zeit wird zeigen, ob die Sslik einen Weg der Erleuchtung beschreiten, so wie ihre <a href="saris.php">Saris</a>-Freunde es ihnen 
		lehren, oder ob sie einem Pfad der Rache und Vergeltung folgen, so wie sie es einst von ihren Verfolgern gelernt haben.<br><br>
		Sslik sind reptilienartige Lebewesen, die geschlechtslos sind und sich in einer asexuellen Art und Weise vermehren. Ihr Verhalten und ihre Lebensweise erscheinen fremdartig im Vergleich zu den anderen Rassen; unglücklicherweise 
		trägt das zu der Abneigung bei, die die anderen lebenden Rassen gegenüber den Sslik haben. Während die Sslik unverkennbar einige Eigenschaften mit den Drachen teilen, scheinen sie jedoch nicht mit ihnen verwandt zu sein. 
		</p>
		</td>
