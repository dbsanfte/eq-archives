		<td colspan='2'>
		<p class='white'><br>
		Zwerge können in allen möglichen Berufszweigen angetroffen werden, tendieren jedoch mehr zu Rollen als Kämpfer oder Heiler. Ein falsches Gerücht besagt, das Zwerge nicht fähig sind, Zaubersprüche anzuwenden. Während es die 
		meisten Zwerge vorziehen, ihre Ziele durch Stärke und körperliche Anstrengung zu erreichen, gibt es in Istaria jedoch einige sehr begabte Zwergenzauberer.<br><br>
		Zwerge sind für ihre körperliche Stärke bekannt und sie benutzen diese natürliche Gabe, um im Kampf Vorteile zu erzielen. Sie sind berühmt dafür, Metall in all seinen Formen verarbeiten zu können und sie haben dadurch viel 
		Reichtum und Respekt erlangt.<br><br>
		Seit dem Beginn des <i>"Zeitalters der Klagen"</i> (das vor kurzem endete), waren die Zwerge von den meisten anderen lebenden Rassen abgeschnitten. Tatsächlich wird angenommen, das die Zwerge eine der ersten lebenden Rassen 
		waren, die von den Untoten angegriffen wurden. Es gab kein Lebenszeichen aus dem Reich der Zwerge, lag doch ihre Hauptstadt Aughundell tief im Einflußgebiet der <i>"Withered Aegis"</i>.<br><br>
		Doch die Wahrheit an der ganzen Geschichte ist, das die Zwerge fast 50 Jahre lang von den untoten Horden belagert wurden. Das wahre Schicksal der Zwerge kam erst kürzlich zu Tage, als die lebenden Rassen die Untoten bei der 
		Schlacht um Tazoon zurückschlugen. Obwohl die Mauern ihrer Stadt durchbrochen worden waren, hielten die Zwerge den untoten Horden alleine stand. Dies ist eine Tatsache, an die sie ihre Zuhörer immer wieder gern erinnern.<br><br>
		</p>
