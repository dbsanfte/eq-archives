		<td width='50%' height='410'>
		<p class='white'>
		Die Gesellschaft und die Kultur der Zwerge ist reich an Traditionen und besitzt ein sehr lange Geschichte. Sie ist aber auch eine der geschlossensten Gesellschaften unter allen lebenden Rassen.<br><br>
		Legenden besagen, das die Zwerge während des <i>"Zeitalters der Götter"</i> erschaffen wurden. Brobbet, der Gott der Ehre, erschuf die Zwerge, so das sie ihm als die Verteidiger der Ehre dienen konnten. In der Gesellschaft 
		der Zwerge kommen  Gerechtigkeit und Ehre vor allen anderen Dingen - dies bedeutet, das es vorkommen kann, das sie jemanden nicht verzeihen können, auf Grund der Taten, die derjenige begangen hat. Die Clans der Zwerge, obwohl 
		häufig gespalten und uneinig bei politischen Entscheidungen, leben alle nach ein und dem selben Leitspruch; Brobbets göttlichen Worten:  "Ohne Ehre, gibt es keine Gerechtigkeit,  ohne Gerechtigkeit gibt es keine Zukunft".
		Die Zwerge haben eingesehen, das die anderen lebenden Rassen nicht den gleichen Wunsch verspüren nach diesem Leitsatz zu leben, so wie die Zwerge es tun. Dies macht ein freundschaftliche Beziehung zu den Zwergen schwierig. 
		</p>
		</td>
