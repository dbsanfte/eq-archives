		<td colspan='2'>
		<p class='white'><br>
		Wenn es eine einzelne Stadt in ganz Istaria gibt, die entworfen wurde, um jeder erdenklichen Form von Belagerungen, Invasionen oder Überfällen widerstehen zu können, dann ist es dies Aughundell - die Gebirgsfestung der Zwerge.
		Tief in den nördlichen <i>"Black Mountains"</i> gelegen wurde Aughundell direkt in den Vorbergen und Steigungen des <i>"Mt. Grenaden"</i> errichtet.<br><br>
		Die Stadt benutzt sowohl natürliche Hindernisse als auch in hervorragender Handarbeit gebaute Anlagen der Zwerge, um zahlreiche Verteidigungsringe vor der Stadt zu errichten. Jede Schicht ist ein virtuelles Bollwerk der 
		Verteidigung, entworfen, um Angreifer zur Aufteilung der Kräfte zu zwingen. Solch ein Design ermöglicht es den Zwergen, die Stadt auch gegen zahlenmässig weit überlegegene Gegner zu verteidigen und bietet zudem zahlreiche 
		Verteidigungsräume, um die eigenen Streitkräfte neu formieren zu können. Das ausgeklügelte Verteidigungssystem erwies sich bei der Verteidigung von Aughundell gegen die Horden der <i>"Withered Aegis"</i> als äußerst erfolgreich. 
		Während solch ein städtisches Layout, mit Serpentinen und schmalen Fluren, nicht gerade förderlich für den Handel mit anderen Völkern ist, überwiegen doch die Vorteile eindeutig die Nachteile eines solchen Systems.<br><br>
		Obwohl Aughundell auf der Basis von Verteidigung und Sicherheit erbaut wurde, bedeutet das nicht, das die Stadt kein Ort der Anmut und Schönheit ist. Die Bildhauer der Zwerge haben ihre Arbeit mit dem natürlichen Gestein des 
		<i>"Mt. Grenaden"</i> perfektioniert und viele der Architekturen wurden direkt aus dem Gestein des Berges geschaffen.<br><br>
		Kunstfertigkeit und Architektur hängen stark von den Vorlieben der unterschiedlichen Zwergenclans ab und Aughundell ist ein Beispiel für die vielen Variationen und Abweichungen in beidem. Metall und Stein sind die bevorzugten 
		Rohstoffe, aus denen solche Kunstfertigkeiten geschaffen werden , obwohl Zwerge im großen und ganzen Einfachheit und Nutzen in ihrer Kunst bevorzugen. Das Herz von Aughundell ist jedoch einer der wenigen Orte, an denen das 
		Vorhandensein von phantasievoller und auffälliger Architektur überwiegt. Dies ist der Ort, an dem die Ältesten der Zwerge über ihr Volk herrschen und viel Liebe fürs Detail sowie feine Handarbeit wurden für den Bau einer der 
		schönsten und prächtigsten Ratshallen in ganz Istria aufgewendet.
		<br><br>
