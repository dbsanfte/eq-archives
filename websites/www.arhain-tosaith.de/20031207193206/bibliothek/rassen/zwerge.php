		<td width='50%' height='400'>
		<p class='white'>
		Einzige Ausnahme hierbei sind die <a href="gnome.php">Gnome</a>, die nach Meinung der Zwerge mit ihnen verwandt sind. Die Zwerge glauben, das die <a href="gnome.php">Gnome</a> lediglich ein wenig fehlgeleitet sind und von 
		ihrem eigentlichen Weg abgekommen sind.<br><br>
		Von der Statur her gehören Zwerge zu den kleineren Lebewesen unter den lebenden Rassen; für ihre Größe sind sie recht stämmig und sind für ihre überlegene Stärke und Beweglichkeit bekannt. Sowohl Männer als auch Frauen unter 
		den Zwergen sind für ihre gepflegten Bärte bekannt. Einige der Zwergenältesten sind sogar für ihre eindrucksvollen , langen Bärte berühmt. Die Stellung eines Zwerges innerhalb seines Clans kann man daran erkennen, wie lang sein 
		Bart ist oder wie gut dieser gepflegt ist.<br><br>
		Sollte man einmal einem Zwerg begegnen, der seinen Bart abrasiert hat, so ist das entweder ein Zeichen dafür, das er die Stellung innerhalb seines Clans verändern will, oder er versucht "sein Glück im Leben zu verändern".
		Zwerge sind von Natur aus sehr abergläubisch und praktizieren oft Rituale, die "bewiesen" haben, das sie ihnen und ihren Verwandten Glück bringen.
		</p>
		</td>
