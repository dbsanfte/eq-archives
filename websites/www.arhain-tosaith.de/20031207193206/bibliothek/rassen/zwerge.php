		<td height='18' colspan='2' background='../../pics/back_top_hell_large.jpg'><a name='#Aughundell'></a><p class='question' align='center'><font class='white'><b>::</b></font> AUGHUNDELL - HAUPTSTADT DER ZWERGE <font class='white'><b>::</b></font></p></td>
