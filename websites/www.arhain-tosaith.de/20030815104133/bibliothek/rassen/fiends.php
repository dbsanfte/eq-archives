		<td width="50%" height="410">
		<p class="white">
		Während des <i>"Zeitalters des Hexenmeisters"</i> begannen die <a href="menschen.php">Menschen</a> intensiv damit, die arkanen Kräfte und deren Verbindungen zum 
		Land selbst zu studieren. Der Großteil der Schulen der Magie, die heute noch praktiziert werden, wurden während dieser Ära entdeckt. Bestimmte Schulen, besonders 
		die, die sich mit mentaler Kontrolle und Nekromantie beschäftigten, waren damals in der menschlichen Gesellschaft verboten. Ein paar Zauberer und Totenbeschwörer, 
		die die Macht dieser verbotenen Schulen der Magie suchten, stellten eine Gefahr für die menschliche Gesellschaft dar und wurden daher ins Exil verbannt.<br><br> 
		Dieses Exil war nicht leicht zu ertragen, und Kriege tobten zwischen den beiden Parteien und erreichten schliesslich ihren Höhepunkt, als die Verbannten anfingen, 
		eine neue Gottheit - Niatha Moraven, Göttin der Vergeltung und Macht - anzubeten.<br><br>
		Mit der Macht eines Gottes im Rücken waren die Verbannten in der Lage, sich in den eisigen Gebieten von Nord-Aradoth anzusiedeln, fernab der menschlichen Gesellschaft.  
		Niatha Moraven gab ihren neuen Anhängern ein auffallend schönes Aussehen, im Gegenzug erhielten sie aber auch Hörner und Schwänze, wie sie bei Tieren vorkommen.
		Bis zum heutigen Tag entrichten die Fiends ihren Tribut an Niatha Moraven, die sie selbst Mutter der Fiends nennen.
		</p>
