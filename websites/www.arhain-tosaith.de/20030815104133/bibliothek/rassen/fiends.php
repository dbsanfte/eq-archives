		<td width="50%" height="410">
		<p class="white">
		Die Fiends stammen ursprünglich von den <a href="menschen.php">Menschen</a> ab, obwohl sie lange Zeit eine mögliche Verbindung mit ihnen verleugnet 
		haben. Äußerlich gesehen ähneln Fiends atemberaubend schönen <a href="menschen.php">Menschen</a>. Ihre bläulich getönte Haut, ihre vorstehenden Hörner am 
		Vorderkopf und ihre Schwänze sind jedoch eindeutige Zeichen ihrer Rasse, die sie von ihren menschlichen Vorfahren unterscheiden. Ihre bläulich schimmernde, 
		eisige Haut ist das Resultat von vielen Generationen , die die Fiends in den kalten Einöden des Nordteils der Welt gelebt haben. Fiends lassen sich nicht 
		durch das rauhe Klima des Nordens stören und entwickeln sich da, wo andere die Kälte unerträglich finden würden.<br><br>
		Alle Fiends sind Geschöpfe natürlicher Schönheit und sind von beeindruckender Statur im Vergleich zu ihren menschlichen Verwandten. Die äußere Schönheit 
		jedoch trügt und überdeckt nur die finstere Natur der Fiends, wie die Vergangenheit gezeigt hat. Die Fiends behaupten, das es einen Grund gibt, warum alle 
		anderen Rassen und sie sich selbst Fiends nennen.
		</p>
		</td>
