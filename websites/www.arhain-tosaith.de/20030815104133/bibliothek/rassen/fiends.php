		<td height="18" colspan="2" background="../../pics/back_top_hell_large.jpg"><a name="#Kirasanct"></a><p class="question" align="center"><font class="white"><b>::</b></font> KIRASANCT - HEIMAT DER FIENDS <font class="white"><b>::</b></font></p></td>
	    </tr>
	    <tr>
		<td height="2" colspan="2" background="../../pics/line2.jpg"></td>
	    </tr>
	    <tr>
		<td colspan="2">
		<p class="white"><br>
		Von der gigantischen Stadt Kirasanct aus, die hoch oben in den Bergen im Norden Aradoth's liegt, herrschen die Fiends über ihre eisige Heimat. Kirasanct ist eine recht junge 
		Stadt, genau wie die Rasse, die sie bewohnt. Die Stadt ist ein Zeugnis für den Wunsch der Fiends nach Abgeschiedenheit und Ruhe vor Außenseitern.<br><br>
		Kirasanct ist ein Festungsanlage, bestehend aus  Metall und Stein, mit einem massiven , zentral gelegenen Turm im Herzen der Stadt. Ein spinnenförmiges Muster überzieht die 
		gesamte Stadtmauer und verleiht der Stadt aus der Ferne ein furchteinflössendes Schattenbild. Die Stadt liegt auf einer Hochebene in der Mitte einer riesigen Senke, die vom 
		zentralen Turm und der Stadtmauer aus überblickt werden kann. Ohne Zweifel besteht der Zweck der Stadt darin, unerwünschte Besucher fernzuhalten und wenn man die Natur der
		Fiends in Betracht zieht, dann weiss man, das damit alle anderen lebenden Rassen gemeint sind. Sogar in der heutigen Zeit, in der eine Zusammenarbeit erforderlich ist, bleibt 
		Kirasanct ein unwirtlicher Platz für alle außer den Fiends.<br><br>
		Es wird behauptet, daß tief unter den eisigen Mauern von Kirasanct oder möglicherweise in einer nahe gelegenen Höhle, ein Portal zum <i>"Reich des Zwielichts"</i> ruht. Gerüchten 
		zur Folge arbeiteten die Fiends vor dem Beginn des <i>"Zeitalters der Klagen"</i> aktiv an der Wiederherstellung des Portals, um eine Verbindung zwischen Istaria und dem <i>"Reich 
		des Zwielichts"</i> herzustellen, wo die Gottheit der Fiends - Niatha Moraven - leben soll.<br><br>
		Die Fiends haben nie ein Geheimnis aus ihrem Wunsch gemacht, die Verbindung zu ihrer gewählten Göttin zu verstärken; tatsächlich wählten die Fiends den Bauplatz für Kirasanct 
		über einem starken Quell magischer Essenz, in der Hoffnung, das dieser ihre Rituale und Zauberkräfte verstärken würde um ihre gesteckten Ziele zu erreichen. Mit dem Beginn des 
		<i>"Zeitalters der Klagen"</i> wurde die Entscheidung, nahe einem Quell starker und manchmal instabiler magischer Essenz zu bauen, gerade im Kampf gegen die <i>"Withered Aegis"</i> 
		bekräftigt. Die lebenden Rassenbenötigten einen Platz der leicht gegen eine Invasion verteidigt werden konnte, um die Erforschung von Zaubersprüchen vorantreiben zu können. Die 
		Fiends zeigten ein seltenes Zeichen von Zusammenarbeit und waren bereit, einen Großteil der Zauberforschung im Zusammenhang mit der Entwicklung neuer Strategien im Kampf gegen 
		die <i>"Withered Aegis"</i> aufzunehmen.<br><br> 
		Ausgerüstet mit einer bedeutenden Menge magischer Essenz und einer nicht geringen Anzahl an Zauberern ist und bleibt Kirasanct ein wichtiges Zentrum für die Erforschung neuer 
		Zaubersprüche.<br><br>
