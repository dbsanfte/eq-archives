		<td width='50%' height='430'>
		<p class='white'>
		Die Saris sind eine stolze Rasse und sind von katzenhafter Abstammung. Sie existieren bereits seit vielen Jahren in <i>"Lesser Aradoth"</i> und teilen sich die Insel mit den oft geächteten <a href="sslik.php">Sslik</a>. 
		Die Saris leben in relativem Frieden mit den <a href="sslik.php">Sslik</a> zusammen und sie sind eine der Rassen, die die anderen lebenden Rassen im <i>"Zeitalter der Klagen"</i> am meisten mit Material und Arbeitskräften 
		unterstützt haben. Dies ist keine große Überraschung, steht doch der Grundgedanke und die Zivilisation der Saris im extremen Gegensatz zu den Untoten der <i>"Withered Aegis"</i>. Die Saris sind eine sehr spirituelle Rasse 
		und sie betrachten das Verändern und Ausbeuten von Seelen als eine Verletzung ihrer moralischen Grundsätze.<br><br>
		Die Saris erfreuten sich lange Zeit an dem Luxus, ihrer Lebensweise in relativ sicherem Abstand zu den Horden der <i>"Withered Aegis"</i> nachkommen zu können, lebten sie doch an den äußersten des Festlandes. Diejenigen
		Rassen, die unter den Angriffen der <i>"Withered Aegis"</i> besonders zu leiden hatten, insbesondere die <a href="elfen.php">Elfen</a>, hegen aufgrund dieser Tatsache eine gewisse Abneigung gegenüber den Saris.
		</p>
