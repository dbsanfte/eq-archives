		<td colspan='2'>
		<p class='white'><br>
		Kion, die Heimat der Saris von Istaria, ist eine offene und langgestreckte Ansammlung von Gebäuden entlang der sandigen Küstenstreifen von <i>"Lesser Aradoth"</i>. Die Saris haben sich einen individuellen Baustil angeeignet, der durch 
		kulturelle und geschichtliche Ereignisse geprägt ist. Farbe und Design dienen in der Gesellschaft der Saris als eindeutiger Indikator für Funktion und Zweck und ihre Architektur spiegelt dies wider. Kion existiert schon seit langer 
		Zeit in relativer Ruhe als großer Vorposten der Saris. Es gibt keine Mauern um die Stadt selbst, aber die zentralen Gebäude von Kion sind zum Schutz vor Überfällen und Belagerungen befestigt worden.<br><br>
		Die Stadt hat sich im Laufe der Jahre nur unwesentlich verändert, doch die Neuöffnung der Teleporttore brachte einen ständigen Besucherstrom der anderen lebenden Rassen nach Kion. Ein Großteil dieser Besucher kommt nach Kion, um 
		einen der wenigen Lehrmeister für Mönche in Istaria zu besuchen. Kion besitzt eine lebhafte Wirtschaft, nicht zuletzt durch eine strategisch gute Lage zu verschiedenen Hauptrohstoffquellen begünstigt.<br><br>
		Nicht einmal Kion und dessen bisherige relative Sicherheit sind von dem Krebsgeschwür der <i>"Withered Aegis"</i> verschont beblieben. Bösartige Kreaturen leben in der näheren Umgebung der Stadt und ein unachtsamer Reisender könnte sich 
		schnell in einer unangenehmen Lage wiederfinden.
