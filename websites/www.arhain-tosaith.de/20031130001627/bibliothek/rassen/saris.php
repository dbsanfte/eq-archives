		<p class='white'>
		Ein leichter Anflug von Überheblichkeit gegenüber allen anderen trägt nicht gerade zu einer Verbesserung der Verhältnisse zu den anderen Rassen bei, doch die von den Saris angebotene Unterstützung im Kampf gegen die
		<i>"Withered Aegis"</i> wurde bisher nie abgelehnt.<br><br>
		Saris haben eher eine durchschnittliche Körpergröße und ihr gesamter Körper ist mit einem leichten Fell bedeckt. Das Fell der Saris kann vielerlei Farben und Muster aufweisen und ganze Familien der Saris werden oft
		durch Fellfarbe und Muster unterschieden. Saris sind im allgemeinen etwas kleiner als 2 Meter, annähernd so groß wie Menschen.<br><br>
		Die Saris sind mit Abstand die gewandeste aller lebenden Rassen und sie eignen sich ausgezeichnet als Kundschafter. Sie sind außerdem dafür berühmt, eine führende Rolle unter den Mönchen von Istaria zu haben, verstehen 
		sie es doch hervorragend, die Kunst des unbewaffneten Kampfes mit ihren spirituellen Kräften zu verbinden. Durch ihre natürliche Geschicklichkeit sind sie in solchen Berufen sehr begabt, die eine hohe Fingerfertigkeit 
		voraussetzen. Viele Handwerker der Saris sind berühmte Schneider und Juweliere. Diese Handwerksberufe entsprechen den Vorlieben der Saris für leichte Kleidung und Rüstungen, sowie ihrer angeborenen katzenhaften Neugier 
		für glänzende Edelsteine und Metalle.
