		<td width="50%" height="410">
		<p class="white">
		Die Gnome bemühen sich, ausgezeichnete Verbindungen zu allen anderen Gesellschaften Istaria's zu halten und machen sich für eine Vereinigung aller lebenden Rassen im Kampf gegen die untoten 
		Horden der <i>"Withered Aegis"</i> stark.<br><br>
		Vom Äußeren her sind Gnome ungefähr so groß wie <a href="zwerge.php">Zwerge</a>, haben jedoch nicht ganz so breite Schultern. Es ist jedoch offensichtlich, daß sie viele körperliche Eigenschaften 
		mit ihren Vettern - den <a href="zwerge.php">Zwergen</a> - teilen. Gnome sind nicht von Natur aus stämmig, aber ihr Körperbau kann viele verschiedene Formen haben, von muskulös bis stattlich.<br><br>
		Ihre Köpfe scheinen proportional etwas größer zu sein als der Rest des Körpers;  dies verleiht den Gnomen oftmals ein lustiges Aussehen, häufig verbunden mit dem allgemeinen Ausdruck von 
		Verwirrung und Aufregung. Dies prägt den typischen Gesichtsausdruck der Gnome.<br><br>
		Haar- und Augenfarben der Männer und Frauen weisen ein breites Spektrum an Farben auf, der Farbton ihrer Haut ist jedoch in der Regel hell.
		</p>
