		<td colspan="2">
		<p class="white"><br>
		Das auf einer hohen Steppe zwischen den nördlichen und den südlichen Ausläufern der <i>"Granitefall Mountains"</i> gelegene Rachival war lange Zeit die Hauptstadt der Gnome, bis es vor ca. 
		30 Jahren von den untoten Horden überrannt wurde. Die Untoten vernichteten die letzten Überreste der Armee der Gnome , nachdem diese von den restlichen lebenden Rassen getrennt wurden als 
		die Untoten südwärts gegen sie marschierten. Kurz danach verschwand das Reich der Gnome von der Landkarte und die restlichen Überlebenden flüchteten nach Norden in Richtung Tazoon.<br><br>
		Bis zum heutigen Tag waren die Gnome nicht in der Lage, ihre alte Heimat wieder zu erobern; die meisten ihren angestammten Ländereien, einschließlich Rachival, befinden sich immernoch unter 
		der Herrschaft der untoten Horde.<br><br>
		Nach dem Sieg der lebenden Rassen über die Untoten bei der Schlacht um Tazoon kam es zu Verhandlungen, an deren Ende es zum Abschluß eines Bündnisses im Kampf gegen die Untoten kam - 
		unterzeichnet von allen lebenden Rassen. Wie auch immer, die Gnome haben die besten Chancen, ihre alte Heimat wieder in Besitz nehmen und vollständig wieder herstellen zu können.<br><br>
		Einstmals das führende Zentrum wenn es um die Verbindung zwischen Technologie und Magie ging ist Rachival heute jedoch nurnoch ein Ort von Tod und Zerfall. Viele ihrer Innovationen stehen 
		untätig im Herzen dessen, was einige Gelehrte als einen der größten Wirbelstürme in ganz Aradoth bezeichnen.<br><br>
		Es ist wenig bekannt über die gegenwärtige Lage in der Stadt selbst, jedoch berichten jene Abenteurer, die tapfer genug sind um sich näher an die Stadt heranzuwagen, daß der Himmel über der 
		Stadt von dunklen und dicken Wolken verhangen ist und der faulige Nebel des Sturms über dem ganzen Land liegt. Einige Abenteurer berichten sogar von entstellten, metallischen Kreaturen, die 
		auf den Ländereien rund um die Stadt patroullieren sollen.
