		<td height="18" colspan="2" background="../../pics/back_top_hell_large.jpg"><a name="#Rachival"></a><p class="question" align="center"><font class="white"><b>::</b></font> RACHIVAL - EHEMALIGE HEIMAT DER GNOME <font class="white"><b>::</b></font></p></td>
	    </tr>
	    <tr>
		<td height="2" colspan="2" background="../../pics/line2.jpg"></td>
