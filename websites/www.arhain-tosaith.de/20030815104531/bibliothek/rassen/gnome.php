		<td width="50%" height="430">
		<p class="white">
		Die Gnome von Istaria stellen möglicherweise am besten die Zukunft dar, die vor Istaria und den anderen lebenden Rassen liegt.<br><br>
		Während sie gewöhnlich nicht als engagierte Anwender arkaner Kräfte bekannt sind, sind sie doch die Rasse, die die Kräfte der Magie in eine neue, vorher unbekannte Richtung lenken kann -  
		den Weg der Technologie. Die Gnome scheinen extrem geschickt darin zu sein, die Kräfte der Magie so zu binden und zu formen, das diese zum Antreiben von großen und exotischen Maschinen und 
		Vorrichtungen genutzt werden können. Die Gnome bemühen sich auch den Abstand zu verkleinern, der zwischen den Wegen der Magie und der Technologie besteht.<br><br>
		Eine der definierendsten Eigenschaften der gnomischen Gesellschaft ist ihre Hingabe für die Erfindung neuer Dinge. Infolgedessen entrichten die Gnome ihre Lehnstreue im großen und 
		ganzen an Istara, die Göttin der Schöpfung, obwohl sie es vorziehen, ihr den Spitznamen "die Mutter der Erfindung" zu schenken.<br><br>
		Gnome erfüllen viele Rollen und Funktionen innerhalb der Gesellschaft Istaria's, jedoch besonders gut in den wissenschaftlichen Bereichen.
		</p>
		</td>
	    </tr>
