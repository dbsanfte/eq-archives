		<td width='50%' height='580'>
		<p class='white'>
		Die Drachen von Istaria sind ein mysteriöses, uraltes Volk und sie existierten schon vor den ersten Aufzeichnungen der Geschichte Istaria's überhaupt. Um genau zu sein, kommen die 
		meisten Informationen im Bezug auf die früheste Geschichte Istaria's von den Drachen selbst, die diese Informationen mit den anderen Rassen geteilt haben. Die Drachen haben sich 
		immer aus den Angelegenheiten der anderen Rassen herausgehalten; erst seit kurzem streben die beiden Fraktionen der Drachen eine Zusammenarbeit mit den <i>"Naka-Duskael"</i> an, was 
		man aus der Drachensprache grob mit <i>"die Schuppenlosen"</i> übersetzen könnte. Selbst die Drachen haben erkannt, das die Notwendigkeit zu überleben die Aufgabe ihrer isolierten 
		Lebensweise bedeutet. Dies erscheint fast wie ein Hilferuf einer Rasse, die vor dem <i>"Zeitalter der Götter"</i> noch als Gottheiten verehrt und angebetet wurde. Das riesige Abbild 
		eines mächtigen Drachens, der vor Jahrhunderten aus dem Gestein des <i>"Dragon Prech Mountain"</i> geschaffen wurde, ist der Beweis dafür, das die anderen Rassen die Drachen früher 
		mit Ehrfurcht und Achtung betrachteten. Die Drachen erinnern die anderen lebenden Rassen auch gern daran, sobald sie mit ihnen zu tun haben.<br><br>
		Die Drachen erscheinen vom Aussehen her etwas fremdartig im Vergleich zu den anderen lebenden Rassen, was nicht zuletzt and der einzigartigen Natur dieser Rasse liegt. Drachen sind die 
		größten Lebewesen unter allen Rassen und die ältesten Drachen sind mindestens zweimal so groß wie die größten Vertreter der anderen Rassen. Ab einem bestimmten Alter sind Drachen in der 
		Lage zu fliegen. Ihre riesigen Flügel verleihen ihnen etwas Balance und Kontrolle in der Luft; ihre Fähigkeit zu fliegen scheint aber mehr auf dem Nutzbarmachen externer magischer 
		Energien zu basieren. Die Haut der Drachen ist mit dicken Schuppen versehen, die einen größeren Schutz bieten, als der Großteil der von den anderen Rassen benutzten Rüstungen.<br><br>
		</p>
		</td>
	    </tr>
	    <tr>
		<td colspan='2'>
		<p class="white">
		Drachen besitzen auch die natürliche Gabe, gewaltige Energien in Form ihres Drachenodems auf ein bestimmtes Ziel ausstoßen zu können. Viele Drachen bevorzugen Feuer als den Drachenodem 
		ihrer Wahl, jedoch ist Feuer nicht die einzige Form der verwendeten Energien. Das Alter eines Drachen ist ausschlaggebend für die Macht und die Art seines Odems. Drachen meiden die Benutzung 
		von herkömmlichen Gegenständen und Werkzeugen und verlassen sich mehr auf ihre angeborenen, magischen Fähigkeiten um Gegenstände zu schaffen, die ihren Bedürfnissen entsprechen und um 
		ihre Umwelt zu beeinflussen. Drachen sind sehr besitzergreifend; was ihnen einmal gehört ist von größter Wichtigkeit für sie. Sie sammeln im Laufe ihres Lebens Berge von Gold, Edelsteinen 
		und Gegenständen in ihren Drachenhorten und die Größe ihres Drachenhortes scheint ihre Macht positiv zu beeinflussen. Die Lage ihres Drachenhortes ist geheim und nur dem Drachen selbst 
		bekannt.<br><br>
		Es gibt bestimmte Dinge in der Welt von Istaria, vor denen nicht einmal die einzigartige und mächtige Gattung der Drachen die Augen verschließen kann. Mehrere hundert Jahre lang durchlebten 
		die Drachen etwas, was Außenseiter als das große Schisma bezeichnen (grch. Spaltung). Soweit man sagen kann (die Drachen sind nicht gerade dafür bekannt, das sie ihre eigenen Angelegenheiten 
		dem Rest der Welt mitteilen), gibt es 2 Fraktionen unter den Drachen: die Lunus und die Helian. Die Lunus betrachten sich selbst als Vorbild für alle anderen Rassen. Sie sind der Meinung, 
		das die anderen Rassen  der Zivilisation der Drachen dienen sollten (natürlich von einer angemessenen Entfernung aus), oder sie sollten sich einfach aus dem Staub machen. Die Helian betrachten 
		sich als die Hüter des Wissens und als Beschützer der Welt und sie denken, das die anderen Rassen noch viel von ihnen lernen könnten. Während im Laufe der Jahre noch andere Fraktionen 
		existierten, kennzeichnen die Lunus und die Helian die beiden Hauptinteressengebiete in der Drachengesellschaft.<br><br>
		</p>
		</td>
