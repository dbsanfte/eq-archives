		<p class="white">
		Obwohl die Drachen ihre Aufmerksamkeit nun den untoten Horden der <i>"Withered Aegis"</i> zugewendet haben, sind die Erinnerungen and das große Schisma immernoch frisch, so als wäre es erst gestern 
		geschehen. Die Helian führen einen offenen Dialog (so offen ein Dialog mit einem Drachen sein kann) mit den <a href="menschen.php">Menschen</a>, den <a href="zwerge.php">Zwergen</a> und der freien Stadt 
		Tazoon. Die Lunus erachten es als erforderlich, gemeinsam mit ihren Nachbarn das Land gegen die Untoten zu verteidigen, sollte sich dies als notwendig erweisen. Außerdem hegen sie, genauso wie die 
		<a href="fiends.php">Fiends</a>, eine gewisse Abneigung gegenüber den <a href="menschen.php">Menschen</a>, was eine Zusammenarbeit zwischen den Lunus und den <a href="fiends.php">Fiends</a> begünstigt hat. 
		Bis zum heutigen Tag sind die Drachen in 2 Lager gespalten und nur die dunkle Bedrohung durch die <i>"Withered Aegis"</i> zwingt sie, von Zeit zu Zeit zusammen zu arbeiten. Es gibt jedoch nur geringe 
		Chancen, das die Drachen sich in naher Zukunft wieder unter einer Führung vereinen könnten.<br><br>
