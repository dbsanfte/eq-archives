			<td width="90" valign="top" align="right"><p class="question"><u>Aussehen :</u>&nbsp;&nbsp;</p></td>
			<td width="455"><p class="white">Wenn ein Spieler einen neuen Drachencharakter beginnt, wird das ein jugendlicher Drache sein. Der Spieler kann Kopfform und -muster auswählen, Flügelform und -muster, 
			Aussehen des Körpers, des Bauches und alle mögliche anderen Texturen, wie z.B. gestreifte Flanken und gesprenkelte Schultern. Weiterhin kann der Spieler des Gewicht und die Muskulatur seines 
			Jungdrachen wählen, so wie es seinen persönlichen Vorlieben entspricht.<br><br></p>
			</td>
		   </tr>
		   <tr>
			<td width="90" valign="top" align="right"><p class="question"><u>Altern :</u>&nbsp;&nbsp;</p></td>
			<td width="455"><p class="white">Drachen sind die einzige Rasse, bei denen das Altern eine Rolle spielt. Das Alter eines Drachen wird in Reallife-Zeit ab Beginn der Charaktergenerierung gemessen. Sobald 
			ein Jungdrachen ein bestimmtes Alter erreicht hat und sein Hort eine bestimmte Größe besitzt, kann er eine Quest absolvieren, um ein erwachsener Drachen zu werden. Wie hoch das Alter sein muss bzw. wie 
			groß der Hort sein muss werden wir während der Beta entscheiden. Für einen erwachsenen Drachen, der ein uralter Drachen werden möchte, gelten ähnliche Vorraussetzungen.<br><br></p>
			</td>
		   </tr>
		   <tr>
			<td width="90" valign="top" align="right"><p class="question"><u>Fähigkeiten :</u>&nbsp;&nbsp;</p></td>
			<td width="455"><p class="white">Jungdrachen haben die angeborene Fähigkeit, auf ein einzelnes Ziel Feuer spucken zu können. Wenn ein Jungdrachen erwachsen wird, dann erhält er die Fähigkeit zu fliegen. 
			Erwachsene Drachen sind außerdem in der Lage, ihren Drachenodem nicht nur auf ein einzelnes Ziel anzuwenden, sonder auch auf alle Gegner in der Nähe dieses Ziels. Sobald ein erwachsener Drachen ein uralter 
			Drachen wird, kann er die Art seines Drachenodems frei wählen. Von Feuer über Eis bis hin zu Säure. Wir testen im Moment noch andere Formen des Drachenodems um sie ggf. später noch einbauen zu können.
			<br><br></p>
			</td>
		   </tr>
		   <tr>
			<td width="90" valign="top" align="right"><p class="question"><u>Schulen :</u>&nbsp;&nbsp;</p></td>
			<td width="455"><p class="white">Anders als andere Rassen können Drachen nur Drachenschulen angehören. Die Grundschulen der Kategorie "Abenteuer" sind Drachenkämpfer, Drachenmagier und Drachenheiler. 
			Die Schulen der Kategorie "Handel" sind Gelehrter, Sammler, Steinmetz und Wohnungsbauer (Dwelling Crafter?). Drachensteine sind von den Drachen geschaffene Gegenstände, die dem Besitzer des Steines bestimmte 
			Vorteile verschaffen, uralte Drachen können damit außerdem ihren Drachenodem ändern.<br><br></p>
			</td>
		   </tr>
		   <tr>
			<td width="90" valign="top" align="right"><p class="question"><u>Magie :</u>&nbsp;&nbsp;</p></td>
			<td width="455"><p class="white">Drachen sind keine Rasse, die gerne Gegenstände benutzen. Sie verändern und bauen Dinge mit Hilfe ihrer Magie. Drachen sind in der Lage, alle Zaubersprüche anzuwenden, die 
			auch den anderen Rassen zur Verfügung stehen. Außerdem haben sie noch spezielle Zaubersprüche um Rohstoffe zu sammeln oder um ihre fantastischen Gebäude zu errichten, entweder auf der Erde oder im Himmel 
			darüber.<br><br></p>
			</td>
