		<td width='50%' height='510'>
		<p class='white'>
		Während die verschiedenen Philosophien der Drachen zu Beginn noch miteinander harmonierten, begannen sie sich gegenseitig zu behindern, als die anderen Rassen die Drachen nicht länger 
		fürchteten und verehrten, so wie sie es in der Vergangenheit einmal getan haben. Die Lunus (die typischen Kämpfer in der Drachengesellschaft) befürchteten, das die anderen Rassen, insbesondere 
		die <a href="menschen.php">Menschen</a>, letztendlich den Untergang der Drachenrasse herbeiführen würden. Sie sprachen sich für aggressive Maßnahmen aus, um die anderen lebenden Rassen aufhalten 
		zu können. Die Helian (eher die Gelehrten und Zauberkundigen) widersprachen den Lunus, indem sie sagten, das die Drachen die Führung aller Rassen Istaria's übernehmen sollten. Dies sollte ihnen 
		den Respekt und die Verehrung wiederbringen, die die anderen Rassen einst für die Drachen hatten.<br><br>
		Die Differenzen verfestigten sich zwischen den beiden Parteien und mit der Zeit hatten beide Fraktionen eine unterschiedliche Ansicht der Dinge. Die den Drachen innewohnenden, negativen, 
		charakterlichen Eigenschaften, wie z.B. ihre Habgier, trugen ebenfalls ihren Teil dazu bei. Schließlich wurden beide Seiten so unzufrieden, das die Gefahr bestand, das sie sich gegeneinander 
		wenden könnten, sollten nicht sofortige und drastische Änderungen vollzogen werden. Die Helian reagierten als erstes und entschlossen sich, ihre angestammten Ländereien zu verlassen und sich 
		in einem anderen Gebiet niederzulassen. Die Lunus waren nicht glücklich darüber das die Gesellschaft der Drachen auseinander gerissen wurde, dennoch unternahmen sie nichts, um die Helian 
		aufzuhalten.<br><br>
		</p>
