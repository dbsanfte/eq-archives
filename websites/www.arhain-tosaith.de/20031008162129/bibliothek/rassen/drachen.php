		Ansammlung von Türmen. Es gibt wenige kommunale Plätze in Dralk, diese sind jedoch verschwenderisch und detailliert gestaltet. An solchen Plätzen befindet sich das gesammelte Wissen der Drachen, genauso 
		wie detaillierte Erkenntnisse über die arkanen Kräfte. In Dralk gibt es auch einen Tempel , der Dulkar gewidmet ist. Mit einem prächtigen Amphitheater, umgeben von Obsidiantürmen, ist er der größte Tempel 
