		<td width="50%" height="415">
		<p class="white">
		Die Halbriesen stellen die beträchtliche, schlummernde Macht dar, die ein vereintes Istaria aufbringen könnte um den Horden der <i>"Withered Aegis"</i> Einhalt gebieten zu können.<br><br>
		Körperlich ähneln Halbriesen großen <a href="menschen.php">Menschen</a>. Ein normaler Halbriese ist jedoch mehr als anderthalb mal so groß wie ein <a href="menschen.php">Mensch</a> und fast doppelt so breit. Die 
		körperliche Stärke der Halbriesen ist unter allen Rassen fast unübertroffen. Ihre helle Haut ist dicker und widerstandsfähiger als die der meisten anderen Rassen, um im rauhen Klima der Winter Nord-Aradoth's 
		überleben zu können.<br><br>
		Es ist überflüssig zu erwähnen, das die Rolle eines Kämpfers den Vorlieben eines normalen Halbriesens entspricht. Halbriesen tendieren mehr zu körperlich anstrengenden Tätigkeiten, aber das bedeutet nicht, das es in
		der Gesellschaft der Halbriesen keine Zauberer und Gelehrten gibt.<br><br>
		Halbriesen sind Wesen mit einfachen Beweggründen und Motiven und sie sind sehr geduldig, doch man sollte sich davor hüten sie zu reizen, denn sie können gefährliche Gegner sein.
		</p>
