		<td width="50%" height="425">
		<p class="white">
		Die Halbriesen von Istaria sind entfernte Verwandte der <a href="menschen.php">Menschen</a>, wenn man der Legende glauben schenken darf. Die Legende datiert die Geburt der Rasse der Halbriesen auf das Ende des 
		<i>"Zeitalters der Götter"</i>,	als die <a href="menschen.php">Menschen</a> anfingen, die eisigen, bergigen Regionen Nord-Aradoth's zu besiedeln. Durch das rauhe Klima in den Bergen überlebten nur die stärksten 
		und gesündesten der <a href="menschen.php">Menschen</a> und im Laufe der Zeit wurden sie viel größer und körperlich robuster.<br><br>
		Während es durchaus möglich ist, das die Halbriesen das Erbe der legendären Rasse der Riesen in sich tragen kann es genauso gut möglich sein, das sie lediglich das Produkt der lebensfeindlichen Bedingungen ihrer
		Umwelt sind. Dieses isolierte Leben spiegelt sich auch im Umgang mit den anderen Rassen wider, obwohl sich die Zivilisation der Halbriesen die meiste Zeit der aufgezeichneten Geschichte nicht um die Angelegenheiten
		anderer Rassen gekümmert haben.<br><br>
		Die Gesellschaft der Halbriesen betont immer wieder den vernünftigen Gebrauch ihrer enormen körperlichen Kräfte, besonders im Umgang mit den anderen lebenden Rassen. Diese Tatsache, verbunden mit dem relativ großen 
		Sicherheitsabstand zum belagerten Teil Aradoth's hat den Halbriesen eine entscheidende Rolle in der Politik der lebenden Rassen gegeben.
		</p>
		</td>
