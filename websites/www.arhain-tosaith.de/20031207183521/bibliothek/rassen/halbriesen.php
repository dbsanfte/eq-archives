	    <tr>
		<td colspan="2">
		<p class="white"><br>
		Mahagra, ist eine Stadt aus Stein und Metall, gebaut um dem eisige Klima der nördlichen Gebiete trotzen zu können. Sie diente mehrere hundert Jahre lang der Rasse der Halbriesen als Heimat. 
		Mahagra wurde gegen Ende des <i>"Zeitalters des Drachen"</i> gegründet und die Größe der Stadt sowie deren Aussehen hat sich seitdem nur unwesentlich verändert.<br><br>
		Durch die Lage der Stadt hoch oben in den Bergen im Norden Aradoth's lebten die Halbriesen lange Zeit abgeschieden und isoliert von den anderen lebenden Rassen und blieben während des <i>"Zeitalters 
		der Klagen"</i> relativ unbeschadet.<br><br>
		In den verschneiten Waldgebieten im Norden Aradoth's gelegen, ist Mahagra heute ein wichtiges Zentrum im Kampf gegen die <i>"Withered Aegis"</i>, nicht zuletzt wegen der Unterstützung der lebenden Rassen
		bei ihren Kriegsbemühungen durch die Halbriesen. Insbesondere die <a href="elfen.php">Elfen</a> arbeiten seit kurzem eng mit den Halbriesen zusammen um Mahagra als Ausgangspunkt für den Feldzug gegen die 
		<i>"Withered Aegis"</i> zu nutzen und ihre angestammten Ländereien rund um Feladan zurückerobern zu können.
