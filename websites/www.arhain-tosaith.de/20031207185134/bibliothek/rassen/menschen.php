		<td colspan='2'>
		<p class='white'><br>
		Die Hauptstadt der Menschen - Dalimond - liegt südwestlich von Tazoon auf dem westlichen Teil des Kontinentes von Aradoth. Dalimond ist ein verhältnismäßig neues 
		Zentrum des Handels für die Menschen des Vandus-Bündnisses und gilt außerdem als Hauptquartier für deren militärische Operationen. Die Stadt wurde ursprünglich als Bauerngemeinschaft 
		entlang der fruchtbaren Ebenen von Barasavus vor mehreren hundert Jahren, am Ende des <i>"Zeitalters des Krieger-Königs"</i>, gegründet. Im Laufe der Jahre verwandelten sich die 
		nördlichen Ausläufer der Ebenen von Barasavus von üppigen Ländereien in ein großes Ödland. Aber Dalimond dehnte sich weiter aus, trug doch der landwirtschaftliche Zweig einiges 
		zu der auf Handel basierenden Wirtschaft bei.<br><br>
		Dalimond liegt entlang der Bucht von Dalimond und grenzt and die <i>"Sable Straits"</i> und <i>"Lesser-Aradoth"</i>. Die Stadt selbst dient als einer der Hauptfischerhäfen Istarias. 
		Die Fischerei spielt immernoch eine wichtige Rolle in der Wirtschaft der Stadt und viele der feineren Delikatessen des Meeres können häufig auf den Märkten Dalimonds gefunden werden.
		<br><br>
		Dalimond ist nun schon seit fast hundert Jahren die Hauptstadt der Menschen, nachdem die Herrscher des Vandus-Bündnisses Tazoon verlassen hatten, als die Stadt ihre Unabhängigkeit 
		als freier Stadtstaat erklärte.	Dalimond ähnelt in vielerlei Hinsichten dem Design von Tazoon, aber die Größe der Stadt ist bestenfalls ein Bruchteil der Größe Tazoons, insbesondere 
		nach der Ankunft der <a href="gnome.php">Gnome</a> und <a href="elfen.php">Elfen</a> als Flüchtlinge innerhalb der Stadtmauern Tazoons.<br><br>
		Dalimond ist auch eine der wichtigsten Verbindungen auf dem Landweg zu der Festung von Kion - einer <a href="saris.php">Saris'</a> Hochburg - sowie nach Sslanis, einer großen Siedlung 
		der <a href="sslik.php">Sslik</a>. Obwohl reger Handel zwischen den <a href="sslik.php">Sslik</a>, den <a href="saris.php">Saris</a> und den Menschen herrscht , ist dieser jedoch nicht 
		immer ganz einfach und ungefährlich. Obwohl die Horden der <i>"Withered Aegis"</i> größtenteils aus dieser Region vertrieben wurden gibt es dennoch ein paar vereinzelte Gebiete, in 
		denen man auf Untote treffen kann.<br><br>
