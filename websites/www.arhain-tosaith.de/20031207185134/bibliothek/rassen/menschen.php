		<td width='50%' height='440'>
		<p class='white'>
		Die Menschen von Istaria stellen wohl am besten dar, welches große Potential die lebenden Rassen haben. Sowohl bei der Verwirklichung einer Utopie, als auch 
		bei der Zerstörung ihrer eigenen Rassen.<br><br>
		Es ist der Selbstopferung eines Menschen zu verdanken, daß die lebenden Rassen von heute eine Chance im Kampf gegen die <i>"Withered Aegis"</i> bekamen. Es 
		war allerdings auch auch die Gier eines  einzelnen Menschen nach Macht, die die Welt an den Rande der Zerstörung brachte. Die Menschen repräsentieren die 
		Extreme der Zivilisation; die Unberechenbarkeit der Existenz die eine Vorraussage der Zukunft nahezu unmöglicht macht.<br><br>
		Menschen werden oft als Maßstab zum Vergleich mit anderen Rassen herangezogen. Sie sind ca. 6 Fuß groß, wobei Frauen jedoch ein wenig kleiner sind. Die 
		Muskulatur der Menschen ist durchschnittlich, jedoch haben sie die Möglichkeit, ihren Körperbau durch körperliche Ertüchtigung zu verbessern, so das er 
		muskulöser und leistungsfähiger wird. Menschen haben weiche Haut, die jedoch einen natürlichen Schutz vor den Elementen bietet. Menschen sind zweibeinig und 
		sind in der Lage, sich zu Fuß mit relativ hoher Geschwindigkeit fortzubewegen. Die "Kinder von Istara" - die Menschen - sind dazu fähig, auch in den lebensfeindlichsten 
		Regionen zu überleben und sich den Bedingungen der jeweiligen Region anzupassen.</p>
