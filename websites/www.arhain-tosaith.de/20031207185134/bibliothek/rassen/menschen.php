		<td width='50%' height='435'>
		<p class='white'>
		Als Istara - die Göttin der Schöpfung - Istaria erschuf (von ihr zu ihren Ehren so benannt), stellte sie fest, daß sie Wesen benötigen würde, die ihrem 
		Ziel zugeneigt waren: Die Erweiterung des <i>"Reichs der Dämmerung"</i>. Diese Wesen mussten in der Lage sein sich ohne ihren direkten Einfluß auch unter 
		den nachteiligsten Bedingungen entwickeln zu können. So wurde die Legende über die Schaffung der Menschen geboren. Es wird weithin angenommen, daß die 
		Menschen eine der ersten Rassen von Istaria waren, auch wenn einige andere Kulturen sich dazu entschlossen haben, diesen Punkt so wenig wie möglich 
		hervorzuheben.<br><br>
		Die meisten Legenden, die sich mit der Entstehungsgeschichte der anderen Rassen beschäftigen, weisen darauf hin, das diese von verschiedenen Gottheiten 
		erschaffen wurden; als Antwort auf Istara's Schöpfung der Menschen.<br><br>
		Menschen sind sozial veranlagt. Sie unterhalten gute Beziehungen zu den meisten anderen lebenden Rassen und haben kürzlich erst ein paar der Differenzen 
		zwischen ihnen und den <a href='fiends.php'>Fiends</a> behoben.</p>
