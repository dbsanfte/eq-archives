		<td><p class="header" align="center"><u>Allgemeines</u></p>
<p class="white">Das Ziel der Gilde ist in erster Linie Spaß am Spiel und das Zusammensein mit Freunden. Ebenso sind ein Grundstück/Gebäude und ein unabhängiges Produktionssystem 
geplant, um alle Waren innerhalb der Gilde herstellen zu können. Der Fokus der Gilde liegt bei den Tradeskills um andere Spieler (oder Gilden) mit weniger Ambitionen für die Tradeskills all das zu liefern,
was sie für ihre Streifzüge durch die Welt von Istaria benötigen. Trotzdem sind einige Regeln erforderlich, die das reibungslose Zusammenspiel innerhalb der Gilde ermöglichen sollen.<br><br>
Gildensprache: N/A<br>
Server: noch nicht bekannt<br>
Rassenbeschränkungen: N/A</p>

<p class="header" align="center"><u>Struktur der Gilde</u></p>
<p class="white">Die Gilde wird von einem Rat geleitet, der aus 3 Mitgliedern besteht. Dem Personalchef, dem Schatzmeister und dem Wirtschaftsminister. Der Gildenchef wird aus einem 
dieser 3 Posten bestimmt. Dies hat jedoch lediglich symbolischen Charakter, da der Gildenchef alleine keinerlei Entscheidungsfreiheit hat. Entscheidungen, die die 
gesamte Gilde betreffen, werden immer vom Rat gefällt. Unabhängig davon sind jedoch alle Anweisungen der Ratsmitglieder zu befolgen, da in der Regel davon ausgegangen 
werden kann, das diese zum Wohl der Gilde handeln. Kleinere Entscheidungen kann jedes Ratsmitglied in Eigenverantwortung treffen, ohne sich mit den anderen Ratsmitgliedern 
zu besprechen. Der Rat wird nicht gewählt und kann demnach auch nicht abgewählt werden. Änderungen in der Gildensatzung können nur vom Rat beschlossen werden. Alle 
Ratsmitglieder müssen der Änderung zustimmen. Stimmenenthaltungen sind nicht zulässig.</p>

<p class="white"><span class="menu"><u>Personalchef:</u></span>
Der Personalchef trifft Entscheidungen, die die Personallage der Gilde betreffen. Sein Aufgabenbereich umfasst unter anderem eine Vorauswahl der Personen, die für 
eine Aufnahme in die Gilde in Frage kommen und leitet dies and die anderen Ratsmitglieder weiter. Weiterhin kann er den Ausschluß eines Mitglieds aus der Gilde in die 
Wege leiten.</p>

<p class="white"><span class="menu"><u>Schatzmeister:</u></span>
Der Schatzmeister regelt die Geldverteilung innerhalb der Gilde. Ebenso verwaltet er die Schatzkammer und regelt den Verkauf bzw. die Verteilung der darin befindlichen 
Gegenstände. Der Schatzmeister legt die Höhe der Gildensteuer fest (näheres siehe Steuern).</p>

<p class="white"><span class="menu"><u>Wirtschaftsminister:</u></span>
Der Wirtschaftsminister leitet und steuert die Forschung bzw. Produktion innerhalb der Gilde. Er ist für die Beschaffung von Rohmaterialien für die Produktion von Waren 
verantwortlich (kaufen/sammeln). Gelder dafür kann er vom Schatzmeister beziehen.</p>

<p class="header" align="center"><u>Allgemeine Verhaltensregeln</u></p>
<ul><li class="green">Alle Gildenmitglieder haben sich so zu verhalten, das das Bild der Gilde in der Öffentlichkeit nicht geschädigt wird, d.h. keine Beleidigungen, rassistischen oder abwertenden 
Bemerkungen gegenüber anderen Spielern. Dabei spielt es keine Rolle, ob es sich um ein Gildenmitglied handelt oder nicht.<br><br></li>
<li class="green">Generelle Hilfsbereitschaft innerhalb der Gilde und gegenüber anderen Spielern hat Vorrang vor eigenen Wünschen und Interessen.<br><br></li>
<li class="green">Alle Gildenmitglieder haben sich an die Anweisungen des Rates zu halten. Ein Verstoß wird verwarnt, bei mehrmaliger Verwarnung erfolgt ein Ausschluß aus der Gilde.<br><br></li>
<li class="green">Alle Mitglieder haben sich regelmäßig (mind. 2x in der Woche) im Forum und auf der Homepage über Neuigkeiten oder Änderungen zu informieren.<br><br></li>
<li class="green">Jedes Mitglied der Gilde sollte regelmäßig spielen. Uns nützen keine Mitglieder, die nur 1 oder 2 Stunden pro Woche spielen. Das bringt Euch nicht weiter und die Gilde hat 
auch nichts davon.<br><br></li>
<li class="green">Bei längerer Abwesenheit eines Mitgliedes (bedingt durch RL etc.) sollte eine Nachricht im Forum hinterlassen werden.<br><br></li>
<li class="green">Gildeninterne Angelegenheiten sollten auch als solche behandelt und nicht an die Öffentlichkeit getragen werden.<br><br></li>
<li class="green">Mitgliedern der Gilde und Bewerbern ist es untersagt, Charaktere in anderen Gilden zu haben.<br><br></li>
<li class="green">Jedem Mitglied steht es frei, beliebig viele Zweitcharaktere zu besitzen, jedoch können diese nicht in die Gilde aufgenommen werden. Der Übersichtlichkeit halber ist nur ein Charakter 
pro Spieler in der Gilde erlaubt.<br><br></li>
<li class="green">Es ist untersagt Exploits oder Bugs im Spiel auszunutzen. Wer dabei erwischt wird, erhält eine Verwarnung. Zweimalige Verwarnung kann zum Ausschluß aus der Gilde führen. Bei schwereren 
Vergehen kann der sofortige Ausschluß erfolgen.</li></ul>

<p class="header" align="center"><u>Steuern</u></p>
<p class="white">Wie bereits oben erwähnt, liegt der Fokus der Gilde bei den Tradeskills. Ebenfalls ist ein eigenes Grundstück / Gebäude geplant. Da dies aber nicht ohne Geld verwirklicht werden kann, wird 
in der Gilde eine Steuer erhoben. Die Höhe der Steuer wird erst im Laufe der Zeit festgelegt, wird aber keinesfalls so hoch sein, das die Mitglieder die Steuer nur unter großen Anstrengungen 
entrichten können. Jedes Mitglied sollte jedoch bereit sein, das Gildenziel mit finaziellen Mitteln zu unterstützen.</p>

<p class="header" align="center"><u>Raids & Loot</u></p>
<ul><li class="green">Der Rat ist bestrebt, regelmäßig offizielle Raids (Gildenevents) zu veranstalten. Aktive Hilfe seitens der Gildenmitglieder ist dabei erwünscht.<br><br></li>
<li class="green">Bei offiziellen Raids entscheidet der Rat über die Verteilung der Beute. Gefundene Gegenstände werden an Gildenmitglieder nur für den Eigenbedarf verteilt. Loot wird NICHT verteilt 
zur persönlichen Bereicherung einzelner Gildenmitglieder.<br><br></li>
<li class="green">Geld, Edelsteine, Tradeskill-Items und sonstige nichtverteilte Gegenstände wandern in die Schatzkammer. Sollte ein Mitglied einen Gegenstand für etwas anderes als persönlichen Bedarf 
benötigen, so steht es ihm frei Gegenstände gegen einen gewissen Geldbetrag (je nach Art und Wert des Gegenstandes) aus der Schatzkammer zu kaufen.<br><br></li>
<li class="green">Auf inoffizielle Raids oder in kleinen Gruppen die nicht durch den Rat geleitet werden, erfolgt die Lootverteilung nach Ermessen der Gruppenmitglieder. Jedoch sollte darauf geachtet 
werden, das Tradeskill-Items nach Möglichkeit zuerst an die Gilde weitergegeben werden.</li></ul>

<p class="header" align="center"><u>Tradeskills</u></p>
<p class="white">Jedes Mitglied sollte sich auf einen Tradeskill spezialisieren und sich ggf. mit anderen Mitglieder absprechen. Das hat den Vorteil, das die Vielfalt an Tradeskills innerhalb der Gilde gegeben 
ist. Der Support von 1 oder 2 Personen in einem Tradeskillgebiet bringt mehr, als wenn viele Mitglieder in ein und dem selben Skill unterstützt werden müssen. Zum Support der Tradeskills werden 
Teile der Steuer verwendet und , soweit vorhanden, Tradeskill-Items aus der Schatzkammer. Die so hergestellten Items werden als erstes für den Eigenbedarf innerhalb der Gilde eingesetzt. Bei 
Überschuß werden die Gegenstände außerhalb der Gilde verkauft. Das so gewonnene Geld wird zum Großteil wieder in den Support der Tradeskills investiert.</p>

<p class="header" align="center"><u>Bewerbung</u></p>
<ul><li class="green">Man kann sich nur bewerben, wenn man die aktuellen Anforderungen erfüllt. Diese können je nach Bedarf vom Rat geändert werden.<br><br></li>
<li class="green">Der Bewerber sollte die Gildensatzung gelesen und verstanden haben. Nur wenn er allen Punkten zustimmt sollte er eine Bewerbung in Betracht ziehen.<br><br></li>
<li class="green">Weiterhin ist ein Fürsprecher von großem Vorteil. Allerdings ist dies noch keine Garantie das man auch tatsächlich in die Gilde aufgenommen wird.<br><br></li>
<li class="green">Als nächstes folgt die formelle Bewerbung durch Ausfüllen des Bewerbungsbogens auf der Homepage. Darin enthalten sind einige Fragen zur Person selbst, Erwartungen an die Gilde, bisherige Erfahrungen 
mit MMORPG's , Spielzeit usw.<br><br></li>
<li class="green">Sobald das Bewerbungsschreiben eingegangen ist, wird es durch den Personalchef vorausgewertet und ggf. and die anderen Ratsmitglieder weitergeleitet. Je nach Bedarf erfolgt danach ein Gespräch 
zwischen einem Ratsmitglied und dem Bewerber.<br><br></li>
<li class="green">Sobald die Ratsmitglieder zugestimmt haben, durchläuft der Bewerber eine Probezeit. Während dieser Zeit sollte der Bewerber möglichst an allen Gildenveranstaltungen teilnehmen.<br><br></li>
<li class="green">Je nach Onlinezeit des Bewerbers kann die Probezeit variieren, beträgt jedoch mindestens 2 Wochen. Reicht die Probezeit nicht aus, um den Bewerber beurteilen zu können, wird durch den Rat ggf. 
eine Verlängerung festgelegt.<br><br></li>
<li class="green">Während der Probezeit besteht kein Anrecht auf Loot das auf Gildenevents gefunden wurde. (Ausnahme: Kauf aus der Schatzkammer). Mitglieder auf Probezeit besitzen zudem kein Stimmrecht bei Wahlen.<br><br></li>
<li class="green">Nach Ablauf der Probezeit erfolgt eine Abstimmung aller Gildenmitglieder. Erreicht der Bewerber mindestens 75% der Stimmen, wird er als vollwertiges Mitglied (mit allen Rechten und Pflichten) in die 
Gilde aufgenommen.<br><br></li>
<li class="green">Erreicht der Bewerber weniger als 75% der Stimmen, gilt seine Bewerbung als abgelehnt. Er kann sich jedoch zu einem späteren Zeitpunkt neu bewerben, frühestens aber nach Ablauf einer Frist von 4 Wochen.</li></ul>

<p class="header" align="center"><u>Ausscheiden aus der Gilde</u></p>
<p class="white">Das Ausscheiden aus der Gilde erfolgt nach zweimaliger Abmahnung eines Mitgliedes durch den Rat. Natürlich steht es jedem Mitglied frei, die Gilde aus eigenem Antrieb zu verlassen. Beim Verlassen der 
Gilde, ob nun aus eigenem Antrieb oder durch Ausschluß durch den Rat, erlischt jeder Anspruch auf Unterstützung durch die Gilde (Nutzung von Gebäuden, Support bei Tradeskills etc.). Eventuell gezahlte Steuern 
des Mitgliedes gehen in den Besitz der Gilde über. Während der Migliedschaft erhaltene Gegenstände bleiben im Besitz des Spielers (Ausnahme: von der Gilde geliehene Gegenstände).</p>
