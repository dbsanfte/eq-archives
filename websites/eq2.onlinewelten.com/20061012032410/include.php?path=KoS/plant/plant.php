<u>Was soll ich füttern?</u><br><br>
Es gibt 3 Arten von Futter für die Pflanze: Wasser, Dünger und Knochen. Das Futter gibt es nicht beim NPC zu kaufen, sondern
es muss von Mobs gelootet werden. Alle intelligenten Wesen (keine Tiere, das sind auch die von denen man die Status Loots
bekommt) können diese Gegenstände fallen lassen. Wie bei vielen Gegenständen gibt es auch beim Futter unterschiedliche
Qualitätsstufen. Diese ist abhängig vom Level der Mobs von denen man das Futter erkämpf hat.
Die Qualitätsstufe des Futters wirkt sich lediglich auf eine der möglichen Belohnungen durch eure Pflanze aus. Betroffen ist
die "Frische Frucht" (fresh fruit). Die Stufe der Frucht wird auf die geringste Stufe des verabreichten Futters angepasst.
<br><br>
<u>Woran erkenne ich das Futter?</u><br><br>
Der Deutsch-Englisch Mix macht es nach wie vor schwerer für Leute, welche weniger gute Englisch Kentnisse haben. Da das Futter
und dessen Beschreibungen nach wie vor in Englisch sind kann es hier zu Schwierigkeiten kommen. Die Folgende Übersicht hilft
vielleicht dabei. Ein erstes Indiz findet man in der Gegenstandsbeschreibung. Dort steht am Anfang immer
"looted fertilizer treasure" wenn es sich um Futter für die Pflanze handelt. <br>
Wie bereits erwähnt gibt es für jede Qualitätstufe (allg. <i>Tier</i>) auch unterschiedliches Futter. Diese tragen auch
unterschiedliche Namen. Im folgenden sind diese Namen aufgelistet (Reihenfolge: Dünger, Wasser, Knochen).<br><br>
<ul>
  <li>T2 (Lvl 10-19): pouch of peat, flask of rancid water, small decaying bone</li>
  <li>T3 (Lvl 20-29): small bag of ammonium sulphate, flask of stale water, large decaying bone</li>
  <li>T4 (Lvl 30-39): small bag of muriate of potash, flask of pond water, small polished bone</li>
  <li>T5 (Lvl 40-49): small bag of diatomaceous earth, flask of fresh water, large polished bone</li>
  <li>T6 (Lvl 50-59): small bag of ammonium nitrate, flask of pure water, small meaty bone</li>

  <li>T7 (Lvl 60-69) small bag of guano, flask of aerated water, meaty bone</li>
  <li>T8 (Lvl 70): small bag of compost, flask of enchanted water, large meaty bone</li>
</ul>
