<u>Wie füttere ich meine Pflanze?</u> <br><br>
Zuerst einmal musst du deine Pflanze in deinem Haus platzieren. Also einfach in deine Wohnung gehen, rechtsklick auf die
Pflanze in deinem Inventar und Platzieren wählen. Wenn dein neuer Raumverschönerer nun bereit steht oder auch geht (ja laufen
kann dieses Exemplar auch noch!), wird es Zeit zum Füttern. Du musst das Futter dazu nicht einmal bei dir haben. Es reicht
wenn es auf deiner Bank liegt. Mit Rechtsklick auf deine Pflanze öffnet sich nun das Kontextmenü. Dort findest du unter
anderem die hier relevanten Einträge:<br>
"Feed Bones" = Einen Knochen füttern     <br>
"Fertilize" = Dünger verabreichen        <br>
"Water" = Bewässern               <br>
"Check Soil" = Deine Belohnung ernten <br>
Es ist völlig unwichtig in welcher Reihenfolge du welches Futter verabreichst. Es muss noch nicht mal deine eigenen Pflanze
ein. Das heisst du kannst in jedem Haus wo so eine Pflanze steht Gärtner spielen (Ob KoS installiert sein muss ist mir unklar.
Wenn das jemand ohne die Erweiterung geprüft hat kann er mir eine Mail schreiben:
<a href="mailto:Legor@onlinewelten.com">Legor@onlinewelten.com</a>)<br><br>

<u>Was passiert wenn ich die Pflanze falsch füttere?</u> <br><br>
Wenn du Glück hast erhältst du noch eine Frische Frucht. Es gibt mehrere Kombinationen, welche eine solche Frucht hervorbringen
können. Solltest du allerdings Pech haben so erhältst du nur eine verrottete Frucht (rotten fruit). Diese kannst du gleich wieder
zerstören. Sie hat keinen Nutzen und kann weder verkauft noch recycled werden. <br>
Oberstes Gebot eine guten Gärtners: Immer schön mitzählen! <br><br>

<u>Womit belohnt mich meine Pflanze?</u><br>
Kommen wir nun zum interessantesten Teil der Pflanzenzucht. Der Lohn für die harte Arbeit und aufopfernde Liebe deinem
grünen Freund gegenüber. In der folgenden Tabelle ist genau aufgeführt wieviel von jeder Futterart du verabreichen musst
um die dazugehörige Belohnung zu erhalten. Nochmal zu Erinnerung: Ausser für die Frische Frucht ist es völlig ohne belange
von welcher Qualität das Futter ist welches du nimmst. Es kommt hierbei nur auf den Level des Gärtners an. Alle Wurzeln die man ernten
kann sind jeweils 1 mal anwendbar und können nicht gestapelt werden.


