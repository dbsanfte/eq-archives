<p>Qeynos ist eine wohltätige Stadt, die seine Arme jenen geöffnet hat, die 
bereit sind für eine gute Gesellschaft einzustehen und die zerstörten Länder 
von Norrath von allem Übel reinigen wollen. Als Leuchtfeuer von Stärke und guter 
Gesinnung haben gute die guten Rassen von Norrath Unterkunft und Schutz unter 
der Obhut von Antonia Bayle gesucht.Dem tapferen Herrscher über das Königreich 
von Qeynossteht der Kreis der Fünf zur Seite, ein Rat gebildet die aus den Führern 
der fünf Hauptparteien der Stadt. </p>
<p><b>The Qeynos Guard - Military Guardians </b></p>
<p>Die Militärstreitkräfte der Qeynos Wache sind in vier Abteilungen unterteilt, 
deren Kommandanten einem einzelnen General berichten. Die vier Abteilungen sind 
die Stadtwache, die Turmwache, die Qeynos Marine und die Outland Brigade. Der 
General bekommt Aufträge vom Kreis der Fünf, dem regierenden Rat der Stadt. 
Die Soldaten bekommen ihre Ausbildung durch die Stahlkrieger ( Stell Warriors) 
oder vom Orden des Lebens (Order of Life).</p>
<p><b>The Celestial Watch - Defenders of the Divine </b></p>
<p>Die Celestial Watch ist eine fromme Gesellschaft, die von den Schülern der 
jetzt abwesenden Götter der Güte und des Lichtes gebildet wird. Dieser Orden 
ehrt alle guten Gottheiten und ist eine extrem geistige Versammlung. Mitglieder 
überwachen den Himmel auf die Rückkehr ihrer Götter. Sie beten dafür das die 
alten Gottheiten nicht für immer gegangen sind. Die Celestial Watch ist eine 
selbstlose Organisation, die für das körperliche und geistige Wohl der guten 
Leute des Königreiches von Qeynos einsteht. Sie übernehmen manchmal missionarische 
Kreuzzüge zu entfernten Ländern, um das Wort der Rechtschaffenen zu verbreiten.</p>
<p><b>The Concordium - Masters of the Arcane </b></p>
<p>Das Concordium ist eine wohltätige Gesellschaft der Magier, die sich dem 
verbreiten des positiven Einflüsse der geheimnisvollen Künste über Norrath verschworen 
haben. Seine Mitglieder lieben es die Leute von Qeynos zu unterhalten. Sie sind 
bekannt dafür ihre magischen Fähigkeiten, in den Ländern die sie bereisen, zu 
demonstrieren. Obwohl sie die gute Seite der Magie ausüben sind sie extrem starke 
Magier, die zu unermesslich zerstörender Energie fähig sind. Der Auftrag des 
Concordiums liegt darin, das in den zertrümmerten Ländern verloren gegangene 
und geheimnisvolle Wissen zu erwerben und zu schützen. Sollten sie versagen, 
wird es mit hoher Wahrscheinlichkeit in die Hände des Bösen fallen.</p>
<p><b>The Tunarian Alliance - The Silent Sentinels </b></p>
<p>Das Bündnis Tunares stellt die Vereinheitlichung von Druiden, Scouts und 
von allen Waldbewohnern der zerbrochenen Ländern dar. Seine Mitglieder folgen 
den Gesetzen Tunares, den Prinzipien basierend auf der Lehre der Göttin des 
Wachstums. Mitglieder des Bündnisses sind die Verteidiger der Waldlande und 
häufig führen sie patrouillen über die Rändern der Zivilisation hinaus durch. 
Ihre Fähigkeit der Tarnung und risikobereitschaft in das gefährliche Randgebiet 
der bekannten Welt zu reisen haben sie zu erfahrene Spionen und Beobachter gemacht. 
</p>
<p><b>The Ironforge Exchange - Chiefs of Commerce </b></p>
<p>Der Ironforge Exchange besteht aus den Handwerkern und Kaufleuten die Läden 
innerhalb der Stadt von Qeynos besitzen. Der Leiter des Ironforge Exchange ist 
ein Mitglied des Kreises der Fünf und an ihm wird von den Handelsmeistern des 
Hafenbezirks und den Ackerländern berichtet. Die Kaufleute von Qeynos sind immer 
bereit, ihre Kräfte zum Wohle des Reiches oder seinem Volk zu geben. Sie arbeiten 
häufig mit den anderen Parteien in Qeynos zusammen und sind sogar bekannt dafür, 
ein finanzieller Verlust hinzunehmen, wenn ihr handeln dem Wohle des Volkes 
dient. Kein Gewinn ist mehr wert als der Wohlstand von allen Bürgern Antonicas.</p>
<p align="center"><b><u><span style="font-size:12pt;">Eine Neue Welt erwartet Euch !</span></u></b></p>
<p>Die Zeit der Entscheidung ist gekommen. Unterstütze Lucans Träume der Herrschaft 
und Eroberung, oder stehe für Qeynos als Licht gegen die Dunkelheit ein !</p>
<p>Unzählige Abenteuer warten und zahlreiche Fragen müssen beantwortet werden. 
Was verursachte die Zerstörung von Luclin? Sind die Götter wirklich gegangen? 
Welche gefährlichen neuen Gebiete liegen hinter dem turbulenten Meer?</p>
<p>Aus dem Schatten heraus beobachten mysteriöse Gewalten und warten auf Euch. 
Und nun ist die Zeit gekommen in angesicht Antonicas zu stehen und neue Abenteuer 
zu bestehen. Für wessen Sache tretet ihr ein? Welche Geheimnisse werdet ihr 
aufdecken?</p>
<p>Es liegt an Euch die die Zukunft von Norrath zu kontrollieren. </p>
<p><b><span style="font-size:12pt;">Es ist der Morgen eines neuen Zeitalters: Das Zeitalters des Schicksals, 
The Age of Destiny.</span></b></p>
