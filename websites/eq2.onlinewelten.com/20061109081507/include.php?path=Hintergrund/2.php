<p>Die verdorbene Stadt Freeport verbleibt im unvergänglichen Griff seines unsterblichen 
Herren, Lucan D'Lere. Mit der Hilfe seiner Lucanic Ritter, überwacht und manipuliert 
D'Lere die Stadt und seine regierenden Parteien, um seinen Einfluß und seine Herrschaft 
über Freeport auszubauen. Die Bösen Rassen, heimatlos durch die Zerrüttung, 
bilden jetzt ihre Heimat innerhalb der Stadtwände. Die fünf stärksten Parteien 
von Freeport fechten alle um ihre eigene Macht, darauf bedacht ihr bestes zu 
geben, dem dunklen Willen des gnadenlosen Lucan zu beschwichtigen. </p>
<p><b>The Freeport Militia - Military Might </b></p>
<p>Die Freeport Miliz ist die defensive Hauptstreitkraft der Stadt. Sie besteht 
aus Söldnern, Schurken und Raufbolden aus ganz Norrath. Seine Reihen bestehen 
meistens aus Rekruten von den lokalen Kriegerzünften, von den Tavernen und von 
den Grengebieten. Die meisten Milizmitglieder sind Kämpferarten, aber bestimmte 
fachkundige Einheiten umfassen auch andere Klassen. Die Miliz hat eine lange 
Geschichte von Korruption und Brutalitäten. Sie behält immer noch dieses Verhalten 
bei, aber ist eine organisierte und leistungsfähigere kämpfende Kraft, 
- einmal mehr passend für die große Geschäftsstadt von Freeport geworden. Es 
ist eine in hohem Grade erfahrene und organisierte Armee im jetzigem Zustand 
und eine der leistungsfähigsten kämpfenden Kräfte im Angesicht Norrath. Diese 
Organisation wird nicht an irgendeiner Gottheit oder geistigen Lehren gebunden. 
Lucan selbst schuf die Miliz einst und hält seine Hand schützend über sie.</p>
<p><b>The Dismal Rage - Heralds of the Divine </b></p>
<p>Die Dismal Rage ist eine dunkle, finstere Ordnung, die alle bösen Gottheiten 
anbetet. Innerhalb dieser einzelnen Parteien können eine Menge fromme Kasten 
und Glaubensrichtungen gefunden werden, stark miteinander verbunden durch ihre 
dunklen Ziele. Diese Ordnung wird auf einer strengen Lehre aufgebaut, die sich 
begründet sieht in dem Wälzer Pakt des Verfluchten, der gerüchteweise von der 
Ebene des Wissens (Plane of Knowledge) gestohlen worden ist. Diese Organisation 
ist tief geistig und heimtückisch Übel. Priester und Kreuzritter sind mit Dismal 
Rage am häufigsten verbunden, aber andere Klassen werden auch innerhalb seiner 
Reihen gefunden. Hass und das Leiden sind die Antriebskräfte dieser Organisation, 
deren Wille es ist, den Glauben zurück in eine Welt zu holen, die scheinbar 
von den Alten Göttern verlassen worden ist. </p>
<p><b>The Arcane Scientists - Keepers of the Arcane </b></p>
<p>Dieser alte Orden war einst lediglich der Magie gewidmet, aber es ist seitdem 
zu einer massiven Ansammlung von geheimnisvollem Wissen und Artefakten geworden. 
Seine Mitglieder sind emotionslos und stellen die Suche nach Wissen allem voran. 
Seine Wurzeln liegen in einer blutgetränkten, auf dem Massaker aller guten Mitglieder 
der Akademie und der Einführung der schwarzen Künste gegründeten, Vergangenheit. 
Jeder Freeport Bürger, der glaubt, dass er dazu fähig ist, die Eingangsprüfung 
zu bestehen, kann versuchen sich der Gesellschaft anzuschließen. Nach Aufnahme 
muß das neue Mitglied zusichern den Orden durch Forschung, und durch Suche von 
verlorenen geheimnisvollen Artefakten und Wissen, zu unterstützen. Kein Erbarmen 
wird demjenigen gegenüber gegeben der in irgendeiner Weise bei dem Erwerb dieser 
mystischen Energie im Wege steht, und keine Reue wird gezeigt für die Leben 
die geopfert werden müssen, um die Arkane Dominanz der Wissenschaftler zu erweitern. 
</p>
<p><b>The Seafury Buccaneers - Traders of Intelligence </b></p>
<p>Eine Piraten Organisation, die in der Stadt Freeport, von Seeräubern, Geächteten 
und Schurken der hohen Meere gegründet wurde. Diese unangenehmen Leute finden 
es rentabel, bei der Verteidigung Freeports zu helfen, indem die Miliz sie mit 
Informationen feindlicher Schiffe versieht, und ihnen das meiste von dem lässt, 
was sie plündern. Die Seeräuber verstehen sich eher als Piraten als eine respektable 
Marinekraft. Sie versenken und kommandieren die Schiffe und tun dies unter dem 
Schutz von Lucan und den bösartigen Gesetzen von Freeport. </p>
<p><b>The Coalition of Tradesfolke - Commanders of Commerce </b></p>
<p>Diese Koalition ist der inoffizielle Vorstand aller Geschäftstätigkeiten 
innerhalb der Mauern von Freeport, einschließlich aller Satellitengemeinschaften, 
die immer stärker am Rande des Reiches aufkeimen. Die Koalition ist in Wirklichkeit 
ein in hohem Grade organisiertes Verbrechensyndikat und die gefährlichste Partei 
in Freeport. Ein unnachgiebiges Kartell, die alles daran setzen den regionalen 
Handel zu monopolisieren. Es ist eine Hauptkraft im Weltmarkt und ist berüchtigt 
für das Beseitigen jeder möglichen Konkurrenz, auf jegliche Art, mit ökonomischen 
Mitteln oder durch blosse Brutalität. Die Koalition verwendet eine unterschiedliche 
Armee aus Schlägern und Söldnern der verschiedenen Kategorien, um den globalen 
Markt zu seinen Gunsten zu manipulieren. </p>
<p align="center"><b><u><span style="font-size:12pt;">Qeynos </span></u></b></p>
<table align="center" cellpadding="0" cellspacing="0">
