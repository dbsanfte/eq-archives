	<font class=contenttext>Nachdem Scott Hartsman einen langen, mit wenig konkreten Informationen bestückten, "Producers Letter" an die Community richtet, tauchten nun genaue Infos zu kommenden Änderungen auf. <br />
Auch über das Weihnachten in Norrath  - Frostfell - sagte Hartsman, dass man 15 Tage lang Geschenke bekommt. So hat man am Ende 15 kleine Geschenke, die man auch behalten darf! <br />
<table class="quote" width="98%" cellpadding="4" cellspacing="1" align="center"><tr><td class="quote"><b>Zitat</b><br /><font class="quote">Make sure to take part! If you look around in town and talk to the right person, there's a different Frostfell gift for you every day you log in. (Fifteen gifts, and you can collect them all.)</font></td></tr></table><br /><br />
