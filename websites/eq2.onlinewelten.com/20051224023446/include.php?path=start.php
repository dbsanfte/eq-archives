PvP war bisher ein umstrittenes Thema, welches SOE bisher auch kaum ins Spiel impletierte. Lediglich Duelle im Freien mit Ablehnungsoption, oder Gruppenkämpfe in den Arenen von Maj´Dul waren bisher möglich. Vor ein paar Wochen, wurde bereits eine Umfrage gemacht, was denn die Spieler am liebsten für PvP hätten. Dabei kam raus, dass die meisten sich über spezielle PvP Server mit klarem Reglement freuen würden. Genau dies wird SOE nun auch durchziehen. Geplant sind 2 Server, wobei bei einem die Möglichkeit besteht einen Charakter auf ihn zu transferieren, beim anderen geht dies nicht. <br />
<b>Wie wird das PvP dann aussehen?</b><br />
Gut gegen Böse - das soll das neue Konzept sein auf den 2 speziellen PvP Server. Man kann nur mit Spielern aus der eigenen Stadt in den Kampf gegen die Feinde ziehen. Um ein faires PvP zu schaffen kündigte Hartsman an, nichts am PvE- (Player vs. Enemy)system zu ändern, sondern ein besonderes PvP Kampfsystem zu schaffen. Besonders schwer könnten es hierbei Verräter haben. In der Zeit, wo man keine Stadtangehörigkeit hat, ist man sozusagen Freiwild und kann von Qeynos- und Freihafenbewohnern getötet werden. <br />
Für ein faires Spiel wird eine Art Ehrensystem mit ehrenhafte, neutralen und unehrenhaften Siegen eingeführt. Auch Belohnungen wird es für die erfolgreiche Schlacht geben, kündigt Hartsman an. Es wird Statuspunkte und Faction bei der PvP-Fraktion geben und man kann sich durch viele Siege sogar Items kaufen. Der Senior Producer versprach hier, dass diese keinesfalls nur Staubfänger in der Wohnung werden, sondern nützliche Items, die man gebrauchen kann, sein werden. Sogar XP soll es geben bei den Spieler gegen Spieler Kämpfen. Hier betonte er, dass sie hart daran arbeiten das sog. "friend farming" weitesgehend zu unterbinden. D.h., dass sich beispielsweise Freund A von Freund B solange töten lässt, bis B sein Levelup erreicht hat. <br />
<b>Nun ist ein Warlock von Anfang an Warlock, und ein Illu ein Illu!</b><br />
Das bisherige System, dass man sich auf der Anfängerinsel vorerst zwischen Kämpfer, Magier, Priester und Kundschafter entscheidet, fällt weg. Man kann sich nun sofort seine Klasse aussuchen, also gibt es keine Klassenquests mehr. Unter anderem begründet er es mit dem Beispiel des Magiers, da die Klassen, die man mit Level 20 belegen kann allesamt sehr unterschiedlich sind. <br />
<table class="quote" width="98%" cellpadding="4" cellspacing="1" align="center"><tr><td class="quote"><b>Zitat</b><br /><font class="quote">The best example of this is the Mage archetype. The generic Mage is an excellent introductory class if you plan on eventually becoming a Wizard or Warlock. Coercer, Conjurer, Illusionist and Necromancer gameplay ends up being drastically different. The pet classes are very much about cool pets later on, as their direct-damage spells end up being less of the overall play. Likewise, the control classes of Illusionist and Coercer become much more focused on controlling enemies and empowering their allies, as opposed to inflicting direct damage.<br />
<br />
</font></td></tr></table><br /><br />
Spells und Fertigkeiten sollen während der Level 1-20 mehr die gewählte Klasse charakterisieren. Die Änderungen am Klassensystem wurden für Mitte bis Ende Januar angekündigt.<br />
Es gibt viel darüber zu reden und zu diskutieren, denn es handelt sich doch um umstrittene Themen, wonach die deutschsprachigen Spieler irgendwie gar nicht gefragt wurden. Jeder hat sicher eine eigene Meinung dazu, dafür könnt ihr gern <a target="_blank" href="http://forum.onlinewelten.com/showthread.php?p=596222#post596222">unser Forum</a> nutzen. <br />
