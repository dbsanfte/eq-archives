<br />
Änderungen werden durch die Entwicklung von EverQuest II etwas sein das ständig auftritt. Wir haben weitere spannende Änderungen für unsere Charaktermodelle im nächsten Jahr geplant und freuen uns euch die dann präsentieren zu dürfen.<br />
