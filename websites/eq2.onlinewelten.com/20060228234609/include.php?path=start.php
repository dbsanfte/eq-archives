	<font class=contenttext>Eine Frage beschäftigt gerade wohl viele Spieler: Wann kann man endlich das neue AddOn spielen?<br />
Erinnern wir uns..im späten Sommer erschien die erste Erweiterung, genannt Desert of Flames. Und wer erinnert sich nicht an die endlosen Wartezeiten bis man wieder vernünftig ohne Lag und ohne Bug spielen konnte? Wird das wieder so sein?<br />
Die Zeit, ab der man wieder spielen kann, ist laut SOE 23 Uhr. Erst dann soll es möglich sein die Patches für KoS und LU20 runterzuladen. Ob diese Zeit eingehalten werden kann? <br />
Da keiner der GMs auf unsere Anfragen antwortet, ob die ETA sich nach hinten verschiebt, müssen wir wohl oder übel mal das übernehmen, was im Banner des Live-Chats steht: <br />
<br />
<table class="quote" width="98%" cellpadding="4" cellspacing="1" align="center"><tr><td class="quote"><b>Zitat</b><br /><font class="quote">Alle Server sind down. Es wird gerade LU20 und Kingdom of Sky auf den Server geladen. ETA ist 23 Uhr MEZ. Bis dahin kann man KoS nicht runterladen!</font></td></tr></table><br /><br />
<br />
Okay, was macht ihr so, bis ihr wieder spielen könnt und wann vermutet ihr, dass man überhaupt vernünftig zocken kann?</font>
	
