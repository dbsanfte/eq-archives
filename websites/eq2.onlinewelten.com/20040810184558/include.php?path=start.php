<br><br><br><br />
<table class="quote" width="98%" cellpadding="4" cellspacing="1" align="center"><tr><td class="quote"><b>Zitat</b><br /><font class="quote"><br />
Zum Start des Spiels wird es bzgl. des Gilden-Managements noch einige Limitierungen geben, die aber mittelfristig aufgehoben werden. <br />
<br />
Zu Beginn gibt es für jede Gilde vier feste Ränge (Leader, Officer, Member und Initiate). Es wird aber später die Möglichkeit geben individuelle Ränge festzulegen.<br />
<br />
Innerhalb einer Gilde hat man ferner 2 unterschiedliche Subtypen (Patron und Follower), deren Unterschiede sich wie folgt bemerkbar machen:<br />
Ein Patron ist ein aktives Mitglied der Gilde und wenn dieses in seinem persönlichen Ansehen steigt, so steigt auch das Ansehen der Gilde. Follower hingegen steigern nur ihr persönliches Ansehen und haben keinen Einfuß auf das Ansehen der Gilde. Desweiteren besteht die Möglichkeit zu wählen wer Patron und wer Follower ist. Laut den Entwickler ist es aber sinnig ca. 12 – 36 Patrons in der Gilde zu haben.<br />
<br />
Das persönliche Ansehen und das Gilden-Ansehen ist in sofern wichtig, da es spezielle Händler gibt bei denen man sein Ansehen quasi einlösen kann. So ist es dadurch erst möglich größere Häuser, Mounts und Gildenhallen zu erwerben.<br />
<br />
Falls ein Patron eine Gilde verlassen sollte, so verfallen auch die Punkte, die er für die Gilde erarbeitet hat. Sein persönliches Ansehen bleibt davon allerdings unberührt.<br />
