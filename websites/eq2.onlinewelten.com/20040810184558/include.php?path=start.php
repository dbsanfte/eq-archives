	<font class=contenttext><a target="_blank" href="http://www.gamespy.com">Gamespy</a>  hatte Gelegenheit die Aktuelle Version von EQ2 zu spielen. Ihre Eindrücke habe ich für euch übersetzt und wünsche viel Spass beim lesen.<br />
<br />
<b>Was ist Neu?</b><br />
<br />
Seit unserem letzen besuch in Norrath, hat sich so einiges geändert. Die Beta sieht nicht mehr aus wie eine Beta, die Icons sind fertig gezeichnet und alles ist an seinem Platz. Das Interface nähert sich seinem endgültigem Aussehen und das wichtigste, das Spiel läuft jetzt viel flüssiger „selbst mit allen möglichen Details“ für ein noch intensiveres Spielgefühl . Die langen Optimierungen zahlen sich wirklich aus.<br />
<br />
Die grössten Änderungen jedoch finden wir im Content Bereich. Es gibt Tonnenweise davon,<br />
sie haben sich extrem ins Zeug gelegt. Zonen die wir früher besuchten, sind jetzt vollgepackt mit NPCs um mit euch zu sprechen und das alles mit richtiger Sprachausgabe! Viele von diesen wurden dort „postiert“ um etwas mehr leben in die Umgebung zu bringen. Einige zum Beispiel sind richtig „hysterisch“….(„Kannst du mich nicht einfach zurück ins Wasser werfen“) quiekt ein kleiner Rotanga auf der Anfängerinsel (Isle of Refuge), umzingelt von ein paar bösen Monster. („Ich habe nirgends Unterschrieben für so was“)….fiept er ohrenbetäubend weiter.<br />
<br />
Mit der Zeit wenn sich das Spiel der Vollendung nähert, werden Städte nur so sprudeln vor „Leben“, gefüllt mit verschiedenen Charakteren und Persönlichkeiten, anzutreffen kann man diese in jeder Gasse.<br />
Wichtiger noch ist die Tatsache, dass die Quests sehr individuell aufgebaut sind. So kann eine Unterhaltung mit Fremden auf der Straße womöglich eine Anzahl von Geheimnissen bergen, die es einem ermöglicht Lösungen für diese Quest zu bekommen oder auch ganz andere „mysteriöse“ Ansätze ergeben. Selbst durch eure Aktionen im Spiel, kann sich eine neue Quest entwickeln. Während der Demo, stand ich am Strand und hob eine Muschel auf, in dem Moment popte ein kleines Fenster auf und ich wurde gefragt, ob ich die „Meermuschel Kollektion“ Quest machen wolle. Man bekommt jetzt auch Erfahrungspunkte bei entdecken von coolen Locations/Ortschaften, genau wie in World of Warcraft. Sollte das gesamte Spiel eine solche Dichte an Quests bieten, ist es schwer sich vorzustellen dass es den Spielern langweilig werden kann. All dies zeigt uns, das es den Entwicklern sehr am Herzen liegt das die Spieler immer etwas zu tun haben und nicht nur Monster „campen“ um an den Loot zu kommen.<br />
<br />
Neue Interfaces sind an ihrem Platz um dem Spieler die Navigation zu erleichtern. Ein neues Waypoint-Fenster ist jetzt verfügbar, welches einem erlaubt einen gewissen Punkt auf der Karte zu markieren. So zum Beispiel ein wichtiges Gebäude, einen Shop oder einen NPC der erst kürzlich mit einem gesprochen hat. Ein leuchtender Strich wird am Boden erscheinen und euch den Weg bis zum Ziel weisen. Praktisch!<br />
<br />
Als wir EverQuestII das letzte mal sahen, war das Craften „Handwerk“ noch nicht implementiert. Im jetzigen Stadium der Entwicklung ist es drinnen und funktioniert zumindest mit den Grundfunktionen. Während man die Gegend erkundschaftet, finden man Rohmaterial überall verteilt. Im Moment ist es noch so, das die Materialien die abgebaut werden können, leuchten und blinken und so leichter gefunden werden. Diese Rohmaterialien bringt man dann zu einer Art Werkbank....in diesem Falle eine Schmiede oder ein Webstuhl. Jetzt fängt man an die Rezepte oder Baupläne ein zu setzen. Der ganze Vorgang geht recht schnell von der Hand (wenn man sich für einen Gegenstand entschieden hat den man herstellen möchte, werden die Zutaten automatisch dafür abgezogen). Es ist ein „interaktiver“ Prozess, genau so wie etwa ein Kampf. Wenn dein Charakter anfängt auf dem Ambos rum zu hämmern, fliegen die Funken und eine Statusleiste zeigt den Fortschritt wie weit man noch von dem fertigen Produkt entfernt ist. Wie auch immer, dieses ist noch nicht im Spiel zu finden, möglicherweise werden kleine Minispielchen die Aufmerksamkeit des Handwerkers erfordern, und mit bestehen dieser, die Qualität des Gegenstandes drastisch erhöhen…oder aber total zu ruinieren ;)<br />
Bis zur Fertigstellung von EQII, wird es möglich sein seine eigene Schmiede zu kaufen, sie in das eigene Haus zu stellen und sogar seine Freunde daran arbeiten zu lassen.<br />
<br />
Zum Thema Spielerhaus, jedes mal wenn wir diese sehen, werden neue Optionen eingebaut. Während des Tests konnten wir ein Zimmer mit kompletter Möblierung umstellen. Gegenstände können an Wände gehängt werden, man kann sie übereinander stellen (Blumen auf einen Tisch) ganz genau so wie man es haben möchte. Das ganze sieht einfach nur klasse aus!<br />
<br />
Das Entwicklerteam spricht immer noch von einer zu 70%-igen Fertigstellung des Spieles.<br />
Die restlichen 30% sind überwiegend Content „Spielinhalt“ ! Jetzt da das eigentliche Spiel fertig ist und läuft, können die Entwickler die ganzen Geschichten und Quests einfügen die sie so lange geplant und geschrieben haben. Die einzelnen Fragmente setzen sich langsam aber sicher zu einem Meisterstück zusammen.<br />
<br />
Haltet euch bereit für noch mehr EQII Details!<br />
