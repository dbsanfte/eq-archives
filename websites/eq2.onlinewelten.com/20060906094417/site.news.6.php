<br />
*** Crafter Aufträge***<br />
<br />
-	Erfreuliches für Handwerker! Neue Handwerksaufträge wurden eingeführt.<br />
-	Diese Aufträge können ab Subklassenlevel (20) angenommen werden.<br />
-	Belohnungen beinhalten Faction, Status und Geld. Exilanten können kein Faction bekommen.<br />
<br />
<br />
***Erfahrungs- Änderungen ***<br />
-	Wir dachten das Soloquesten auch ein wenig mehr Belohnungen beinhalten sollten, bisher waren wir mit der Erfahrung die jemand Solo sammelt nicht so zufrieden, speziell für diejenigen die es vorziehen etwas niedrigere Kreaturen zu jagen. Daher haben wir die Erfahrung für folgenden Situationen erhöht:<br />
o	Erfahrung für Nicht-Heroische Kreaturen wurde leicht erhöht<br />
o	Erfahrung für blaue Kreaturen wurde leicht erhöht<br />
o	Erfahrung für grüne Kreaturen wurde stark erhöht.<br />
-	Zusätzlich werden wir die Belohnungen für da bezwingen der stärkeren Gegner die  man in einem Raid antrifft erhöhen. Ebenso wird die Erfahrung für epische Gegner stark erhöht.<br />
<br />
*** Die Hand der Götter ***<br />
-	Der Einfluß Götter wird in Norrath immer stärker, die Propheten des Krieges und der Ruhe rufen nun die Gläubigen zur Hilfe.<br />
-	Bewiese deinen Eifer als Gläubiger des Krieges und sprich mit Tychus Zeksworn in den orkischen Öden von Zek<br />
-	Zeige deine Lieb zum Frieden und sprich mit Sensei Makoto Shoda in den orkischen Öden von Zek.<br />
<br />
*** Spielbarkeit***<br />
-	Reittiere/Teppiche können nun durch erneutes benutzen der Pfeife oder der Beschwörung ausgeschaltet werden<br />
-	Die öffentliche Zutrittsberechtigung kann nicht mehr auf den Level Freund oder höher gestellt werden. Die höchste Standardeinstellung ist nun Besucher. Dies betrifft nur die Standardeinstellungen eurer Häuser.<br />
-	Um dem verschwinden von Gegenständen und Münzen Einhalt zu gebieten, kann man nun nicht mehr während einer Transaktion zonen.<br />
-	Es wird keine Errormeldung mehr geben wenn mein sein Ziel während des Erntens wechselt.<br />
-	Das Ertrinken dauert nun ein wenig länger wenn einem unter Wasser die Luft ausgeht. <br />
<br />
*** Spieler gegen Spieler ***<br />
-	Pets im passiven Modus greifen keinen Aggressor mehr an, es sei denn sie werden selbst von ihm direkt angegriffen.<br />
<br />
*** Questen ***<br />
-	Die „Tombs of Night: A search for Answers“ Quest, wurde so geändert das der Scout der nach dem Tot von Lureclaw und Gulp erscheint, nun an Rande des Teiches stirbt, nicht mehr auf dem Stein, so das die Steinprobe ihren Weg in das Spiel findet und aufgenommen werden kann.<br />
-	Einwohner von Beggar´s Court die die Quest „Big trouble…) abgeschlossen haben und nicht mehr mit Durio Dexus sprechen konnten, können dies nun und ihnen wird die nächste Quest angeboten wenn sie mit ihm reden.<br />
