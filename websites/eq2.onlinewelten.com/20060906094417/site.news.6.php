	<font class=contenttext>Hier ist die der FAQ zu EoF aus dem offizeillen SOE EQ2 Forum von Jalek<br />
<br />
<b>FAQ zu Echo of Faydwer</b><br />
<br />
<br />
<b>Wann erscheint Echoes of Faydwer?</b><br />
Das Erscheinen ist für November 2006 geplant.<br />
<br />
<b>Benötigt man die anderen beiden Erweitrungen um Echoes of Faydwer zu spielen?</b><br />
Zur zeit nicht, die Idee dahinter ist mit EQ2 und EoF die Level 1 - 70 mit dem passenden Content abzudecken.<br />
<br />
<b>Wird es eine neue Rasse geben?</b><br />
Ja, die Fae.<br />
<br />
<b>Werden sie gut oder böse sein, oder kann man wählen?</b><br />
Die Fae sind eine gute Rasse und sie werden wie andere Rassen aus Qeynos Zugriff auf alle neutralen/guten Klassen haben.<br />
<br />
<b>Werden die Fae auf dem gleichen Wege wie andere Charaktäre das Spiel beginnen?</b><br />
<br />
Nein, die Idee für die Fae ist das sie ihren eigenen Startbereich bekommen, dort können sie dann ihre ersten Erfahrungen  sammeln und sie werden nie einen Fuß auf die Insel der Zuflucht setzen. <br />
<br />
<b>Also es sind Feen? Können sie denn auch Fliegen?</b><br />
<br />
Nein es sind keine Feen, sie sind die Fae aber sie teilen einige Attribute mit den Feen die man in Norrath sieht aber es sind keine Feen. Nein sie warden nicht fliegen können, es ist aber geplant das sie über dem Boden schweben (sie schwimmen im Wasser und erhalten Schaden wenn sie aus großer Höhe ohne Sicherenfall fallen). <br />
<br />
<b>Und was ist mit uns Bösen?</b><br />
<br />
Gegenwärtig kann man mit einem/einer Fae seine Stadt verraten und hat dadurch die Möglichkeit eine böse Klasse zu spielen, zur Zeit wird keine neue böse Rasse in erwägung gezogen. <br />
<br />
<b>Haben andere Rassen die Möglichkeit in der neuen Stadt zu starten?</b><br />
<br />
Es wurde angegeben das jede Rasse die im  klassichen Everquest die Möglichkeit hatte in Faydwer zu starten nun in New Kelethin starten kann.Diese Rassen wären die Waldelfen, Hochelfen, Halbelfen, Zwerge, Gnome und natürlich die neuen Fae. <br />
<br />
<b>Wird es neue Reittiere geben?</b><br />
<br />
Ja, die derzeitigen Gerüchte handeln von einem katzenartigen Reittier und einem mechanischem Reittier. Diese mechanischen Reittiere stammen noch aus EQ1 und sind keine Kopie von WoW, so passen sie auch in die Geschichte<br />
<br />
<b>Werden wir jetzt Level 80 erreichen können?</b><br />
<br />
Nein es ist keine Erhöhung des levelcaps für Echoes of faydwer geplant.<br />
<br />
<b>Was wird es neue für uns grindaholics geben?</b><br />
<br />
Ein neues subklassen spezifisches Archievementsystem wir implementiert werden. Diese wird nach den derzeitigen Informationen seperat zu dem derzeitigen AA System eingebunden sein. Ebenfalls wird ein göttliches Glaubenssystem eingeführt werden, welches einige spezielle Fertigkeiten und unterschiede in den Fraktionen einführen wird, leider gibt es hier bisher nur sehr wenige Informationen. <br />
<br />
<b>Also kehren die Götter zurück? Welche werden es sein?</b><br />
<br />
Ja, Zebuxoruk für die Rückkehr nach Norrath einige Dinge in Bewegung gesetzt. Nach den derzeitigen Informationen werden folgende Götter mit dem Start von EoF zur Verfügung stehen.<br />
 <br />
Gut<br />
1. Quellious <br />
2. Mithanial Marr<br />
3. Tunare<br />
<br />
Neutral<br />
4. Brell Serilis <br />
5. Solusek Ro<br />
<br />
Böse<br />
6. Innoruuk <br />
7. Rallos Zek <br />
8. Cazic Thule<br />
<br />
<b>Ich spiele einen Dunkelelfen Paladin kann ich Innoruuk verehren?</b><br />
<br />
Nein, die momentane Planung sieht es vor das die Götter nur von den Anhängern der gleichen Gesinnung verehrt werden können. Exilanten werden die Möglichkeit haben alle aus allen Göttern zu wählen  oder sie werden nur die neutralen Götter verehren können, eine endgültige Lösung liegt hierzu aber noch nicht vor. <br />
<br />
<b>Ich habe etwas über Umhänge gelesen, stimmt das?</b><br />
<br />
Umhänge sind eine geplannte Neuaufnahme für die EoF Erweiterung.<br />
<br />
<b>Wie wird dies dann geschehen?</b><br />
<br />
Die derzeitige Idee ist das die Umhänge für alle Charatäre verfügbar werden, Gilden können diese jedoch speziell anpassen und je nach Gildenlevel werden sie spezielle Zusätze haben. <br />
<br />
<b>Können wir unsere eigenen Logos verwenden ?</b><br />
<br />
Nein.<br />
<br />
<b>Ich habe ebenfalls von einem zweiten Ohrring Platz gelesen?</b><br />
<br />
Es wird vermutlich einen zweiten Ohrring Platz geben und laut den Gerüchten soll er für die EoF Erweiterung vorgesehen sein, es wurde aber noch nicht bestätigt.<br />
<br />
<b>Was sind die neuen Rüstungssets über die man etwas lessen konnte?</b><br />
<br />
Diese Sets werden einen Bonus geben wenn alle Rüstungsteile darus getragen werden. Momentan sind aber noch keine genauen Details darüber vorhanden.<br />
 <br />
<b>Werden wir Farben für die Rüstungen bekommen?</b><br />
<br />
Nein.<br />
<br />
<b>Wird e seine Erhöhung des Gildenlevelcaps geben?</b><br />
<br />
Ja eine Erhöhung des Gildenlevels auf 60 ist geplant.<br />
<br />
<b>Was gibt es neues über die Belohungen für Gildenlevel 50?</b><br />
<br />
Derzeit ist nichts über diese Belohnungen bekannt.<br />
<br />
<b>Wird es Gildenhäuser geben?</b><br />
<br />
Momentan ist nichts dergleichen geplant.<br />
<br />
<b>Was ist mit dem Crafting System?</b><br />
<br />
Die jetzigen Pläne beinhalten die Fertigkeiten Basteln (Tinkering) und Umwandeln (Transmuting), die Gerüchte besagen das diese zusätzliche zu den vorhanden Crafterklassen gewählt werden können. Basteln beinhaltet die Herstellung nützlicher Gegenstände, <br />
Umwandeln soll offenbar auf gecraftete und gedropte gegenständen angwendet werden können.</font>
	

