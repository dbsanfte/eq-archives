                Charakters gezielt. Zum Beispiel: Wenn Sie einmal auf F2 drücken, wird auf das entsprechende Gruppenmitglied gezielt. Drücken Sie erneut auf F2, so wird auf den Helfer dieses Spielers gezielt.<BR>- Das „Anhaltende Zauber“-Fenster
                enthält nun mehr Informationen über das Ziel eines Zaubers. Bewegen Sie den Mauspfeil über ein Symbol, so erscheint als Ziel „Selbst“, falls der Zauber auf Sie gerichtet ist, „Helfer“ falls das Ziel ein Helfer ist, „Gruppe“, falls
                es sich um einen Gruppenzauber handelt oder der Name des Zieles, falls es sich um jemand anderen als Sie handelt.<BR>- Hinweise werden nun korrekt aktualisiert und zeigen auch an, wie oft ein Gegenstand noch verwendet werden kann.
                <BR>- Gruppenmitglieder sind nun auf Ihrer Karte zu sehen, selbst wenn Sie noch nicht in diesem Bereich der Zone waren und die Karte noch schwarz ist.<BR>- Zonen während ein Stärkungszauber aktiv ist löst nun keine Nachricht mehr
