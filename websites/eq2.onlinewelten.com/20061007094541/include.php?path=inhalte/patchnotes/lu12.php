                Spieler eingebaut, um besser erklären zu können, wie man ein Kunsthanderker werden kann, und um ihnen zu bei der Entscheidung zu helfen, welche Art von Handwerk sie ausüben möchten.<BR>- Durch das Untersuchen der Notiz, die neue
                Spieler auf der Insel der Zuflucht oder beim Verlassen der Insel von Assistent Dreak erhalten, gelangen sie nun zu einem Quest, der die Spieler zu Ihrer Handelsfertigkeitsgesellschaft führt.<BR>- Sind die werdenden Kunsthandwerker
                erst einmal in der Gesellschaft, werden sie durch die einzelnen Schritte geführt, mit denen verschiedene Arten von Gegenständen hergestellt werden. Dadurch werden die Vorteile jeder einzelnen Handwerkerklasse erklärt.<BR>- Neue
                Spieler lernen wie der Handwerksprozess funktioniert und verdienen mit diesen Quests außerdem Handelsfertigkeits-Erfahrung und Geld. Jede einzelne Station des Quest „Einen Beruf Suchen“ („Seeking a Profession“) vergibt als
                Belohnung verschiedene Bände der „Grundlagen für Kunsthandwerker“-Serie.<BR>- Für den Abschluss der Questreihe erhält der Spieler einen Waffenrock, der ihm einen Bonus auf Kunsthandwerkerfähigkeiten verleiht und ihn zum Bürger
                seiner Heimatstadt macht, falls er das noch nicht ist.<BR><BR><BR>*** Verbesserungen bei der Beute ***<BR><BR>- Bei mitfühlenden Kreaturen besteht nun die Möglichkeit, dass sie Geld verlieren, wenn Sie sie besiegen.<BR>
                - Verschiedene wild lebende Tiere lassen nun beschädigte Felle und Tierhäute fallen.<BR>- Kreaturen hinterlassen nun nicht mehr irgendwelche Körperteile oder andere abstoßende Gegenstände als Beute. Wer will schon Schädel oder von
                Maden zerfressene Klumpen aufheben?<BR>- Manche Kreaturen hinterlassen nun Beutegegenstände, die für Handelfertigkeiten verwendet werden können. Falls ein Gegenstand im Handwerk benutzt werden kann, so wird beim Untersuchen
                erklärt, wie man ihn verwenden kann.<BR><BR><BR>*** Gilden ***<BR><BR>- Gilden verlieren nun nicht mehr an Status oder Stufen, wenn ein etablierter Schutzpatron die Gilde verlässt oder seine Tätigkeit als Schutzpatron aufgibt. Auf
                diese Weise können Gilden die Stufen, die sie einmal erreicht haben, nicht mehr verlieren.<BR>- Die Statuspunkte, welche Patrone erwirtschaftet haben, aber dann aus der Gilde ausscheiden oder ihren Status entzogen bekommen und
                weniger als eine Woche als Patron fungiert haben, werden nicht der Gilde gutgeschrieben. Die Anzahl der Statuspunkte, welche der Gilde entzogen werden, variiert nach der Anzahl der Tage die ein Patron in der Gilde war. Der
                Gildenleiter erhält bei Degradierung eines Patrons eine Warnung, in wie fern es den Gildenstatus beeinträchtigen wird.<BR>- Die Höchststufe für Gilden liegt nun bei 30. Zusätzliche Gildenerfahrung kann nur erreicht werden, wenn die
                Höchststufe angehoben wird.<BR>- Es gab einen Fehler, durch den viele Gildenstufen niedriger angezeigt wurden als sie tatsächlich sind. Dieser Fehler wurde inzwischen behoben, weshalb einige Gilden eine Erhöhung ihrer Stufe
                feststellen können.<BR>- Sie können nun (für eine Gebühr von 5 Silberstücken) eine In-Game-Nachricht an alle Mitglieder Ihrer Gilde versenden. Geben Sie einfach „Gilde“ als Empfänger Ihrer Nachricht an. Sie allerdings keine
                Gegenstände anhängen und die Nachricht nur an die Gilde schicken, der Sie angehören. Die Gildenführer können entscheiden, welche Ränge eine Gildenmail verschicken dürfen.<BR>- Sie können nun nicht mehr gleichzeitig zwei
                verschiedene Gildenverfügungen durch das Töten desselben NSC abschließen.<BR>- Sie können nun alle 20 Minuten eine neue Handelsfertigkeitsverfügung erhalten, statt wie bisher nur alle 30 Minuten.<BR>- Die Händlerausrüstung, die von
                den Stadthändlern verkauft wird, kann nun von allen Klassen getragen werden.<BR><BR><BR>*** Mysterien in den Minen ***<BR><BR>- Blasse rattenartige Kreaturen - ähnlich den Rattonga nur etwas kleiner - wurden in der Umgebung
                verschiedener Minen, an Orten wie Antonica, den Gemeinlanden und den orkischen Öden gesichtet.<BR>- Es ranken sich Gerüchte um uralte Artefakte, die diese alten Wesen suchen könnten.<BR>
                - Die Kreaturen sollen angeblich über eine große, finstere Macht verfügen.<BR>- Einwohner von Qeynos können weitere Informationen von Perle Honigwein im Hafen von Qeynos erlangen, während Einwohner von Freihafen mehr von Mareva
                D'iniv in Nord-Freihafen erfahren können.<BR>- Die Quests führen Sie je nach Stufe an verschiedene Ziele.<BR>- Der Quest für Spieler der höheren Stufen führt zu einem besonders anspruchsvollen instanzierten Einzel-Gruppen-Verlies.
                Diese Zone bleibt auch nach Beenden des Online-Ereignisses bestehen.<BR><BR><BR>*** Die Spaltpfoten-Saga ***<BR><BR>- Wenn Sie zuvor das Vertrauen der Gnolle im Quest „Eine verdunkelte Scherbe“ gewonnen, jedoch Ihre Scherbe
                gelöscht oder verkauft haben, so können Sie nun bei Gummischlund im Spaltpfotenbau eine weitere Scherbe erstehen. Wenn Sie den Quest gelöscht haben, um eine neue Scherbe zu erhalten, so sollte die Phase „Das Vertrauen der Gnolle
                gewinnen“ aktualisiert werden, sobald Sie in den Spaltpfotenbau zonen.<BR>- Um Verwirrungen zu vermeiden: eine „glühende azurfarbene Scherbe“ mit Auftriebeffekt wird nun als „leuchtende azurfarbene Scherbe“ bezeichnet. Die Version
                eine „glühende azurfarbene Scherbe“ beim Zauber „Rückkehr zu den Spaltpfoten“ wurde nicht geändert.<BR>- Das „Krabblernest“ („Crawler´s Nest“) sollte nicht mehr behutsamen Abenteurern den Endraum verschliessen. Zusätzlich hat die
                Königin ihre Höhle noch sicherer verbarrikadiert. <BR>- Wenn man Tesch Tesch Val Nurkal oder Nisch Val Valkar bekämpft, bekommt man keinen Erfolgszeitgeber mehr für diese Zonen auferlegt.<BR>- Der 2-Stunden Erfolgszeitgeber für die
                Soloarena wird nun erst dann ausgelöst, wenn man sich seine Belohnung holt.<BR>- Die „Entzündbares Fell“ („Flammable Fur“) Zone ist nun auf 6 Charakteren begrenzt.<BR><BR><BR><BR>*** Gameplay ***<BR><BR>- Nahrungs- und Trinkeffekte
                verschwinden nun nicht mehr, wenn Sie in einer anderen Zone wieder belebt werden als in der Sie gestorben sind.<BR>- NSC haben bei einem Spawn ihre latenten Zaubereffekte (wie beispielsweise Unsichtbares sehen) nicht korrekt
                erhalten, obwohl sie diese Fähigkeiten erhielten, wenn sie aus irgendeinem Grund aktiviert und zurückgesetzt wurden. Diese NSC haben nun ihre latenten Fähigkeiten, sobald sie in der Welt auftauchen. Daher werden nun einige
                Kreaturen, anders als vorher, Unsichtbares sehen (oder unsichtbar sein).<BR><BR><BR>*** Zonen und Bevölkerung ***<BR><BR>- Für einige instanzierte Zonen gibt es Beschränkungen der maximalen Anzahl von Spielern, die sich in ihnen
                aufhalten können. Jeder Spieler, der die Zone betritt und dabei die maximale Anzahl an Spielercharakteren überschreitet, wird nach 20 Sekunden aus der Zone geworfen. Charaktere, die aus einer Zone entfernt werden sollen, erhalten
                vorher eine Warnung. Falls ein anderer Spieler die Zone verlässt, so wird der erste Spieler darüber informiert, dass er nun nicht mehr aus der Zone entfernt wird.<BR>- Wächter-NSC sollten nun keine zonenweite Abschlachterei
                veranstalten, wenn sie ein einzelnes Ziel angegriffen haben.<BR>- Schleicher in den Waldruinen flüchten nun nicht mehr sobald sie einen niedrigen Gesundheitswert erreichen.<BR>
                - Die Waldfackeln im Wald von Nektulos haben nun ein neues Erscheinungsbild.<BR><BR><BR>*** Epische Begegnungen ***<BR><BR>- Der Wirkungsbereich großer Kreaturen entspricht nun dem Bereich, in dem auch Sie sie treffen können.<BR>-
                In den meisten instanzierten epischen Raubzugzonen wird nun nur noch die vorgesehene Anzahl von Spielern zugelassen. Jeder Spieler, mit dem die maximale Anzahl überschritten wird, wird nach 20 Sekunden aus der Zone entfernt.<BR>-
                Varanak der Immerwährende attackiert nun nicht mehr sofort diejenigen, die nach einem Kampf mit ihm wieder belebt wurden. Zusätzlich wurde die Statue daran erinnert dass es ihre Aufgabe ist, Venekor zu helfen.<BR><BR><BR><BR>
                *** Quests ***<BR><BR>- Das Questbelohnungs-Fenster wird nun nicht mehr blockiert, wenn Ihnen bei jeder zweiten Stufe Charakterfortschrittsoptionen zur Verfügung stehen.<BR>- Erb-Quests können aus Ihrem Tagebuch gelöscht werden und
                fallen nun unter das 75-Quest-Maximum.<BR>- Charly Aschenpeitsche in Lavasturm kann nun nicht mehr angegriffen werden und muss sich daher nicht mehr vor den Furcht erregenden Abenteurern verstecken.<BR>- Der Priester Kelian bietet
                nun den Priestern ab Stufe 20, die ihn grüßen, kein Priesterklasse-Quest mehr an. Außerdem hat Kelian sich entschieden, sich eher im Stile eines Priesters zu gewanden.<BR><BR><BR>*** Gegenstände ***<BR><BR>- Pfeile werden nun beim
                Zonen oder Anmelden nicht mehr von der Ausrüstung entfernt und landen auch nicht mehr im Inventar.<BR>- Haupttruhen verfallen nun nach 20 Minuten nachdem sie zum Öffnen freigegeben wurden.<BR><BR><BR>*** Zauber und Kampfkünste ***
                <BR><BR>- Die Lehrling-IV-Version der Fähigkeit „Abenteurers Hohn“ hat nun den passenden Effekt.<BR><BR><BR>*** Handelsfertigkeiten ***<BR><BR>- Die Rezepturen für die Herstellung von primären Zwischenkomponenten mithilfe von
                Apotheker, Geomantik, Holzhandwerk und Weben, die früher 10 Treibstoffeinheiten brauchten, benötigen nun nur noch 2 Einheiten.<BR>- Sie sollten nun in Quests zur Erreichung von „Mittlerem Blutdurst“ vorankommen und diese
                abschließen können.<BR>- Die Rezeptur für den Eibenkampfstock verwendet nun die Reaktionskunst des Holzverarbeitens statt der Reaktionskunst des Waffenschmiedens.<BR><BR><BR>*** Steuerungen, Befehle und Benutzeroberfläche ***<BR>
