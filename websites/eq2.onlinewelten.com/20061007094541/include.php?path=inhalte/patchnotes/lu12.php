                Einstellungen und Kanalinformationen mit grösserer Zuverlässigkeit abspeichern.<BR>- Die eckigen Klammern [] erscheinen nun um die Gegenstandslinks im Chat-Fenster (z.B. [Gegenstand Name]).<BR>- Sie können nun eine Taste zuweisen
                um zwischen Ihren letzten beiden Zielen hin- und herzuschalten. Öffnen Sie um eine Taste festzulegen das Menü Optionen und klicken Sie auf die Kategorie Befehle und dann auf das Pluszeichen (+) neben den Zielerfassungstasten.
                Klicken Sie das Kästchen neben „Voriges Ziel auswählen“ und wählen Sie dann die Taste, die Sie zuweisen möchten.<BR>- Das Raubzugsfenster zeigt nun korrekt an, wenn Raubzugsmitglieder tot sind.<BR>
                - Mentoreninformation passt nun richtig in das Raubzugsfenster.<BR>- Wenn Sie „/whoraid“ eingeben, so wird eine Liste aller Raubzugsmitglieder an das Chat-Fenster geschickt, mit /whogroup erhält man eine Liste mit
                Gruppenmitgliedern im Chat-Fenster.<BR>- Der /wc Befehl funktioniert genauso wie /whochannel. Eine Liste von Kanal-Teilnehmern wird im Chat-Fenster angezeigt.<BR>- Wenn Sie die Maus über eine Tasche in Ihrem Inventar bewegen, so
                wird nun der Inhalt der Tasche in einem Hinweisfenster angezeigt.<BR>- Taschen in Ihrem Inventar sind nun mit „offen“ gekennzeichnet, falls Sie sie geöffnet haben.<BR>- Das Verriegeln eines Schnelltasten-Fensters verhindert nun,
                dass Schnelltasten-Symbole daraus entfernt werden können.<BR>- Die Statistiken und Widerstandswerte werden nun richtig angezeigt, wenn Sie einen Gegenstand untersuchen, den Sie nicht tragen.<BR>
