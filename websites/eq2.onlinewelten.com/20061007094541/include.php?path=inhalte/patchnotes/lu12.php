                Sie das Kontrollkästchen „Chatnachrichtszeit anzeigen“.<BR>- Taschenbezeichnungen bleiben auch nach dem Zonen aufrecht.<BR>- Man kann keinen Quest mehr löschen, solange der Kategoriename ausgewählt ist.<BR>
