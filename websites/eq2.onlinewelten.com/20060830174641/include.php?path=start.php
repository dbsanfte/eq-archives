	<font class=contenttext>John Smedley der Präsident von Sony Online Entertaiment hat letzte Woche in den SOE Blog etwas geschrieben was einem doch sehr Nachdenklich macht. Es geht um das Thema  Kinder in Online Spielen und die Gefahren die davon ausgehen. John berichtet da über ein Erlebniss das seine Tochter vor kurzem hatte. <br />
<br />
Auch uns sollte dieser Blogeintrag etwas  zum Nachdenken anregen. Nicht nur das unsere Kinder mit Computern mitunter sehr gut umgehen können, auch finden sie  im Internet immer wieder neue Sachen, oder gar Spiele die sie haben möchten. Und gerade bei Online Spielen ist es so das ihr Kind auch Kontakt zu anderen Menschen hat bzw. andere Menschen Kontakt zur ihrem Kind aufnehmen können.<br />
 <br />
Man sollte daher  unbedingt mit seinem Kind/seinen Kindern darüber Reden welche Risiken so ein Spiel haben kann und vorallem das man ihnen beibringt keine Persönlichen Daten (Name, Alter, Adresse etc.) weiter zu geben. Auch sollte man ihnen beibringen das sie solche Vorkommnisse, vorallem wenn sie auch noch bedrängt werden sofort erzählen den nur so kann man dagegen Effektiv etwas Unternehmen!<br />
<br />
Viele Spiele Hersteller stellen in irgendeiner Art und weise eine Kontaktmöglichkeit zur verfügung, so das man solche  und andere Vorkommnisse melden kann. <br />
<br />
Natürlich haben wir für euch den Blogeintrag auch komplett übersetzt. Hier die Übersetzung von Kyorli:<br />
<br />
<hr /> <br />
<br />
Sei Aufmerksam<br />
<br />
21.08.2006<br />
<br />
An diesem Wochenende hatte ich eine interessante <br />
Erfahrung. Meine älteste Tochter (9 Jahre) <br />
spielte ein Onlinegame (keines von unseren und <br />
auch nicht WoW) und irgendjemand fragte sie wie <br />
alt sie sei. Ich habe ihr beigebracht solche <br />
Personen sofort auf die Ignorliste zu setzen, <br />
sie via In-Game Befehl zu melden und mir sofort <br />
darüber zu berichten. Da dies in diesem Spiel <br />
schon vorher einmal passiert ist (mit exakt <br />
derselben Reaktion von ihr) habe ich den Account <br />
sofort gekündigt. Ich bin Vater von 4 Kindern im <br />
Alter von 5 bis 11 Jahren. Alle 4 spielen <br />
Spiele. Ich selbst spiele aktiv mit meinem <br />
ältesten Sohn (11 Jahre). Meine beiden Jüngsten <br />
(5 und 6 Jahre) spielen ebenfalls (in diesem <br />
Fall Disney´s ToonTown, das ich als ein sehr <br />
sicheres spiel ansehe).<br />
<br />
Warum erzähle ich davon? Das ist sehr einfach, <br />
für Kinder sind Onlinespiel einfach großartig. <br />
Mein Sohn ist ein blitzschneller Schreiber auf <br />
der Tastatur und liebt Onlinespiele über alles. <br />
Wir erlauben bestimmte Zeiten um zu spielen und <br />
nutzen aktiv die Elternkontrolle, sofern sie in <br />
den Spielen angeboten wird.<br />
<br />
Meine Frau und ich haben uns mit unseren älteren <br />
Kindern zusammengesetzt und mit ihnen darüber <br />
diskutiert was in der Onlinespiel Welt in <br />
Ordnung ist und was nicht. Sie wissen das sie <br />
keine persönlichen Informationen jeglicher Art <br />
herausgeben sollen und das sie uns sofort <br />
informieren sollen wenn danach gefragt wird. Bei <br />
allen Spielen die sie spielen, habe ich selbst <br />
die Freundesliste kontrolliert um sicher zu <br />
gehen, das sie alle dort im realen Leben <br />
persünlich kennen. Wir lassen sie auch nur <br />
Spiele spielen bei denen wir sicher sind das sie <br />
für ihr Alter geeignet sind.<br />
<br />
Wir kennen alle die Geschichten darüber, das <br />
Kinder von älteren Unbekannten kontaktiert <br />
werden und das diese dann versuchen die Kids zu <br />
überreden irgend etwas gefährliches oder <br />
schlechtes zu tun. Ich schreibe hier um darauf <br />
extrem Aufmerksam zu machen. Seid euch als <br />
Eltern bewusst welche Spiele eure Kinder spielen <br />
und welche Kommunikation dort passiert.<br />
<br />
Wie in der realen Welt gibt es auch dort einige <br />
schlechte Menschen. Es ist unser Job als Eltern <br />
sicher zu stellen das unsere Kinder es <br />
verstanden haben was sicheres Spielen ist.<br />
<br />
Es ist interessant bei einer Onlinespiel Firma <br />
zu arbeiten, während meine Kinder alt genug sind <br />
einige von unseren Spielen zu spielen. Dies gibt <br />
mir eine starke Auffassung über Online <br />
Sicherheit. Ich kann es nicht oft genug sagen, <br />
es ist wichtig dass die Eltern wissen was ihre <br />
Kinder tun und welche Spiele sie Online spielen. <br />
Daher erachte ich es als äußerst wichtig hier <br />
bei SOE, das es Eltern erlaubt wird auch andere <br />
Tools zu nutzen um zu prüfen was ihre Kinder <br />
online machen.<br />
<br />
Ich würde es begrüßen wenn eine Elternkontrolle <br />
implementiert würde die es den Eltern erlaubt, <br />
einmal täglich eine Mail zu erhalten mit einem <br />
Chatprotokoll der Gespräche die ihr Kind an <br />
diesem Tag geführt hat.<br />
<br />
Bisher habe ich diese Idee aber noch nicht mit <br />
unserer Geschäftsführung und den Technikern <br />
besprochen. Es ist möglicherweise eine Menge <br />
arbeit so etwas zu implementieren und es ist <br />
möglich das dies nicht sonderlich gut mit der <br />
derzeitigen Gesetzgebung übereinstimmt. Aber ich <br />
weiß das dies etwas ist das ich als Elternteil <br />
gerne sehen würde.<br />
<br />
Ich würde mich über eure/ihre Meinungen dazu <br />
sehr freuen, fühlen sie sich frei mir eine Mail <br />
zu senden jsmedley@soe.sony.com<br />
<br />
John Smedley spricht ausschlieslich Englisch, wenn ihr ihm also eine Mail senden wollt dann tut dies in Englisch! <br />
<br />
Ihr könnt natürlich auch mit uns im Forum über dieses Thema Diskutieren, wir freuen uns über  jedes Komentar disbezüglich!!<br />
