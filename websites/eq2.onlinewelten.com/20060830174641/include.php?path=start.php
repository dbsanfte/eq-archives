-	Epische Gegner haben nun keine Chance mehr mit einem Zauber einen kritischen Treffer zu landen.<br />
-	Paladin: Divine Favor hat jetzt keine Hassreduktion mehr. Die Dauer wurde von 2 Minuten auf 3 Minuten erhöht.<br />
<br />
*** Handel***<br />
-	Gegenstände werden nun bei Petbesitzern korrekt ins Inventory gelegt.<br />
<br />
***Spieler gegen Spieler ***<br />
-	Das Dorf Shin wird nun nicht mehr durch die Feind Regel geschützt<br />
-	Die Feind Flag wird nun automatisch gesetzt sobald eine Stadt/Dorf betreten wird das nicht die Gesinnung des Spielers hat.<br />
<br />
*** Handwerksfertigkeiten ***<br />
-	Der Brennstoffverbrauch in fast allen Rezepten wurde geändert. Bei vielen Rezepten wurden die Brennstoffe reduziert, einige andere Benötigen nun mehr Brennstoffe. Versorger Rezepte wurden nicht geändert.<br />
-	Handwerks Questen (Arbeitsaufträge) nutzen nun den Handwerkslevel anstatt des Abenteuererlevels um die Erfahrung und Statusbelohnungen festzulegen. Der Handwerkslevel legt nun auch die Farbe der Quest im Questtagebuch fest.<br />
-	Juweliere mit dem Level 56 oder höher sind nu in der Lage Das Symbol von Lect´Mun Sul Rezept zu schreiben.<br />
-	Bandoliere, Taschen, Satchels und sheats können nun mit neuen Rezepten imbued werden. Diese Rezepte sind ein automatischer update der Rezeptbücher für diejenigen die schon die entsprechenden Bücher besitzen. Gleichzeitig werden alle Level 60 und /0 Rezepte keine weiteren zusätzliche Komponenten benötigen.<br />
-	Sisalwurzeln können nun für Level 10-19 Rezepte als Rare Stoffkomponente genutzt werden.<br />
-	Disease Imbued Ebony Wand werden mit dem korrekten Namen angezeigt.<br />
-	Das Steel Chain Mantle Rezept ist in Steel Chainmail Mantle umbenannat worden.<br />
-	Brennstoffanzahl für strong boxes wurde angepasst.<br />
-	Schreiner Rezepte für Verkaufscontainer wurden so angepasst das sie dem Level entsprechend Brennstoffe verbrauchen.<br />
-	Seltene Rundschilde und Buckler benötigen nun die korrekte Anzahl an Brennstoffen.<br />
-	Die Ablaufzeit für Gifte bleibt nun beim Zonenwechsel bestehen.<br />
-	Die Rezepte zum Imbuen von Schilden  für Level 60 Rüstungsschmiede haben jetzt den gleichen Level wie der einfache Gegenstand.<br />
-	Die Essence of Unfliching Will wurde umbenannt in Essence of Burning Will.<br />
-	Es gibt einen klaren Unterschied zwischen Lvl 50 und Lvl 60 Hexdolls.<br />
<br />
*** User Interface ***<br />
-	Es kann keine Post mehr zu Empfängern die im Trial of the Isle befinden geschickt werden.<br />
-	Es gibt jetzt im Postfenster einen Spam-Button der genutzt werden kann um Spammails zu melden, dies soll helfen beleidigende Mails zu melden und diese dann mit allen Anhängen zu löschen.<br />
-	Ein Doppelklick auf einen Gegenstand im Überlaufslot transeferiert diesen nun in das Inventar und nicht mehr in Personafenster.<br />
-	Einen Gegenstand aus der Housevault erzeugt keine Fehlermeldung mehr, bei dem Versuch ihn anzulegen.<br />
<br />
*** Trial of the Isle Änderungen ***<br />
Trial of the Isle ist eine freie Demoversion die Spielern die Möglichkeit gibt Everquest 2 zu testen. Unglückcherweise wird dies von einigen skrupellosen Individuen augenutzt um das Enduser License Agremment zu brechen, wie z.B. das spammen von legitimen Spielern.<br />
Um diesem vorzubeugen haben diese Testaccounts nun eine Limitierung der Interaktionen mit anderen Spielern. Diese Limitierung wird aufgehoben sobald ein Spieler sich entscheidet von der Trialversion auf die Vollversion umzusteigen. <br />
<br />
-	Es können keine /tells mehr zu anderen Servern oder an andere Spieler gesendet werden.<br />
-	Man muß auf der Freundesliste eines Spielers stehen um ihm einen /tell senden zu können.<br />
-	Es kann kein Handel mehr mit anderen Spielern getrieben werden.<br />
-	Trial of the Isle Spieler können nicht mehr in eine Gilde eingeladen werden.<br />
-	Trial of the Isle Spieler können keine Gilde gründen oder sich an der Gründung einer Gilde beteiligen.<br />
-	Sie können keine Gegenstände beim Brocker oder in Verkaufscontainern zum Verkauf anbieten.<br />
-	Sie können kein In-Game Mail versenden oder empfangen.<br />
-	Sie können nicht in serverweiten Chat-kanälen schreiben.</font>
	
