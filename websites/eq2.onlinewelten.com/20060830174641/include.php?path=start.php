-	Der City Record Keeper wurde durch den Arbeitsauftragsvormann ersetzt, dieser gibt nun auch Arbeitsaufträge ohne Zeitlimit heraus. Um diese zu Starten muß man das Schreiben vom Schreibtisch des Vormanns aufnehmen.<br />
-	Weise haben nun auch die Wahl zwischen Aufträgen mit und ohne Zeitlimit beim Vormann.<br />
-	Statusbelohnungen für beide Arten von Arbeitsaufträgen wurden korrigiert.<br />
-	Die Geldbelohnungen für die meisten Arbeitsaufträge wurden korrigiert.<br />
-	Arbeitsaufträge ohne Zeitlimit können nun korrekt abgeben werden.<br />
-	Arbeitsaufträge ohne Zeitlimit haben nun einen Text der darauf hinweißt dass es kein Zeitlimit gibt.<br />
-	Arbeitsauträge können nun aus dem Questtagebuch gelöscht werden.<br />
<br />
*** Erfahrungs Änderungen ***<br />
-	Die XP Belohnung für das töten von grünen Mobs wurde nun wieder leicht reduziert um eine bessere Balance zu erhalten. <br />
<br />
*** Stadt Gilden Raids ***<br />
-	Die alten Gesellschaftsquesten die für die Stadt Gilden Raids verwendet wurden, sind durch eine neue Questserie ersetzt worden.<br />
<br />
*** Zonen und Bevölkerung ***<br />
-	Murdunk´s Fall wurde vollständig erneuert und heißt nun nicht mehr länger Pool of Ruin. Unser Tipp für diejenigen die es mögen in Ruinen herumzulaufen, es können nun an verschiedenen neuen Stellen welche gefunden werden.<br />
-	Die Eisscholle in Immerfrost auf der sich die Handwerksarbeitsplätze befanden ist durch die starke globale Erwärmung, die durch Handwerker dort erzeugt wurde, geschmolzen.<br />
<br />
*** Questen ***<br />
-	Wenn eine Quest mit Zeitlimit nicht erfüllt wird, wird dies nun korrekt im Questhelferfenster angezeigt.<br />
<br />
*** Gegenstände ***<br />
-	Meuchelmörder, Raufbolde, Schänder und Troubadure können nun den original Questgeber für Relic und Hooloh Hüte aufsuchen und ihre derzeitige Kopfbedeckung gegen einen neuen Professionshut eintauschen. Bitte denkt daran das der Tausch nicht mehr rückgängig gemacht werden kann.<br />
-	Die Reparaturkosten für Fed Gegenstände wurde stark reduziert. Vorher betrugen die Kosten das Vierfache der Reparatur von Legendären Gegenständen.<br />
-	Der Effekt von Scallywag´s Plumed Hat funktioniert nun korrekt.<br />
-	Der Dornenholz Kampfstab hat nun das korrekte aussehen.<br />
-	Der Krug von Lord Everling hat nun die korrekte Anzahl an Ladungen.<br />
-	Bei Schilden und Symbolen wird nun immer angezeigt in welchem Slot sie getragen werden können.<br />
<br />
