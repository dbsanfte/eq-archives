<li>Shadowknights - 58; Shaman - 58</li> 
<li>Warriors - 58; Wizards - 58</li>
</ul>
</li><br/>
<li><div class="orange">What you must have:</div>
<ol>
<li>A Rechargable, Shrink Device</li>
<li>An Indoor Insta-click Device</li>
<li>Ssra Emperor Keys Pieces - Zazuzh's Idol, Zeruzsh's Ring and a Taskmasters Pouch.</li>
<li>VT Shards from:
