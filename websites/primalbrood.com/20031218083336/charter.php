<h1>The Charter of Primal Brood</h1><br/>

<h2>1.  Several things to know about Primal Brood:</h2>
<p>
Primal Brood is an Everquest Test Server guild for serious high-level players interested in raiding professionally and playing skillfully together regularly in exploring some of the most dangerous places in Norrath.  Primal Brood endeavors to work as a team to accomplish progressively greater challenges. Every member of Primal Brood is important, respected and appreciated.
</p>
<p>
We have a low overhead, politics reduction, guild management system.  Our system of Rules and Guidelines are designed to prevent arguing or disruption of game play. All Rules and Guidelines are clearly posted and are upheld. The guild leaders are entrusted to protect the interests and vision of the guild and have final say on any proposed rules or guild lines. 
</p>
<p>
All members have a "level focus" and are actively seeking to reach level 65 and further enhance their character with raid friendly AA abilities.  Members of Primal Brood endeavor to be honorable, kind, and respected by the Test Server community.  
</p>
<h2>2.  Reasons for denied membership or guild-removal:</h2>
<ol type="a">
<li>Constant negativity (especially concerning loot). </li>
<li>Attempting to lead Primal Brood anywhere for a "raid" without prior approval.</li>
<li>Sharing your account information with non-Primal Brood players from any server. </li>
<li>Sharing our strategies and tactics with people outside guild. </li>
<li>Sharing things said in /guildchat or /raidchannel with people outside guild.</li> 
<li>Only participating in raids that can further your character(s).</li>
<li>Using the name "Primal Brood" to intimidate others.</li>
<li>Defaming Primal Brood with rude and insulting conduct to others.</li>
<li>Badmouthing Primal Brood.</li>
<li>Ninjalooting, Killstealing & Training.</li> 
<li>Selling items or characters on ebay.</li>
</ol>
