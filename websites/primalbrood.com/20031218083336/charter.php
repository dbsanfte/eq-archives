<ul>
<li>Clerics - 56</li>
<li>Bards - 56; Beastlords - 58</li>
<li>Druid - 58</li>
<li>Enchanter - 56</li> 
<li>Mages - 56; Monks - 58</li> 
<li>Necromancers - 56</li>
