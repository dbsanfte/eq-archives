</li>
<li><div class="orange">Applications:</div>
Primal Brood follows it's Charter closely and takes it very seriously. If you still feel you would like to be considered for membership, you can fill out the application for review.  The Primal Brood Application can be found <a href="http://www.primalbrood.org/forums/viewtopic.php?p=9099#9099">here</a>.</li>
<li><div class="orange">Hopping.</div>
Primal Brood does not consider "guild shoppers" to be serious or focused. So if you've applied to other guilds, it would be to our mutual benefit if you concentrated your efforts on them. This will increase your chances of gaining acceptance into the other guild(s).</li>
</ol>

<h2>5.  Attitude:</h2><p>
We expect every member of Primal Brood to be respectful, polite, and empathetic to other players on the Test Server. Our members are mature, responsible, and caring and it is expected that they will act that way. Any inexplicable reports of bad behavior (i.e. disrespect, rudeness, disregard for other players safety) will result in warnings and possible expulsion from the guild.
</p>
<h2>6.  Class Balance/Characters:</h2><p>
While Primal Brood membership is not based specifically upon what class a person plays, it is a factor. If a person is undecided upon which "main" class or character they wish to play in the end game - take the time to determine that prior to applying to Primal Brood. The character that you apply to Primal Brood will be considered your "main".  Changing "mains" is NOT allowed. We need to maintain class balance as much as possible. This may affect your membership into the guild.
</p>
<h2>7. Guild Communication:</h2>
<p>
<ol type="a">
<li><div class="orange">Disagreements:</div> Primal Brood forbids arguing, negative comments, verbally attacking other members in any form of EQ communication.  It is unacceptable in all situations.  Pledges and member are expected to be mature and use /tells to resolve their differences.</li>

<li><div class="orange">Hot Topics:</div> Everquest is a game that does not involve the "real" world.  As such, discussions of politics, religion, operating systems and any other "hot" topics are not acceptable. Discussion of current events that are important to Americans may offend our Danish members or visa versa. Negative comments reduce the enjoyment for all members.</li>

<li><div class="orange">Language:</div> People are free to use whatever language they see fit, so long as the purpose is not to attack another person. If you do not like to see "curse" words, we suggest you turn your filter back on. Please try to limit lewdness to something that wouldn't offend the average sailor. If a guild member specifically mentions excessive foul language, respect for members takes precedence over this allowance.</li>

<li><div class="orange">Spam:</div> Do not use /guildchat and/or /channel to carry on a conversation with another person in which the majority of the guild is not involved or interested. Use /tells or create a channel for your conversation so as not to spam the main communication channels. </li>
</ol>
<h2>8. Connectivity:</h2>
<p>
Going LD every 5 minutes is counterproductive to everyone. A stable internet connection is highly recommended and we encourage you to contact your ISP to determine any alterations you can make to enhance it. 
</p>
<h2>9. Loot/Rewards:</h2>
<p>Primal Brood Leaders determines who will be awarded loot based upon the raiding needs of the guild as a whole. This method is not open to debate or discussion. We do not equip characters that have not contributed to the guild in any way. If this system of rules is not comfortable for you, then you should not consider applying for membership.
<ol type="a">
<li><div class="orange">Things to think about before requesting Loot:</div>
<ol type="i">
<li><i>Research:</i> It is recommended that you research 2-3 items from various mobs (Ssra, VT, PoP, etc.) per slots and make a list for yourself to use to determine what will benefit your character and - by extension - Primal Brood as a whole.</li>
<li><i>"Saving up":</i>  Waiting for Uber Loot 001 off Top Uber Mob 002 will see many disappointed, angry people. Not everyone will get "first" drop of an item and it is not a personal slam if you do not.</li>
<li><i>Negativity:</i> Complaining to anyone other than Leadership about loot issues will not get them resolved. Gossip hurts morale, is counterproductive and could lead to guild removal. PM's are the best method to convey information to Leaders and in-game tells should be used as a last resort.</li>
</ol>
</li>
<li><div class="orange">Loot is awarded on several factors:</div>  Loot is determined using several factors and is awarded only by who sends a /tell for the item. You are responsible for knowing what you need and what you should ask for. If you chose to not send a /tell, Leadership assumes you have no interest in that item. However, bottom line is - if you don't ask, you won't be considered for that item.
<ol type="i">
<li><i>Raid Attendance:</i>  Show up consistently. If you appear for a week, then disappear for 3 or more - don't expect to be rewarded items. This means, if you can only show up for one day a week, don't miss that day.  Primal Brood does not equip the character select screen. If you only show up for Item X runs and do not contribute to the guild in any other way, you will be asked to leave.</li>

<li><i>Last Loot/Slot:</i>  If you recently got awarded an upgrade to your greaves, chances are good that you will not be awarded another upgrade to that slot a day later unless no one else requests it.</li>

<li><i>Guild Contribution/Loyalty:</i>  This is considered the "intangible" element and only used as a final tie breaker decision making tool. Leaders know who helps others to improve themselves and, by extension, Primal Brood on non-raid days. The Leaders know who has been in Primal Brood for a long time and who has consistently helped the guild as a whole. Seniority = Loyalty.  Playing 24/7/365 isn't a factor in guild contribution if you are not helping Primal Brood as a whole in the process.</li>
</ol> 
<li><div class="orange">Loot Request Guidelines:</div><br/>
<ol type="i">
<li><i>2 Mins:</i>  Everyone has 2 full minutes to send in a /tell for loot. That is more than enough time to compare your loot and do your homework on the spot since you didn't prepare ahead of time. </li>
<li><i>Rot:</i>  Rot loot is not free loot. If you wanted it, you should have asked for it. Rot is for bots, not mains. We don't want to see things destroyed but anyone who thinks we will outfit 60+ off of one boss mob should seek professional help.</li>
<li><i>Bot Standing:</i>  The Bot requests will be determined by their Main Characters contributions. This will not affect the Main Characters requests for loot at all and is not considered "loot" for the Main.</li>
</ol>
</li>
</ol>
<h2>10. Raids:</h2>
<ol type="a">
<li><div class="orange">Shrinks.</div>  Shrink devices are required for all applicants. If you are not one of the assigned pullers, you need to shrink as soon as you enter the raid zone.</li>

<li><div class="orange">Channels.</div>  Join channels before you move to the raid zone.  If you are not in channel, you will not get a group.  If you do not know the channel name, ask.</li>

<li><div class="orange">Questions/Chatting.</div>  
<ul>
<li>Raid Leaders - Raids are not the time to play 20 questions with the raid leaders.  Nor is it time to give unsolicited "suggestions".  Raid Leaders are extremely busy.  Any time spent responding to you holds up the other 40-60 people and takes the raid leaders attention away from responsibilities. </li>
<li>Group mates - Ask your group mates raid procedure questions. If no one in group can answer your question, request the group leader get the answer. </li>
</ul>
</li>
<li><div class="orange">Raid Say.</div>  Raid say is a restricted channel for raid leaders only. </li>
<li><div class="orange">Authority.</div>  Do not assume authority to communicate things which you are not responsible for, this would include instructions to zone or camp in bad situations, and giving instructions. The raid leader assigns people these responsibilities. 
</li>
<li><div class="orange">Buffs.</div> Do not ask for buffs.  Buffs are automatically done.  If you need a buff and do not receive it, ask your group leader to get it for you. It's the group leaders' responsibility to communicate with buffers.
</li>
<li><div class="orange">Exploring.</div> Your ability to hide from creatures does not entitle you to a solo tour while we are raiding.  Do not wander. </li>

<li><div class="orange">AFK.</div> If you need to afk, it is your responsibility to inform the group leader and arrange to be moved should we move in the meantime.  If you do not and you are left behind, it is your responsibility to get either a CoH from a Mage or ask a rogue to drag you.
</li>
<li><div class="orange"> Placement.</div> Do not stand between pullers and MT for any reason.</li>

<li><div class="orange">Attacking.</div> Do not attack, cast or make funny faces at the target until the assigned MT calls for /assist.  This means you have a hotkey with /target MT-name on it.</li>
<li><div class="orange">Proc/Aggro Weapons.</div>  If you are not the MT/ST/Spite, the aggro/proc weapons get put away.  Pulling aggro of the MT might be funny to you, but getting TL'ed out will not be.
</li>
<li><div class="orange">Max Distance.</div> Stay at maximum melee distance from the mob.  This is the point at which you can no longer back away and still hit.</li>
</p>
