      <U><B><P>Summery</P></B></U>
      <U><B></B></U><FONT SIZE=2> 
      <P>RPP stands for raid participation points.   The RPP system is a method of loot distribution Conquest uses to most fairly award its members for their effort they put into the guild.  The premise of the entire system is that the fairest way to distribute loot is to make each individuals ratio of time invested to loots received equal.</P>

<P>Each time someone attends a raid, they receive RPP for it.  The amount of RPP received for the mob depends on the loot that mob drops.  When someone wins a lotto, they lose the amount of RPP that the item is worth.  The more desirable and valuable the item, the more the item costs.  Lotto’s are restricted to the person with the most RPP's who wants the item, and anyone within 5 current RPP of them.</P>

</FONT><U><B><P>Lotto Restrictions:</P>
</B></U><FONT SIZE=2>
<P>Items are subject to class / race restrictions regardless of RPP values.  For example casters are not eligible to lotto on a cloak of flames.</P>

<P>You may enter lotto's using your RPP's for any level 55+ characters that you control.</P>

<P>Those with negative RPP's may only enter lotto’s on no-drop items.</P>

</FONT><U><B><P>Items won under the RPP system:</P>
</B></U><FONT SIZE=2>
<P>Items that have been won under the RPP system may not be traded, sold, or given to a twink.  A twink is defined as any character less than 55.  At 55 that character becomes an alt.  </P>

<P>There are exceptions to this rule.  There are some cases in which it would be stupid not to trade the item for something else.  These are rare occasions, however.  The most important thing about this situation is that you in NO way got an item that another member would use, for the purpose of selling/trading.  There are some items that have very high platinum values, but very low RPP values.  Woushi scales, weapons, and shield are some obvious examples.  Someone who would use these items should not have to lotto against someone who just wants to purchase the item for very cheap RPPs, and make a huge profit in east commons.  If you think you may have a trade that is an exception to the rule, talk to the RPP officers. (Itzlegend, Diirk, Ketsui).</P>

<P>The item however, can be sold back into the system at any time for RPP's (see trade ins). </P>

</FONT><U><B><P>Special lotto rules:</P>
</B></U><FONT SIZE=2>
<P>Anyone who has a permanent invite to our raids are treated exactly like a conquest member under the RPP system.  </P>

<P>In rare occasions we may invite someone outside of the guild just for that particular raid.  In the case where we would be doing that just to make the raid a success, they will receive an equal proportional random with those who need the item.</P>

<P>For example if there are 7 conquest members at a raid who need the item,  the lotto would be done like:  Conquest 1-7, outside invite 8.   /random 1 - 8.  If the lotto turns up 1-7, the item is lotto'd as per normal RPP lotto rules within the guild.</P>

<P>Keep in mind Conquest very rarely, if ever, needs someone outside the system in order to make a raid a success. 99.9% of all people on conquest raids who are outside of guild will have their own RPP points and participate in the system as if they were a member of conquest.</P>

</FONT><U><B><P>The lotto process:</P>
      </B></U><FONT SIZE=2> 
      <P>When an item is dropped, someone on the raid will shout out for anyone 
        wishing to lotto on the item to give them a tell. Once all the tells have 
        been received this person will look over the RPP values and then let the 
        raid know the people that are eligible to lotto. </P>
      <P>If the item is tradable, you must have positive RPP and be within 5 current 
        RPP's of the person with the highest value who wants the item in order 
        to be included on the lotto.</P>
      <P>If the item is no drop, and no one who has positive RPP wants it, those 
        who are negative are allowed to enter on the lotto.<br>
        <br>
        Note: Not being able to lotto when negative RPP's is determined strictly 
        off of your RPP value - IRPP's are not taken into account. When determining 
        if you are within 5 points of the person with the most, IRPP's are taken 
        into account.<br>
      </P>
      <P>You are given the points for the raid at the completion of the raid. 
        The majority of lotto's are considered to be done after the completion 
        of the raid.</P>
      <P>If no one wishes to lotto for a tradable item, it goes to the guild bank. 
        It will be lotto’d at later raids. When it becomes obvious no one under 
        the system wishes to purchase the item, it will be up for sale to the 
        general public for raid funds. Members get first picks on purchasing items, 
        but there is no member discount.</P>
      <P>If no one wishes to lotto for a no drop item it is destroyed, or it decays. 
        There are no exceptions to this rule.</P>
      </FONT><U><B> 
      <P>Trade Ins:</P>
      </B></U><FONT SIZE=2> 
      <P>In the case you should upgrade from an item won under the RPP system, 
        you may trade the other item back into the system and get the points back 
        you paid for that item. If someone else in the guild wishes to purchase 
        the item (with RPPs), you get full RPP value back for the item. If no 
        one in the guild wishes to purchase the item, you get 1/2 RPP value. If 
        the item was not won under the RPP system, you can trade in that item 
        for 1/2 RPP value, if someone in the guild wishes to purchase the item.</P>
      </FONT><U><B> 
      <P>Receiving and Losing RPPs:</P>
      </B></U><FONT SIZE=2> 
      <P>The are two ways to earn RPP's - attending raids, and trade ins. </P>
      <P>That said there are some cases in which RPP's may be modified to match 
        the situation. One of these is showing up excessively late. If someone 
        shows up after the mob is in the process of being pulled, or has already 
        been engaged, they receive 1/2 RPP value.</P>
      <P>There are certain raids some members can't participate in, against their 
        own will. Sleeper’s tomb for those without keys, and plane of growth for 
        rangers and druids are two examples. In these cases, if the person is 
        online they will be given credit for those raids. Veeshans Peak is not 
        included in this exception - it is each member’s own responsibility to 
        complete their VP key.</P>
      <P>Much more frequently then any of us would like to see, verant has a really 
        bad habit of retroactively nerfing items. When an item is nerfed, the 
        first thing that is done is we create a new value for the item. Once that 
        has been done, those who won that item under the RPP system will be refunded 
        the difference in prices. In the case that item has been rendered useless 
        to the person who has it (meaning they would never use it anymore), they 
        will be refunded full RPP value for the item.</P>
      </FONT><U><B> 
      <P>Item and mob values - how they are determined:</P>
      </B></U><FONT SIZE=2> 
      <P>Let's start out with an example. Let's say mob X drops item Y, and for 
        simplicity, it drops item Y every single time, and only drops 1 of item 
        Y as its total loot pool. Item Y is a mediocre item, that everyone eventually 
        would like to own. Let’s say we rate the item at a value of 5RPP. Let’s 
        say this mob takes an average of 24 people to kill. In this case, the 
        mob would be worth 0.21 RPP for killing. </P>
      <P>Why? Well let’s consider the fundamentals of determining the values. 
        How could someone, in our example, earn their item Y? I think everyone 
        can agree that once that person receives item Y, they should go back and 
        kill that mob 24 more times, until everyone gets item Y. Thus, once they 
        go 24 times, they have completely earned that item. Thus, the formula 
        for a mobs value is loot/people present.</P>
      <P>RPP officers determine loot values. The value of the loot depends on 
        many factors.</P>
      <P>Desirability - This is a combination of all the other factors. An items 
        value is related directly to how desirable it is.</P>
      <P>Quality - How much of an improvement the item offers over other single 
        group campable items.</P>
      <P>Haste items - Haste items are typically higher value.</P>
      <P>No drop - No drop items typically have a lower value since they can never 
        be traded back into the system.</P>
      <P>Rarity - Typically rarity has a very small impact on the cost of an item. 
        However there are certain items that we can get high quantities of with 
        little effort - so those items have a lower cost then they would if they 
        dropped off a different mob.</P>
      <P>Once the values of the items the mob drops are determined, there are 
        two types of raids we do in conquest, when it comes to RPP values. </P>
      <P>Fluctuating value raids - Fluctuating raids have a value that is exactly 
        loot purchased/people present. This type of raid guarantee's zero inflation 
        (inflation is bad). Some example of raids that fluctuate in value (meaning 
        the less amount of people the more RPP’s you get, and the more loot that 
        drops the more RPP’s you get) are epic mobs, Temple of Veeshan armor farming, 
        dragon farming, etc.</P>
      <P>Static value raids - Many raids aren’t fluctuating because that would 
        result in false reports of guild participation. For example if Trakanon 
        was a fluctuating raid, it may be worth 0 RPP’s one time because he dropped 
        2 items no one needs, and it may be worth 1.2 RPP’s the next because he 
        dropped 2 breastplates that we needed. Instead of making these large mob 
        raids fluctuate in value depending on loot, we take an average RPP value, 
        and reward that amount of points for each raid.</P>
      </FONT><U><B> 
      <P>IRPP's - the basic principles:</P>
      </B></U><FONT SIZE=2> 
      <P>Some events give IRPP instead of RPP. The events that give IRPP are the 
        events that do not have rewards in the form of loot. Some examples of 
        things that give IRPP are mob/zone recon, and failed attempts. Certain 
        successful raids may also give IRPP if they have excessively poor rewards 
        for the effort. </P>
      <P>IRPP's are designed to adjust the relative buying power of players.</P>
      <P>RPP's are balanced by RPP's leaving the system when items are won. IRPP's 
        are balanced with IRPP adjustments that are done every week or two.</P>
      <P>In a nutshell, IRPP's give a certain amount of points to those that go 
        to the event, and take away a certain amount from those who did not attend. 
        On an RPP raid everyone who attends may receive 1RPP. On an IRPP raid 
        everyone may receive 0.5 IRPP, while those who did not go lose 0.5 IRPP. 
        It has the exact same effect in either case - those who go, get X amount 
        of points up on those who don't. The difference is, by doing it this way 
        we don't get inflation.</P>
      </FONT><U><B> 
      <P>IRPP's in depth: The math.</P>
      </B></U><FONT SIZE=2> 
      <P>First thing, what is IRPP for? Well, the main idea of the RPP system 
        is that RPP going in equals RPP going out. That said there are certain 
        events that we can't reward RPP for because it would cause inflation. 
      </P>
      <P>However there are still other things such as failed attempts, recon, 
        etc that people should be rewarded for. We reward for these in the form 
        of IRPP.</P>
      <P>IRPP fundamentals:</P>
      <P>1) IRPP going in = IRPP going out. Always. The sum of all IRPP = 0.</P>
      <P>2) IRPP goes INTO the system when people participate in failed raids, 
        recon, against creatures that do not drop quality loot but we still need 
        to kill, etc. IRPP goes OUT of the system in the form of IRPP adjustments.</P>
      <P>3) IRPP's main function is to provide a small shift in current RPP from 
        those who do not participate in mob's which reward IRPP, to those who 
        do.</P>
      <P>Now, I know this is still very cryptic - but look at the formula and 
        results for the following example IRPP raids / adjustment and I think 
        it will make more sense. </P>
      <P>First, remember that the formula for current RPP is: </P>
      <P>RPP + IRPP = Current RPP</P>
      <P>Let’s say we have 2 IRPP raids. A Gozzrem attempt, And a failed Dain 
        attempt. Both are worth 0.2 IRPP. Gozzrem had 36 people - Dain had 39.</P>
      <P>Everyone who went to Gozzrem received 0.2 IRPP</P>
      <P>Everyone who went to dain received 0.2 IRPP</P>
      <P>Now, lets look at the IRPP adjustment that goes along with these raids. 
        An IRPP adjustment is a negative amount of IRPP given to EVERYONE under 
        the RPP system. How much the IRPP adjustment is (this time it was 0.25) 
        is directly dependent on how much IRPP went into the system since the 
        last adjustment. Since IRPP going out has to equal IRPP going in, here 
        is how i figure out how much to make the adjustment:</P>
      <P>36 people received 0.2 IRPP for going to Gozzrem = 7.2 IRPP enters the 
        system</P>
      <P>39 people received 0.2 IRPP for going to dain = 7.8 IRPP enters the system</P>
      <P>So, before i make the adjustment we had a total of (15) IRPP that has 
        entered the system. When i make the adjustment, I need to make a total 
        of 15 leave the system.</P>
      <P>So the formula is, of course:</P>
      <P>IRPP since last adjustment divided by total number of people in the system.</P>
      <P>I.e. 15/60 (assuming 60 people are under the RPP system)</P>
      <P>15/60 is 0.25, so everyone gets -0.25 as the IRPP adjustment.</P>
      <P>1) 0.2irpp X 36 people = +7.2 IRPP</P>
      <P>2) 0.2irpp X 39 people = +7.8 IRPP</P>
      <P>3) -0.25irpp X 60 people = -15 IRPP.</P>
      <P>Total IRPP currently in the system = 0</P>
      <P>Now, the result of this is those who went to none of the IRPP events 
        will end up with less current RPP. Those who went to _some_ of the events 
        will be close to breaking even, and those who went to all of the events 
        will come out with more current RPP. </P>
      <P>In this specific example:</P>
      <P>If you went to neither Gozzrem or Dain, you lost 0.25 IRPP</P>
      <P>If you went to either Gozzrem or Dain, you lost 0.05 IRPP</P>
      <P>If you went to both Gozzrem or Dain, you gained 0.20 IRPP</P>
      </FONT><U><B> 
      <P>What the RPP system accomplishes</P>
      </B></U><FONT SIZE=2> 
      <P>A lot of things, including but not limited to:</P>
      <P>The most obvious thing accomplished is it rewards based on each persons 
        time invested / items received ratio. No other looting system is able 
        to do this as accurately as this type of system.</P>
      <P>It allows people to continue their interest in character advancement 
        long after they max out equipment on one character.</P>
      <P>It eliminates the problems with alternate characters rolling on loot. 
        In most other systems if you allow people to lotto with an alternate char, 
        you end up with anyone with 2 chars getting twice the loot. This isn’t 
        the case with RPP, as the points are based on the player and shared between 
        their chars. Basically, if someone is equipping two characters, they are 
        simply splitting their earnings 50/50 between the 2 characters.</P>
      <P>This system also encourages and rewards people for coming to ALL events.</P>
      <P>There is no confusion about who deserves the item. This also gets rid 
        of situations where people disagree on the level of participation of a 
        member. The numbers are right there on the page for anyone to look at.</P>
