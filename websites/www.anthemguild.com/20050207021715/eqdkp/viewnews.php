      <b style="font-size:13px">The old year is dead, All Hail the New Year!</b> <span class="small">(submitted by Barangi at 08:05am EST)</span><br /><br />
      Another year goes by and with it, another expansion gets added to the list of "Been there, Done that!". During the first half of 2004 the word Anthem spoken on E'ci was equal to speaking the two words Vex Thal. We we're all over the place, clearing the zone more or less every single respawn, gearing up our raid force for the push into the elemental planes.<br />
<br />
In early March 2004 we gained elemental plane access by besting Rallos Zek the Warlord in our 3rd attempt. The focus started slightly shifting towards the Planes, but for the first few months after nailing RZ, we were still the uncrowned masters of VT and Ssra.<br />
<br />
Wanting as broad a range of targets as possible, at least I think that's the reason, alot of the guilds focus was also placed upon obtaining Kod'Taz access. Weeks were spent where it felt like we'd all been convicted and sent to serve a lifetime in the windy, rocky canyons of the Tipt and Vxed expeditions. By the beginning of August enough members had completed these expeditions, that an attempt was made at Smith Rondo and wouldn't you know it, we won - Welcome Anthem to Kod'Taz and the first 'real' steps into Gates of Discord could be made.<br />
<br />
By the end of August we had our annual real life guild meeting. Roughly 40 of our members from USA, England, Germany, Sweden and of course Denmark made the trip, halfway round the globe for some, to a beachhouse on the west coast of Denmark and spent a week together, for the most part in weather matching your average danish summer - a.k.a. rain and lots and lots of wind.<br />
<br />
During the fall and early winter of 2004 we netted our first couple of Elemental God kills, bagging Fennin Ro and Xegony and failing over and over on the Squid King of the Reef. To quench our thirst for Revenge upon The Big Kahuna we've cleared all his minions in the Reef several times and feel that we are at least somewhat even at the moment.  Due to a selfsacrificing, tireless and ill-rewarding endeavour of a select few - gotta love sarcasm, huh?, Anthem also gained access to the Ikkinz raids during this period and subsequently went on to beat all but the very last one of them. Not even the Primals hiding in the remote caverns of Yxxta could count themselves amongst the few mobs escaping our searching Eye of Endless Encounters, and were forced to add themselves to our list of "Put up no fight, got Owned!".<br />
<br />
All in all we've been pretty busy this year and although at some points the end goal of all these crazy things we run around doing can be hazy if not down right invisible, I'm sure that in the Grand Scheme of Supreme Dictator Sacilia of the Clan AFK, quite a few little x's has been added in the "To Do" section.<br />
<br />
We've had numerous addidtions to the guild over the past year and yet, we still manage to make sure, that we never have an abundance of people online. This is achieved by the force known to some as The Burn Out. Several people have moved on to other games or decided to take a break from EQ for a bit and some have made the life turning decision to quit all together. From here a very big "Welcome class of 2004!" to all the new faces and an equally big "Thank you for the Fish! See you at the 5 year Reunion!" to all the people that's moved on for one reason or another.<br />
<br />
<br />
Lastly, but by no means the least, I know that a few of our members know people or are related to people involved in the disaster in Asia. I think I speak for all current and former members of Anthem when I say, that we all hope and pray that each and every one of your friends or loved ones will be found and be safe and, in the event that they should be lost, that you will think of all of us as friends and use us in getting a grip on what ever sorrow or difficulty you may experience.<br />
<br />
<center>HAPPY NEW YEAR, EVERYBODY!</center>
