<BR>
Rules are those guidelines which the guild operates under that are not up for debate.  These rules will be followed by every member of Legerdemain.
<BR><BR>
<P>
Fellow guild members will always be treated with respect<B>.</B>  There will be no flaming<B>,</B>
bashing<B>,</B> hazing<B>,</B> or anything other than respectful behavior shown<B>,</B> especially in
<B>/</B>guildsay<B>.</B> Any blatently disrespectful treatment of another member in <B>/</B>guildsay will be resolved
by <B>/</B>guildremove<B>.</B>  If you are the target of blatently disrespectful comments in <B>/</B>guildsay<B>,</B>
do <B>NOT</B> respond in kind<B>.</B>  If you do<B>,</B> you will also be <B>/</B>guildremoved<B>.</B>  If you have
a problem with another guild member<B>,</B> attempt to solve it in <B>/</B>tell<B>.</B>  If you can<B>'</B>t<B>,</B> bring
it to the attention of the guild leader<B>.</B>  You are also required to treat any other people
in Everquest with respect<B>.</B> Remember<B>,</B> weather you like it or not<B>,</B> you<B>'</B>re representing
Legerdemain out there<B>.</B>
</P>
<P>
Unconditionally accepted alternate characters<B>.</B>  Any race<B>,</B> class<B>,</B> or level<B>;</B> your alternate
characters are welcome<B>.</B>  If you are an officer<B>,</B> your alternate characters will be too<B>.</B> The
highest rank attained in the guild by your main character transfers to any and all alternate
characters<B>.</B>  You receive rank in Legerdemain on a personal level<B>,</B> not a character level<B>.</B>  No matter what
character you<B>'</B>re on with though<B>,</B> you will be using <B>/</B>role to hide your class and level rather than
<B>/</B>anon<B>.</B>  No<B>,</B> you don<B>'</B>t have to hide your class and level<B>,</B> but if you feel you must<B>,</B> use <B>/</B>role<B>.</B>  <B>/</B>anon
removes your guild tags from view<B>.</B>  There should never be a reason that you don<B>'</B>t want someone
to know what guild you<B>'</B>re in<B>.</B>  If you<B>'</B>re about to do something questionable that you don<B>'</B>t want the guild
to be held responsible for<B>,</B> sorry<B>,</B> but <B>/</B>guildstatus will reveal your guild anyway<B>.</B>  Besides<B>,</B> if you<B>'</B>re
doing that sort of thing<B>,</B> perhaps you should re<B>-</B>consider what guild you<B>'</B>re in<B>.</B>
</P>
<P>
Never will you be required to attend any guild functions<B>.</B> If you<B>'</B>re busy playing <B>/</B>gems<B>,</B>
in a group<B>,</B> watching TV<B>,</B> or kiting a spider <B>-</B> you do what you wish<B>.</B>  It may be in your
own interests to join in guild functions<B>,</B> and others may try to peer pressure you into it<B>,</B>
but there are no guild rules requiring you to attend any raids<B>,</B> meetings<B>,</B> parties<B>,</B> or anything<B>.</B>
Remember folks<B>,</B> it<B>'</B>s all for fun<B>.</B>




