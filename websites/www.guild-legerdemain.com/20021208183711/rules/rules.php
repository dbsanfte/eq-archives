<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>O</B></font></TD></TR></TABLE>ur strict rules are in place for specific reasons; to protect our guild members from eachother, from the community, and to do our best to ensure that they have the opportunity to enjoy the game.  If these rules seem too harsh, too uptight, or too condemning, then this isn't the guild for you.  It would be nice if we didn't have a need for rules, but over the past three years, we've demonstrated that we can not do without them.  The majority of these rules are what some would consider "common sense" or "common courtesy".  They are planely stated and are strictly enforced.<BR>
Like any rules, the dividing line between right and wrong can get blurred at times. Also, there are ways around any rule. We can only do our best to protect the kind hearted Legerdemain members. Even if you have not broken any of the rules directly, if you are perceived to be "working around" the rules on multiple occassions, you can be removed. I'd suggest you not even get close to that blurred line.<BR>
There are no warnings for violations, however, you will only be immediately removed for one violation if your violation is blatant. If your violation is hearsay, it must be corroberated by others. Several un-corroborated violations will also warrant a removal.<BR>
There will be no debating whether or not a violation warranted removal.  The final judgement belongs to the guild leader; Terrenoth.  If you feel you need an explanation for your removal, one will gladly be given.  If you retaliate with a defense for your position or any sort of attack, you'll simply be put on /ignore.<BR>
Once you've been removed from the guild, you will have to wait at least one month before you can apply to the guild again.  Your former guild mates will then vote on whether or not you deserve to be welcomed back into our ranks.   They will also decide if you should have to pay any sort of fine in the way of Points.<BR><BR>
It is a privilege to be a member of Legerdemain, not a right.<BR><BR>
