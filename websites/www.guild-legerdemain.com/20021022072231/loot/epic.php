<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>E</B></font></TD></TR></TABLE>pic loot is handled the same way as any other piece of <U>point loot</U> when on a <u>Sanctioned Raid or Strike</U>.  The difference between normal loot and epic loot lies in how you go about getting to the mob.  If you happen to be on a <U>Sanctioned Raid or Strike</U> and a piece of epic loot drops, great!  It will be /randomed amongst those who wish to pay for the item as described in our <U>Point System</U>.  The item is also subject to <U>Triple Cost</U> if someone can afford it and is willing to pay.<BR><BR>

What about those times when you want to specifically target an epic mob for YOUR epic piece.  You don't want anyone else to have a shot at the loot, especially considering you have to turn something in to spawn the mob; for instance.  If the entire purpose of the event is to get YOU this item from this mob, that would be a <U>Sanctioned Epic</U> event.  <U>Sanctioned Epic</U> events require a number of points to be spent by the requestor just to get the event going.<BR><BR>

You also  have the option of having an un-sanctioned epic.  In such a case, un-sanctioned event rules apply. (see <a href="http://www.Guild-Legerdemain.com/events/unSanctioned.php">Un-Sanctioned Event</A>)  You wouldn't have to pay a single point for your Epic item.  There are a couple of benefits for doing a Sanctioned Epic rather than un-sanctioned, though.  The Sanctioned Events are run by an SRL who is more knowledgable and seasoned than most other event leaders.  Each of the attendees will get points for attending, assuming at least 12 members show up.  For those that feel guilty about soliciting guild help, you can rest easy knowing you earned and paid for the help that was provided.<BR><BR>

Why would I ever want to do my epic as Sanctioned, you ask?  One of the more difficult parts of getting an epic event completed is having the people actually show up.  The next part is having the organization to get the job done.  A Sanctioned epic event offers points to people who meet the level requirements for the event.  This increases the likelyhood that people will show.  Holding a sanctioned epic event makes a statement that you are serious enough about your epic to pay for it with hard earned points.  This also increases the likelyhood that people will show up.  It does not guarantee that people will show, though.  Also, a sanctioned event is run by an SRL.  This increases the chances that the job will actually get done provided enough people show up.<BR><BR>

You are more than welcome to get by on good looks instead.  Put together an event and cross your fingers.  Perhaps ask someone to run it who has a little more experience with such things.  Unfortunately, you can't ask an SRL to run an un-sanctioned event.  Maybe run it yourself and hope for the best.  You never know, maybe you have much more experience with that mob or place than any of the SRL's.  It is, after all, your epic and you can handle it any way you wish; assuming you abide by our rules, of course.  You could pay another guild to take out your epic mob.  You could make friends outside of Legerdemain and solicit their help when the time comes.  There are any number of ways for you to go about getting the help you need.  If you want to have Legerdemain get your epic piece for you within a <U>Sanctioned Epic</U> event, there is a price you must pay in points and a level requirement you must meet.<BR><BR>

Each of the epic quests has been divided up by the battles they must complete.  The battles have been rated by difficulty and assigned a difficulty grade.  Several of the lesser battles were removed from the lists entirely.  Such battles could be handled by you alone, or with a single group.  A point value of 500 points was assigned to each quest.  These points were divided amongst the remaining epic battles based on their difficulty grade.  Each epic drop still has a point value, but since you're paying for the battle itself, you need not worry about the additional item cost.  The item cost is there for when the epic item drops on an event which is not a <U>Sanctioned Epic</U> event, but merely a <U>Sanctioned Raid, Strike, or Alt</U>.  To be able to pay for one of these epic battles, you must be at least level 55.  If you're not, you need to be worrying about getting exp more than getting your epic.<BR><BR>

If you'd like more information about <U>Sanctioned Epic</U> events, when and how the points are actually paid, how one goes about setting one up, etc. please visit the <a href="http://www.Guild-Legerdemain.com/events/epics.php">Epic Event</A> page.<BR><BR>




