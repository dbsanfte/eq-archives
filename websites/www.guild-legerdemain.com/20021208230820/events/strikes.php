<font size="-1">Note: The majority of this standard has been hijacked from the great example set by <a href="http://www.harmonyofsouls.org" target="_hos">Harmony of Souls</a></font><BR><BR>

<B>FCFS defined</B><BR>
First Come First Served. Prexus, in general, follows a policy that allows the first force to engage a mob the rights to kill it unencumbered. You must have a force capable of killing the mob and be in the vicinity to engage it. If you do not have a force sufficient, and another group has gathered who does have a force, you should politely step aside.<BR><BR>

<B>What does FCFS apply to</B><BR>
At its basic level, every single engagement on Prexus is FCFS. In practice, it only applies to large scale encounters, and rare, roaming spawns. FCFS does not apply to experience camps and the nameds they generate (assuming the force doing the exp can kill the named). By definition, the exp group is already there, and can kill the named mob. If they cannot reasonably kill the named mob, it is then subject to FCFS rules.<BR><BR>

<B>Watchers and Trackers are not "camping" the mob</B><BR>
Even if you sit watching a spawn for 3 days straight, you have no more right to the mob than a wandering player does. Sitting at a spawn point only gives you the advantage of information. You will be the first to know the mob has spawned. If you cannot muster your force before another guild is ready, you have lost the FCFS race.<BR><BR>

<B>Kiting the mob</B><BR>
Kiting is not allowed to secure a mob. If you are kiting a mob without doing damage, you have absolutely no rights to it, and it can be taken from you at any time. What’s more, kiting to prevent another guild from pulling the mob is considered bad form.<BR><BR>

<B>Mustering for a FCFS mob</B><BR>
Do not interfere with another guild’s muster. Let them gather their force with as little hindrance as possible. Move into a reasonable position in the zone, but do not enter the mob’s aggro area until you have a force ready to engage.<BR><BR>

<B>Communication</B><BR>
No person, except the SRL, on the raid will engage in ANY public communication with the competing raid before, during or after the engagement other than to congratulate them if they were victorious. If you are not the SRL and someone sends you a tell asking about your strike, do NOT be misleading, threatening, or derogatory.  Answer honestly and respectfully or don't answer at all.<BR><BR>

<B>Pull it or step aside</B><BR>
When you are ready to move on the mob, announce it to the other raid and move your troops. An honorable guild will let the first one ready to go try first. By the same token, once you announce you are moving in, do so. Engage the mob within reasonable time, or forfeit. It is perfectly fair for the prepared guild to send a message of "pull or move aside" to the competing guild. Legerdemain will issue this twice. The third time, we will move ahead and pull the mob.<BR>
Once one guild is ready to engage, the competing guild should move out of the line of sight so as to reduce lag. If the first guild loses, they have forfeit their rights to the mob, and the waiting guild can step in and finish it off. <BR><BR>

<B>Engagement</B><BR>
Once a guild engages a mob, no other guild should interfere. Let the group live or die on their own. FFA is NOT FCFS, trying to out-damage another raid is considered bad form. If the first guild dies, the waiting guild can do anything they choose.<BR>
You MUST be actively engaging and damaging the mob. If your raid wipes almost completely (i.e. one or two casters are alive and out of aggro range) you forfeit. If you have to do CR to re-engage, you lose.<BR><BR>

<B>The aftermath</B><BR>
If you stepped over corpses, have the courtesy to assist in the CR. Send the competing raid the status of the mob- dead or you failed.  You could have also choosen to help with the competing guild's CR before you engaged.  Maybe drag their corpes out of harm's way and rez a cleric of theirs before you begin.  The decision of when to help with CR will be based on how the two guild's have been interracting.  Regardelss of any arguments, the offer to help with CR should be made.<BR><BR><BR>


<B>General things you should do:</B><BR>
Shake hands afterwards. We learned this in grade school, and it still helps. Whether in public channels or privately, smile and offer congratulations to the victor (gratsing the mob when he wipes a raid is not necessary)<BR>
Announce your intention to pull. Let the other guild know you have won the race and are taking your turn.<BR>
Communicate. If someone asks you what you are there for, tell them. If you won the race, there is nothing to lose and it will save people wasting their time.<BR><BR>

<B>General things you should not do:</B><BR>
Do not berate, abuse or heckle the competing raid<BR>
Never ever train anything on the other raid. It’s cheating, plain and simple<BR>
Do not kill triggers. If you lost, you lost.<BR>
Do not lie to the other raid. Don’t misinform them intentionally or try to delay them to get ahead.<BR>
Never reply to a campcheck with "Zordak is camped". It is stupid and embarrassing to your guild.  Responding with "I am watching for Zordak" is more logical, tho not necessary at all.<BR>
Do not stay in the area while a competing guild fights, thus lagging them and crippling their raid.<BR><BR>

<B>Points:</B><BR>
The regular 10 points will be awarded for a strike, regardless of the outcome.  Double points will be awarded for killing any point mob for the very first time as a guild.  As usual, points gained on a Sanctioned Strike are not counted towards your total until the entire strike is completed and reported.  For more detailed information about loot distribution, check out <a href="http://www.Guild-Legerdemain.com/loot/ourLoot.php">our loot</A> rules.<BR>

