<a href="http://www.Guild-Legerdemain.com/rules/rules.php">Our Rules</a>
<HR width="75%" color="#773322">
<TABLE width=50% border=0 cellspacing=0 cellpadding=0><TR>
<TD bgcolor="black" align="center">The Rules</TD><TD align="center"><a href="http://www.Guild-Legerdemain.com/rules/reasoning.php">Reasoning</a></TD><TD align="center"><a href="http://www.Guild-Legerdemain.com/rules/examples.php">Examples</TD>
</TR></TABLE>
</CENTER>
<HR width="75%" color="#773322">
<BR>
<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>1</B></font></TD></TR></TABLE> <B>Begging.</B> There will be no begging in /gu or any other channels whatsoever. Begging is asking for money or equipment without offering to repay the giver with fair market value. This is an issue I feel VERY strongly about. If you think that what you're about to say MIGHT be seen as begging, don't say it. The <A href="http://pub50.ezboard.com/flegerdemainfrm9">altar of arms</A> is the ONLY place we are allowed to wish for things as long as our wish is not directed at anyone specifically.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>2</B></font></TD></TR></TABLE> <B>Trading.</B> /gu is NOT to be used for item trading or selling. If you must share items with guild members, do so in the <A href="http://pub50.ezboard.com/flegerdemainfrm9">altar of arms</A>. If you want to sell or buy something do it in the facilities provided by EQ like /auction or /channel ecauction. Even the <A href="http://pub50.ezboard.com/flegerdemainfrm9">altar of arms</A> can be used to sell items to guild members. It's normally used to give items away, though.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>3</B></font></TD></TR></TABLE> <B>Services.</B> A service is any act, combine, spell, or effort that one uses to aid another character in some fashion such as a port, rez, or item making. You will NOT request a service of any kind in /guildsay. You can offer services in /guildsay, but to request them you should make a post in the <A href="http://pub50.ezboard.com/flegerdemainfrm9">altar of arms</A> which is not directed at anyone specifically.<BR>
Sending tells for services is against the rules, but it is a  touchy subject within the gray area of the rules. This means that if you send a tell asking for a service, the person getting the tell can report your actions. Now, this information would be hearsay and can't be used, alone, to remove you from the guild. If there are numerous complaints about you requesting services in /tells, though, you will be removed. I'd suggest, if you intend to make a request in tells, that the person your sending a tell to JUST offered their services in /guildsay.<BR>
The exception to this rule is when you are grouped or raiding with the person involved where related services apply.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>4</B></font></TD></TR></TABLE> <B>Respect.</B> You wll treat everyone in EQ with respect no matter what they may have done. You represent Legerdemain in your words and actions. If you are unclear about what <I>"respect"</I> is, then you will eventually violate this rule enough times to be removed. Perhaps the best guidelines here are <B><I>"If you can't say anything nice, don't say anything at all"</I></B>, and <B><I>"Do unto others as you'd have them do unto you."</I></B> If you have a "mortal enemy", or someone on our blacklist, /ignore works wonders. /petition can help for persistant irritants.  Everyone has bad days, and things will get said that probably shouldn't have.  Do your best to keep that to a minimum.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>5</B></font></TD></TR></TABLE> <B>Foul Language.</B> You will NOT use foul language in ANY public channel. You will also NOT be lewd or crude. Yes, we sometimes get a little bit out there with our insinuations and innuendos in /guildsay, but we will NOT go too far. We do NOT cross <B>"that"</B> line. If you are unclear about where <B>"that"</B> line is, don't go anywhere near it. If you are unclear about a particular word being defined as <B>"foul"</B> or not, don't use it. Some words that are generally accepted are crap, hell, arse and shizz. Even the overuse of such accepted words, though, is frowned upon.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>6</B></font></TD></TR></TABLE> <B>Alternates.</B>  Your alternate characters will be welcome in Legerdemain regardless of their level.  You MUST add your alt to the web page once it has been invited or it will be removed from the guild.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>7</B></font></TD></TR></TABLE> <B>LFG in guildsay.</B> You can state in guild that you are LFG no more than once every 15 minutes.  This is the only method you may use to look for a group in guildsay.  Those starting groups, or rotating group members in and out are allowed to state in guildsay what Class and level range they are looking for.  You are not allowed to specifically target a person in /gu for your group nor pester someone in /tells for groups.  This rule does not apply to guild events.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>8</B></font></TD></TR></TABLE> <B>Bored in guildsay.</B> There are hundreds of ways to complain about being bored. Don't do it in /guildsay. You are allowed to state that you are available if someone needs/wants you in /guildsay, but not to complain about being bored.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>9</B></font></TD></TR></TABLE> <B>Counceling in guildsay.</B> You are not allowed to bring the guild down. Horrible things happen in real life. Perhaps some of those things happen to you. Perhaps some of those things happen to me. We feel for you. Do NOT share that with the guild. If you share your list of hurt and pain with the guild, add being removed from Legerdemain to that list.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>10</B></font></TD></TR></TABLE> <B>Anonymous.</B> You are not allowed to use the /anon tag on any of your characters who are Legerdemain members at any time for any reason. The /role tag can be used at your discression.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>11</B></font></TD></TR></TABLE> <B>Hazing.</B> The ribbing or teasing of fellow guild members is allowed as long as it is handled respectfully and without foul language. You are not allowed to make such hazing a habit; particularly if you constantly target the same person. If you don't know how much teasing is too much, stop. Don't find out.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>12</B></font></TD></TR></TABLE> <B>Prejudice.</B> You will not make hurtful reference to ANY race, religeon, ethnicity, age, weight, or financial status. There will be no hateful jokes, remarks, or discussions on these topics.<BR><BR>


<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>13</B></font></TD></TR></TABLE> <B>Guild Events.</B> You are not obligated to attend any guild events at all.  If you choose to be a guild member who doesn't raid, that's fine with us.  You are, however, required to participate if you attend an event.  If you do not, you can be removed from the raid.  If you perpetually attend events only to sit around without participating, you may eventually be removed from the guild.<BR><BR>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>14</B></font></TD></TR></TABLE> <B>Help Me!</B> We all would like help now and then.  There is only one instance when you actually NEED help.  If your clothed corpse is going to rot, and you've already been trying to get a necro/SK to summon it for the past three days, you NEED help.  You can ask for help in /guildsay if this is the case.  If you're camping a contended mob, you should post your intention to do so.  When it pops, you're allowed to /guildsay that your mob has popped and that you're gathering forces.  If it's a Sanctioned event, follow the protocal stated in the description of Sanctioned events on this website.  Everything else, post it in the Playground and hope that enough people show up.  If they don't, try it again some other time.<BR><BR>


<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>15</B></font></TD></TR></TABLE> <B>The SRL is the Boss.</B> Your <U><I>Sanctioned Raid Leader</I></U> is your boss on a Sanctioned Event.  The SRL could be right.  The SRL could be wrong.  The SRL may cost you plat, time, exp, and a few aspirin.  The SRL is still your boss on a Sanctioned Event.  You do not question or contradict the direction of the SRL unless your opinion is asked for.  You do not dispute the distribution of loot.  You do not complain about the way groups were organised.  You do not complain that you're not getting enough exp.  The SRL is doing their best to make the event successful and enjoyable for everyone.  If you have constructive criticisim, talk to them about it later.  Do not attempt to engage in idle chit-chat with the SRL.  They are busy.  If you simply can not understand these concepts, don't come to Sanctioned Events.<BR><BR>


