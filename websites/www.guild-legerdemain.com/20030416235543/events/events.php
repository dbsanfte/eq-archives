<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>T</B></font></TD></TR></TABLE>here are five different kinds of events.  A general description has been provided describing what the various events are and how loot is distributed in the <a href="http://www.Guild-Legerdemain.com/loot/pointSystem.php">Point System</a> pages.  As a side note, no Legerdemain member is obligated to attend any event whatsoever.  There are no rules stating otherwise, and your lack of attendance will only be a liability when distributing loot on Sanctioned events. Conversely, if you attend an event, you must participate.<BR><BR>

There are four different kinds of Sanctioned events; raids, strikes, alternates, and epics.  There are also un-sanctioned events.  The differences are simple.  On a Sanctioned event, a <I><U>Sanctioned Raid Leader</U></I> is running the show and loot is handled according to our point system.  On an un-sanctioned event, anyone <B>BUT</B> a <I><U>Sanctioned Raid Leader</U></I> is running the show and loot is handled however the event leader decided.<BR><BR>

Several questions may come up about what constitutes an un-sanctioned event, how do I deal with the competition on a strike, how do I run an un-sanctioned event, how many points would purchasing my epic battle cost, or any number of other questions.  The following pages are in place to help answer some of those questions.  If you have any questions that have not been answered on this web page, please e-mail <a href=mailto:Terrenoth@yahoo.com>Terrenoth</a> or visit our <a href="http://pub50.ezboard.com/blegerdemain" target="_forum">Forums</A>.<BR><BR>

