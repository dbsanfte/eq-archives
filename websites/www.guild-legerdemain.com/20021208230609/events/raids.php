<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>S</B></font></TD></TR></TABLE>anctioned Raids are our bread and butter, so to speak.  These are the events that have the most impact on us as a guild.  Can we take Vindicator? Do we lay waste to the Royalty of Chardok?  How often do we farm Ntov?  Do we chase epic pieces in the planes? Many more questions will be answered with each Sanctioned Raid.  It is also these raids that will determine what kind of equipment our members have.  In turn, these raids will determine how "powerful" our members are and, as a result, what mobs and zones are targetable by us as a guild in future raids.  Because of the importance of these Sanctioned Raids, missing them has a consequence.  Each member of apporopriate level to attend a Sanctioned Raid who does not, will have 3 points removed from their total.  The loss of points in this manner will never move a member's point balance below zero nor will it cause a member to go further negative.<BR><BR>

There is no need to worry about the loss of points in this way.  Sanctioned Raids present the only involuntary loss of points.  There are plenty of ways to make points if you wish to.  Of course real life is more important than EQ.  You will miss Sanctioned Raids and lose points as a result, but it will not devistate your position in the guild.  The loss of points in this fashion is in place merely as an additional discouragment of selective raiding.  Keep in mind that it would take missing 50 Sanctioned Raids to lose 150 points.  Assuming we have 2 Sanctioned Raids per week that you miss, that means it would take roughly 6 months to lose 150 points this way.  Also assuming we have 2 Sanctioned Raids per week, it would take roughly 15 raids to make all of the points back.  2 months to make up 6 months of absence.  That's assuming you don't attend any other Sanctioned Events at all, and that we don't kill any Point Mobs on any of those raids.  It would most likely take less than 2 months to make it up if you attended any other Sanctioned Events.  This penalty is so miniscule, that it may actually be increased depending on how it performs over time.<BR><BR>

A Sanctioned Raid will always be run by a <U><I>Sanctioned Raid Leder</I></U>.  While many may possess the will and enthusiasm to lead, few have the knowledge, experience, and skill to make high-end raids an enjoyable success.  Considering the importance of our Sanctioned Events, there will be no exceptions.  If you are not an SRL, you may not run a Sanctioned Event of any sort.  If you are interrested in becoming an SRL, visit our <a href="http://www.Guild-Legerdemain.com/loot/SRL.php">SRL page</A> which describes their duties in detail.<BR><BR>

Our Sanctioned Raids must be posted by a <U><I>Sanctioned Raid Leder</I></U> in the <a href="http://pub50.ezboard.com/flegerdemainfrm10" target="_Plygnd">Playground</A> of our message boards.  The SRL must entitle the post with an <font color="blue">"</font><font color="black">S-</font><font color="blue">"</font> followed by the name of the zone or mob followed by the date follwed by the time.  A Sanctioned Raid for the Plane of Hate might have a subject of <font color="blue">"</font><font color="black">S-PoH/9-1/10amCST</font><font color="blue">"</font>.  The post must be made at least one week (168hours) before the target date/time.<BR><BR>

You will lose 2 points if you are late to a Sanctioned Raid without prior notification including an accurate time estimate.
An accurate time estimate means that if you notify the SRL, by post or tells, that you will be one hour late, you will still lose 2 points for being late if you show up two hours later.  You, of course, will not lose points if you show up close to or before the time you estimated when it is possible for you to join the raid.  It may turn out, though, that we have no way to get you to the raiding party.  If that is the case, you will simply not be able to attend and therefore lose the 3 points for not attending.  The idea here is that everyone has real lives to attend to.  They take the time out to show up to a raid on time.  There is no reason why we should punish those people by making them sit on their bum waiting for you to ride the boat or cook breakfast.  The Sanctioned Raids are posted a week in advance.  That should be plenty of time to park at the designated area ahead of time.<BR><BR>

What can we do a Sanctioned Raid on?  We can do a raid on just about any 50+ish type area or mob that has a chance of droping point items.  A Sanctioned Raid must have at least 12 members in attendance including the SRL.  If a point mob is killed during a raid, the points are added to the members who were in attendance at the mob's time of death.  We are not allowed to call Sanctioned Raids which have already determined a winner of a particular piece of loot.  An SRL can not post a Sanctioned Raid to specifically get you a Nightgown of Sexiness.  Now, an SRL can post a raid on the mob that drops such an item.  If someone happens to be the only person on the raid who can use the item, by design or by coincidence, that's perfectly fine; assuming that same mob or area also drops enough other loot to justify the raid.  The opportunity for other eligable members or guests to be in on the loot, however, MUST remain intact.<BR><BR>

How do you get the SRL to raid where you want to go?  Well, talk to the SRL's.  They will take your request into consideration.  You might also post about your desire to raid a particular zone or mob.  Try to feel out if there are others who want to attend a Sanctioned Raid in that area.  There are all kinds of places to go and try.  Don't worry too much about what we can and can't do.  If your request is too far out of our reach, chances are that an SRL won't pick it up.  You should still post about your desire, though.  Who knows what may happen :><BR><BR>

What about epic drops on raids?  Regular epic drops are handled as described in our <a href="http://www.Guild-Legerdemain.com/loot/pointSystem.php">Point System</a> depending on whether or not they are no-drop or multi-questable.  Anyone with sufficient points, if called out by the loot distributer in a random lineup, is fully capable of requesting to Triple Cost in an effort to secure the item.  Now, what if we're on a raid and going somewhat near your epic mob?  There is no problem with letting the SRL know that we'll be near an epic drop. The SRL will determine if the mob would take the raid an additional 5 minutes, half hour, 2 hours, or what.  The SRL may not be familar enough with that epic mob and simply decide not to go there based on his or her lack of knowledge.  If it is decided to stop by the epic mob, the loot will be open to any eligable person to pay for in accordance with our <a href="http://www.Guild-Legerdemain.com/loot/pointSystem.php">Point System</a>.  Being the person who mentioned the epic mob, or being the person who wants it most etc.. does NOT guarantee you the item if there is someone else on the raid who is in the same loot order as yourself.  For mobs that must have an item turned in before they are killed, the person doing the turn-in will be determined according to our loot order before the attack.  In other words, if two members of the raid have the trigger item and are both in the same loot order, they must /random or Triple Cost before the fight.<BR><BR>

You may have noticed that getting an epic drop in this fashion can be much cheaper.  While this is true, there are a few things to take into consideration.  An SRL is NOT allowed to do a Sanctioned Raid to get you your epic piece.  If you want one done specifically for you, that's a <a href="http://www.Guild-Legerdemain.com/events/epics.php">Sanctioned Epic</a> event and it will cost you additional points.<BR>
For example; we could do a Sanctioned Raid on the Chardok Royals.  If we do so successfuly, we will probably end up with a Prince Head(chanter epic), King note(cleric epic), and a Queen blade(warrior epic).  Getting these items on a raid means that anyone who is eligable for them according to our <a href="http://www.Guild-Legerdemain.com/loot/pointSystem.php">Point System's</a> loot order, has a shot at the item.  While this would be perfect if you were the only person needing an epic drop, it would not be in an SRL's best interests to run a such a Chardok Royals <U>Sanctioned Raid</U>.  The other loot that drops off of the Royals simply isn't substantial enough to warrant an attack without the epic drops.  The attack's alterior motives would be recognized and the SRL would be in jepordy of losing his or her position.  Now, if we were to have two or three cleric's in need of notes on that same raid, even if we still only have one warrior who'd benefit from the Queen blade, the Sanctioned Raid would be justified.<BR><BR>

If you attend a Sanctioned Event and can not gate or port, have a gate potion of some sort handy.  Buy one from a shammy, quest one from Thurgadin, or invest in an item that can port you out.  Honestly, the 200-500plat you may spend on a gate potion is WELL worth the peace of mind.  You could have that in your inventory for 6 months without ever using it.  Knowing it's there in case you do need it, though, is priceless :><BR><BR>



