<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>A</B></font></TD></TR></TABLE>ny member of Legerdemain has the capability to hold an un-sanctioned event.  These events MUST be posted in the <a href="http://pub50.ezboard.com/flegerdemainfrm10" target="_pgnd">Playground</A> of our message boards.  They don't specifically need to be posted an hour, a day, a week, or a month in advance, but they must be posted before the event takes place.  How far in advance is completely up to the person holding the event.  It may be in your own interests to post the event with enough notice to allow others to shcedule their days accordingly, though.<BR><BR>

There is only one major rule for un-sanctioned events.  <U><I>Sanctioned Raid Leaders</I></U> are NOT allowed to run them.  If you would like to benefit from the experience of an SRL, then you should attend Sanctioned Events.  As long as that rule, along with the other <a href="http://www.Guild-Legerdemain.com/rules/rules.php">
rules</a> of Legerdemain, is followed, you can pretty much do what you want.<BR><BR>

Loot can be distributed as you like, groups formed how you like, communication handled however you like, and strategy executed exactly as you like.  You can have outside guests, or make it guild only.  It's all up to you.  Un-sanctioned events do not affect point values in any way whatsoever.<BR><BR>

Keep in mind that these events do not allow you to guilt-trip our members while you're on-line.  You are only allowed to <FONT color="#222EE">/gu the un-sanctioned raid on BlackBurrow has begun.  We're gathering in Qeynos Hills at the zone to BB.</FONT>  You are not allowed to <FONT color="#222EE">/gu aww, come on! I know you're out there! Come to my raid.  I see you, Bob.</FONT>  You are not allowed to <FONT color="#222EE">/gu Please! I came to your raid. We only need one more tank, Fred.</FONT> Your bunz will be removed from the guild before you can blink.  Don't even kid around about such things.  If your event doesn't have enough people show up of their own free will, try again another day.<BR><BR>

Sometimes, people will want to hold un-sanctioned Strikes.  That's fine.  Post that you're camping the mob for an un-sanctioned event over a given period of time.  This "heads up" post is what will give you the right to say <FONT color="#222EE">/gu Woushi has popped. As I posted, I intend to do an un-sanctioned Strike.  We're gathering in WL at the rings, if you're interrested.</FONT>  Stating something like this in guildsay is fine IF you've made your post ahead of time.  If you spout off without having posted, or, again, try to guilt-trip people into coming to your event, you will be removed from the guild.<BR><BR>

Un-sanctioned events can be really fun.  Our guild is a place for fun within Everquest.  The two go together as long as nobody allows their greed to overwhelm them.  We will not have our members try to force eachother into events.<BR><BR>


