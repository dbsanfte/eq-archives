<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>N</B></font></TD></TR></TABLE>on-pointed loot is that loot which does <B>NOT</B> have a value listed for our point system.  There will be no-drop, dropable, class specific, all/all, quest pieces, weapons, and armor.  All of these pieces of loot are to be handled in the same way for Sanctioned Events.
<BR>
The items will be /randomed immediately.  If someone on the raid misses the /random call, tough luck.  If you are interested in loot, pay attention.  For those that are paying attention, /randoms will be handled according to the following order:
<OL type="1">
<LI>
Anyone in attendance who is capable of using/questing the item in question and has not already won a piece of non-point loot on this raid.
<LI>
Anyone in attendance who is capable of using/questing the item in question.
<LI>
Open Random.  Anyone in attendance who wants the loot can be included on the random.
<LI>
Rot/Destroy
</OL>
Any non-point loot gained in our Sanctioned Events belongs to the winner; free and clear.  There is no obligation to keep the loot in guild, on your main, or to prevent anyone from selling the items they have won.<BR>
<BR>
Money items and cash split are handled at the discression of the <U><I>Sanctioned Raid Leader</I></U>.  Money items can be ignored, selectively gathered and distributed, redirected to clerics, funneled into his/her own pockets, or summarily destroyed.  Cash on a raid is a very secondary issue.  Sure, it's nice to be compensated for the 100plat of peridots you just spent, but that's really not a priority.  Gathering all the plat and plat items for distribution can be a hair pulling experience itself.  There's no need to torture your <U><I>Sanctioned Raid Leader</I></U> by obligating them with that burden; especially after a long hard raid.<BR>





