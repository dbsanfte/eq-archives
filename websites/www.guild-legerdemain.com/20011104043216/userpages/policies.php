<BR>
Policies are those guidelines that can be removed or altered by a majority vote within Legerdemain.
<BR><BR>
<B><Font size=+1>
Language
</font></B>
<p>
Foul language is not acceptable.  Yes, there is a foul language filter, but that is not a permit to use foul language.
The filter is merely a stop-gap measure to help protect you from those who choose to break the rules.  You are not to use
foul language in /guildsay, in /ooc, in /auction, nor /shout.  If your group members find foul language acceptable, 
then feel free.  You must be certain, however, that they are comfortable with your language.  Do not use foul language in /tell 
unless you are certain that the recipient has no problem with your foul language.
If you are uncertain if a word qualifies as "foul" or not, don't use it.
If you are uncomfortable with the foul language of a guild member, report it to an officer or the guild leader.
Remember, if your language makes someone uncomfortable, they will most likely not say anything to you about it.
They'll merely harbor ill feelings toward you and the guild you represent.
</p>
<BR>
<B><Font size=+1>
Free Equipment
</font></B>
<p>
Often, guild members will give equipment to each other freely.  This is a perfect example of the spirit that 
sparked Legerdemain's initial creation.  It's perfectly o.k. to give a gift or accept one without monetary obligation.
There have been items freely handed out within Legerdemain that were easily worth 20k, 30k, and 50k plat.
Do not sell any item that has been freely given to you by another guild member UNLESS you have made absolutely
certain that there is no other guild member that can use the item on their main character.  Alternate character 
inclusion is purely optional.
This same policy also applies to equipment that has been gained from a group or raid
that was at least 50% Legerdemain members.  Your guild helped you get that item.  If you don't need it anymore, repay
the kindness.
If you see a guild member selling an item that you believe to be "guild loot", report it to an officer or the guild leader.
</p>
<BR>
<B><Font size=+1>
Begging
</font></B>
<p>
Begging is soliciting for equipment or money in any communication channel. 
Don't do it.  If you are caught begging by a guild member, your membership in Legerdemain may seriously be at risk.
If you need to <b>borrow</b> some money, or would like to trade for some equipment, feel free to ask your guild.
If you spot a guild member begging, report it to an officer or the guild leader.
</p>
<B><Font size=+1>
Guild Services
</font></B>
<p>
Teleportation, resurrection, corpse summoning, tailoring, and many other skills or spells can be considered guild services.
If you feel you are in need of a service, attempt to find someone outside of the guild
to help you out before you ask your guild members.  /ooc or /auction are quite helpful when in need of such services.
Sometimes, it's extremely difficult to find anyone to help you out.  Times like that, your guild will come to your aid.
If you continually solicit your guild whenever you get an itch, your fellow guild members will begin 
to resent giving out these services freely.  After all, they could be spending that time getting exp, or providing
the service for someone who would pay.</p>
<p>An exception to this rule may be when the guild is gathering for a raid or similar event.  At that time, speed my be
essential and take precedence over common courtesy.  Even so, try to arrive at raid locations well before the actual event
when locations are provided ahead of time.  This will speed the event's start, and save your teleporters the half an
hour to an hour porting yer behinds around.</p>
<p>Whenever you receive a guild service, let the provider know exactly how much you appreciate their effort.  Sometimes,
a pat on the back is all we need.  To repay your guild for its free services, be certain to provide whatever aid you
can when a fellow guild member asks.
</p>
<p>
If you feel that this policy is being violated against you, feel free to ask the member to read the policy.  Do not worry about
hurting the member's feelings, nor take it upon yourself to explain the policy to them.  Simply ask them to visit the guild's
website and read the policies.  Leave it at that.  If the recipient of this advice persists in making an issue out of the
situation or consistantly violates this policy over time, please forward their aggression or actions to the guild leader or one of the
officers.  This is a very serious issue and should be treated as such.
</P>
<B><Font size=+1>
Power Leveling
</font></B>
<p>
Power leveling is gaining experience by killing mobs that are either much higher level that you'd normally be able to kill,
at a much faster pace than you'd normally be capable of, or both.  Power leveling is made possibly by the aid of a character
who is many levels above your own or by several characters of similar level.
Legerdemain has nothing against Power Leveling provided that you are not taking mobs from characters that are of appropriate
level to kill the mobs you're taking.  It's best to find a secluded area with mobs that are hardly ever camped to
power level.
Do <B>NOT</B> ask for power leveling.  If at some point a fellow guild member, or group of them, decide that they'd like to help
you get a level or two, then be very appreciative.  Power Leveling is extremely non-productive for the person(s) who are
providing the help.  They don't gain exp, loot, nor experience in an unfamiliar zone.
Keep in mind that it's ill advised to power level anyone's first character.  
</p>
<B><Font size=+1>
Twinking
</font></B>
<p>
Twinking is providing an alternate character with equipment that he/she could not possibly have attained through normal
means.  Legerdemain has nothing against twinking.  However, you should <B>NOT</B> twink alternate characters with equipment
that could be used by main characters in Legerdemain if that loot was gained by Legerdemain.  Some may choose to 
supply guild members with equipment that they gained personally rather than supply a twink.  While that is very admirable
and very much the type of behavior we like to encourage in Legerdemain, it is not mandatory.
</P>
<B><Font size=+1>
Farming
</font></B>
<p>
Farming is the acquisition of items by killing Mob's that are much lower level than the farmer.
The only thing Legerdemain has against farming is taking camps from people that are of appropriate level.
If you are in the process of Farming, make a hot-key to respond to camp checks with. i.e.- "/ooc Farming king. Will
give camp to non-farmers."
You may loose camps this way.  You may be tricked out of camps this way.  Don't let it bother you.  Those camps
will always be there and that spot was getting boring anyhow.
</p>




