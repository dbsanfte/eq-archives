<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>C</B></font></TD></TR></TABLE>ome do my epic.  It's a relatively common request.  You see, each class has an epic quest of their own.  Almost every member of Legerdemain either has their epic or would like to have it completed.  You are not special or unique in this want.  How do you propose that we determine who gets help first?  We obviously can't help everyone at once, but to help one person before another shows favoratism, doesn't it?  At least in some peoples' eyes, it does.<BR><BR>

You are more than welcome to put togther un-sanctioned raids to complete your epic.  There will be no points offered taken away in such an un-sanctioned event.  There will also be no guarantee that enough people will show up to help.  They could be spending the same time helping any of the other members get an epic piece.  Why should they help you over someone else, or even over themselves?  What level of comitment have you shown?  Why do you deserve their help?  What guarantee do they have that you're going to help them in return?<BR><BR>

A Sanctioned Epic event provides an answer to some of those questions.  You must be at least level 55 and must pay the required points when the time comes.  Each of the epic quests has been divided up by the battels they must complete.  The battels have been rated by difficulty and assigned a difficulty grade.  Several of the lesser battels were removed from the lists entirely.  Such battles could be handled by you alone, or with a single group.  A point value of 500 points was assigned to each quest.  These points were divided amongst the remaining epic battels based on their difficulty grade.  Each epic drop still has a point value, but since you're paying for the battle itself, you need not worry about the additional item cost.  The item cost is there for when the epic item drops on an event which is not a <U>Sanctioned Epic</U> event, but merely a <U>Sanctioned Raid, Strike, or Alt</U>.  Some epic pieces require you to spend a huge amount of time tracking, or raiding a zone for random drops, or picking up a ground spawn in a difficult area to get to.  We can't do Sanctioned Epic events for such things.  You'll either have to get them on your own, or pay for it as an epic drop on a <U>Sanctioned Raid, Strike, or Alt</U>.<BR><BR>

There are Epic raids, Epic triggered raids, Epic strikes, and Epic triggered strikes.  The difference is how rare the mob may be.  An epic raid is for a mob that's consistantly up.  An example would be the King of Chardok.  He has a two our spawn time so even if he was down when we started, he'd probably be up by the time we got to him.  An epic triggered raid is for the same situation, but a trigger has to be handed in before we can make the kill.  An example might be High Scale Kirn in the Hole.  Both of these types of epic events can be scheduled ahead of time.  An Epic Strike is for a mob that is more rare and can't be scheduled ahead of time.  When this mob pop's, it is a rush to beat other guilds to it.  An example would be Zordak Ragefire.  An Epic Triggerd Strike would need to have a trigger handed in before the battle.  An example would be Faydedar.<BR><BR>

How do I go about buying one of these events?  For the Epic Raid and Epic Triggerd Raid, you must secure an SRL.  You can choose the date and time, but you'll need an SRL that's willing and able to run the event at that time.  Once you've found one, the SRL will need to post about the event in the <A href="http://pub50.ezboard.com/flegerdemainfrm10" target="_play">Playground</A>.<BR>
For a strike, you'll simply need to post your intent to hold a Sanctioned Epic Strike; a "heads up" post, if you will.  Describe the mob and, roughly, the time frame.  Your vigile can last no longer than 2 weeks.  Once 2 weeks have gone by,  you need to cancle the request.  You can re-post the request at least 2 weeks after the cancelation.  This is done to protect you, as well as us , from camping insanity.  Once your mob pops, you'll need to let an SRL know about it.  If we have enough people on-line, the race begins.  You are also more than welcome to add outside help for any type of epic event.  If you have outside friends that are willing to help, let the SRL know.  It's valuable information when determining whether or not we have the forces on-line to proceed.  An SRL can't refuse any help you may have gotten based on personal prejudices for any Epic Event.  It's your event and you're entitled to any help you can get.<BR><BR>

How are my points paid?  Once all of the forces have gathered, a decision must be made.  Do we proceed with what we have or not?  This decision is up to you, not the SRL.  If you decide that we will continue forward, you've just spent half of the points for the event.  We then march forward into battle.  You pay the other half if we win and your item drops.<BR><BR>

Take note: Several of these epic mobs can be done as a regular Sanctioned Raid or Sanctioned Strike.  For this to happen, enough people who also need an epic drop from the mob must be on-line and ready to take advantage of the Raid/Strike.  In cases where several peoples' epics can be done one after the other, a Sanctioned Raid can be set up.  The order of the battles will be determined by /random and Triple Cost.<BR><BR>

