<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>S</B></font></TD></TR></TABLE><U><I>anctioned raid leaders</I></U> do not have an easy job.  It's a thankless job as well.  Many will criticize while few could do a better job; or even step up to the plate for that matter.  You must be able to type quickly and have a wealth of patience.  If not patience, then tact. hehe<BR>
<BR><BR>
<FONT color="black" size="+1"><B>What are the responsabilities of a </B><U><I>Sanctioned Raid Leader</I></U><B> in regards to running an event?</B></FONT><BR>
<OL type="1">
<LI>Post about Sanctioned Raids at least one week(168 hours) in advance.
<LI>Record the time, date, location, and appropriate level range for the event.
<LI>Print out a current Point Value listing for the zone in which the event is to take palce.
<LI>On the day of the event, print out a Point Balance sheet for all guild members and guests who are of appropriate level to attend the event.
<LI>Show up at least 30 minutes before events are scheduled to begin.
<LI>For dungeon endeavors, have a Corpse Recovery plan prepared.
<LI>Set-up and inform about the channel(s) that will be used during the event.
<LI>Set-up and inform about any special rules or things that need to be taken into consideration on the event.
<LI>Help organise transportation for event members.
<LI>Organise the groups in such a manner to esure the minimal loss of life and total success of the raid.
<LI>Record event participants.
<LI>Re-organise the groups throughout depending on arrivals/departures.
<LI>Record late arrival times and departure times.
<LI>If you can not determine a departure time because they left the raid without letting you know, record them as having left the raid 5 minutes after it began.
<LI>Do your best to keep the event informed about what's going on.
<LI>Answer questions from strangers about why they can't just come over to loot/faction.
<LI>Ask event members to be patient when they pummel you with questions.
<LI>Politely ask people who wish to strike up conversations to chat with you another time.
<LI>Diplomatically converse with any group/raids that are in contention with your event.
<LI>Set-up a CoH pair if a CoH mage is in attendance and if late arrivals are permitted.
<LI>Assign a Main Assist and, if neccessary, a Secondary and Tertiary Assist etc.
<LI>Assign a Puller.
<LI>Organise the movements and pulling of the raid as it begins.
<LI>Try to keep track of participation.  If someone is not participating, remove them from the event.  They're only adding lag.
<LI>Try to be aware of frequent AFK and LD's.  There is a point at whcih an event member is hampering the raid more than helping.  At such a point, remove them from the event.
<LI>When loot drops, determine who gets the loot based on our loot rules.
<LI>Record the winner of any <U>Point Loot</U> and weather or not it was <U>Trippled</U>.
<LI>Determine and implement the strategies that the event will use.
<LI>Record the time of death for any <U>Point Mobs</U>.
<LI>Determine the best time to call the event off based on the event's goals and how long the event has already been going on.
<LI>Help organise out-bound transportation for your event members.
<LI>Record the time at which the event ended.
<LI>Fill out a report on this website covering the event.
</OL>
You may have surmised that it could beome difficult to print out point values and balances when on a <U>Strike</U> type event.  A <U><I>Sanctioned Raid Leader</I></U> will have to get to the <U>Strike</U> location FAST.  If he/she doesn't have a second computer available, he/she will need to log off to print out the values.  This could take 10 to 15minutes.  During this time, that SRL will not be available to the <U>Strike</U> party.  That's right, people will have to survive on their own for that long hehe.  It is true that even such a short time could put us behind a competitor for a particular mob.  If that happens, then so be it.  We'll just have to get there with 15minutes to spare next time.<BR>
<BR>
<BR>
<FONT color="black" size="+1"><B>What other responsabilities do they have?</B></FONT><BR>
<BR>
<OL type="1">
<LI>You are obligated to drop what you are doing to attend to your SRL responsabilities.  That is, assuming real life isn't in the way.  RL > EQ in all cases.
<LI>If you are informed that a strike mob is up and available, you must evaluate whether or not we have enough forces available to kill the mob.  Granted, not all of the forces on-line would neccessarily show up to a strike, but there's no point in even calling one if we don't have the forces on-line.  If we do have enough forces, you muster the strike regardless of whether or not you really want to.
<LI>Guild members will inform you about what place they'd like to see raided next.  They'll tell you weather or not they'd like to do an Alt raid.  They'll let you know if they never want to go back to that last place again.  They'll let you know all kinds of things.  You must take all of this information into consideration, post sanctioned raids with a time, date, and location, and follow through.
<LI>You must interact diplomatically with any group or raiding force that may be in contention with your raid/strike's objectives.  It is true that some people simply can not be reasoned with.  You must do your best.
<LI>You must be willing to report the actions of your fellow guild members.  If they are behaving in a manner that is against our standards, you must let me know.  If they refuse to back down or stay off of /ooc/shout/tells with a contending raid force, you must let me know.
</OL>
<BR>
<BR>
<FONT color="black" size="+1"><B>How much of this work can I wipe off on some un-suspecting sucker?</B></FONT><BR>
<BR>
<B>Groups.</B> The organisation and re-organisation of the groups is a job that can be shared with a willing guild member.  The recording of the arrival/departure times comes with it too.  Setting up CoH can also be a part of this detail.  It's not an easy job by any means.  The very success of the raid can be a function of how well the groups were set-up.<BR>
<BR>
<B>Movement/Pulling.</B>  The movements and pulling for the event can be handed off to the Main Assist or Puller for the raid if they're willing.  This means that the <U><I>Sanctioned Riad Leader</I></U> wouldn't be telling the raid when or how to move nor what's being pulled and from what direction.  There are advantages and disadvantages to this.  Sometimes the Puller/MA isn't very experienced in the area and needs guidance.  Sometimes the Puller/MA doesn't want to be held accountable for a mistake and would prefer for every movement to be approved.  On the other hand, sometimes it's the <U><I>Sanctioned Raid Leader</I></U> who isn't exactly sure of the best path or pulling method. It's best to decide beforehand who's going to be calling the shots for movement/pulling.<BR>
<BR>
<B>Loot.</B> Loot is huge. Especially with the point/no-point/loot orders and such in Legerdemain.  If you're not use to it, distributing loot can be very nerve wracking.  This is not a job to share with just anyone on a whim.  All of the <U>Point Loot</U> must be recorded as well.  There can be no forgotten or misplaced <U>Point Loot</U>.<BR>
<BR>
Sharing with willing helpers can certainly aleviate a lot of the pressure that a <U><I>Sanctioned Raid Leader</I></U> must certainly feel. Keep in mind, though, that while you are handing off these chores to someone else, they are still your responsibility.  Ultimately, your status as a <U><I>Sanctioned Raid Leader</I></U> and even possibly as a guild member can be removed if your responsiblities are grossly neglected.  Take care who you choose to share chores with.<BR>
<BR>
<BR>
<FONT color="black" size="+1"><B>This loot distribution is hell!  What's the best way that I can get through it alive?</B></FONT><BR>
When a piece of loot drops, one must first determine if it's <U>Point Loot</U> or not.  Consult your print-out.  <U>Non-Point Loot</U> is pretty easy:<BR>
<FONT color="#2222EE">/loot Anybody who can use Toenail Sliver and hasn't won any non-point loot send me a tell!</FONT><BR>
If you get no response, move to the next one.<BR>
<FONT color="#2222EE">/loot Anybody who can use Toenail Sliver send me a tell!</FONT><BR>
If you get no response, move to the next one.<BR>
<FONT color="#2222EE">/loot Anybody who WANTS Toenail Sliver send me a tell!</FONT><BR>
That's it.  If you still don't get a response, let it rot or destroy it.<BR>
<BR>
Now, some people are going to want stats.  You, as a <U><I>Sanctioned Raid Leader</I></U> get to determine how that's going to be handled.  You can have all the stats printed out or available on a nearby computer and call them out as you call the loot out.  You can ask the Master Looter of the group to call out the stats.  You can handle each case individually depending on who wants what stats.  You can tell everyone that no stats will be called out and that everyone should already know what they want.  It's up to you.<BR>
<BR>
When a piece of <U>Point Loot</U> drops, things can get a little complicated.  The following may sound like a huge amount of stuff, but it must be handled in a very short amount of time.  If someone who you know would want the loot is AFK or LD, that's unfortunte.  Keep things moving.  We can't afford to have a piece of loot rot because you wanted to be nice.<BR>
<BR>
Consult your print-out to find the point value and determine if the <U>Point Loot</U> is no-drop, Multi-Questable, and/or Epic.<BR>
If it's dropable and/or mult-questable and not epic:<BR>
<FONT color="#2222EE">/loot Send tells for the Uber Spoon of the Tick at 60 points!!</FONT><BR>
Random amongst those mains and guests that sent you a tell, assuming they had a positive point balance.<BR>
If you get no response..<BR>
loot it into the guild bank yourself or ask someone else to (see guild bank)<BR>
<BR>
If the loot is anything else:<BR>
<FONT color="#2222EE">/loot Send tells for the Uber Spoon of the Tick at 60 points!!</FONT><BR>
<BR>
Take down all the names.  People who have alts parked nearby are advised to send a tell like <I>"For MyAltname on the Uber Spoon of the Tick"</I> when the item is no-drop.  Once you have all the names written down:<BR>
<BR>
For no-drop non-MQ non-epic loot:<BR>
Write a 1 next to the names of Mains and Guests and have a positive point balance.<BR>
Write a 2 next to the names of Alts who have a positive point balance.<BR>
Write a 3 next to the names of Mains who are already negative.<BR>
Write a 4 next to the names of Alts who are already negative.<BR>
Write a 5 next to the names of Guests who are already negative.<BR>
<BR>
For Epic Drops (Dropable and/or Multi-Questable):<BR>
You only need wory about Mains with a positive point balance.  If there aren't any, it's looted into the guild bank.( see guild bank)<BR>
<BR>
For Epic Drops (No-Drop and Non-Multi-Questable):<BR>
Write a 1 next to the names of Mains who have a positive point balance.<BR>
Write a 2 next to the names of Mains who are already negative.<BR>
Write a 3 next to the names of Alts who have a positive point balance.<BR>
Write a 4 next to the names of Guests who have a positive point balance.<BR>
Write a 5 next to the names of Alts who are already negative.<BR>
Write a 6 next to the names of Guests who are already negative.<BR>
<BR>
Now that you have the priorities, you just go down the line and /random amongst those with the same priority starting with 1.<BR>
<FONT color="#2222EE">/loot I have 1)Bob, 2)Fred, 3)Jan, and 4)Elmo for the Uber Spoon of the Tick at 60 points.</FONT><BR>
Now several who don't understand the loot rules or their position in them will start sending you tells right here.  They'll be asking why they aren't in the lineup.  It is possible that you may have made a mistake.  You might double check the standing of the people who just sent you tells.<BR>
<FONT color="#2222EE">/loot I have 1)Bob, 2)Fred, 3)Jan, and 4)Elmo for the Uber Spoon of the Tick at 60 points.</FONT><BR>
Be sure to repeat yourself at least once.  You especially want to give the <U>Triple Cost</U> people enough time to type their statement. If there are no Tripplers:<BR>
<FONT color="#2222EE">/random 1 4</FONT><BR>
If there are Tripplers, add them to their own random.  They need to have stated their intent to triple in the loot channel. You will then:<BR>
<FONT color="#2222EE">/loot I have 1)Bob at triple cost.</FONT><BR>
Once is enough.  If there are no other Tripplers, then Bob gets it.  If someone else also Tripples:<BR>
<FONT color="#222EE">/loot I have 1)Bob and 2)Jan at triple cost.</FONT><BR>
Once is enough.  Random shortly afterwards.<BR>
<BR>
Now, you may have noticed that loot gets tricky when the item is no-drop.  It's not as bad as it may look.  When you get good, you can simply look at the list of those who want in on the loot, and look for any 1's.  If there are any, you then look for any other 1's.  Then you have your people.  If there aren't any 1's, you then look for 2's.  You can get pretty quick at it. <BR>
<BR>
<FONT color="black" size="+1"><B>Uh oh.  I scr00d up a loot drop! NoooO!</B></FONT><BR>
Don't worry about it too much.  Everyone is going to make mistakes.  We can only do our best to minimise them.  Admit your mistake, apologise, and move on.  If you have a tendency to make mistakes a lot, perhapse you should get someone else to do loot for you.<BR>
<BR>

<FONT color="black" size="+1"><B>This <U><I>Sanctioned Raid Leader</I></U> stuff is pretty nasty! What a cruddy job!  How can I get my friend hooked up with this gig?</B></FONT><BR>
There really aren't any set requirements to become a <U><I>Sanctioned Raid Leader</I></U> other than a slightly masochistic streak hehe.  An SRL has more knowledge about various zones and mobs than most.  An SRL has way too much time on their hands to think about the best strategies for various mobs or areas.  An SRL has proven him or herself on more than one occasion as a raid leader.<BR>
I'd suggest that you help out other SRL's for a while. Perhaps help with loot and/or groups.  Run a few un-sanctioned events.  Put together an un-sanctioned strike or two.  Maybe when those things become easy, you can request from me to become an SRL.  Ultimately, your stay in office will be determined by the guild members who you lead into battle.  They will let me know whether or not you're doing a bang-up job.  If and when there comes a time that your position as SRL is removed, you must be willing to accept that gracefully if you ever intend to become an SRL again.<BR><BR>

<FONT color="black" size="+1"><B>Once I become a <U><I>Sanctioned Raid Leader</I></U>, will I still be able to run un-sanctioned events?</B></FONT><BR>
No.  As an SRL, you have more knowledge, expertise, and skill as a raid leader than the average guild member might.  If not, you at least have more of a fetish for punishment than most hehe.  The point is, you have an aknowledged skillset.  If you are to run an event, it must be a Sanctioned one.<BR>
You are more than welcome to attend any un-sanctioned events which are run by other guild members.  You must refrain from poking your nose into the leadership of the event DURING the event.  Now, if someone would like to ask your advice, or seek your council about an upcoming event BEFORE it happens, great.  If someone wants to talk with you about what could have been done better or worse AFTER an event, that's fine.  You must not, however, fall into the trap of runing an event by remote control.  If a member wishes to benefit from your expertise, they should attend a raid you run, not attempt to have you hold their hand while running their raid.<BR>
Our future SRL's need to stand on their own feet.  They need to make mistakes, have triumphs they can call their own, and need to deal with difficult situations as they come.  Your "help" would not really be help.  It would be sheltering them from their responsibilites and preventing them from growing as a raid leader.<BR>
In short, if you're on someone else's raid, keep your mouth shut and smile pretty :><BR><BR>

