<P>
Legerdemain is devoted to seeking out magic of all sorts. All races and religions who seek out this common bond find sanctuary within our ranks. We live and breathe the magic of Norrath. No book, sword, weapon, or item is beyond our interest.
</P>
<P>
Inhabitants of Norrath have long held their prejudices against one another for petty reasons. Magic is the one true constant, the warmth in our hearts. Any feelings of distrust, hatred, or anger are to be set aside in our efforts. While traveling the lands through our quests, we shall cause no pain to other potential seekers of magic. Our flock will seek to aid others in their endeavors until those others show themselves to be a threat to Legerdemain or any other true pursuers of sortilege.
</P>
<P>
Legerdemain will absorb the magics of Norrath into it's being. Given time, all of Norrath will realize their misguided ways and join our enlightened society. Until that time, we will search the lands, brave any hazard, slay any misshapen monstrosity for Legerdemain.
</P> 



