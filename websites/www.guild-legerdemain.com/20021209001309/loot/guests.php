Guest's points are not totaled up between all of their characters.  They are individually totaled depending upon which of their characters attended the event or spent points.  We do this because we do not know which of your characters are your main, which are actually your friend's characters, nor which have been sold or are going to be sold.  It's none of our business anyway.  If that character has earned the points, it deserves a shot at the loot.<BR><BR>

At some point, a guest may decide that they wish to become a member of Legerdemain.  If they are approved through our current process, their account will be converted to a member account.  When that happens, the points which have been earned by each of the guest's characters will be totaled and added to the one member's new account.  They can then be spent and earned as a collective number.<BR><BR>

Guests do not have the same privileges as our members do in regards to loot.  They are treated as equals when the item is Multi-questable or dropable, assuming the guest has sufficient points.  The same is true of items which are no-drop and non-multi-questable, but the guest must have sufficient points.  If the guest does not have enough points, our members with no points are considered before a guest with no points.  Epic drops are almost completely off-limits to guests.  The only chance a guest has at an epic drop is a no-drop epic drop.  In such a situation, our members are considered first.  For more details about our loot orders, check out the <a href="http://www.Guild-Legerdemain.com/loot/pointSystem.php">Point Systemt</A>.<BR><BR>

To Register for a guest account, your character must meet our minimum level requirement of 40.  You must click the <A href="http://www.Guild-Legerdemain.com/userpages/register.php">Registration</A> link and fill in the blanks.  Once you've submitted a request, a confirmation will be e-mailed to the address that you provided.  It will contain a confirmation link.  Once you have confirmed the account, you'll be able to log-in to the site and enter your character information. Do your best to keep your level up-to-date.  When a <U><I>Sanctioned Raid Leader</I></U> prints out a list of guests, they screen by level before printing.  If you show up to an event which you meet the level requirements for, but were not listed on the site as meeting, the SRL will not have you on the list of guests.  Your chances of attending the raid will drop significantly.  Guests who have earned points by attending previous raids will be considered before first time guests.  A running total of earned points is maintained, so that even if you've spent points, the total number of points you had earned is retained for each of your characters.<BR><BR>




