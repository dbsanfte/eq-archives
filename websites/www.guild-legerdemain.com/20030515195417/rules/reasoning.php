<TR><TD>
<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>1</B></font></TD></TR></TABLE> <B>Begging.</B> Legerdemain members are not parasites to eachother nor to other people in EQ. If you want something, earn it. Gifts are items/buffs/plat that are given out of the free will and kindness of the gift giver. That means NO outside influence brought about the giving of the gift.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>2</B></font></TD></TR></TABLE> <B>Trading.</B> A lot of the kind souls in Legerdemain will feel obligated to help out their fellow guild member by purchasing items at inflated prices. Several members would sell items to guild members at a seriously low price. We don't need guilt-tripping being broadcasted over /gu. This is akin to Begging. The facilities provided by EQ for trading work just fine.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>3</B></font></TD></TR></TABLE> <B>Services.</B> A LOT of people have a hard time saying <B>"no"</B>. They continue to provide services every day and build up a resentment. Their play time has been hijacked for providing their valuable service. Eventually, EQ becomes more of a chore than a fun thing to do. We will not do this to our members. There are THOUSANDS of people that play on our server. Get your service elswhere or post your request in the <A href= "http://pub50.ezboard.com/flegerdemainfrm9"> altar</A>.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>4</B></font></TD></TR></TABLE> <B>Respect.</B> All we have in EQ is our reputation. We do not need it to be tarnished by anyone. Surely, some people will be upset with us and do their best to tarnish our reputation, but such things can't be avoided. We will, however, prevent from adding to the flames as best we can.  Besides, the game is MUCH more fun if we do not dwell on those things we dislike or hate. Sometimes, the pot boils over, the lid pops off, and a ton of steam pours out.  This doesn't need to be a common occurance.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>5</B></font></TD></TR></TABLE> <B>Foul Language.</B> Foul language is called <B>"foul"</B> for a reason. It's offensive. Young people and not so young people play EQ. None of them need to be exposed to foul language. This is also a rule of EQ's. They included a foul language filter not as an acceptance of foul language, but as a stop-gap measure. It is still very much against the rules and is /petitionable.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>6</B></font></TD></TR></TABLE> <B>Alternates.</B>  We invite people, not characters. Surely, we need to have some people with high level characters and a firm knowledge of how the game works if we're going to raid successfuly. This is why we have a level requirement for your main. Your alternate character, though, is welcome as well. This allows you to enjoy the conversation and company of your guild members even if you don't feel like playing your main.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>7</B></font></TD></TR></TABLE> <B>LFG in guildsay.</B> It is not the responsability of this guild to get you groups outside of the events we hold. If you happen to get a guild group, great. If you can't find a guild group, tough luck. There are thousands of people on our server at any given point. If you absolutely can't find a group, you need to work on your social skills. Sometimes one class is more needed in a particular zone than another at various points in the day. This does not mean it's impossible for you to get a group.<BR>
It is not the job of this guild to hold yer hand and guide you over to a prosperous group.
The questions <i><B>"Is anyone doing anything?"</B></I> and <I><B>"Is something exciting going on?"</B></I> are two of the worst questions out there. Of course we're doing something. We're playing EQ and trying to have some fun. The word <B>"exciting"</B> is subjective. What is exciting to one person is not exciting to the next. Assuming we're all playing a game for fun, yes, we're all doing something exciting. It may not be excting to you, but it is to some.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>8</B></font></TD></TR></TABLE> <B>Bored in guildsay.</B> It is not the job of this guild to make sure that you are entertained from minute to minute. EQ has hundreds of thousands of mobs, thousands of tradeskill recipies, thousands of people, and a ton of zones. If you're bored, that's your problem. Maybe you need to log off and do something constructive. Stating that you are bored, in whatever fashion, is an insinuation that someone should fix that for you. It doesn't matter if that's the way you ment it or not. We do not need to pelt our guild members with your inability to keep yourself entertained. I'm sure we all have enough luggage without having to bear your cross as well.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>9</B></font></TD></TR></TABLE> <B>Counceling in guildsay.</B> It may sound harsh, but this is a GAME that is played as an escape for entertainment. Phsychologists get paid a buttload of money for a reason. This guild is not here to provide you what normally costs $200/hour for $12/month. If you have some serious real life issues, you should log off and take care of them. When you're ready to play a game for fun, we'll be here.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>10</B></font></TD></TR></TABLE> <B>Anonymous.</B> There should never be a reason that you don't want someone to know what guild you're in. If you're about to do something questionable that you don't want the guild to be held responsible for, sorry, but /guildstatus will reveal your guild anyway. Besides, if you're doing that sort of thing, perhaps you should re-consider what guild you're in. If you're looking for some privacy on a character that's in Legerdemain, shut off guildsay and put /afk up.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>11</B></font></TD></TR></TABLE> <B>Hazing.</B> We all have feelings. Teasing someone can be fun for everyone. That is, until it goes too far. Exactly where <B>"too far"</B> stands is different for each person.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>12</B></font></TD></TR></TABLE> <B>Prejudice.</B> This game is played, in part, to escape such crap in real life. There is no need to bring it to our guild members.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>13</B></font></TD></TR></TABLE> <B>Guild Events.</B>  Real Life can get in the way of Event timing.  You may consider raiding to be boring.  You may not feel that a particular person needs or deserves your help.  Whatever your reasoning, you are not obligated to attend any events.  There may be a penalty attached such as losing points for missing a Sanctioned Raid, or perhaps alienating a particular guild member, but you are free to pay those consequences without being in danger of losing guild membership.<BR>
If you attend a raid, though, you had best be participating.  If you can't participate because your newborn child needs 10 of your minutes every other minute, leave the raid.  If you can't participate because debilitating butt pain makes you walk around for a half hour every 10 minutes, leave the raid.  Whatever your problem or reason is, if you don't have the time to raid, don't attend.  It is disrespectful and just plain rude to handi-cap a guild function with your problems.
</TD></TR>
<TR><TD>

<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>14</B></font></TD></TR></TABLE> <B>Help Me!</B>  We play this game for fun.  If you'd like to have some assistance to get an item, kill a mob, or get an item in some other fashion, post about it.  We may help you get to it at a time that is convenient for us, NOT right now this second because you said.  We all have real lives to attend to and our time in EQ is limited.  You are not the ~special~ member in the guild whom everyone else is in the guild to aid on your whim.  Even if the mob you're after is a contended mob, you can post that you're camping it and would appreciate some assistance when it pops.  To assume that our sole purpose is to get you phat lewt is incorrect.  To assume that it is your right to make every guild member feel obligated and/or guilty to help you out is rude.
</TD></TR>
