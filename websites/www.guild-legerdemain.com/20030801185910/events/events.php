party, roleplay, or whatever.  All of the events have one thing in common.  Those who attend are there to smile and have a
good time.  We have no mandatory events, but if you decide to come, bring a smile and we'll do our best to provide the good time.
<BR><BR>
Anyone can run an event.  Spur of the moment, posted ahead of time, detailed plans, or winging-it in a new zone; anyone can do it.  You may have a better
turn-out if you post ahead of time, but that's completely up to you.  There are no level restrictions.  There are no "main" vs. "alt" restrictions.
If you are a member and have the key, flag, or level requirement, you are more than welcome to attend. There is, therefore, never a need to ask "/gu Am I high enough to come?" or "/gu Do you need me?".
Any member can attend if they can and want to.  Transportation, though, may or may not be provided as the event's leader decides.
Guests need only ask the person who is running the event if they can attend.<BR>
Only one restriction here, though.  I don't want to see a silly question similar to "/gu Anyone wanna do something?".  Please, try to have some direction.  Maybe it's just me, but that kind of question
forms a picture in my mind of a 3 year old who's holding their hand out because they need someone to guide them to the restroom and make sure they pee correctly.  Please, have a task, goal, mob, piece of loot,
place to go... something, anything.  "/gu I'm heading to Chardok if anyone wants to join me.".. "/gu Fear is open.  I'm starting a small raid if you'd like to come."<BR>
<BR>
If you bring down the party by generally spreading ill-will, bad vibes, curses, complaints, or other nonsense, be
prepared to be asked to leave.
<BR><BR>
Legerdemain members will occasionaly participate in events that are run by other guilds.  You are expected to behave
at such events even if those around you are not.  Each of our members is a representative of our guild and an example of the qualites we value.<BR>
<BR>
When you decide to run an event, keep in mind that you may not get the turn-out you were hoping for. Sorry, we're a small guild.  Even when getting help
from outiside the guild, your event may not have the neccessary numbers to succeed. It happens. Try again later.  Really, don't give up.  Try not to be
discouraged.  Keep trying.





