<font size="+3">
Loot Policy
</font>
<BR>
The /lootnodrop confirmation box should ALWAYS be on.  Everyone should get the confirmation box when
attempting to loot a no-drop item.
</CENTER><BR>

<font size="+3">I</font>t is unfortunate, but arguments over loot and its distribution have been the
driving destructive force which has plowed though many guilds as well as Everquest in general.  Legerdemain
has set forth its loot policy here for that very reason.  Any and all members of Legerdemain are expected
to be familiar with this policy and to follow it closely.  This is still a "policy" and thus is subject to
change from a majority vote within Legerdemain.<BR><BR>

Where This Applies<BR>
Zone Last Piece<BR>
Planar Loot<BR>
-all Legerdemain<BR>
-mostly Legerdemain<BR>
-minority Legerdemain<BR>
Other Raid Loot<BR>
-all Legerdemain<BR>
-mostly Legerdemain<BR>
-minority Legerdemain<BR>
Single Group Loot<BR>
-all Legerdemain<BR>
-mostly Legerdemain<BR>
-minority Legerdemain<BR>
Our Loot Theory<BR><BR>

<B><font size="+2">Where This Applies</font></b><BR>
This policy applies in every situation, unless it has been declared BEFOREHAND that the person organizing the raid or putting
together the group wishes to do loot differntly.  Once this different way of doing loot has been sufficiently described to the
potential participants THEY can decide if they wish to attend or not with the different policy in effect.  If they decide to group/raid
under the new rules, they have no right to complain to the guild or raid/group leader for any loot policy deficiencies or disagreements.
Under any circumstance where no loot policy was declared... THIS policy applies.<BR>
Such a situation might be-- "Please come to COM to kill Reavers.. I need a Jade Reaver!"  This establishes that the person needing help
and forming the raid is going to be the one looting the item and that any loot for the other participants is purely coincidental.
It doesn't establish it very well though.  To avoid arguments one should add "And I get to loot the first Jade Reaver"<BR>
Another situation might be-- "Please come help me pharm the King in Sebilis... I want to start a monk"  This establishes that the
person starting the group wishes to loot the Fungi Tunic and that no other participants in the group would have a shot at it unless
more than one dropped.  It doesn't establish this very well though, so to avoid arguments one should add "And I am going to loot
the first Fungi Tunic."<BR>
<BR>
<B><font size="+2">Zone Last Piece</font></B><BR>
In the event that a Legerdemain member is familiar enough with the loot in a zone, he/she may declare him/herself "zone last piece"
for the zone if there is only one piece of equipment that drops that would benefit him/her.  Keep in mind that this does NOT mean
specific areas in the zone.  i.e.- if we're raiding the Arena in Kael, and you need the legs to complete your Thurgadin armor,
you are not "zone last piece".  You are "Thurgadin Armor Last Piece" and are free to let the raid leader know.  Once you have
declared yourself "zone last piece" you should record this in <a href="http://pub50.ezboard.com/blegerdemain">Atol's Mystic Stone</a>
room of our message boards.  The raid leader should be aware of your declaration and merit you your piece if it should drop.
Your character will only ever be given the "zone last piece" drop in that particular zone on a Legerdemain raid.  You will not be
included in any randoms other than any random all's.  Once you've attained your "zone last piece" item.. that's it for you for that
zone with the exception of random all's. "Zone last piece" will take prescidence over all other "last piece" or "merit" statuses in
the event of a conflict regardless of level. "Epic" pieces, however, will still be decided upon by level of completion and character level.<BR>
This status must be declared PRIOR to the raid in the "Atol's Mystic Stone" room.
Each raid leader should check here for "zone last pieces" before raids.  If any "zone last piece" declarations conflict, the item will
be randomed amongst them reguardless of any other merit or character level.<BR><BR>
<B><font size="+2">Planar Loot</font></B><BR>
Most planar items are no-drop.  The loot distribution must be decided immediatly and
the recipient must loot before the body rots.  Because of this, mistakes may be made and accidents may happen.
Legerdemain members are expected to be understanding and forgiving in such situations. <BR><BR>
<B>-all Legerdemain</B><BR>
<U>Need Before Greed</U>. Any planar items will be randomed amongst the members of that class/race who can use it.  This inclues
breasplates and robes which are "merited" by most. If you recieve an item, you are not to be included on any further
randoms of your class untill all members of your class have recieved a piece of armor.  The exception to this would be
if the only person left in the drop rotation already has the piece that drops next.<BR>
<u>Epic Pieces</U>.  Epic pieces will be "merited" amongst those who wish to persue their epic.  The "merit" will be decided by
who is furthest along in their epic.  Where this is too close to be a deciding factor, the characters level will decide.
If the levels are the same, the epic item will be randomed.<BR>
<U>Last Piece</U>.  If you have only one slot in which planar armor would benefit you, you are considered "last piece".  In
this situation, it is your responsibility to let the raid leader know that you are "last piece".  If you become "last piece"
during the raid, it is also your responsibility to let the raid leader know.  If you are "last piece", and the armor piece drops,
that armor is yours to loot.  Please wait for the raid leader to confirm this, as someone else in the raid may be "last piece"
with the exact same piece.  In such a case, it will be randomed between the two of you.<BR>
<U>Regular Merit</U>.  There may be cases where someone's level takes presidence over normal loot proceedures.  For instance, a Magician
is level 58 and has been on multiple Hate raids run by Legerdemain, but still has no Apothic to show for it.  An Apothic
crown drops and all four mages on the raid lack this piece and have yet to recieve a drop on this raid.  The raid leader
MAY choose to "merit" the crown to the 58th level mage who has never gotten a Hate drop.  You do not have to be completely
devoid of planar drops to be "merited" an item.  This was just an example of how "merit" may come into play.  This will
be decided by the raid leader and is to be used extremly sparingly and only in desperate situations.<BR><BR>
<B>-mostly Legerdemain</B><BR>
Same as above, but "Regular Merit" will not be applied to people outside of Legerdemain; good friend or not.<BR>
Epic drops will be merited to Legerdemain members before outside attenders.
<BR><BR>
<B>-minority Legerdemain</B><BR>
If only a minority of Legerdemain members are in attendance, it is most likely that the raid is not being run by Legerdemain.
In the odd situation where Legerdemain is in the minority, but "running" the raid, rules are the same as above.  The only difference
will be that Robes and Breasplates are also to be "merited" amongst the highest level characters of that class to comply with Old School
loot proceedures.<BR>
"Zone Last Piece" does not apply.<BR><BR>
<B><font size="+2">Other Raid Loot</font></B><BR>
Other Raids can be considered just that.  Any time multiple groups show up to advance against a foe or area.<BR><BR>
<B>-all Legerdemain</B><BR>
No-Drop items should be handled as descrbied above, as should Epic drops.  The above doens't account for non-class specific loot
but the same spirit applies; Need Before Greed.  If an all/all int/mana item drops, a tank should not be in on the random.  Likewise,
if a haste item drops, only tanks should be in on the random.  This seperation of classed items can be ticky.  For instance, if an
all/all weight reduction bag which weighs zero drops, it would be a monk item.  While usefull for everyone, it would most benefit monks.
If you are unsure what classes should be in on the random, feel free to ask the guild.  If arguments spring up as to which item should go
to which classes, loot policy for each item will be decided upon by Legerdemain majority vote and placed here for future reference.
In the case that all members in attendance of the specific class have that piece or better, it will be randomed by the secondary classes.<BR>
For Droppable loot, the item should be looted by the master looter for the group that got the killing blow.  Then loot distribution
should then be handled by the raid leader either after the completion of the raid, or on the spot.  Whichever is more convenient for
the raid leader.<BR>
The distribution should be Need Before Greed.  In the event that nobody on the raid "needs" the item, it will either be randomed
by all interrested in the item OR be "guild banked" by the raid leader to be given to a Main in the guild who "needs" the item.
That decision is up to the raid leader.<BR><BR>

<B>-mostly Legerdemain</B><BR>
Same as above.  Note- there should NEVER be a Master Looter for a group that is not a Legerdemain member.  Also, the only time
a non-legerdemain member should loot, is when he/she has been called to loot a no-drop item.<BR>
Epic drops will be merited to Legerdemain members before outside attenders.
<BR><BR>
<B>-minority Legerdemain</B><BR>
If only a minority of Legerdemain members are in attendance, it is most likely that the raid is not being run by Legerdemain.
In the odd situation where Legerdemain is in the minority, but "running" the raid, rules are the same as above.  The only difference
will be that "Zone Last Piece" does not apply.</BR><BR><BR>

<B><font size="+2">Single Group Loot</font></B><BR>
<B>-all Legerdemain</B><BR>
Need Before Greed.  Randomed amongst the people who NEED the item.  If nobody in the group NEEDS the item, it can either be
"guild banked" to give to a MAIN character later or can be randomed amongst the group however your group decides to do
randoming.<BR>
<B>-mostly Legerdemain (more than half)</B><BR>
Considering Legerdemain would have majority in the group, Legerdemain would decide how to do loot.<BR>
Same as above, but "Zone Last Piece" does not apply, and no item may be "guild banked".<BR>
<B>-minority Legerdemain (less than or equal to half)</B><BR>
Loot Policy is decided by the group.<BR><BR>

<B><font size="+2">Our Loot Theory</font></B><BR>
The idea behind our loot policy is to allow for a distribution of loot that will allow the guild to raise in strength
as a whole.  As it was pointed out once, you can't expect much success as a guild if the Monk who's always
pulling in all raids is still wearing all cured silk at level 60.<BR>
It is possible, with the policy described above, for some members of a raid to walk away with two or three pieces
of armor or drops while other members walk away with none.  It is unfortunate, but that is a possability.  What
we ask our members is to be patient in these situations.  You can only be "zone last pieced", "Last Pieced", "merited",
or "randomed" out of drops so many times before it's your turn.  We are not taking in such a huge number of guild members
as to always keep you at the bottom of the armor drop list.  If we stick together, everyone will eventually have
all the armor and items they dream of.<BR>
