<TABLE align="left" background="http://www.Guild-Legerdemain.com/images/texture3.jpg" border=2 bordercolor="#9966EE" cellpadding=2 cellspacing=0><TR><TD><font size=+3 color="#FFCC00"><B>L</B></font></TD></TR></TABLE>oot is the single largest cause of pain and heartache in Everquest.  Camping for loot, grouping for loot, farming for loot, raiding for loot, trading for loot, or questing for loot.<BR>
<BR>
Some people feel that they deserve certain pieces of loot more than other people.  They've raided more and still don't have it, have raided less and have had less chances at loot, been in the guild longer and have seniority, are brand new members and need everything, are higher level and still need it, are lower level and would use it more, have crappy equipment and need to upgrade, or have awesome equipment and are therefore more valuable to the guild.  There are hundreds of thousands of possible reasons behind why one person deserves one piece of loot more than another.  I've heard a great deal of them.<BR> 
<BR>
Some may not even consider who is more deserving.  They just know they want that piece of loot and will do whatever it takes to get it.  It doens't matter to them if someone needs it more or deserves it more.  I want it.. gimmi it. Who do I need to kill, bribe, or kiss-up to?<BR>
<BR>
Some don't give a darn about loot.  They could care less.  Sure, they're not going to turn down a piece of needed loot if it's plopped down in their laps, but they're certainly not going to cut anyone else out of their chance for that loot.  They'll sit quietly in the background; having gone to every single raid, helped guildmebers day after day, never complaining, and never whining.  They'll sit there.. waiting to be the last person who needs the piece of loot, and win by default when the time comes.<BR> 
<BR>
These are just a few of the types of people out there and how they might react to a piece of loot.  There are many more and the reactions may change based on the type of loot or how long they've been after it.<BR>
<BR>
You may now have the beginnings of an idea about how difficult a fair loot distribution might be. What is fair in the eyes of one will not be in the eyes of another.  Arguments break out, jealousy festers and grows, and hatred breaks down the bonds of friendship.  All of these things are not coducive to a good time.  I have, therefore, decided that a complex loot system, involving point values, is needed for our Sanctioned Events. It may not be the best system in EQ.  It may need to be endlessly tweaked, or done away with entirely, but this is the system as it exists today.  There are probably tons of ways around the loot rules.  I'm sure they can be taken advantage of.  I can only do my best to ensure that it is very difficult to do so.<BR>
