<BR>
The following outline of the Point System isn't completely descriptive of each situation.  It is meant as a framework to cover a huge amount of ground.  Once you understand the framework, some other sections of this website can help fill in the walls, doors, windows, and shingles.  If you still have questions, please feel free to ask them on our forums or e-mail <a href=mailto:Terrenoth@yahoo.com>Terrenoth</a>.
<BR>
<BR>

<OL type="A">
<LI><B>Gaining Points</B>
   <OL type="i">
   <LI>10 points gained per full Sanctioned Event attended
   <LI>Partial points gained for partial Sanctioned Event attendance
   <LI>Members gain points per person, not per character
   <LI>Guests gain points per character
   <LI>Extra points awarded for killing point mobs
   <LI>Double extra points awarded for killing a point mob for the first time
   </OL>
<LI><B>Losing Points</B>
   <OL type="i">
   <LI>The point cap is 1000 points.  Points gained after the cap are, in essence, lost.
   <LI>2 points deducted for being late to a Sanctioned Raid (Raids only) without prior notification and accurate time estimate
   <LI>3 points deducted for not attending Sanctioned Raids (Raids only), if of appropriate raid level range
   <LI>Triple Cost
   <LI>Sanctioned epic events
   <LI>Once someone has a negative point balance, they may ONLY go further negative if they win a no-drop point item, or if their Zone Last Piece item drops
   </OL>
<LI><B>Sanctioned Events</B>
<OL type="i">
<LI><b>All Sanctioned Events</B>
    <OL type="a">
    <LI>All Events are run by a <i><u>Sanctioned Raid Leader</u></i>
    <LI>The <i><u>Sanctioned Raid Leader</u></i> must fill out the Event Report directly after the Event on the web page
    <LI>All Events have at least 12 guild members in attendance
    <LI>Alternate characters will <B>NOT</B> attend unless specifically asked to by the <i><u>Sanctioned Raid Leader</u></i> or unless it's an Alt Raid. In either case, they are treated as mains for the duration of the Event in regards to loot and points.
    <LI>Neither members nor guests will play more than one character simultaneously
    <LI><i><u>Sanctioned Raid Leader</u></i> are not allowed to disclose ANYONE's current point balance during an event
    </OL>
<LI><B>Sanctioned Raids</B>
    <OL type="a">
    <LI>Posted at least one week(168 hours) in advance
    <LI>If you are within the appropriate level range and do not attend, you will lose 3 points
    <LI>If you are late without prior notification and accurate time estimate, you will lose 2 points
    </OL>
<LI><B>Sanctioned Strikes</B>
    <OL type="a">
    <LI>No points lost for absence; appropriate level or not
    <LI>Regular raid points granted for attendance; successful or not
    <LI>Additional points granted only if successful and in attendance when the Point Mob died(or if LD'd during the kill)
    <LI>Can't be posted in advance due to the nature of the Strike Mobs
    </OL>
<LI><B>Sanctioned Alt Raids</B>
    <OL type="a">
    <LI>No points lost for absence; appropriate level or not
    <LI>All alternate characters are treated as mains in regards to loot and points
    <LI>More than one character CAN be played simultaneously (if the <i><u>Sanctioned Raid Leader</u></i> agrees), but the person will only receive one set of points
    <LI>Alternate characters OR mains of appropriate level may attend
    <LI>Posted at least one week(168 hours) in advance
    </OL>
<LI><B>Sanctioned Epics</B>
    <OL type="a">
    <LI>No points lost for absence; appropriate level or not
    <LI>Must be at least level 55
    <LI>There are epic strikes, epic triggered strikes, epic raids, and epic triggered raids
    <LI><U>Epic raids</U> and <u>epic triggered raids</U> must be scheduled at least one week(168 hours) in advance
    <LI><U>Epic strikes</U> can't scheduled due to the nature of the Epic Mob.
    <LI><U>Epic triggered strikes</U> may or may not require to be scheduled depending on the nature of the Epic Trigger. (see <a href="http://www.Guild-Legerdemain.com/events/epic.php">Epic Events</a>)
    <LI>Additional points will be granted for Point Mobs normally
    <LI>The requestor will decide if the battle will proceed once all help has arrived
    <LI>There are point costs associated with requesting a Sanctioned Epic Event.  Please see <a href="http://www.Guild-Legerdemain.com/events/epic.php">Epic Events</a> for details.
    </OL>
</OL>
<LI><B>Guests</B>
  <OL type="i">
  <LI>Must have a Guest Account on the web site BEFORE the raid starts to acquire points
  <LI>Points are calculated per character not per person
  <LI>Do not lose points for lack of attendance
  <LI>Do not have to be allowed on events.  They can be refused at the discretion of the <I><U>Sanctioned Raid Leader</U></I>
  <LI>Start with zero points
  <LI>Can NOT purchase epic events with points
  <LI>The ONLY times a guest can go negative is when the loot in question is a no-drop and non-MQ item/epic.
  <LI>Can NOT become a <U><I>Sanctioned Raid Leader</I></U>
  </OL>
<LI><B>Loot Order</B>
<OL type="i">
<LI><B>General</B>
   <OL type="a">
   <LI>Points will be spent for Point Items in EVERY situation but rotted or destroyed items
   <LI>When two or more people qualify for the same loot right they will be allowed to either <U>Triple Cost</U> or /random
   <LI>When two or more people <U>Triple Cost</U>, the winner will be determined by /random
   </OL>
<LI><B>Multi-Questable and Dropable Items</B>
   <OL type="a">
   <LI>Mains and Guests who have a positive point balance
   <LI>Handled by the SRL as he/she sees fit. (merit/looted/rot/sold/etc)
   </OL>
<LI><B>No-Drop and Non-Multi-Questable Items</B>
   <OL type="a">
   <LI>Mains and Guests who have a positive point balance
   <LI>Alts who are parked nearby and have a positive point balance
   <LI>Mains who are already negative
   <LI>Alts who are parked nearby but are already negative
   <LI>Guests who are already negative
   <LI>Rot/destroy.  If an item is to be destroy, it MUST be done by a class/race who can NOT use the item
   </OL>
<LI><B>Epic Drops (Dropable and/or Multi-Questable)</B>
   <OL type="a">
   <LI>Mains with sufficient points to keep from going negative after payment
   <LI>Handled by the SRL as he/she sees fit. (merit/looted/rot/sold/etc)
   </OL>
<LI><B>Epic Drops (No-Drop and Non-Multi-Questable)</B>
   <OL type="a">
   <LI>Mains who have a positive point balance
   <LI>Mains who are already negative
   <LI>Alts who are parked nearby and have a positive point balance
   <LI>Guests who have a positive point balance
   <LI>Alts who are parked nearby and are already negative
   <LI>Guests who are already negative
   <LI>Rot/destroy.  If an item is to be destroyed, it MUST be done by a class/race who can NOT use the item
   </OL>
</OL>
<LI><B>Triple Cost</B>
   <OL type="a">
   <LI>A person who has loot rights (according to our loot orders) can state that they'll pay triple item cost by saying <U>I will Triple</U> in the loot channel.  If there is no further contention, they win the item
   <LI>When to triple; when you see your name displayed by the person who's handling loot in a fashion similar to <I>"I have Bob, Jan, Fred, Spot, and Wilbert for the Uber Spoon of the Tick.  Anyone else?"</I>  That's your opportunity.  You must state your intent to triple BEFORE the loot handler actually /randoms
   <LI>If more than one person is willing to pay triple cost, they will /random
   <LI>Once you have stated <U>I will Triple</U>, you may not change your mind
   <LI>You can not back out of a <U>Triple</U> for any reason.  (see penalties)
   <LI>You can NOT participate in triple cost if winning would put you into the negatives. (see penalties)
      </OL>
<LI><B>Last Piece</B>
   <OL type="a">
   <LI>Last Piece on armor sets is no longer respected
   <LI><U>Zone Last Piece</U> will be respected for members only (see <a href="http://pub50.ezboard.com/flegerdemainfrm15">Atol's Mystic Stone</A>)
   <LI>Items won due to <U>Zone Last Piece</U> will still cost the normal item cost
   <LI>It is allowable to go negative or further negative for <U>Zone Last Piece</U>
   <LI>When two or more members are <U>Zone Last Piece</U> for the same item when it drops, whoever went <U>Zone Last Piece</U> first will get the item
   </OL>
<LI><B>Penalties</B>
  <OL type="a">
  <LI>If you have purchased a piece of loot, there are no pentalties for whatever use you find for it.  If you want to sell it, give it away, burn it, or have it bronzed, that's your choice.  You earned the points to pay for the item and it is, therefore, yours to do with as you wish.
  <LI>Any case of Ninja Looting will be dealt with ASAP by /guildremove, accidental or not.  Guests that are guilty of this will be added to our <u>banned</u> list.  I'd suggest having the /lootnodrop setting set to <b>always</b> display loot reqestor(confirm box) for no-drop items.
  <LI>In a case where someone states <U>I will Triple</U> and backs out or refuses to loot the item, a new winner may loot and pay for the item.  The person who backed out will still have to pay for the item at triple cost.  I'd suggest you not waste our time with a <U>Triple</U> unless you are serious about it.
  <LI>If you attempt to <u>Triple</u> when a win would put you into a negative point balance, you will not be included in the /random by the <U><I>Sanctioned Raid Leader</I></U> or informed of your mistake, but the points will be deducted from your balance anyway.  I'd suggest you not waste our time with a <U>Triple</U> unless you can pay for it.
  </OL>
</OL>



