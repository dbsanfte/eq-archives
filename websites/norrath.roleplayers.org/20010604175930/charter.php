<p>
<font size=1 face=verdana>The basis of our guild is Honor and Friendship.
Honor in hunting, fighting, and most of all, Honor in grouping. It is the
intention of this guild to be known across Norrath as a people welcome
into any group.<p>

Membership will be by invitation only. To gain entrance into the guild,
one must have at some time grouped with a member and been found to be a
good and fair player. During times of recruitment, officers may invite at
will. Recruited members will be expected to follow the Code of Honor.
<P>
1. No "ninja-looting".<br><br>
2. No "kill-stealing".<br><br>
3. Be honorable about looting, make sure others in your party get their
fair share.<br><br>
4. Be an honorable party member. Fight hard and fair. Do not leave the
part in a position of danger.<br><br>
5. Be the first to offer help to anyone in need, be it guild member or
not.<br><br>
6. Help others in your guild, in the way of quests or fights, unless doing
so would put your own life in danger.<br><br>
7. No begging from other guild members....it is our Code of Honor to help
when we can, but this is to be unsolicited help.<br><br>
8. No begging from other players outside the guild. This includes, but is
not limited to "shouts" asking for items. The Norrath Militia does not ask
for any handouts.<br><br>

This Code can be ammended upon agreement by the Council and the Officers;
only after being put to a vote by all available members.
