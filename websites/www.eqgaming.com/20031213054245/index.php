<font color="#999999"><b><a href="modules.php?op=modload&amp;name=News&amp;file=index&amp;catid=&amp;topic=5&POSTNUKESID=18857b0e880f6ed9548e2d8334f426d5"><img src="images/topics/cheshire.gif" border="0" Alt="Information" align="right" hspace="10" vspace="10"></a></B></font>
<br />
Over the last few days there has been a growing community concern about possible cheating, exploiting and platinum duplication.  Rumors and speculation have begun to run rampant, and I've received a lot of concerned email on the topic.<br />
<br />
First of all, I want to thank you for your concern.  The fact that you worry about this stuff as much as we do makes me feel good about the community that I work for.  I want to especially thank those that have sent in detailed information about what they thought might be dupe or exploit situations.  That information has been very helpful.<br />
<br />
With your help, we have been able to discover and eliminate some unusual ways of cheating.  Obviously I can't go into detail about exactly how this cheating was done.  I can tell you that several of our programmers and designers took lengthy breaks from working on their current tasks to define, investigate and smash those exploits.  Most of these methods for cheating have been removed.  The few that remain will be fixed shortly.  We will be watching, and anyone using them will be banned.<br />
<br />
At the same time, our Customer Service folks have been diligently tracking down the cheaters.  We have banned accounts and deleted characters in the hundreds.  It's never a good thing to be forced to remove so many accounts, and we're not happy that such cheating was possible.  We are pleased, however, to let you know that we are confident that we have located the majority of those that exploited the game and have removed their characters or accounts.<br />
<br />
Obviously we won't be able to prevent all of the possible ways to cheat.  The folks that insist on trying to cheat have proven to be persistent and clever (and here is where I wonder why they don't apply that energy and skill to something beneficial...).  We need your help to locate these issues.  The multitude of eyes and ears of our players is always the best source of information for us.  If you ever suspect that you have discovered something that seems like an exploit, please send that information to us through the Developer's Corner AND through /bug.  Please don't assume we have heard the information already.  We'd rather have ten reports about something like this than none.<br />
<br />
I'd also like to address a rumor about the nature of some of the cheating that people have been talking about.  There has been speculation in the community that in order to pull off some of the rumored exploits someone had to be working on the &quot;inside&quot;.<br />
<br />
We take such possibilities very seriously.  And we have investigated this very thoroughly.  We keep track of all special EverQuest commands issued.  We have looked into the possibility that someone working here had a hand in helping others cheat, and we have discovered no evidence that indicates that to be the case.  Also, the nature of the cheat did not require such inside help.  I can't describe the cheat method in any detail, but there was an experience cheat that allowed extremely fast leveling.  This required some rather sophisticated cheating, but was being done without inside help.  Obviously we have removed that exploit and banned any accounts that used it.<br />
<br />
Thank you for playing EverQuest.  And thank you for you help making the game fun.<br />
<br />
Have a great holiday season.<br />
<br />
<br />
Alan<br />
