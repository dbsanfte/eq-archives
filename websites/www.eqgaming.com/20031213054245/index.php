<br />
- Verrell Cogswin can help convert red dragon scales into green dragon scales. <br />
<br />
- Fixed the Undead and Fire event in the Plane of Time. There was a bug that could cause some of the minions to fail to spawn. <br />
<br />
- Raotin Teawel will always give out the correct robe for completion of his quest. <br />
<br />
- Thought Destroyer has returned to the Plane of Hate. <br />
<br />
- Check with the Town Crier of your home town for news. There is information about the recent activities of the Wayfarers that should prove interesting. <br />
<br />
- We have made some improvements to the Plane of Air avatar rings. We have added a random interval to the respawn time of the Plane of Air avatar rings, placed apparitions at the avatar spawns so that it is possible to tell when the event is available, and the Avatar of Smoke will now respawn properly. <br />
<br />
- The Mujaki event in Plane of Nightmares was completely rewritten.  It should now be a lot more intelligent about where it sends players. <br />
<br />
- Increased the number of items found at the end of a successful LDoN raid. <br />
<br />
<br />
** Skills and Alternate Advancement ** <br />
<br />
- Channeling Focus was not giving bards the proper reduction to the chance of missing a note.  It is now fixed and gives messages to indicate when it is has helped. <br />
<br />
- Corrected a problem that was causing Alternate Advancement buff duration increase abilities and duration focus effects to negatively affect lull spells. <br />
<br />
- We have fixed a bug that could cause pick pocketed items to not show up on your cursor until you zone. This could also sometimes cause the client to crash. <br />
<br />
- Added /stoptracking command so that you no longer have to re-open the track window and hit cancel if you want to cancel your tracking quickly. <br />
<br />
- Activated AAs from Planes of Power were not working if the user did not have Shadows of Luclin registered. This has been fixed. <br />
<br />
<br />
** Spells and Pets ** <br />
<br />
- The Aura of Pain Recourse can no longer be removed by Radiant Cure. <br />
<br />
- When the character changes size (through illusion), other players will no longer see the mounted player separate from their horse. <br />
<br />
- Magician Pets will no longer attack the caster who summoned them. <br />
<br />
- Hitting your own pet while in a PVP area or while you have the PK flag on will no longer kill it. <br />
<br />
- Cataclysm of Ro has had its movement rate bonus removed to fix a stacking issue with the Selo's line of movement rate songs. <br />
<br />
- Cassindra's Chant of Clarity and Cassindra's Chorus of Clarity now lasts 3 ticks instead of being instant. <br />
  <br />
- Cloak of Luclin, Cloak of the Akheva and Frostreaver's Blessing will no longer be overwritten by Call of the Rathe. <br />
  <br />
- There are still some issues with Frostreaver's blessing being overwritten by some spells.  We are aware of the issue and hope to get it resolved soon. <br />
<br />
- Protection of the Cabbage, Protection of the Glades and Protection of the Nine will block Temperance, Aegolism and Virtue. <br />
<br />
- Ice Flame of E`ci now has the standard 2.5 second recast time. <br />
<br />
-Reclaim energy should now function properly on the pet summoned by Child of Bertoxxulous. <br />
  <br />
-Beastlord warders focused by Summoner's boon should now look as they should. <br />
<br />
<br />
** Interface ** <br />
<br />
- We have added the consider color to the Target window. The art used to display the consider color can be removed or edited via XML by custom skins. <br />
<br />
- We have also added a 3D target indicator.  The ring color indicates the con color of the target.  This can be turned off in the Options window. A new settings file in the UI folder can be edited by players to customize the appearance of the indicator, including different animated textures for each con color and other interesting settings. <br />
<br />
- Added /fontface command (usage /fontface &lt;fontname&gt;, e.g. /fontface Courier). This will change, on the fly, the fonts used by the interface (and over character's heads). Fonts can also be selected in the General Options page. <br />
<br />
- Added /tell windows. Each time you get a &quot;tell&quot; from a new character, a new chat window would open. That window will only display &quot;tells&quot; from the particular character, and any message sent from the chat window would automatically be sent as a &quot;tell&quot; to that character. You can turn this option on and off in the Options window. If you have the maximum number of chat windows open when a new tell is received, the tell will go to the main chat window <br />
<br />
- Temporary pets will no longer send their buffs to the pet window. Generally they have none, and they would replace the buffs of any standard pet. <br />
<br />
- The buff display portion of the pet window will now fade. <br />
<br />
- The Auto-inventory area of the Inventory window now fades with the parent window. <br />
<br />
- The Dump button in raid window now creates the proper, non-blank, file. <br />
<br />
- We have also added time-stamp to Raid Dump output file. <br />
<br />
- Pop-up dialogs no longer close when you press ESC. This will prevent the rez dialog from being closed accidentally. <br />
<br />
- Lay on Hands will no longer &quot;gray out&quot; the Inspect and Open hot keys in the Hotbutton window. This was fixed earlier in the Actions window, but now it is fixed in the Hotbutton window as well. <br />
<br />
- Alt-tabbing in and out of EQ should no longer cause mouse issues. <br />
<br />
- Fixed a bug that sometimes left charmed pets health bar in the group window after the owner of that pet is killed. <br />
<br />
- Find trader can now be cancelled in bazaar. <br />
<br />
<br />
** Items ** <br />
<br />
- The Copper Medal of Rapture now gives a bonus to Int. instead of Wis. <br />
<br />
<br />
** For the New Player ** <br />
<br />
- Left-clicking on an NPC prints out a message indicating what type of NPC they are and indicating that you should right-click on them. This message can be turned off in the Options window. <br />
<br />
- New characters will now start with a bag. <br />
<br />
- Added a tip window that pops up when you invoke the Quantity window that explains the use of Shift and Control when selecting items. <br />
<br />
- All characters will gain a Sense Heading skill of 200, if it was below 200. All new characters will start with a Sense Heading of 200. <br />
<br />
<br />
** Miscellaneous ** <br />
<br />
- Explore mode works properly again. <br />
