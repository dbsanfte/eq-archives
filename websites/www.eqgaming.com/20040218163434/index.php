<br />
- Fixed a problem with short-duration pets (Rage of Zomm, cleric hammers, wizard flaming swords and such) so that they will no longer dissipate before engaging the target NPC. <br />
<br />
- Reclaim Energy will now return 75 percent of the mana used to summon the pet, 95 percent if the caster has Improved Reclaim Energy. <br />
<br />
- Lull spells with duration less than 5 should no longer be lasting as if they had duration 5. This will reduce the duration of some lull-type spells to their proper duration. <br />
<br />
- Fixed a problem that caused Protection of the Nine to block Blessing of the Nine. <br />
<br />
- We corrected an issue where the same druid damage over-time spell cast on an NPC by two different druids would not stack. <br />
<br />
- Bulwark of Vie was reducing spell damage as well as melee damage. It now only reduces melee damage. <br />
<br />
- Eye of Zomm will no longer cause players summoned pets to suicide if commanded to kill the eye. <br />
