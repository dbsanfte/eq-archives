<br />
*** AA REFUND *** <br />
<br />
- Extended Notes 3 and Sionachie's Cresendo have been refunded (More details below). If you had these bard AAs and were close to 30 AA points stored, make certain that you spend enough points to have 30 or less unspent AA points before you zone. All AA points over 30 are removed when you zone. <br />
<br />
- Improved Reclaim Energy has been refunded to magicians due to changes with the amount of energy received when cannibalizing their pets. If you have this Magician AA and were close to 30 AA points stored, make certain that you spend enough points to have 30 or less unspent AA points before you zone. All AA points over 30 are removed when you zone. <br />
<br />
<br />
<br />
** Melee enhancements ** <br />
<br />
We have been building an enhancement to the melee system, and the first part of it is now Live. <br />
<br />
The yellow bar now represents endurance rather than stamina. <br />
<br />
All Disciplines now require an expenditure of endurance to use. They still have a re-use timer, and they can't be used more often than the timer allows. <br />
<br />
Disciplines have now been divided into a few different timers. <br />
<br />
We have also added a few of the new melee skills to the game. These are the skills that do not use the new &quot;opening&quot; system, but can be used without an opening present. The &quot;reactionary&quot; skills and the opening system will remain on Test for further tuning. <br />
<br />
Warriors have been given a mitigation boost. This affects all warriors at all levels. <br />
<br />
Monks have been given the ability to dodge blows from attackers behind them. This affects all monks with the Dodge ability. <br />
<br />
All existing disciplines can be purchased as tomes in either East Commons or the Plane of Knowledge. To learn a discipline, the Tome must be turned into your guildmaster. <br />
<br />
Several new disciplines have been added for warriors, monks and rogues who are above level 60. <br />
<br />
<br />
<br />
** Play King's Court in Shadowhaven! ** <br />
<br />
Shandeling's Roost in Shadowhaven now houses a game of chance. To play you will need to buy a King's Court Token. You then take this token and turn it in to any of the dealers. Based on what your hand turns out to be, you will be awarded a prize. The highest hands will return a gold ticket as the prize. This Ticket can be turned in to win prizes such as a Guise of the Deceiver, Fungus Covered Great Staff, or Holgresh Elder Beads. Good luck to all that play! <br />
<br />
<br />
<br />
** Items ** <br />
<br />
- Purchased augments, that have not been bound to an item yet, can be sold back to Dible Hedledrap in South Ro. <br />
<br />
