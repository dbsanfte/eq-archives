<br />
- We've changed the +12 Wis on the Copper Medal of Rapture to +12 Int. Really, we have! <br />
<br />
- We have lowered the minimum duration to 5 ticks on Affliction Efficiency I-IV and Affliction Haste I-IV foci. <br />
<br />
- Timeless Coral Greatsword will no longer claim to be out of charges when it procs. If you own one of these swords, you will need to petition a GM and ask them to replace your current Coral Greatsword with a new one. <br />
