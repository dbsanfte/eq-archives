      <tr>
        <td class="top_separator">
        Mailing List Rules
        </td>
      </tr>
      
       <tr>
        <td>
        <blockquote>
        <br />
        The following rules apply to all users of the Conclave of Guilds mailing list.
        Failure to abide by these rules may result in disciplinary action.  If you find any
        of these rules unclear, please send an email to 
        <a href="mailto:coglist-owner@conclaveofguilds.com">coglist-owner@conclaveofguilds.com</a>
        with your questions.<br />
        <ul>
        <li>
        All messages to the mailing list should have an appropriate subject line.  Failure to
        fill out the subject line can cause confusion and make it difficult to sort through
        the messages from the list.<br />
        <br />
        </li>
        <li>
        Subject indicators should be used where appropriate. These indicators make it easier
        for members to find messages which appeal to them.  Multiple subject indicators
        should be used when appropriate to the message.  The subject indicators for this list
        are:<br />
        <br />
        [RECRUITMENT] - To be used on all messages promoting your guild (*not to exceed more
        than one email each month PER GUILD*) within the list.<br />
        [SPOILERS] - This tag indicates an email which reveals information which is not
        common knowledge.  This includes item/spell/creature statistics, game mechanics 
        breakdowns, quest information, and any other topic which some players may wish to
        avoid knowledge of.<br />
        [*servername*] - For any message that pertains only to a specific server.<br />
        [OFF-TOPIC] - To indicate any discussion of subject matter which does not directly
        relate to Everquest II or the Conclave of Guilds website.<br />
        [TECH] - For any message which deals with technical issues such as driver problems,
        installation issues, or other difficulties.  This is also appropriate to any email
        related to hardware and software.  *Discussion of prohibited third-party software is
        not acceptable.*<br />
        <br />
        </li>
        <li>
        Please use only standard text in email sent to the list.  HTML code cannot be read
        by all email clients.<br />
        <br />
        </li>
        <li>
        All messages to the list should be written in the English language. If you do choose
        to write in a language other than English, please also write a full English
        translation of your message.  The majority of the readers on the mailing list are
        native English speakers, and many of them are only literate in that one language.
        Out of courtesy, please use the language the majority of western gamers do.<br />
        <br />
        </li>
        <li>
        Replying with an entire message quoted is not acceptable.  You may quote small,
        relevant pieces of a prior email in order to give context.  Quotes should appear in
        line with your reply, and be clearly marked.<br />
        For example:<br />
        <br />
        ** Gordo said:
        ** I think that every halfling should be forced to shave their feet!<br />
        The feet make the halfling! What will you demand next, ogres going on a diet?<br />
        <br />
        </li>
        <li>
        Your email signature should be no more than 5 lines long.  Do not enclose any
        personal information in your signature to the list.  You never know when someone will
        fax you something unpleasant at work, or call you for no legitimate reason.<br />
        <br />
        </li>
        <li>
        Language and subject matter in your posts should be appropriate to individuals of all
        ages and beliefs.  This means no swearing, no foul or suggestive comments, and in
        general keep the subject matter "clean" out of respect for others. Everquest II is a
        game with some mature themes, which happens to be played by some very young gamers.
        What may be deemed appropriate for you or your friends may not be for everyone, so 
        be courteous please.<br />
        <br />
        </li>
        <li>
        Flaming people on the list is not allowed.  Disagreements are commonplace in the
        world, however it is expected that members of the Conclve of Guilds community will 
        behave appropriately during such times.  Resorting to sending emails full of insults
        and foulness is unacceptable, and will not be tolerated.<br />
        <br />
        </li>
        <li>
        Spamming the list is prohibited.  Sending multiple copies of an email is considered
        spamming.  Advertising excessively is considered spamming.  Excessively quoting a
        prior message is considered spamming.  Having an email signature which is too large
        is spamming.  Sending attatchments to the list is spamming.  Essentially, anything
        which results in a larger amount of traffic to the mailboxes of list users than
        required is spamming, and unacceptable.  Think before you hit send.<br />
        <br />
        </li>
        <li>
        Disclosing information which is protected by an NDA is illegal.  Do not share any
        such knowledge you may posess.  In addition, it is absolutely not acceptable to email
        the list regarding any prohibited third party software.  Yes, this was stated once
        already, but it is serious enough to be mentioned twice.<br />
        <br />
        </li>
        <li>
        The rules of the mailing list may be updated at any time, and once posted on this
        page, are binding for all members.<br />
        </li>
        </ul>
        </blockquote>
        </td>
