        <td class="top_separator">
        Information on Conclave of Guilds Internet Relay Chat
        </td>
      </tr>
      <tr>
        <td>
        <blockquote>
        <br />
        What is IRC you may wonder?  The acronym stands for Internet Relay Chat, a relatively
        old method of serving real-time chats which is still powerful and popular today.  The
        IRC servers used by Conclave of Guilds are the DALnet servers.  This is due to the
        restrictions placed on IRC hosting by our service provider, and the fact that DALnet
        offers registration of nicknames and channels.  For more information on IRC at 
        DALnet, check out <a href="http://www.dal.net/">www.dal.net</a> and read their 
        services and help sections.<br />
        <br />
        Taking part in the Conclave of Guilds Internet Relay Chat is simple if you have some
        experience with IRC.  Even if you happen to be a novice, you should be able to chat
        quickly and easily as long as you follow the instructions on this page.<br /> 
        <br />
        How do you start chatting?  Simply choose an IRC client, or utilize the one on the
        <a href="http://www.dal.net/">DALnet homepage</a>.  Should you wish to download an
        IRC client, there are many choices available.  Many of the options are listed on the 
        <a href="http://www.dal.net/software/index.php3">DALnet software page</a>.  Simply
        sample the various clients until you find the one which best suits you.<br />
        <br />
        Logging on to the Conclave of Guilds IRC is quick and easy as well.  If you choose to
        use the <a href="http://www.dal.net/">DALnet client</a> on their homepage, simply
        input a nickname and click "Go!" within the "Chat now!" section.  Once logged on to
        the DALnet servers, type '/join #CoGmain' to jump into the #CoGmain channel.<br />
        <br />
        If you have chosen to use an IRC client, the details for logging in are a bit
        different with each piece of software.  The main things to remember are that you want
        to join a DALnet server, and the channel to 'join' is #CoGmain once you have logged
        on.<br />
        </blockquote>
        </td>
      </tr>
      <tr>
        <td class="top_separator">
        IRC Chat Rules for #CoGmain on DALnet
        </td>
      </tr>
      <tr>
        <td>
        <blockquote>
        <br />
        All users of the services on DALnet must abide by their
        <a href="http://docs.dal.net/docs/netiquette.html">'netiquette'</a> policies.  This
        is simply courtesy to the individuals who provide the IRC service to Conclave of
        Guilds and our users.<br />
        <br />
        In addition, as a user of the Conclave of Guilds IRC channel, you must abide by the
        policies of the Conclave of Guilds itself.  These policies are similar to those
        governing the use of the <a href="mlist.php">CoG mailing list.</a>  Please be sure
        to read the rules below, as use of the #CoGmain channel is dependant upon following
        them.<br />
        <br />
        <ul>
        <li>
        All public chatting should be done in English.  If you do decide to type something
        in a language other than English, please also write a full English transation as your
        next message.  The majority of the users on #CoGmain are native English speakers, and
        many of them are only literate in that one language. Out of courtesy, please use the
        language the majority of western gamers do.<br />
        <br />
        </li>
        <li>
        Private messages should contain subject matter which is appropriate to the topic of
        discussion. Please do not send inappropriate messages in private to any of the other
        users in the channel. If another user requests that you stop sending them messages,
        you must cease immediately.<br />
        <br />
        </li>
        <li>
        Language and subject matter during chat should be appropriate to individuals of all
        ages and beliefs.  This means no swearing, no foul or suggestive comments, and in
        general keep the subject matter "clean" out of respect for others. Everquest II is a
        game with some mature themes, which happens to be played by some very young gamers.
        What may be deemed appropriate for you or your friends may not be for everyone, so 
        be courteous please.<br />
        <br />
        </li>
        <li>
        Indulging yourself by flaming another chatter is not allowed.  Disagreements are
        common during chat sessions, however it is expected that members of the Conclve of
        Guilds community will behave appropriately during such times.  Resorting to insults
        and foulness is unacceptable, and will not be tolerated.<br />
        <br />
        </li>
        <li>
        Excessive echoing (anything which causes text to appear on the screens of the other
        chatters) is considered spam.  If you type quickly, that is fine, feel free to enter
        new messages as many times as you would like.  However do not send one message over
        and over.  Do not execute needless commands repeatedly.  (For example, do not change
        your nick over and over again.)  Out of consideration for others, do not fill their
        screens with junk!<br /> 
        <br />
        </li>
        <li>
        Disclosing information which is protected by an NDA is illegal.  Do not share any
        such knowledge you may posess.  In addition, it is absolutely not acceptable to chat
        regarding any prohibited third party software.<br />
        <br />
        </li>
        <li>
        The rules of the #CoGmain IRC channel may be updated at any time, and once posted on
        this page, are binding for all members.<br />
        </li>
        </ul>
        </blockquote>
        </td>
