                              <p><font size="2">Well it's been out now for months, 
                                and Camelot players have been chatting about it 
                                in just about every chat room. We've seen it posted 
                                on just about every Camelot message board. So 
                                what the hell is it?<br>
                                <br>
                                GM Associates expanded their product line once 
                                again, but this time for DAoC. You know those 
                                trade skills which take forever to get up? Well 
                                now you can be AFK while your character sits by 
                                the forge and ups his/her trade skills.<br>
                                <br>
                                Since we love Camelot, we tried it out. And here's 
                                the deal:<br>
                                <br>
                                <b>The Test:</b><br>
                                First, if you're serious about trade skills -- 
                                especially if you sell items on ebay -- this IS 
                                the product for you. At higher levels, trade skills 
                                take upwards of 5 minutes for one click of a component 
                                -- meaning many long hours of boredom. Practicing 
                                trade skills in DAoC is quite frankly a pain in 
                                the ass, not to mention a serious time commitment. 
                                So, we put the Thumper V2 VT (Camelot) to the 
                                test.<br>
                                <br>
                                Trade skills in DAoC (even with the Thumper) still 
                                require some manual intervention. With the Thumper 
                                this intervention is limited to only those times 
                                when your inventory of goods is depleted. One 
                                person manually training their skills was spending 
                                3-4 hours a night reading a book and clicking 
                                their mouse while sitting at their keyboard. With 
                                the Thumper, the time it takes to increase your 
                                skill remains the same, but in this 3-4 hour time 
                                frame we only had to spend 15-20 minutes of actual 
                                time at the keyboard to go refresh supplies. Not 
                                only that, when the manual trade skill guy just 
                                couldn't stand it anymore and went to bed, our 
                                Thumper kept training our character the entire 
                                night. You can pretty much train forever with 
                                the Thumper, but you have to plan on intervening 
                                now and then to go refresh supplies and select 
                                the appropriate component to build. IN later levels, 
                                you can stack your character with supplies and 
                                go to sleep while the Thumper practices for you. 
                                Wake up the next morning, refresh your supplies, 
                                go to work and come back and repeat the process 
                                again. It really is almost funny how easy it is 
                                to become an expert in your trade skills with 
                                this little device.<br>
                                <br>
                                For you ebayers that have multiple characters, 
                                this device is truly amazing. We took 3 separate 
                                characters all trained somewhat in armorcraft. 
                                We had 2 characters that would thump components 
                                while the third character would thump to put them 
                                all together. As they grew in capabilities it 
                                became readily apparent that we could flood ebay 
                                with goods for sale for our server easily once 
                                we attained an appropriate level. <br>
                                <br>
                                We started around 10:00pm one night and ran our 
                                Thumper against a manual skill practicer. We were 
                                able to get all three of our characters to 200+ 
                                in one session (about 4.5 hours), spending a total 
                                of 15 minutes at the keyboard per character (we 
                                were running one Thumper per character). Our manual 
                                skill practicer was also able to do it in 4.5 
                                hours (with a headache and an aching wrist), also 
                                achieving the 200+ in about 4.5 hours.<br>
                                <br>
                                When we passed the 200 mark, skill practicing 
                                noticeably slowed down. While our manual practicer 
                                was continuing on with his skill practicing, we 
                                spent an extra 10 minutes initially timing and 
                                preparing supplies for our character. We then 
                                spent another 5 minutes double checking the timing 
                                interval on our Thumper. So, we were behind 20 
                                minutes from our competition. Then we turned the 
                                Thumper on and went down to watch TV, stopping 
                                back every 45-60 minutes to check our supplies 
                                (and to make fun of our manual practicer). Well, 
                                he finally went to bed from eye strain and we 
                                let the Thumper run the rest of the night, checking 
                                it once every 2-3 hours to load up supplies again. 
                                In the morning our manual practicer had attained 
                                289 and our &quot;thumped&quot;&quot; character 
                                had attained a wopping 409. All in all, he had 
                                invested another 2.5 hours and we had invested 
                                a total of 45 minutes. The total was now manual 
                                = 6.5 hours and Thumper =70 minutes.<br>
                                <br>
                                We decided to push up to the 400 mark, and here 
                                is where the Thumper really began to shine. For 
                                every 3 hours our manual practicer spent practicing 
                                those trade skills we spent approximately 20 minutes 
                                (once you get the hang of loading your inventory 
                                with the appropriate amount of goods it's a breeze). 
                                And with each level, the delay in between clicking 
                                increases exponentially. Trade skills can go towards 
                                the 1000 mark with intervals upwards of 5 minutes 
                                in between clicks. That means the average manual 
                                player gets to practice that trade skill 12 times 
                                per hour only -- with some serious down time in 
                                between (better get a book to read and a comfortable 
                                chair). At the higher levels, we could run our 
                                Thumper the entire night and not get through our 
                                inventory of supplies (in the start of trade skill 
                                practicing, skills can be practiced very quickly 
                                because the time delay in between practicing is 
                                extremely short). <br>
                                <br>
                                <br>
                                <b>Summary &amp; Conclusions:</b><br>
                                In summary, the major benefit in pre-200 range 
                                of the Thumper is that the time spent at the keyboard 
                                is reduced, and you get to practice the planning 
                                of supplies for your character (which you have 
                                to do anyway when manually practicing trade skills). 
                                The post-200 skill range is actually fun and entertaining 
                                with the Thumper providing <b>dramatic </b>reduction 
                                i nthe time spent at the keyboard.<br>
                                <br>
                                The time savings are <b>significant</b>, especially 
                                as you attain higher trade skill levels. There 
                                just is no better way to practice your skills 
                                than doing them while AFK. Kudos to GM Associates 
                                for yet another great product.<br>
                                <br>
                                <b>Lessons Learned:</b><br>
                                1. It probably is better to practice up to 50 
                                or so manually to get the hang of the trade skills, 
                                unless you are a trade skill veteran.<br>
                                2. Always always err on the side of a higher delay 
                                on your Thumper. This will avoid you coming back 
                                to your computer and seeing your trade skills 
                                being canceled because in the time that you were 
                                gone your skill increased such that your Thumper. 
                                clicks are now canceling your training sessions.<br>
                                </font><font size="2">3. Practice at night! After 
                                300 or so in skill level, load up your character 
                                and go to bed. If you really have a gaming problem 
                                then set your alarm for halfway through the night 
                                and load your character back up again with supplies.<br>
                                4. Don't sell short your planning session! Spending 
                                about 5 minutes before hand analyzing your consumption 
                                rate of supplies can do wonders to giving you 
                                the information you need to buy the appropriate 
                                amount of each item. Normally people simply sit 
                                by the forge and they get the warning message 
                                that they are short on product x, and then they 
                                say &quot;oops&quot; and go run and buy that material 
                                component. Spend some time and buy the appropriate 
                                amount of each item, then go have fun with your 
                                family as the Thumper increases your trade skills.<br>
                                <br>
                                Hope this little review helps. And for those of 
                                you who always wanted to do trade skills but didn't 
                                quite have the patience to dedicate months -- 
                                check out the Thumper at <a href="http://www.thumperv2.com" target="_blank">www.thumperv2.com</a>.<br>
