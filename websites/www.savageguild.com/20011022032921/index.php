<TD COLSPAN=2>
<font face="Verdana,Arial" size="2" color="white">
***Patch Day***<br>
<br>
The following changes have been implemented on the production servers as part of today's patch:
<br>
 *General Changes*<br>
<br>
- NPC corpses level 55 or over will now last 30 minutes before decaying. This should help those on large multi-group encounters who need some prep-time before looting items.
- The item "Woe" has been repaired. If you receive the "Item out of charges" message when your "Woe" attempts to fire its spell, please contact a GM to trade out the item.
- The spell "Mark of Karn" has been changed. The recast-time has been reduced significantly and the Hitpoint-return is now scaled inversely based upon the delay of the weapon. In addition, a hitpoint return will only take place when the target is hit with a primary melee weapon, or the primary hand if you are unarmed.
- Some more tradeskill component vendors have been placed within the world to make certain tradeskills easier to use in your home town.
- "AFK" and "LD" status will now be reported above player's heads.<br>
<br>
*Fleeing NPCs*<br>
<br>
Last week's patch caused NPCs to flee more than before due to a bug that was fixed. After evaluating the situation, we decided to reduce the chance to flee, but not to the extent that it was reduced before. NPCs were previously much more "brave" than they should have been.<br>
<br>
As part of the same change, charmed NPCs also began fleeing when low on health. We've determined that this is not a good situation for the players. As such, we have stopped charmed creatures from fleeing per player request.<br>
<br>
*Level 1 Character Purge*<br>
<br>
The Level 1 character purge has been completed. All level 1 characters that have not been played within the past 30 days have been deleted.
<br>
*New Server Active*<br>
<br>
Tholuxe Paells, a new server open to new characters only, is now active and ready for play. Enjoy! As a reminder, /movelog registration will take place on Mithaniel Marr and Tunare Friday evening from 6PM to Midnight (PDT: GMT-7). Registered characters will be moved to a second new server, Drinal, early next week.<br>
<br>
***User Interface Changes***<br>
<br>
Many UI enhancements were made in today's patch:<br>
<br>
*Moving and Resizing Windows*<br>
<br>
The data windows in the full screen "HUD" mode may now be moved by clicking in the upper left-hand corner, moving them to where you want, then clicking again. The "spell effect" and "chat" windows can be resized by clicking on the lower right-hand corner, dragging to the appropriate size, and then clicking again. Coordinates for window locations in each resolution are stored in the EQCLIENT.INI file.<br>
<br>
*Bugs with Several Commands Fixed*<br>
<br>
We fixed a problem with /book, /sit, and /doability that allowed them to be executed at inappropriate times, such as while charmed or feared. They should now only function when the native button would have functioned if pressed.<br>
<br>
*Miscellaneous Additions*<br>
<br>
Added the following /-commands:<br>
<br>
- /camp: Causes your character to camp out. You must be sitting to use /camp.
- /disband: Will disband you from your current group, or turn down an invitation to join another group.
- /invite: Will invite the target into a group, or accept an invitation if one is pending.
- /attack: Will toggle the state of "Auto-attack". You may also add a parameter of "on" or "off" to explicitly set the state.<br>
<br>
In addition:<br>
<br>
- CTRL-1 through CTRL-8 will cast the spell in the specified spell-slot.
- ":" (colon: Short for /emote) and "'" (apostrophe: Short for /say) will now bring up the chat line in the same fashion as the /-key and ENTER.
- The "R" key (by default) takes you into reply-mode as always, bringing up a reply to the last person sending you a /tell. However, you can now TAB and SHIFT-TAB to cycle through the last 10 people that have sent you /tells. <br>
<br>
*Pauses in Socials*<br>
<br>
You may now enter pauses in social batches with the /pause command. /pause takes an argument from 1 to 600, with the value being equal to the number of tenths of seconds (i.e. /pause 100 will yield a 10 second pause). <br>
<br>
For example, a social consisting of:<br>
<br>
/sit off
/cast 1
/pause 100
/sit on
<br>
...would cause you to stand up, cast the spell in slot 1, wait 10 seconds after you've STARTED casting the spell, and sit down.<br>
<br>
Furthermore, you can also use the /pause command on the same line as another social by separating the commands with a comma. Even though the pause command is specified first, it is executed AFTER the command on the same line.<br>
<br>
For example:<br>
<br>
/sit off
/pause 100,/cast 1
/sit on<br>
<br>
...would have the same effect as the example above. It is important to note that the comma can only be used to separate a /pause command from another, and MUST be specified first on the line. 
<br>
*Emote Codes*<br>
<br>
The @ symbol has been replaced with a series of %-codes that expand into various pieces of information, and now works in ALL chat channels (emote, say, shout, ooc, auction, group, guild). 
<br>
The new %-codes are: <br>
<br>
%T - Returns the current target.
%S - Returns the subjective gender-specific pronoun for the target (He, She, It).
%O - Returns the objective gender-specific pronoun for the target (Him, Her, It).
%P - Returns the posessive gender-specific pronoun for the target (His, Her, Its).
%R - Returns the race of the target (only works on Player characters).<br>
<br>
For example, if you have a target of "a gnoll", the following emote:<br>
<br>
/point say points at %T indicating that he is ready to kill %O.<br>
<br>
...Your character will execute the "point" animation with a text output of "CharacterName points at a gnoll indicating that he is ready to kill it."
<br>
- The EverQuest Team <br>


 

