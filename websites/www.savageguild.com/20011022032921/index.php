<font face="Verdana,Arial" size="2" color="white">
Seems like the NDA for players in the beta4 test of <A STYLE='color: #ff9900' href="http://www.darkageofcamelot.com/">Dark Age of Camelot</a> has been lifted so websites now showing more detail of this up and coming MMORPG are starting to show up on the web ..  <br><br>
A couple of the more interesting sites have been pointed out by our very own KlanWolf in our new <A STYLE='color: #ff9900' href="http://www.savageforums.com/forumdisplay.php?forumid=28">DAoC forum</a> ..
<br><br>
The first one entitled <A STYLE='color: #ff9900' href="http://lumthemad.net/personal/camelot/trade_skill_howto.htm">Trade Skill HOWTO: A Guide To The Crafting Arts</a> gives an indepth look into which professions your choosen class can work towards in game. Here's an extract ..<blockquote><i>As you continue to grow in your chosen craft, you’ll find that learning a trade can be expensive. You can continue to “powerskill” your way to mastery but this will require significant investment, either from your own adventuring or from your guild.</i></blockquote>Deffo a worthwhile <A STYLE='color: #ff9900' href="http://lumthemad.net/personal/camelot/trade_skill_howto.htm">read</a>.
<br><br>
The second website worth having a look at is called <A STYLE='color: #ff9900' href="http://copland.udel.edu/~trevor/camelot/">The Classes of Camelot</a> which gives a rundown of all the classes within the game and what they can do. As noted on their news page ..<blockquote><i>The NDA has recently been lifted, so over the course of the next few weeks, information here will increase immensely; Look for strategy guides and spell lists/combat style lists for each class in Camelot, and more!</i></blockquote>heh, If you can't wait any longer go <A STYLE='color: #ff9900' href="http://copland.udel.edu/~trevor/camelot/">here</a> to check it out.
