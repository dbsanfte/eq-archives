&nbsp;<font size="2"><b>Guild Charter</b></font><br>

<P><B><FONT face=Verdana,Arial color=olive size=3>~ </FONT><FONT 
face=Verdana,Arial color=#ffdd00 size=3>Leadership</FONT><FONT 
face=Verdana,Arial color=olive size=3> ~</FONT></B></P>
<P>We operate a system that we like to call "a friendly dictatorship". The idea 
behind this system is to avoid lengthy disputes with in the Guild. If an issue 
comes up, the officers and the leaders are to discuss it, with input from all 
guild members. If that issue cannot be resolved by the officers and the leaders, 
then the leader decides on it. The leader's word is final.</P>
<P>&nbsp;</P>
<P><B><FONT face=Verdana,Arial color=olive size=3>~ </FONT><FONT 
face=Verdana,Arial color=#ffdd00 size=3>General Behaviour</FONT><FONT 
face=Verdana,Arial color=olive size=3> ~</FONT></B></P>
<P>There will be no Ninja Looting, Kill Stealing, Camp Takeovers or Player 
Harassment. If a member is caught doing this he will be immediately removed from 
the Guild. 
<P>The use of /guildsay is for Guild related talk and discussion. Please show 
consideration to other members when using this channel. At times, often during 
Guild Raids, officers may request that everyone avoids using /Guildsay for a 
period of time. Personal requests and messages should use /tell instead.</P>
<P>&nbsp;</P>
<P><B><FONT face=Verdana,Arial color=olive size=3>~ </FONT><FONT 
face=Verdana,Arial color=#ffdd00 size=3>Guild Property Items </FONT><FONT 
face=Verdana,Arial color=olive size=3>~</FONT></B></P>
<P>Sometimes you may be given an item declared as "guild property". Guild 
property means you are not allowed to give that item away. If you don't need 
that item anymore, you are to give it back to the guild. Of course you also have 
to give all guild property items back if you leave the guild. Returned items 
will go to the next who needs it, to be decided by the officers. If noone needs 
a returned item, it goes back to the original donator.<BR>Please announce all 
new guild property items and all holder changes to the leader, so he can keep 
track of them. 
<P>[ Note: This replaces the former "guild bank", because this new rule is much 
easier to handle, since everyone can be a donator, and any officer can take back 
a guild property item which is not needed anymore by the current holder. I.E., 
there is no need for a "guild banker" to be available for that. ]</P>
<P>&nbsp;</P>
<P><B><FONT face=Verdana,Arial color=olive size=3>~ </FONT><FONT 
face=Verdana,Arial color=#ffdd00 size=3>Loot Rules </FONT><FONT 
face=Verdana,Arial color=olive size=3>~</FONT></B></P>
<P>We try to keep this simple, since rules like a seniority system often cause 
dismay and endless discussions. On a guild raid (dragons, planes, tough 
dungeons, where all or almost all players are in the guild) or a guild camp 
(like camping the frenzied with an all guild group), the participating players 
decide beforehand whether this raid or camp be a guild pickup or not. If not, 
the group(s) are free to decide what to do with the loot. If its a guild pickup 
though, all acquired items of note will become guild property, as described 
above. The participating players should, of course, be first choice when 
distributing those guild property items. 
<P>If non-guild players are present, normal /randoming applies (preferably need 
before greed). If a guild member wins, and the raid/hunt was declared guild 
pickup, the guild property method applies to that item.</P>
<P>&nbsp;</P>
<P><B><FONT face=Verdana,Arial color=olive size=3>~ </FONT><FONT 
face=Verdana,Arial color=#ffdd00 size=3>Alternate Characters </FONT><FONT 
face=Verdana,Arial color=olive size=3>~</FONT></B></P>
<P>Any regular member may have any number of alternate characters in the guild, 
no matter what level. This is to enable that member to see guildchat at all 
times.</P>
<P>&nbsp;</P>
<P><B><FONT face=Verdana,Arial color=olive size=3>~ </FONT><FONT 
face=Verdana,Arial color=#ffdd00 size=3>Recruitement </FONT><FONT 
face=Verdana,Arial color=olive size=3>~</FONT></B></P>
<P>Except for alts (see above), anyone wanting to join the guild has to be a) 
level 36 at least, and b) invited by at least two regular members. The new 
member will be put on a two week trial. During that time the new member must 
make an effort to group with other guild members. The trial period may be 
extended at anytime, especially if the new member fails to group with other 
members. The inviting officer is responsible to keep track of the trial period. 
When the trial period is over, any full member who grouped with the new member 
can vote on whether the new member becomes a regular or not. It needs at least 
two "yes" votes, and more "yes" votes than "no" votes, for the new member to be 
accepted as a regular. Any officer can veto on that. All recruitments must be 
announced to the guild leader.


