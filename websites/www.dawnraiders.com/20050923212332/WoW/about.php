        <span style="font-weight: bold">The History</span>
	<br />
	
	<br />
	Dawnraiders started as a EverQuest Guild on the European based server Venril Sathir that went live in 2002. Since Venril Sathir was a "no movelog" server from the start the members had to start from level 1, and work their way up.
	<br />
	
	<br />
	The original members, and those that joined in the first few months had very little previous raiding experience, but what we all had incommon was a firm desire to reach the end-game, and to raid our way there... so to speak.
	<br />
	
	<br />
	From the very first dragon raids of original EQ we moved on to the low-end content in the expansion "Ruins of Kunark", and to the icy wastelands of "Scars of Velious". 
	<br />
	
	<br />
	Dawnraiders started to take shape into a highly successful raiding-machine. When we left Kael, and Temple of Veehsan behind us DR had learned it's lessons well. Not only did we like raiding - we were getting good at it!
	<br />
	
	<br />
	We fought our way into Sleeper's Toomb, we lay waste to Ssraeshza, we aquired keys to Vex Thal, we spanked Aten Ha Ra so hard she couldn't sit for a week - and then we did it all again.
	<br />
	
	<br />
	By this time we had started to eye the Planes Of Power. We had killed some of the lesser guardians of the Planes, but after clearing Vex Thal we started to progress for real.
	<br />
	
	<br />
	The Gods cried out and tried to stop us, and while we didn't win every battle we always won in the end. With Hundreds of bloody battles behind us we closed in on Plane of Time itself. The elemetal Gods fell, and suddenly we stood in the home of Gods - in fact we were standing more or less in their living room!
	<br />
	
	<br />
	The Goal was ahead. Quarm, the four-headed dragon, the guardian of Zebuxoruk's prison, was going to end up as a carpet in the DR guild house - it was just a matter of time.
	<br />
	
	<br />
	The Candyshop was robbe... err... Plane of Time was beaten. Quarm was dead, and Dawnraiders turned it's attention to the next target...
	<br />
	
	<br />
	<span style="font-weight: bold">The Future</span>
	<br />
	
	<br />
	Dawnraiders are aiming for the high-end game in World of Warcraft. We like raids, we plan to participate in the Battlegrounds, we want to be one of the top guilds of the server.
	<br />
	
	<br />
	We are, however, going to continue in our old spirit. We will not be a guild that demand 100% attendance to all raids. We do understand that real life sometimes have to come first. 
	<br />
	
	<br />
	Most of us are working, have families, children, and other things that often demand our attention. We want to allow our members some freedom, we want to be a guild with a family feeling, and at the same time we want to be a high-end raiding guild... Does it sound impossible? Not at all!
	<br />
	
	<br />
	We have done it before, after all...
	<br />
	
	<br />
	<span style="font-weight: bold">The people</span>
	<br />
	
	<br />
	We are a bunch of friends that love to play together - and we always want to meet new friends; If we find that someone fits in with our way of playing, and with our personalities, and that also meet our recruitment criteria, we will welcome them with open arms. As long as raid limits and such allow it we are open for recruitment.
	<br />
	
	<br />
	Our MMPORG-community covers three games right now (World of Warcraft, EverQuest and EverQuest II) and we have members in a number of European countries, as well as some in the US.
	<br />
	
	<br />
	Dawnraiders members meet quite regularly in real life. Often over a weekend. So far meetings have taken place in England and in Belgium, but it is far from impossible that we will meet in... France (?) sometime. We grab a few beers, have a lot of laughs, tries some nice dance moves... and have a great time.
	<br />
	
	<br />
	We do not like Drama, we hate fighting and childishness. The members that have children get enough of that at home...
	<br />
	
	<br />
	We like to beat hard encounters - many of us are competative - we want to win... with as few problems as possible... simple as that.
