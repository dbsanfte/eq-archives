	<b>New to the Grey Council? FAQ's answered here:</b><br><br>
	
	<ul>
	<li>As an initiate, can I participate in GC chat/email lists/message boards/etc? Do I need to sign up for everything?<br>
	Initiates can and should participate in any or all of the above. The private message boards are where most of our out-of-game discussion takes place.
	<p>
	<!--message boards-->
	<li>How do I read the GC message boards?<br>
	Guild events are posted to the <a href="http://www.greycouncil.org/private/event_msgboard.php">events message board</a>. We also have a <a href="http://pub8.ezboard.com/fgreycouncilgeneral">public message board</a> and a <a href="http://www.greycouncil.org/private/priv_msgboard.php">private message board</a>. Here's how you read them:
	<ol>
	<li>Sign up for an <a href="http://www.ezboard.com">EZBoard</a> account if you don't have one.
	<li>Log into ezboard with your new (or existing) account, and post a request for access to the private boards on GC's main public board.
	<li>When an officer grants you access to the private boards, you should now be able to read the public and private boards.
	</ol>
	<p>
	<li>How do I get into the Members Only section of the website?<br>
	Email <a href="mailto:ali@hippiegeek.com">Ardynn</a> for the username and password.
	<p>
	<li>I want to be listed on the Member List. How can I get my name up there?<br>
	Email any officer - their addresses should be on the <a href="http://www.greycouncil.org/members.php">Member List</a>.
	<p>
	<li>My name/level/class/race/astrological sign on the Member List is incorrect. How do I fix this?<br>
	Email any officer. :)
	<p>
	<li>How do I sign up for the mailing list?
	<br>The email list is pretty quiet nowadays, but if you'd like to sign up, <a href="https://mailman.veriomail.com/mailman/listinfo/eq-l">click here</a>.
	<p>
	<li>Is there a GC chatroom?<br>
	Yes, we have an IRC channel at irc.stratics.com, called gc-members. Come join the party. The address is: stratics.tac.net port 6667. No password is required.
	<p>
	<li>What is mIRC? How do I get into the chatroom?<br>
	mIRC is a shareware IRC chat room program. You can download it <a href="http://www.mirc.com">here</a>. To log into the chat room:
	<ol>
	<li>Start up mirc.
	<li>Connect to irc.stratics.com.
	<li>In the status window type /join #gc-members.
	</ol>
	Some people have trouble using mIRC if they have a firewall at work. To get around this, try this: go to <a href="http://chat.stratics.com">chat.stratics.com</a>, log into the server listed above, and type /join #gc-members.<br>

</ul>
