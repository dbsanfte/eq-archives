	<font size="+1"><b>D</b></font>ecisions are made by a consensus of the Council Leaders. Leaders shall be chosen for each career path. Every race upon Norrath is accepted into the fold unless they disobeyed the rulings of the Leaders and/or the Guild itself. Religion does not enter into the acceptance factor nor does a persons previous history with the law, other guilds or rulers.
	<br><br>
	<img src="images/clear_dot.gif" alt="" height="5" width="500"><br>
	<font size="+1"><b>N</b></font>ew Guild members will enter into a trial period determined by the Leader for the new Guild member. If the Leader is not satisfied at any time during this trial period the member can be ejected although a reason needs to be provided to the other Leaders upon request.
	<br><br>
	<img src="images/clear_dot.gif" alt="" height="5" width="500"><br>
	<font size="+1"><b>N</b></font>ew members can be required to make donations to the Guild before acceptance is allowed.
	<br><br>
	<img src="images/clear_dot.gif" alt="" height="5" width="500"><br>
	<font size="+1"><b>T</b></font>here shall be a Leader that is the spokesperson for that career. Ranger, Warrior, Wizard, Mage, Enchanter, Necromancer, Bard, Rogue, Paladin, Shaman, Cleric, Shadowknight and Monk shall have one Leader that will help direct those under his tutelage.
	<br><br>
	<img src="images/clear_dot.gif" alt="" height="5" width="500"><br>
	<font size="+1"><b>D</b></font>onations to the Guild are not required but expected. Everyone should assist the Guild in what little ways they can. Some have trade skills, others have extra gold, others might have unforeseen talents.
