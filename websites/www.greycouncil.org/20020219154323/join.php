<b>Notes:</b> There is no level limit to join GC! We accept folks of any age. However, since much of our application process involves grouping and raiding with other members, it is to an applicant's advantage to be of an appropriate raiding age. A large number of guild raids are 50+ and raids to certain select locations are 55+. Please contact an officer if you have specific questions about level-related issues.
<br><br>
Grey Council members are expected to adhere to a high standard of conduct - Read our <a href="rules.php">Rules</a> section to find out more. If you don't think you can follow these rules, don't apply.<br>
<center>...</center>
<br>
<b>The Application Process</b><br><br>
The 3 stages of Grey Council membership are as follows: Applicant, Initiate, Full Member.
<br><br>
<b>Applicant</b>: To be considered an applicant to Grey Council you must A) be unguilded, B) post an official application on our <a href="http://www.greycouncil.org/applicantboard.php">application board</a>. At the very least your application post should include: your character name, class, level, details of your past everquest experience, and your reasons for pursuing membership into the guild.
<br><br>
Once considered an applicant you will be contacted by Manslayer and asked to group and raid with the guild for a period of typically 3 weeks. This period will allow us to get to know you better and evaluate how well you fit in with other Grey Council members. It is expected that during this period you raid or group with us often enough for us to be able to make this determination - if you can't or do not your application period may be extended.
<br><br>
After sufficient exposure your application will be reviewed by the guild and two sponsors will be asked to step forward. Should you fail to meet the guild's requirements or lack initial sponsors your application can be dropped. Fulfilling these requirements grants you initiate status.
<br><br>
<b>Initiate</b>: As a Grey Council initiate you will be guilded as a trial member and given access to our private members forums. At the end of your trial period your membership will again be reviewed and an additional 3 sponsors will be required. If, at the end of this period, you fail to meet GC standards or do not have additional sponsorship you may be given an extended trial or completely removed from the guild. An initiate's trial period lasts on the average of 3-4 weeks.
<br><br>
<b>Full Member</b>: Once your trial period is passed you are granted with full membership into Grey Council. Full membership includes complete access to guild resources as well as the ability to sponsor initiates.
