Hail Nordlys, Slayers of Dragons
</div>
<div class='bodytable' style='text-align:left'>
<a href='news.php?cat.1'><img style='float: left; border:0'  src='e107_themes/nordranious/images/bullet1.gif' alt='' /></a>
<div style='text-align:center'><br />
We decided to push the boat out for our latest raid target, and headed over to the Plane of Valour, to try our might against <b>Aerin`Dar</b>. We had expected him to put up a strong fight, and he didn't disappoint. His Golem friends didn't help matters either, giving our Crowd Control Team a few headaches along the way.<br />
<br />
But we pulled through, and soon had bits of Glass Dragon flying all over the place, as he hit the floor dead.<br />
<br />
<br />
<img src='http://homepage.ntlworld.com/jaywood1/aerin.jpg' alt='' /><br />
One dead dragon, as ordered. The small speck stood about halfway between his head and body is me - that's how huge this guy is.<br />
<br />
<br />
We're a guild who like to do things our own way, and discover things ourselves. Today we discovered how mean Everquest can be at times. After killing <b>Aerin Dar</b>, our remaining raid carried on (brilliantly) kiting and picking off the Golems that were still running round. We noticed the Planer Projection has spawned as normal, and decided to clear the golems first, as the dead were rezzed back in.<br />
<br />
Big mistake.<br />
<br />
After what seemed like only a few minutes, he despawned on us, leaving the entire raid without a flag. It was no biggie really, as everyone was more then happy with our big kill.<br />
<br />
After cursing at <b>Aerin`Dar's Corpse</b> a few times, we headed on over to the Plane of Storms, and took down <b>Jeplak, Lord of Srerendi</b>. He was the ideal mob for everyone to take their slight frustration out on.<br />
<br />
Lewtz from Aerin`Dar were:<br />
<br />
<a href="http://everquest.allakhazam.com/db/item.html?item=16694">Shoulderpads of the Visionary</a> Grats to Bolerus<br />
<br />
<a href="http://everquest.allakhazam.com/db/item.html?item=17165">Honourable Longsword</a> Grats to Gearinl (our LD king for the night)<br />
<br />
<br />
And from Jeplak:<br />
<br />
<a href="http://everquest.allakhazam.com/db/item.html?item=17156">Girdle of the Storm Giant</a> Grats to Bonkh<br />
<br />
<br />
All in all, another great evenings raiding was had. Our lack of flags has only made us more determined to go back and beat the shiney Dragon down again soon.<br />
