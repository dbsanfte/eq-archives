                  <font size=<? echo 2; ?><p>(Note: Militia is NOT moving to the new server)</p>

<p>We will be opening a new server and moving characters from the E'ci and The Rather severs to this new server upon the request of the customer. If you choose to move your characters to the new server, please be aware that all of your characters on the old server will be moved to the new server.</p> 
<p>To request to have your characters moved to the new server, all you need to do is type "/movelog yes" into the chat window while playing a character on that server during the time that the move log is open.</p> 

<p>We will be opening the move log for these two servers on Friday, March 16th, 2001 at 6:00 pm. PST (which is Saturday morning at 2:00 am GMT). We will be closing the move log on Sunday, March 18th, 2001 at 11:59 pm PST (7:59 am on Monday the 19th GMT). The new, yet unnamed, server should be opened some time during the week of March 19th. We'll announce the exact date as soon as we can. </p>

<p>There are a few things to keep in mind when choosing to move your characters to the new server. The most important thing to keep in mind is that character corpses will not be moved with the characters. So it is important to make certain that you have looted all of the corpses that you want to loot before the characters are moved. </p>

<p>Also, characters names are unique on the new server. Because characters will be moving from two separate servers onto the new one, there may be cases where two characters with the same name are created on the new server. Because character names must be unique, one of the two characters will be chosen at random and have an 'x' added to the end of their name. If you find that one of your characters has had an 'x' tacked onto their name after the move and you would rather have a new name, please contact your GM by using the /petition function. The GM will help you to change the name of your character. </p>

<p>Guild structures do not follow the characters to the new server. We will be unable to reestablish guilds until at least a week has passed after the split. On any day after the new server has been up for eight days, the guild leader can /petition for a GM to help them reestablish the guild. Please do not petition for this before seven days have passed, we will not be able to set up your guild before then. </p>

<p>We will not be moving characters back to the old server, so make certain that you want to move your characters before you type "/movelog yes". And we will not be moving characters for those that fail to execute the movelog command during the stated window of opportunity. </p>

Alan 
