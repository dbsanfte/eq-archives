The Rathe and E`Ci have been split to Zebuxoruk and since The Rathe is my server (plus the fact that I know the site needs this functionality), I'm adding a page to have characters switch servers.  There will also be a guild server-switching page for guild admins.<br>
<br>
On top of that, my new site is coming along nicely, although I'm not too sure how well it's going to be received, being that there are a few others out there who do similar things.  I'll just have to wait and see I guess.<br>
