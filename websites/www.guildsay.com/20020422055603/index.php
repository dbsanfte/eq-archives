						<td class="headline" align="left"><a name="#24">The State of Guildsay.com</a></td>
					</tr>
					<tr>
						<td class="body">
							I haven't posted anything recently, and maybe you're thinking Guildsay has gone the way of so many other EverQuest-related sites, lacking funding and drive to support a free site.<br />
<br />
For the most part, that's correct, but the lack of funding was never really a problem.  It still isn't, actually, but I'd like to see if I can give it a nudge.<br />
<br />
As you may have noticed, I stopped serving ads on Guildsay recently.  Blah blah... ad companies are failing, yada yada.  I mainly killed the ads because they were timing out and it was causing a huge slowdown when displaying the page heh.<br />
<br />
So I was thinking to myself today... Guildsay isn't what I originally dreamed it would be.  I dreamt of guilds using this site exclusively for their management needs, public and private forums, calendars, event listings, server collaboration, and even an item database to link to your items so others could find out what, exactly, the stats were of the items on your body at any time.  But I was pressured to release the code because I was sitting on it for months and months, wishing I really had that drive to make all these other really nice features that I was sure people would appreciate.<br />
<br />
And you know what?  I think I'm finally going to get around to all the things I wanted this site to be when I first thought about creating it.  I no longer really like the way it turned out and, being that it was my first major (and it is major, even though it may not seem like it) web project, I can accept that and move on.  But I don't want to let the site die.  I refuse to cite funding issues and wipe the site from existence.<br />
<br />
So I ask you... would paying maybe $5 or $10 every 6 months (this is just off the top of my head) for improved guild functions, the use of an item database, and lots of other things I can't think of at the moment be too much to ask?<br />
<br />
I'm not saying Guildsay would become a pay site, but if you wanted to "kick it up a notch" as they say, a small fee would be paid and everyone would be happy.<br />
<br />
So I ask that you <a href="mailto:heffling@guildsay.com?subject=Site Direction">e-mail me</a> with your thoughts and concerns on this proposal and/or new additions to the site you'd like to see.<br />
<br />
I see some EverQuest sites fail because they never offered anything for a bit of a price, and I see others like <a href="http://www.eqmaps.com">EQMaps</a> thrive because of their outstanding content and relatively low montly fee.  I'd rather not end up like the former.
