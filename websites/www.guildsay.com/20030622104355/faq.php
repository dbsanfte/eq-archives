			<tr>
				<td class="body">
					You're a smart one, aren't you?  Well it goes like this.  If you created the guild, you have the option -- while logged in and viewing a character -- to set any character as the Guild Leader.  From there, you have control of the guild and a drop-down box will appear for you in every guild member's character screen.<p>In here, you can assign roles of Guild Officer, Guild Member, or Retired, as well as appoint up to four Guild Leaders.  Guild Officers and the Guild Leader can verify new characters, post guild news, and generally administer the guild.<p>This drop-down box is also where you can unguild a character if they defect or just decide to quit the guild for any reason.  Simply highlight the "Unguilded" option in the box, submit the information, and they're now without a home.				</td>
