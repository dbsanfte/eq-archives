				<td class="title">
					<a name="3">3. How do I create my character(s)?</a>
				</td>
			</tr>
			<tr>
				<td class="body">
					Before you can create your character(s), you need to have a valid user account and be logged in.  Click <a href="#1">here</a> to find out how to do that if you don't know how to, already.<p>After creating your account and logging yourself in, go <a href="http://www.guildsay.com/guilds/view_server.php">here</a> and select the server your guild is on.  If your guild does not show up, then either another guildmate has created it and it is sitting in the verification queue, or it's not created and you can <a href="#2">create it</a>, yourself.<p>Once you see your guild and you are in the guild page, look in the upper-right corner for an option to "Create Character."  Click on it and you will be brought to the character creation screen where you need to fill out the information and type in your guild's password (you knew that would come in handy sometime, right =) to add yourself into the verification queue.<p>If you're the guild creator, you have the power to verify your newly created character.  If not, you can still do so if you have been appointed Guild Leader or Guild Officer (more on that, <a href="#6">below</a>).  Otherwise, you need to wait until one of your guildmates with enough power verifies you.  Sorry, but thems is the breaks.
