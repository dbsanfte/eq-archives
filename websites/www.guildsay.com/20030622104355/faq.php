					<a name="2">2. How do I create my guild?</a>
				</td>
			</tr>
			<tr>
				<td class="body">
					Before you can create your guild, you need to have a valid user account and you need to be logged in.  Click <a href="#1">here</a> to find out how to do that if you don't know how to, already.<p>After creating your account and logging yourself in, go <a href="http://www.guildsay.com/create/create_guild.php">here</a> and fill out all the required information.<p>Your guild password will be used by your guildmates to add themselves to the guild, so keep this away from people you do not want trying to join your guild, and give it out amongst your ranks.<p>After creating your guild, it will be put into the validation queue for one of the handsome admins to verify.  Just as a note, <a href="http://www.guildsay.com/guilds/view_character.php?id=5">Qweeby</a> likes to eat people who use profanity when creating their guild names, so try to keep it to what your guild name <i>really</i> is, please.
