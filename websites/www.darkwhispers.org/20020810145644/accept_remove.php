		<strong>Removal Procedures:</strong></p>
		<p class="text">
		Although we all hope that these procedures will never be needed, even in Norrath sometimes it is 
		necessary to prepare to deal with these situations. Not only do your actions toward other guild 
		mates count but your actions to other citizens in Norrath count as well. Please think before you 
		act rashly and out of frustration and anger. We are all here to play a game and have fun together. 
		Every member is a representative of every other member of the guild. You do not stand alone in 
		Norrath. When you act, you act for all of Dark Whispers. All the people you represent will not 
		appreciate it if you act poorly and set a bad precedent, and every member you have poorly 
		represented will bring it to the attention of the officers who can act upon it accordingly. 
		The next few paragraphs will describe how the officers will work to make sure that only those 
		who care about the guild and the other members in it will be allowed to stay a member. 
		</p>
		<p class="text">
		<strong>The First Offense:</strong> A single officer may issue a warning on a first offense. This 
		is to be taken seriously. It means that if an incident occurs again it will be looked on with even 
		less tolerence than normal. Unless the offense occured in Guild Chat the warning will be issued 
		through a /tell, if it did occur in Guild Chat then it will be issued via Guild Chat.<br /> 
		<strong>Second Offense:</strong>  If a second offense occurs then at least 3 officers must agree to 
		put the member on a 2 week "Probation" period. If another offense occurs during this period then 3 
		officers must agree to remove the member permanetly from the guild. If the "probation" period goes 
		well and and no further offenses occur then the member is put back to the first offense status. 
		If another offense occurs then at least 3 officers decide whether to keep it at second offense 
		status or move it third, and will be acted upon accordingly.<br />  
		<strong>Third Offense:</strong> At the third offense status then at least 3 officers must agree to 
		that the removal of the member is neccessary, and will be announced through Guild Chat. 
		</p>
		<p class="text">
		<strong>Special Cases</strong><br /> 
		If there is only one officer online, and a situation arises that the officer thinks warants 
		forgoing the first and second offense stages; then the officer will diffuse the situation as 
		best as he/she can. Then warn the offending member that they have acted extremly poorly and 
		that their actions will be brought to the attention of the other officers ASAP and acted upon 
		accordingly which may or may not result in severe conseqenses. 
		</p>
		<p class="text">
		If there is only one officer online and a severe situation arises that obviously warrants 
		immediate removal from the guild, then the officer will take a vote from all the available 
		members online. If there is a majority backing to this decision then the offending guild 
		member will be immediatly removed from the guild. An act of immediate removal would be 
		needed in only the most severe cases such as EXTREME verbal abuse and threats. 
		</p>
		<p class="text">
		If there is only one officer and no other members online, save the one that is creating the 
		offense, then the officer would take any screen shots possible displaying the offense. As soon 
		as possible the situation and any evidence available will be brought to the attention of the 
		other officers and acted upon accordingly. 
		</p>
