<a href="search.php?query=&topic=3&author="><img src=images/topics/beer.gif border=0 Alt="Guild" align=right hspace=10 vspace=10></a>
Temple of Dawn was formed with the intention of getting friendly people
together to have a good time. Being a good gamer on EQ can be taught, being
a good person is ingrained within only some of us.
Everyone within ToD knows one another, and it is this mutual belief in
being friendly that has brought us closer together.
<br><br>
We have over 35 members that are 40th+, but we cater to lower level people as
well with guild events and raids for as low as 18-25th level.
<br><br>
So many people think it is about where you can go and what you can do. Well,
it is about that, but it is also about having a good time with people you
know. We are even working on a Norrathian Alliance among some smaller guilds
to prevent all the "uber" guilds from swallowing up everyone and leaving a
few people out to dry (I laugh when I see that specific guilds will NOT take
any Rangers below like 50+ lvl - WE welcome all lvls above 10th).
<br><br>
Come see what we are about and group with some members. You will be
pleasantly surprised.
<br><br>
Harmonious Cadenza<br>
Minstrel of the 53rd Song<br>
