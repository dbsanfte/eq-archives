                           Miscellaneous Items <br>
<br>
                           - Reduced the 'bottleneck' for getting Howling Stone keys by increasing the availability of one of the quest items. <br>
<br>
                           - Erudite guards will now be much less friendly to Kobolds. <br>
<br>
                           - Vendors are once again selling the Coldain Tanner's Kit. <br>
