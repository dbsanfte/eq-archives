<br>
                           'Combine' container changes <br>
<br>
                           We've made a change to 'combine' containers. In order to prevent people from accidentally destroying items, all containers with a<br>
                           'combine' button will not combine any items that do not form a complete recipe. This will be a huge boon to craftspeople all across<br>
                           Norrath. But this removes the only drawback to using trade containers as backpacks. Their reduced weight and often greater carrying<br>
                           capacity made them more desirable as bags, with the compensating risk that you might just lose something if you made a mistake. <br>
<br>
                           We will be increasing the weight of portable 'combine' containers somewhat. Where some of these containers weighed under 1<br>
                           pound, they will now weigh as much as 4 pounds for the largest sewing kit. <br>
<br>
                           Along with this we are making a change to tailor made backpacks. In case you didn't know, most tailor made packs have a built in<br>
