                           use helmets that show no graphics. <br>
<br>
                           - Five and ten charge versions of Potions of the Bone Field have been added. <br>
<br>
                           - Kilva's Skin of Flame potion has been changed. It no longer has the same effect as the Kilva's Blistering Flesh potion. <br>
<br>
                           - Removed the tinting from Dark Forge and Resonant armors. Tinting was never really intended to be on those pieces and, frankly,<br>
