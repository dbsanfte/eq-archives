			<p>So you're interested in becoming a Guardian? Or maybe your more interested in the life of a Pirate? Either way, your in the right place. All we ask is that you read through the following, and if your still interested, apply. So lets get started shall we?

		<p>The Life of a Guardian -</p>

		<p>Should you choose the path of rightousness (but not sinlessness) you will wish to join up with the Guardians. They protect and serve the esteemed Princess Lakotah. Following her guidance the Guardians are a nobel bunch. However, despite their role as the honorable protectors of the throne, and indeed, of Norrath itself, they are perhaps the most laid back group of nobels one ever did see. A night with the guardians is one filled with laughter, fun, and more often than not, at least one naked Wood Elf. The life of a guardian is filled with more than protecting the princess and nudity however. The guardians have mode it their delf appointed duty to see as much of Norrath as possible, and cleanse it of it's evils. They delve into places of danger and emerge victorious with the prizes to prove it. The life of a Guardian is an exciting one indeed.</p>

		<p>The Life of a Pirate -</p>

		<p>If you can pound back a keg of ale, and still be coherant enough to ask for more, the life of a Rival of the Throne is probobly best suited for you. The Rivals are a motly bunch of pirates who's goal in life is to pillage and plunder all of Norrath. One day, a Pirate may be working grudgingly at the side of a Guardian, and the next, he may be stabbing the very same guardian in the back with a rusty rapier. The pirates are honorless and rowdy, and for every count of nudity in the Guardian camp, the pirates have two. Pirates trust no one but themselves and their mug of ale. </p>

		<p>So now that you know what each guild is all about, it's time to read the Rules and Goals. These apply to both guilds. Once you have read them, you may proceed to the application page where you will choose your affiliation, and apply. At that point, you may join our chat using the command /join PrincessLakotah. Your application will be reviewed, and you will be contacted by an officer of the appropriate guild regarding your acceptance. During the time you spend in the chat room, you are encouraged to accept any offers to group with guild members, and to participate in any discussions that occur there.</p>
		

