			<tr><td class="titlebg" colspan=2 align="center">Welcome to the Lore Page - Info on the Compendiums</td></tr>
			<tr><td class="windowbg">
				This section of the site contains two areas. The Compendium of Lore and the Compendium of News.
				<p>The Compendium of Lore is designed for you all to add the in-game lore (no fan-fiction please) to our guild knowledge. This includes lore gained from quests, quest items/books, and merchant bought books that include the history of Norrath. Don't forget that the lore given with the adventures in the Lost Dungeons of Norrath from the Wayfarer's Brotherhood. (You know, when you talk to the people to increase the power of your Adventurer's Stone every few wins.)
				<p>The Compendium of News is for people to add all the articles from their home town newspapers. These newspapers are sold by the Town Criers in your home town. I know that in the past, EverQuest newspapers contained different information, to include quests, tradeskill recipies, and other useful data.
				<p>I set this section up because it has been my observation recently that the game of has gone from being a world with history and lore for people to explore to one of a hack-and-slash level grind. I realize that it is practically impossible for us to gain all the lore that exists in the game, but if nothing else, I will take this task upon myself to gather. Participation in this IS NOT MANDATORY, but encouraged.
				<p>All guild members have the ability to add to the compendiums, so feel free to add the information yourself. I just don't want to see my favorite game reduced to a hack-and-slash level grind as the core focus of the game. I know that not everyone that plays actually cares about such info as the lore, but it is all a part of having a role-playing universe. 
			</td></tr>
