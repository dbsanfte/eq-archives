<font color="blue"><strong>
<br>
Welcome weary traveler!<br>
Relax and stay awhile!<br>
Come in from out of the cold with us,<br>
You've walked your last lonely mile!<br>
<br>
Take the time to know us all,<br> 
Each one of us unique,<br>
We've all answered the same call,<br>
This is the place you seek!<br>
<br>
Our rules are few, for rules constrain,<br>
The first is show respect;<br>
To our Brethren, and others too;<br>
Throughout the lands we all inspect!<br>
<br>
The second is not so much a rule,<br>
In truth, a simple request;<br>
To selflessly assist your Brethren,<br>
If their life should be hard pressed.<br>
<br>
The pain the world causes others<br>
Need not be felt here!<br>
If we unite as sister and brother;<br>
Troubled paths will be swept clear!<br>
<br>
The third quality one must possess,<br>
Be ye Troll, or Dwarf or Elf;<br>
No matter your race or clrf or Elf;<br>
No matter your race or class;<br>
Get to know yourself!<br>
<br>
Group with your Sisters and Brothers;<br> 
As often as you can;<br>
And remember that all the others<br>
You meet throughout the lands-<br>
<br>
Are lonely out there now;<br>
They've no fire to keep them warm,<br>
Brighten their lives with a buff or SoW,<br>
And help keep them from harm;<br>
<br>
They are weary travelers;<br>
You'll find them wherever you roam<br>
Perhaps they're another Brethren,<br>
Wanting to come home.<br>
<br>
<br>
Bereg Spellsynger, Guild Leader of the Twilight Brethren
