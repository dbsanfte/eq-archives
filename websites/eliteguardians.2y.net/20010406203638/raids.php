      <P align=center><FONT color=#d3be75 face=Verdana size=4>*Raid Guidelines
      for Elite Guardian hosted Raids/Events*</FONT></P></TD></TR></TBODY></TABLE>
<P align=left><FONT color=#ffffff><FONT face=Verdana,Arial size=2>This document
will be used as a guide for all guild members and as a tool for raid leaders for
raids hosted by the Elite Guardians. In addition it contains guild raid
policy.<BR><BR>Foremost I would like to mention that the primary goal of any
raid is to have fun. It is a chance for you to achieve things in an organized
fashion which require more than one person to obtain.<BR><BR>Raids although
primarily to have fun, will always have an in game objective. That objective can
range from just clearing out a dungeon to becoming familiar with the layout or
to actually target specific areas in a dungeon where you are expecting to obtain
certain items.<BR><BR>Whatever the objective there needs to be a degree of
organization to help achieve the fun factor and meet the objective.<BR><BR>I
will break down the elements of a raid and explain each element in the following
text:<BR><BR></FONT></FONT><B><I><FONT color=#d3be75 face=Verdana,Arial
size=2>COMMUNICATION: </FONT></I></B><FONT color=#ffffff face=Verdana,Arial
size=2><BR><BR>Due to the design of Everquest our methods of communicating is
limited during a raid. In order to communicate during a raid with maximum
through put we assign one raid leader. It is the raid leaders responsibility to
lead parties by effectively communicating to the party leaders and it is the
responsibility of the party leaders to effectively communicate with they're
respective party members. It is the responsibility of the party members to
provide feedback to the party leader. This is the key to leading any raid. It's
the communication between the raid leader, party leader and it's members. Once
this dialog is established you can begin to maneuver as one through whatever
obstacles.<BR><BR>This is not as easy as it sounds. It is all to easy to be
distracted while in a raid which prevent effective communication. Things to
interfere is guild chat, melee combat messages, group chat and even the
excitement of the moment as you are landing that critical blow to a dry bone
skeleton or Fire Giant. Other factors include messages from people not even
participating in the raid, who may just happen to be in the same
area.<BR><BR>Communication is the most important part of any raid, once that
line of dialog is severed anything can happen and instant death and massacre can
result. It has to be the scariest part of the raid for the raid leader. Remember
the chain of communication. It goes from the raid leader to the party leader to
the party member and back. You cannot deviate from this rule.<BR><BR>If the raid
leader says to fall back that message is intended only for the party leaders. It
is up to the party leaders to order the group to fall back. The reason for this
is because you need to move as a unit to protect each other and another reason
is there maybe members in the party who don't see our guild chat because they
are in a different guild.<BR><BR>It is the responsibility of the party members
to keep the party leader apprised of your mana levels and status. The raid
leader will frequently need to know the status of the groups and that
information must be readily available to the party
leader.<BR><BR><BR></FONT><B><I><FONT color=#d3be75 face=Verdana,Arial
size=2>RAID LEADER ROLE: </FONT></I></B><FONT color=#ffffff face=Verdana,Arial
size=2><BR><BR>It is the raid leaders role to maneuver the group through the
raid to its conclusion. You represent the raid and are responsible for everyone.
We all know raids can be risky but you must temper risk with safety of all
parties. Speed should be the last thing on your mind. You should guide the group
methodically through whatever dungeon/plane you are in. You must have the pulse
of the group. If you have to fall back and regroup then do it. It is far better
to stop and med up and heal then to go that extra stretch and deplete everyone's
resources because it is going to be that surprise spawn that will get you every
time. You can consider it progress to clear out a room but remember it will
re-spawn so no matter how deep you go into a dungeon consider yourself
surrounded at all times.<BR><BR>The raid leader must insist that he/she has a
good line of communication. If you do not have that then you need to stop as
soon as possible and regain it. Not having it can result in you being in a room
all by your lonesome and that could turn disastrous.<BR><BR>You also carry a
heavy burden, everyone is looking to you to get them through this. You will be
the one holding the 'RUN' button, 'ATTACK' button etc... By the way the 'RUN'
order is a general order and should never be issued. The reason is because it is
an instant panic button, everyone will scatter in different directions. If you
must retreat, say RETREAT or something to do it in an organized fashion. RUN is
not acceptable. Have an escape plan in place for emergencies before going in.
One common method is to have evac capable parties or gate capable.<BR><BR>When
leading a raid with multiple guilds it is a good idea to make sure your party
leaders are in the same guild so you can issue commands. It is a difficult
process to send individual tells to each party leader, instead use Guild
chat.<BR><BR>In the event that you find yourself leading an unorganized raid and
organization is not in the immediate future you are obligated to call off the
raid. Pursuing the raid without organization is only going to result in disaster
and disaster goes against the primary objective and fun aspect of the raid. This
does not mean gate out and leave everyone. You should always walk into a raid
with some sort of escape plan. Remember not everyone can gate, and not everyone
can be binded etc..<BR><BR>You as raid leader needs to see the raid through to
its conclusion. If RL issues arise then you need to clearly delegate a new raid
leader or better yet have an alternate to take over incase of
emergencies.<BR><BR>Loot policy is enforced by the raid leader. You have to take
responsibility for how loot is divided if you don't, then it will erode the
moral of the parties and cause a breakdown in communication. As raid leader you
must be unbiased and fair to the loots distribution. There is a section devoted
to this.<BR><BR>Also keep in mind that you are the icon for this raid and
represent the guild and are to handle any external issues.<BR><BR>The success of
the raid leader is dependant not on whether you meet your objective, but that
you achieve team work and by doing so has enriched everyone's gaming experience
and confidence. Always remember the primary goal is to have
fun.<BR><BR><BR></FONT><B><I><FONT color=#d3be75 face=Verdana,Arial size=2>PARTY
LEADER ROLE: </FONT></I></B><FONT color=#ffffff face=Verdana,Arial
size=2><BR><BR>The party leader plays a very important role. You are responsible
for keeping your party working as a unit based on the direction provided you
from the raid leader. You must always seek the guidance of the raid leader,
provide the raid leader feedback and successfully communicate to your party
members. Failure to do this will most likely result in very unfavorable results
not only for your party but for the entire raid group. The raid leader needs to
keep the pulse of the entire group and it is critical that you provide him/her
with sufficient feedback to allow that. This includes the need to rest for a
bit, meditating and healing up, as well as your parties readiness to move
forward. You are the critical point in the communication process. Communication
will be relayed to you by your party members to the raid leader.<BR><BR>The raid
leader is not interested in details, only in summary information, giving him a
descriptive status of each member of your group will only cause more
communication than necessary. You need to be able to make the judgment as to
whether your group is fit to go further, or whether you group is in trouble or
not.<BR><BR>The raid leader is counting on you to follow all instructions. This
is not a power trip of the raid leader, it is to be considered a vital part of
the raid because the raid leader knows what all parties are doing and better
knows what actions need to take place. Additionally you are there to set an
example for your party. Your party members will be looking to you for guidance
and co-operation<SPAN style="FONT-FAMILY: Verdana; FONT-SIZE: 10pt"><O:P>
</O:P></SPAN>with the raid leader. By providing that example you free up
uncertainties within the party and allow members confidence to win over and do
there jobs and enjoy the benefits of team work.<BR><BR>The party leader will
also be consulted upon for decisions that the raid leader needs to
make.<BR><BR>In the event that you do not find the corporation of your party
members you must for the benefit of the raid inform the raid leader because that
issue must be resolved immediately. Anyone who is not following your direction
must be removed from the group if they cannot conform. Remember we all want to
survive and have fun, having a dis-functioning party will only lead to
disaster.<BR><BR>You will also be responsible for loot distribution for your
party.. The last thing we want is for someone in the party to get greedy, it
will disrupt the moral of the group. Please refer to the guild loot
policy.<BR><BR></FONT><B><I><FONT color=#d3be75 face=Verdana,Arial size=2>PARTY
MEMBER ROLE: </FONT></I></B><FONT color=#ffffff face=Verdana,Arial
size=2><BR><BR>The party member is a very important role to fill, of course
there would not be a raid with out it. Being in a raid where there can possibly
be more than one party can be difficult and requires effort on your part to play
your role to a tee. Your main objective is to follow your party leaders
direction. If your party leader says to CHARGE, then charge, if you party leader
says to RETREAT then you must retreat. Your actions impact every group in the
raid not just yours alone. It is critical that you keep your party leader
informed of any concerns you have so that he/she can address the issue. The
party leader may need to elevate it to the raid leader depending on the concern
you may have.<BR><BR>It is key to remember that this is a corporative effort and
solo based decisions cannot be tolerated. Everyone is depending on everyone else
to play there part.<BR><BR>Once you enter the raid, all concern for yourself
must diminish. Concern over your level , over your experience and over loot
should be of minimal value. Your main function is to operate as a team. The raid
may not have time to regroup because someone is not getting experience anymore,
or because someone is upset that they did not get a piece of loot, or even
because you lost a level. The only thing you must accomplish as a member of the
party is to follow direction until the conclusion of the
raid.<BR><BR>Communication is important with your party leader. Some members may
opt to turn on the guild chat filter and various other filters to insure a clear
line of communication within the group.<BR><BR>A party member needs to know
there own capabilities and even be aware of the other members
capabilities.<BR><BR>Loot tends to be one of the major issues when going on a
raid. Some of you are after a particular item even. But if things go wrong in
the loot department please do not abandon your guild mates, see the raid till
its conclusion and address the issue with an officer of the guild.<BR><BR>In the
event that your party member is killed you must be willing to accept
responsibility as the party leader if so directed by the raid
leader.<BR><BR>Always unless directed otherwise, stay with your group. Too many
times I have seen someone run in a panic and end up causing the deaths of many
more and even a short lived raid. You should go into the raid with the
understanding that you might die. If you cannot face this possibility then you
should reconsider joining the raid in the first place.<BR><BR><BR></FONT><FONT
color=#d3be75><B><I><FONT face=Verdana,Arial size=2>RAID ARRIVAL TIME:
</FONT></I></B><FONT face=Verdana,Arial size=2><BR></FONT></FONT><FONT
color=#ffffff face=Verdana,Arial size=2><BR>A raid commences at the established
time it was announced. This means that all the groups must be formed by this
time and entering the dungeon. It is the responsibility of each to get to the
designated place on time. Everyone signing up for the raid is counting on you to
be able to accomplish this. Showing up at the last minute will only disrupt the
raid organization. Therefore the following rules are in place:<BR><BR>1. Arrive
at least 30 minutes before the raid is to commence.<BR>2. Be willing to assume
the responsibilities that the raid leader places on you.<BR>3. Be sure to voice
any concerns about the group makeup to your party leader.<BR>4. Understand the
raid guidelines and loot policy.<BR>5. Make sure you come prepared. Have your
food and water and water ever components are required to allow you to see this
raid through to its completion.<BR>6. Only those who have signed up in the event
forum may participate in the raid.<BR>7. If you arrive late you risk loosing
your reserved spot in the raid.<BR><BR></FONT><B><I><FONT color=#d3be75
face=Verdana,Arial size=2>LOOT POLICY: </FONT></I></B><FONT color=#ffffff
face=Verdana,Arial size=2><BR><BR>The loot policy for raids is established to
provide a standard means of loot distribution. You must be willing to accept
this policy prior to going on the raid. The loot policy is not meant to be
complicated but there are several things which must be considered. This policy
is established by the officers and is available at all times and is not to be a
matter of debate once the raid commences. A successful raid does not have time
to be addressing these kinds of issues, there are more important things to worry
about, like re-spawn etc.<BR><BR>Failure to comply to the loot policy can result
in termination from the raid and since it is guild policy it can also result in
your termination from the guild.<BR><BR>This policy will be in place for all
Raids hosted by our guild. Other guild hosted raids may have a different policy
, if so that policy must be RESPECTED.<BR><BR><B>Note:</B> If you are attending
a raid hosted by a different guild make sure you understand the loot
distribution if it is going to be a concern for you during the
raid.<BR><BR>Those outside our guild attending one of our raids must comply with
this policy as well. If they don't they must be terminated from the
raid.<BR><BR>The raid leader will make the determination on whether auto split
is on or off, but the decision needs to be made prior to the raid
commencing.<BR><BR>Item distribution will work as follows:<BR><BR>The raid
leader will maintain a 'random list' in alphabetical sequence of all members of
the raid. This will be used to keep track of who has received an item and who
has not. Everyone in the raid will be allowed only 1 item per raid until
everyone in the raid has received an item. Once everyone has received an item
the 'random list' is cleared and starts over.<BR><BR>When an item is dropped the
raid leader will ask who wishes to participate in the random. If it is a class
specific item only those within the class and who does not already have the item
and has not previously received an item may participate, if there are none then
it is offered for random to anyone who has not previously received an item. The
raid leader will determine the number of members participating in the random and
cast a /random 1 &lt;number participating&gt;. The resulting number will
determine which person alphabetically based on the 'random list' (of only those
who are in the random) receives the item. Once a member receives an item they
are marked on the list as receiving an item and are prohibited from
participating in any further randoms.<BR><BR>*note: only the raid leader casts
the random*<BR><BR>The leader of the party who scores a kill are the only ones
permitted to loot. NO DROP items must remain until the random is finished and
must be looted by the individual that won the random.<BR><BR></FONT><B><I><FONT
color=#d3be75 face=Verdana,Arial size=2>FINALLY: </FONT></I></B><FONT
color=#ffffff face=Verdana,Arial size=2><BR><BR>This guide has been adopted and
approved by the guild officers and is subject to change. It is the
responsibility of the officers in the guild to keep this document up to date.
Deviation from these guide lines and policies may only be approved by Blum
(Guild Leader).<BR><BR>If you have an issue about the guild raid guide or loot
policies please bring them up to a guild officer so that the issue can be
resolved.<BR><BR>It is our hope by having a uniform way of handling our raids
that we stream line the process so that we can make our gaming time during raids
more productive and enjoyable.<BR><BR><BR>If you have any questions on this
please see an Elite Guardian Officer. Thank you.<BR></FONT></P>
