<!--EZCODE FONT START--><span style="color: orange">Our Goal</span><!--EZCODE FONT END--><br>
We want to become one of the most respected raid guilds on the Venril Sathir 
server. This means that we will select our members carefully.<br>
<br>
The Dawnraiders strive to create a fun community where every member has input 
into the guilds direction. This means we will hold votes over important 
decisions. <br>
<br>
We are not a casual guild, we do expect our members to attend raids and level up 
with us. But we are neither a hardcore guild, this means you don't have to 
attend every raid we plan. Fun and friendship should always be the keywords in 
everything we do.<br>
<br>
<br>
<!--EZCODE FONT START--><span style="color: orange">Recruitment</span><!--EZCODE FONT END-->
<br>
When you apply to our guild please try to follow these guidelines:<br>
<br>
The current minimum level for application is level 46.<br>
<br>
1. When applying please include your characters name, level, EQ experience, and 
what you are looking for in a guild. <br>
2. Applicants should contact the guild recruitment officer or guild leader 
in-game. <br>
3. Applicants are also encouraged to group and raid with us so we can gather 
information on your playing style.<br>
4. 2 Full members will have to vouch for you before you can join the guild.
<br>
Once you are accepted to our guild you will become a "trial member". trial 
members don't have the loot benefit a full member has. See the section about 
loot later on...<br>
<br>
<br>
<!--EZCODE FONT START--><span style="color: orange">Code of conduct</span><!--EZCODE FONT END-->
<br>
As a member of the dawnraiders you are expected to act in such a manner as to 
protect and enhance the image of the guild on the server and all its related 
Internet forums and guild boards. Members are expected to follow all guidelines 
published by Verant including the "play nice policy". Members are not to engage 
in the use of profanity or other offensive name-calling or racial slurs, 
particularly in a broadcast environment. Anyone found to be in violation of this 
code will be immediately deguilded after an investigation has been conducted.<br>
<br>
<br>
<!--EZCODE FONT START--><span style="color: orange">Raids</span><!--EZCODE FONT END-->
<br>
When most of our members are around level 50 we will start raiding 3 times a 
week. This number might increase as we grow. Members of the guild are encouraged 
to attend at least one scheduled raid each week. Members are expected to 
contribute to the guild, if we find a pattern where members only attend raids 
where they can improve their own gear, they will be immediately removed from the 
guild.<br>
<br>
During raids we will reimburse any costs a character has from our guild funds. 
This can include, but is not limited to, peridots and other expensive reagents, 
coffins, ranged items such as Antonian Javelins, damage shield potions, port 
stones, etc. This is rule applies to anyone joining our raids.<br>
<br>
<br>
<!--EZCODE FONT START--><span style="color: orange">Loot Policy</span><!--EZCODE FONT END--><br>
As to loot distribution we will use a DKP system. Every trial and full member 
will gain DKP points for each raid they attend. Every piece of loot will have a 
static DKP value. A full member will always have the right to an item over a 
trial member even if this trial member has more DKP.<br>
<br>
<br>
<!--EZCODE FONT START--><span style="color: orange">Leaving the Guild</span><!--EZCODE FONT END--><br>
Make no mistake, leaving the guild means you will have no possibility to return. 
Any items and money placed under your care should be returned to the guild.<br>
<br>
You ARE NOT required to return any item that was awarded to you during a raid.
