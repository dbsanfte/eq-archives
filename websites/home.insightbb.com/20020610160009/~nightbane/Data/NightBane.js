// Function to debug errors in html generated by scripting.  To test, call this function in a link or some other form.
// For example, <a href=javascript:debugPage()>Debug Me</a>  This creats a link, I usually throw it at the bottom of a 
// page.  If something does not look right, I click on it.  It opens a new window and when you view the source, you can 
// see the actual html that is generated to figure out where the problem is occuring.

function debugPage()
{
 	var range = document.body.createTextRange();

	if (range!=null) 
	{
		var w = window.open()
		w.document.write( range.htmlText )
	}
}

