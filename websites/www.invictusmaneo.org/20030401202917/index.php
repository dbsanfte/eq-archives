          <font size="-1">
            Well I usually don't like posting news about what we're farming, but extraordinary events require mention, even if said events don't revolve around killing the next boss mob in EQ's endless ladder of progression.  I'm sure you're all just *dying* to know what could be so special that my notoriously lazy ass actually decided to update the news.  No?  Well you're here reading this anyway, suck it up and let me elaborate.
<br>
<br>
First off, we've been spending a lot of time in Tactics.  In a situation reminiscent of "Mission - Ancient Aegolism", our main goal lately has been the aquisition of seldom seen artifacts known as the "Blade of War".  However, as we have often found, the mere act of declaring a single drop as our main priority has a direct correlation to said loot never fucking dropping.  No, the extraordinary event that happened wasn't that another Blade of War dropped for us.  Last 2 kills = Mask, Boots, Earring, Choker.
<br>
<br>
So what was so extraordinary you ask?  Patience my son.
<br>
<br>
Our tale starts late last week.  Another excursion into Tactics begins... little did we know that our old friend Murphy was about to pay us a return visit.  With his return came 3 days of struggling against the RZ encounter, losing in every conceivable way.  Finally Saturday rolled around and we got serious... (better known as, we were bribed with a free day on Sunday if we could conjure up a win).  The excitement started to build...
<br>
<br>
<center>
<img src="images/ogre-poop.jpg">
<br>
<img src="images/bigwin.jpg">
</center>
<br>
<br>
And a big win it was, seriously it was probably our cleanest RZTW kill to date, no deaths to the big man himself, and only a ranger casualty to the add cleanup afterwards.  How do I know this?  Well because, as the news updater, people make sure to remind me of the details...
<br>
<br>
<center>
<img src="images/fortyfive.jpg">
<br>
<br>
<img src="images/rz-dirtnap.jpg">
</center>
<br>
<br>
So was this oh-so-gratifying kill the pinnacle, this extraordinary event that actually conviced me to update news again?  Hell no, remember I'm lazy.  So what was it?  Well during one of our many graveyard trips last week, we decided that we needed to show our gratitude to our selfless leader, Fantor.  For those that don't know it, the man has taken a vow of poverty, donated his millions to charity, and declared that he'd never loot a single item again, ever.  Of course, like the corrupt cops in Training Day, we looked at him strangely, and told him we'd feel better if he'd just take some.  Thus "the plan" was born.  Appreciation would be forced upon him... or we'd be cleaning out the bathtub.
