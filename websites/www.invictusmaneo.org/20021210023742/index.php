            This update is a little overdue, people have been buggin' me to post one, since we have been rather busy, but I'm a lazy ass.  
<br>
<br>
Ever have one of those raids where it seems fate is against you?  That no matter what you do, some greater force is whispering in your ear "YOU WILL LOSE".  I'm not talking about the tough fights, where you scrape out a win against all odds.  I'm talking about the fights where people make all sorts of little mistakes, and they start adding up into huge pain.  Well our last Emperor fight was one of these raids.
<br>
<br>
It started off fine - Blood engaged, adds locked down.  Order to kill Blood and pop the big guy is given.  POOF! Our wizard group has been evac'd to zone in.  Yup, don't ask. Ok ok, no need to panic, CoH chain still up so we can get em back no problem.  So we're in the midst of getting our wizards back up into the Emp room, and Murphy begins to stroll over to the tank-mez group.  Not long after, one of the nastier snakes slithers his way up a diagonal doorframe, and poofs into the wall.  And where do all walled mobs go? The zonein of course! Our wizards now had company, with more on the way.  The walled mob slowly but surely started his own CoH chain, and managed to get about 2 more groups summoned to zonein before the frustrated people at zone got fed up and slaughtered him.  While this was all happening, toss in occassional LD's on our enchanters due to the "OMG I can't miss another power source" zerg force we had.  Fun!
<br>
<br>
Well we finally got everyone back up into the room, killed Blood, and then waxed the Emperor.  Murphy must have had to log for dinner by then - the fight was pretty non-eventful after that.
<br>
<br>
