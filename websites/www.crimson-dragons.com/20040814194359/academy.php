<p align="center"><i>"Training should be so realistic that it makes real battles feel fake." -- <b>Richard Marcinko</b></i><p>


<p align="center">
<b>Crimson Dragons supports three Academies to help foster knowledge within the different schools of discipline.  
These three academies group our members according to classes, so that they may learn different tactics, tips and 
ideas from each other.  This sytem provides for easy access to experts that are ready to share their knowledge with 
those of less experience.</b></p>


<div align="center">
<h2>The Academy of Melee</h2>
<h3>(The School of Fighters)</h3></div><p>

<img src="pics/t.gif" width=41 height=51 alt="" border="0" align="left">his Academy is comprised of Warriors, Rangers, Paladins, 
Monks, Shadow Knights and Rogues.  The members of this academy are the front line soliders of Crimson Dragons.  They strive to 
master the art of physical combat, tactics and warfare.  These mighty adventureres, strong in body as well as in mind form the 
core of the Crimson Dragons Fighting Force.<p><br>

<div align="center">
<h2>The Academy of Sorcere</h2>
<h3>(The School of Magic)</h3></div><p>

<img src="pics/t.gif" width=41 height=51 alt="" border="0" align="left">his School is the home of the pure casters, such as 
Wizards, Magicians, Enchanters and Necromancers.  This Academy fosters learning of the arcane and scientific arts associated with 
spell casting.  These brilliant and ever curious minds form the inquisitive heart of Crimson Dragons.  Their active pursuit of 
knowledge serves to benefit the guild as a whole.<p><br>


<div align="center">
<h2>The Academy of Mysticism</h2>
<h3>(The School of Theology and Healing)</h3></div><p>

<img src="pics/t.gif" width=41 height=51 alt="" border="0" align="left">his Academy consists of those who draw their power from 
spiritual, natural and mystical sources, such as Druids, Shamans, Clerics and Bards.  These talented individuals are the heart 
and soul of the Crimson Dragons, striving to achieve a spiritual balance within themselves and the world around them.  Their powers 
of healing and nurturing make them a most valuable resource for the guild.


