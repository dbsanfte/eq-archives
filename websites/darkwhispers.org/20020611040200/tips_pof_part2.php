		 <p class="text">
		<strong>PLANE OF FEAR 1.0.2</strong><br /><br />
		
		Fear Primer - for all you n00bs
		</p>
		<p class="text">
		My previous post was for break types and styles ... this one is a fear
		primer for anyone relatively new to the plane of fear. NOTE: I really didn't
		find one when I first went - not even at safehouse - as there was only a
		guide for pulling hate.
		</p>
		<p class="text">
		Listen to the Raid Leader: it is their raid. Other peoeple may ooc or shout
		(which they shouldn't), but in the end - the raid leader is calling the
		shots. This also means - even though you are feeling ansy cause the leader
		is working on no shows or groups ... be patient and attenative. You really
		don't want to miss one piece of information that may save your or more
		important - the RAIDS life. Wait until the end of instructions and until the
		raid leader says 'Are there any more questions?' before you ask him or her
		something. They have a billion tells and things going on ... so once again
		... be patient.
		</p>
		<p class="text">
		NOTE what type of break it is going to be: It is important that you know if
		it is going to be North or West. The two different breaks have different
		strategies - and if you go the wrong way - not only will you die - but you,
		yes by yourself, can have teh whole raid killed and in a sticky spot. IF
		WEST <------ GO LEFT out of the portal ... and down the hill to camp. There
		are now 2 different North varietions ... so listen to the leader.
		</p>
		<p class="text">
		Make sure that you get the Primary and Secondary Assist down: That means
		make hot keys with /assist PriamryPerson and another with /assist
		SecondaryPerson
		</p>
		<p class="text">
		Be Patient: The time it takes to coordinate a raid can sometimes be shifted
		due to circumstances. Once you get in a pattern with a well established raid
		group - things will go faster - but note - it takes time.
		</p>
		<p class="text">
		Invisibility: Once upon a time - it seemed that everything would come after
		you no matter what. But as I have spent much time in Fear - I have
		experimented with invis and the mobs. Note - if you are a ShadowKnight or a
		Necro and don't have a Circlet of Shadows - you are WRONG - it is the best
		thing next to Jboots. Even when I have pulled ... I will invis up to
		'lesson' the aggro radius and to scout for monks and such.
		</p>
		<p class="text">
		It was during these times that I noticed that less and less mobs really
		detected invisibity. I had ruled out Tentitle Terrors due to once getting
		dispelled from them as I ran through them invis - and was still invis when I
		did, but the truth is - THEY DON'T see invis. In Fact - I have pulled a
		corpse out of the graveyard and I mean CENTER - if not closer to the gorgon
		roost with Turmoil Toads - Fetid Feinds - Worry Wraiths - Amy Knights and
		Warrios all around me. No aggro. I notice that more and more - mobs con
		indifferent when I am invis - and have confirmed that EVERY MOB is
		indifferent to invis at one point or another.
		</p>
		<p class="text">
		BUT - I have also noticed that there are SOME that do see invis. Now this is
		one of 2 things. A) I have aggroed a mob - and don't know it - and when i go
		out invis - it is still aggro on me and it doesn't matter if I am invis - it
		is a scowling mob. B) I am convinced that there are some mobs - probably the
		frightfingers ... but could be any of the caster type MoBs (Worry Wraiths -
		Glare Lords) that cast See Invis on MoBs. Kinda like in Sol A. There are
		those wizzies and shamans you just can't get by - they see invis.
		</p>
		<p class="text">
		Examply - same night - I go back into the GY to drag another body ... I am
		just North of the Boogy House ... and I am standing with the toads and
		gorgons and all the other baddies that hang there ... and so I start heading
		north - trying to get this loc on the body. (I am not about to cast locate
		corpse in the middle of all these mobs ... my nutsack is shrivled enough
		thank you). So ... I am heading north and thanks to my SB Live (which btw -
		helps me pull as I can hear about everything in the zone ... and where it is
		coming from) I hear the speed up steps of a Fetid Fiend t my right. I look -
		and sure enough - here it comes ... note - nothing else has attacked me
		yet - but I know what is going to happen - so I bolt towards the firewall
		... and you know what - even though I am invis - I start a train ... the
		other MOBS that there - pick up on the aggro and start on me - I see a WW
		start to cast - and at this point I figure I am dead. But I make it out -
		and make the west wall behind the Fetid House (which was broken - and
		everyone has moved to the North Camp - cause we were doing CR for someone
		else) and luckily FD. So I /q out and come back - and try again ... same
		thing - it is this ONE Fetid Fiend in the North Part of the Graveyard.
		Everything else was cool ... so we ended up getting a coffin for that one.
		</p>
		<p class="text">
		Other Times - like this past Saturday - after Guinn left - I was elected to
		pull (and btw - thank you Pimm and HHeather - I love pulling) - so I start -
		I get invis to scout and see the MoB layout ... and then get within aggro
		range and click off invis ... and mr baddy comes a chasin ... which I take
		it back and do the monk thing. I did this from West Wall to the Glare Lords
		on the East side - and had moved the peeps to the Frightfinger house. NOT
		once did I get prematurely aggroed because I was invis.
		</p>
		<p class="text">
		BUT NOTE - some mobs do see - for whatever reason - and when they do - the
		other stuff will aggro you.
		</p>
		<p class="text">
		Regardless - I know for a FACT that invis is very important - and when you
		break - YOU SHOULD ALWAYS have invis on. If you don't you are WRONG!
		</p>
