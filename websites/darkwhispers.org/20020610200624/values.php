		<p class="text">
		<strong>Statement of Values</strong><br />
		 The purpose of the definition of values is to declare as a guild what we hold to in 
		 the core of our being. Without values the guild will suffer from members that share 
		 not the same heart and vision. As stated in the Bible, "A house divided will not stand". 
		 Does this mean there is not constructive criticism or debate? No. In fact it is through 
		 debate and criticism that we grow and keep each other honest. Values differ than Goals. 
		 A value is a moral belief or a system of thought that guides action. A goal is an objective 
		 to be realized and achieved. The guild is founded on values, not goals. The guild sets 
		 goals and sets out to achieve them in the midst of retaining the values. No value 
		 should be compromised reaching a goal, or that value is nullified. 
		</p>
		<p class="text">
		<strong>Integrity/Openness:</strong> The quality of possessing and steadfastly adhering to high moral principles or professional standards and the ability to express those verbally and in action.<br /> 
		<strong>Family Focused:</strong> A group whose members are related in origin, characteristics, or occupation.<br />  
		<strong>Valor:</strong> Courage, especially that shown in war or battle. <br /> 
		<strong>Justice:</strong> Fairness or reasonableness, especially in the way people are treated or decisions are made.<br /> 
		<strong>Mercy/Compassion:</strong> Kindness or forgiveness shown to an offender or to somebody a person has power over.<br /> 
		<strong>Humility:</strong> The quality of being modest or respectful.<br /> 
		<strong>Teamwork/Sacrifice:</strong> A cooperative effort by a group or team / a giving up of something valuable or important for somebody or something else considered to be of more value or importance. We work for the team win.<br /> 
		<strong>Leadership/Empowerment:</strong> We challenge others to their personal best. We enable others to get the job done.<br /> 
		<strong>Respect for the Individual:</strong> We trust and respect one another. We value each person for his or her personal unique perspective and contribution. 
		</p>
		<p class="text">
		Now in light of the value of Leadership and Empowerment - we are to challenge each other (and 
		those not in the guild) to their personal best, which is reflected in the rest of the values. 
		Some values might seem a dichotomy, such as Mercy and Justice - Valor and Humility, and the 
		challenge is that in a situation where we are standing in Valor, are we remembering Humility? 
		Or in the place of Justice, are we remembering Mercy (or Vice Versa)? No one is perfect, but 
		as we remember to challenge each other to the values we shall remain balanced. 
		</p>
		<p class="text">
		The goals remain yet to be determined, and the long-term goals will be more solid and not change
		as much as short-term goals. Current goals will be detailed on the guild web page.<br /> 
		In closing, we respect individuals, and are a family. No one individual however is above the family,
		and is subject to the family, including the guild leader. For planning goals and direction, there
		will be a democratic method. In fact most decisions will be done through polls on the guild EZ Board
		that will be set up - though the leadership will do the initial debate and post the options on the
		board. 
		</p>
		<p class="text">
		<strong>Please do not come to this guild expecting that all your needs will be met - both emotionally or 
		equipment wise.</strong> We do care, and are concerned about equipping our guild members. But demands for 
		specific items will not be tolerated. There will be a wish list, and based on need and importance, 
		the guild will set goals to obtain the gear specified. Also, many of us have other friends, guilded
		and not, and it is not going to always be possible to get in a group/raid with a guild member. Do 
		not take this personal, but rather be open-minded and try to put yourself in the others shoes. We 
		want to make sure that if given an option that we will make efforts to include the family in all 
		things, but some situations prohibit that. Some examples is that if we ever have higher level 
		clerics, that their sole purpose be to run around all night rezzing people will not be tolerated, 
		unless they choose to function in this propensity. We do not want to abuse or neglect. In the end, 
		the above would be considered common sense, but expectation needs to be set. We will try to care 
		and respect all with what resources we have, but no one person or groups of people are perfect. 
		Thus the commitment to our value statement to preserve the guild. 
		</p>
